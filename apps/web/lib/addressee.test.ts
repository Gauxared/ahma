/**
 * Адресат поручения — против «46 адресатов на 55 поручений».
 *
 * НАЙДЕНО НА ЭКРАНЕ КЛИЕНТА, а не набором.
 *
 * Панель «Что проверить человеку» показывала: 55 шт. · 46 адресатов. Один и тот
 * же человек приходил пятью написаниями — «Артемий», «Артемий / планирование»,
 * «Артемий / проектный блок», «Артемий / сметный блок», «Артемий / финансовый и
 * юридический блок», — потому что владельца пишет модель свободным текстом.
 *
 * Смысл группировки — «кому это отдать». При сорока шести адресатах на
 * пятьдесят пять поручений группировки нет: список пересказан другим порядком.
 */
import { describe, expect, it } from "vitest";

import { адресат, адресаты } from "./addressee.js";

describe("адресат поручения", () => {
  it("один человек с пятью уточнениями — один адресат", () => {
    const строки = [
      "Артемий",
      "Артемий / планирование",
      "Артемий / проектный блок",
      "Артемий / сметный блок",
      "Артемий / финансовый и юридический блок",
    ];

    expect(new Set(строки.map(адресат))).toEqual(new Set(["Артемий"]));
  });

  it("организация с ролью сводится к организации", () => {
    // «Заказчик / руководитель проекта» и «Заказчик / сметчик» — это один
    // получатель: отдают их обоих заказчику.
    expect(адресат("Заказчик / руководитель проекта")).toBe("Заказчик");
    expect(адресат("Заказчик / сметчик")).toBe("Заказчик");
  });

  it("разные разделители режутся одинаково", () => {
    // Модель пишет свободно: слэш, точка, тире, запятая. Разбирать один вид и
    // не разбирать другой значило бы чинить проблему наполовину.
    for (const строка of [
      "Ваныч / финансовый блок",
      "Ваныч · финансовый блок",
      "Ваныч, финансовый блок",
      "Ваныч — финансовый блок",
    ]) {
      expect(адресат(строка), `не разобрано: «${строка}»`).toBe("Ваныч");
    }
  });

  it("разные люди НЕ схлопываются", () => {
    // Сведение написаний одного человека не должно превратиться в потерю
    // разных: тогда поручение уйдёт не тому.
    expect(адресат("Халиль / подряд")).toBe("Халиль");
    expect(адресат("Виктор / договор")).toBe("Виктор");
    expect(адресат("Халиль")).not.toBe(адресат("Виктор"));
  });

  it("пустой адресат остаётся пустым, а не становится «прочими»", () => {
    // «Поручение без адресата» — это его свойство (§9). Подставить сюда
    // получателя значило бы придумать того, кому никто ничего не поручал.
    expect(адресат("")).toBe("");
    expect(адресат("   ")).toBe("");
  });

  it("адресат без уточнения не меняется", () => {
    expect(адресат("Расчётный модуль")).toBe("Расчётный модуль");
  });

  it("поручение ДВОИМ приходит обоим, а не третьему несуществующему", () => {
    /**
     * ВТОРОЙ ЗАМЕР НА ЭКРАНЕ КЛИЕНТА: 55 поручений и 28 адресатов. Среди них
     * «Заказчик и руководитель проекта», «Заказчик и снабжение подрядчика»,
     * «Заказчик и проектировщик» — каждое завело СВОЮ группу из одного пункта.
     *
     * Такой группы нет в жизни: есть заказчик и есть руководитель проекта, и
     * поручение адресовано им обоим. Свести его к первому значило бы потерять
     * второго; оставить отдельной строкой — заставить обоих искать себя.
     */
    expect(адресаты("Заказчик и руководитель проекта")).toEqual(["Заказчик", "руководитель проекта"]);
    expect(адресаты("Заказчик и снабжение подрядчика")).toEqual(["Заказчик", "снабжение подрядчика"]);
  });

  it("«или» — тоже двое: владелец не выбран, и увидеть должны оба", () => {
    // Поручение без определённого владельца — не повод спрятать его от обоих
    // кандидатов: кто-то обязан его забрать (ТЗ §9).
    expect(адресаты("Заказчик или договорной отдел")).toEqual(["Заказчик", "договорной отдел"]);
  });

  it("союз внутри слова НЕ режет имя", () => {
    // «Людмила» содержит «и»; «Виктор или» — нет. Без пробелов вокруг союза
    // разбор искрошил бы имена.
    expect(адресаты("Людмила")).toEqual(["Людмила"]);
    expect(адресаты("Инициатор договора")).toEqual(["Инициатор договора"]);
    expect(адресаты("Снабжение и логистика / закупки")).toEqual(["Снабжение", "логистика"]);
  });

  it("уточнение режется ДО союза, а не после", () => {
    // «Артемий / проектный и сметный блок» — это один человек с уточнением,
    // а не двое: союз стоит внутри уточнения, которое в заголовок не идёт.
    expect(адресаты("Артемий / проектный и сметный блок")).toEqual(["Артемий"]);
  });

  it("одиночный адресат остаётся списком из одного", () => {
    expect(адресаты("Артемий / планирование")).toEqual(["Артемий"]);
    expect(адресат("Артемий / планирование")).toBe("Артемий");
  });
});
