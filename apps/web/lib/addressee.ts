/**
 * АДРЕСАТ — ЧЕЛОВЕК, А НЕ СТРОКА, КОТОРУЮ НАПИСАЛА МОДЕЛЬ.
 *
 * Замерено на прогоне клиента: 55 поручений и 46 адресатов. Модель пишет
 * владельца свободным текстом, и один и тот же человек приходит пятью
 * написаниями: «Артемий», «Артемий / планирование», «Артемий / проектный блок»,
 * «Артемий / сметный блок», «Артемий / финансовый и юридический блок».
 *
 * Смысл группировки — «кому это отдать». При сорока шести адресатах на
 * пятьдесят пять поручений группировки нет: список просто пересказан другим
 * порядком.
 *
 * Режется по первому разделителю. Уточнение НЕ ВЫБРАСЫВАЕТСЯ — «Артемий /
 * сметный блок» точнее, чем «Артемий», — оно остаётся у самого поручения; в
 * заголовок группы идёт человек.
 *
 * ВТОРОЙ ЗАМЕР, ПОСЛЕ ПЕРВОЙ ПРАВКИ: 55 поручений и 28 адресатов. Осталось то,
 * что режется не разделителем, а союзом: «Заказчик и руководитель проекта»,
 * «Заказчик и снабжение подрядчика», «Заказчик или договорной отдел».
 *
 * Это НЕ ОПИСКА и не третий человек — это поручение ДВОИМ. Свести его к первому
 * значило бы потерять второго, а держать отдельной группой — завести адресата,
 * которого не существует, и заставить обоих искать себя в списке. Поэтому
 * адресатов у поручения может быть несколько, и оно показывается каждому.
 */

/** Уточнение роли: «Артемий / сметный блок». Берётся то, что до разделителя. */
const УТОЧНЕНИЕ = /\s*[/·|,—–]\s*/u;

/**
 * Союз между адресатами.
 *
 * Пробелы вокруг обязательны: без них «или» съело бы «Людмила» изнутри, а «и» —
 * любое слово с этой буквой. Русский союз ищется как отдельное слово, потому
 * что границы слова в JS считаются по ASCII и на кириллице не работают.
 */
const СОЮЗ = /\s+(?:и|или)\s+/u;

/**
 * Все, кому адресовано поручение. Обычно один; двое — когда модель написала
 * «X и Y» или «X или Y».
 *
 * Пустой адресат остаётся пустым: «поручение без адресата» — это его свойство
 * (ТЗ §9), и подставлять сюда «прочие» значило бы придумать получателя.
 */
export function адресаты(owner: string): readonly string[] {
  const голова = owner.split(УТОЧНЕНИЕ)[0]?.trim() ?? "";
  if (голова === "") return [owner.trim()];

  const части = голова
    .split(СОЮЗ)
    .map((часть) => часть.trim())
    .filter((часть) => часть !== "");

  return части.length === 0 ? [голова] : части;
}

/**
 * Первый адресат — там, где получатель нужен ровно один (заголовок, сортировка).
 *
 * Группировка так НЕ делается: для неё есть `адресаты`, и поручение двоим
 * обязано попасть к обоим.
 */
export function адресат(owner: string): string {
  return адресаты(owner)[0] ?? owner.trim();
}
