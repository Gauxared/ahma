/**
 * Листы агента по нескольким документам — против молчаливой потери трёх из четырёх.
 *
 * КАК ЭТО НАШЛОСЬ
 *
 * На прогоне эталонного входа (7 документов, 4 сметы, все десять агентов)
 * сметчик вернул лист «Сходимость сметы» по КАЖДОЙ из четырёх смет. В книге
 * `03_Сметный_анализ` оказался один такой лист с четырьмя строками — по одной
 * смете. Три остальных исчезли: сборка складывала листы по первому вхождению
 * `id` и отбрасывала повторы.
 *
 * Худший вид потери из возможных. Заголовок обещает предмет целиком, таблица
 * под ним заполнена, порядок не нарушен — отличить «проверена одна смета» от
 * «проверены все четыре» нельзя ничем, кроме сверки с артефактом.
 *
 * ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ
 *
 * Не «листы сводятся», а что при сведении НЕ ТЕРЯЕТСЯ НИ ОДНА СТРОКА и ни одно
 * значение не встаёт под чужим заголовком.
 */
import { describe, expect, it } from "vitest";

import { groupByAgent } from "./check-read-model";

function обзор(
  path: string,
  sections: readonly Record<string, unknown>[],
  capability = "estimate_review",
): Record<string, unknown> {
  return { path, capability, verdict: "🟡 условно", findings: [], sections };
}

const СХОДИМОСТЬ = (columns: readonly string[], rows: readonly (readonly string[])[]) => ({
  id: "convergence",
  title: "Сходимость сметы",
  purpose: "итог сметы против суммы позиций",
  columns,
  rows,
});

describe("листы одного агента по нескольким документам", () => {
  it("строки всех смет доезжают до листа, а не строки первой", () => {
    const [агент] = groupByAgent([
      обзор("/о/ЛСР-1.xlsx", [СХОДИМОСТЬ(["Показатель", "Значение"], [["итог", "354 580"], ["сумма позиций", "354 580"]])]),
      обзор("/о/ЛСР-2.xlsx", [СХОДИМОСТЬ(["Показатель", "Значение"], [["итог", "1 204 000"]])]),
      обзор("/о/ЛСР-3.xlsx", [СХОДИМОСТЬ(["Показатель", "Значение"], [["итог", "88 100"]])]),
    ]);

    const лист = агент!.sheets.find((sheet) => sheet.id === "convergence");

    expect(лист, "лист сходимости не собран").toBeDefined();
    expect(лист!.rows, "строки смет потеряны при сведении").toHaveLength(4);
    expect(JSON.stringify(лист!.rows)).toContain("1 204 000");
    expect(JSON.stringify(лист!.rows)).toContain("88 100");
  });

  it("первой графой встаёт документ — иначе строки четырёх смет неразличимы", () => {
    const [агент] = groupByAgent([
      обзор("/о/ЛСР-1.xlsx", [СХОДИМОСТЬ(["Показатель"], [["сошлось"]])]),
      обзор("/о/ЛСР-2.xlsx", [СХОДИМОСТЬ(["Показатель"], [["не сошлось"]])]),
    ]);

    const лист = агент!.sheets[0]!;

    expect(лист.columns[0]).toBe("Документ");
    expect(лист.rows.map((row) => row[0])).toEqual(["ЛСР-1.xlsx", "ЛСР-2.xlsx"]);
  });

  it("колонки совмещаются ПО ИМЕНИ, а не по номеру", () => {
    /**
     * Замерено на настоящем прогоне: у «Сходимости» по первой смете четыре
     * колонки, по второй — пять. Совмещение по порядку сдвинуло бы значения на
     * графу: числа встали бы под чужими заголовками, и таблица врала бы,
     * оставаясь заполненной.
     */
    const [агент] = groupByAgent([
      обзор("/о/ЛСР-1.xlsx", [СХОДИМОСТЬ(["Показатель", "Значение"], [["итог", "354 580"]])]),
      обзор("/о/ЛСР-2.xlsx", [
        СХОДИМОСТЬ(["Показатель", "Основание", "Значение"], [["итог", "лист 3", "1 204 000"]]),
      ]),
    ]);

    const лист = агент!.sheets[0]!;
    const графа = (имя: string) => лист.columns.indexOf(имя);

    expect(лист.columns).toEqual(["Документ", "Показатель", "Значение", "Основание"]);
    expect(лист.rows[1]![графа("Значение")], "значение встало под чужим заголовком").toBe("1 204 000");
    expect(лист.rows[1]![графа("Основание")]).toBe("лист 3");
  });

  it("отсутствующая у документа графа помечается прочерком, а не пустотой", () => {
    // Пустая ячейка в таблице чисел читается как ноль (§9). Прочерк говорит
    // «такой графы у этого документа не было» — это другое утверждение.
    const [агент] = groupByAgent([
      обзор("/о/ЛСР-1.xlsx", [СХОДИМОСТЬ(["Показатель"], [["итог"]])]),
      обзор("/о/ЛСР-2.xlsx", [СХОДИМОСТЬ(["Показатель", "Отклонение, ₽"], [["итог", "12 400"]])]),
    ]);

    const лист = агент!.sheets[0]!;

    expect(лист.rows[0]![лист.columns.indexOf("Отклонение, ₽")]).toBe("—");
  });

  it("лист по одному документу графу «Документ» НЕ получает", () => {
    // Лишняя графа с одним и тем же значением во всех строках — шум: она
    // отодвигает содержательные колонки и ничего не различает.
    const [агент] = groupByAgent([
      обзор("/о/ЛСР-1.xlsx", [СХОДИМОСТЬ(["Показатель", "Значение"], [["итог", "354 580"]])]),
    ]);

    expect(агент!.sheets[0]!.columns).toEqual(["Показатель", "Значение"]);
  });

  it("сведение объявлено в назначении листа, а не подразумевается", () => {
    // Читатель видит первой графой «Документ» и должен понимать, откуда она.
    const [агент] = groupByAgent([
      обзор("/о/ЛСР-1.xlsx", [СХОДИМОСТЬ(["Показатель"], [["итог"]])]),
      обзор("/о/ЛСР-2.xlsx", [СХОДИМОСТЬ(["Показатель"], [["итог"]])]),
    ]);

    expect(агент!.sheets[0]!.purpose).toContain("сведено по 2 документам");
  });

  it("разные листы одного агента не смешиваются между собой", () => {
    const [агент] = groupByAgent([
      обзор("/о/ЛСР-1.xlsx", [
        СХОДИМОСТЬ(["Показатель"], [["итог"]]),
        { id: "overheads", title: "НР и СП", purpose: "нормативы", columns: ["Норматив"], rows: [["89%"]] },
      ]),
      обзор("/о/ЛСР-2.xlsx", [СХОДИМОСТЬ(["Показатель"], [["итог"]])]),
    ]);

    expect(агент!.sheets.map((sheet) => sheet.id)).toEqual(["convergence", "overheads"]);
    expect(агент!.sheets.find((sheet) => sheet.id === "overheads")!.columns).toEqual(["Норматив"]);
  });

  it("листы разных агентов не сливаются по совпавшему id", () => {
    // `margin_impact` завели и снабженец, и подрядчик — это РАЗНЫЕ листы в
    // разных книгах, и склеить их значило бы отдать снабженцу чужую таблицу.
    const агенты = groupByAgent([
      обзор("/о", [{ id: "margin_impact", title: "Влияние закупки", purpose: "п", columns: ["А"], rows: [["закупка"]] }], "procurement_map"),
      обзор("/о", [{ id: "margin_impact", title: "Влияние подряда", purpose: "п", columns: ["А"], rows: [["подряд"]] }], "subcontract_plan"),
    ]);

    for (const агент of агенты) {
      expect(агент.sheets).toHaveLength(1);
      expect(агент.sheets[0]!.rows).toHaveLength(1);
    }
  });
});
