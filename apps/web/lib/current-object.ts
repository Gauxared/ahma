/**
 * Выбранный объект: чтение с проверкой по базе.
 *
 * COOKIE ХРАНИТ ВЫБОР, А НЕ ПОДТВЕРЖДАЕТ ЕГО
 *
 * Значение приходит от браузера. Объект по этому шифру мог быть удалён,
 * переименован или вовсе принадлежать другому арендатору — и если поверить
 * cookie на слово, рельс начнёт предлагать ссылки на чужой или несуществующий
 * объект. Поэтому шифр здесь сверяется с базой ПОД АРЕНДАТОРОМ: RLS отвечает на
 * вопрос «есть ли такой объект у этого клиента» так же, как на все остальные.
 *
 * ЧТО ВОЗВРАЩАЕТСЯ, КОГДА ВЫБОРА НЕТ
 *
 * `chosen: undefined` — и это НЕ ошибка: пользователь, только что вошедший,
 * объект ещё не выбирал. Рельс в этом состоянии показывает объектные разделы
 * не ссылками, а текстом с поводом «объект не выбран» — то же правило, что для
 * неготовых разделов, и по той же причине: ссылка, ведущая в никуда, хуже
 * отсутствия ссылки.
 *
 * ПОЧЕМУ ПЕРЕЧЕНЬ ВСЕХ ОБЪЕКТОВ ТОЖЕ ЗДЕСЬ
 *
 * Переключателю в шапке нужен список, и брать его отдельным запросом из
 * оболочки значило бы два обращения к базе на каждый экран вместо одного.
 */
import { createPrismaClient, withTenant } from "@platform/db/prisma";

export interface ObjectChoice {
  readonly code: string;
  readonly name: string;
}

export interface CurrentObject {
  /** Выбранный объект, если он есть у этого арендатора. */
  readonly chosen: ObjectChoice | undefined;
  /** Все объекты арендатора — для переключателя. */
  readonly all: readonly ObjectChoice[];
}

/**
 * Потолок перечня в переключателе.
 *
 * У АПРИ объектов единицы, но у клиента с портфелем их будут десятки, и
 * `<select>` на триста строк — это не переключатель. Когда потолок начнёт
 * задевать, переключатель заменится поиском; до тех пор честнее показать
 * первые пятьдесят, чем притворяться, что список полон.
 */
const LIMIT = 50;

/**
 * @param onScreen шифр объекта, экран которого открыт, если экран объектный.
 *
 * АДРЕС — ТОЖЕ ВЫБОР, И БОЛЕЕ СВЕЖИЙ, ЧЕМ COOKIE.
 *
 * Пройдено руками: клиент открывает объект из реестра, попадает на его
 * загрузку — а рельс слева при этом мёртв, и в шапке написано «объект не
 * выбран». То есть человек СТОИТ на объекте, а система утверждает, что объекта
 * нет. Чтобы рельс ожил, надо было отдельно выбрать в шапке то, что уже открыто
 * на экране.
 *
 * Экран объекта знает, про какой он объект, — это факт, а не догадка по адресу.
 * Cookie при этом остаётся: она отвечает на другой вопрос — «куда вести с
 * НЕобъектных экранов» (Пульт, Журнал, Доступ), где спрашивать не у чего.
 */
export async function readCurrentObject(
  tenantId: string,
  cookieValue: string | undefined,
  onScreen?: string,
): Promise<CurrentObject> {
  const db = createPrismaClient(process.env["DATABASE_URL"]);

  try {
    const all = await withTenant(db, tenantId, (tx) =>
      tx.projectObject.findMany({ orderBy: { code: "asc" }, take: LIMIT, select: { code: true, name: true } }),
    );

    // Открытый экран главнее сохранённого выбора: cookie может указывать на
    // объект, с которого человек уже ушёл.
    const wanted = (onScreen ?? cookieValue ?? "").trim();
    // Сверка со СПИСКОМ, уже прочитанным под арендатором: второй запрос по
    // шифру дал бы то же и стоил бы ещё одного обращения. Заодно закрыт случай
    // «в адресе шифр чужого арендатора»: такого объекта в списке нет.
    const chosen = wanted === "" ? undefined : all.find((object) => object.code === wanted);

    return { chosen, all };
  } finally {
    await db.$disconnect();
  }
}
