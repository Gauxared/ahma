/**
 * Свежий прогон объекта — одна реализация на всех, кто про него спрашивает.
 *
 * Спрашивают уже двое: перенаправление `/objects/[code]/checks/latest` и доска
 * агентов, которая по умолчанию показывает последний прогон. Второй запрос того
 * же разошёлся бы с первым при первой правке — например, один считал бы
 * свежесть по созданию записи, другой по началу исполнения, и «последний
 * прогон» на двух экранах оказался бы разным.
 *
 * СВЕЖЕСТЬ СЧИТАЕТСЯ ПО НАЧАЛУ ИСПОЛНЕНИЯ, А НЕ ПО СОЗДАНИЮ ЗАПИСИ
 *
 * Проверка, которую поставили и отменили, не начавшись, «последней» быть не
 * должна: смотреть в ней нечего. Поэтому порядок — сначала по `startedAt`, и
 * только при равенстве по `createdAt`.
 *
 * И ЭТОГО НЕ ХВАТАЛО: `NULLS FIRST` ДЕЛАЛ РОВНО ОБРАТНОЕ
 *
 * В Postgres `ORDER BY x DESC` ставит `NULL` ПЕРВЫМИ. У не начинавшейся
 * Проверки `startedAt` пуст — значит она и оказывалась «свежайшей», то есть
 * правило работало наизнанку, а комментарий утверждал обратное. Поймано на
 * гейте Д2: доска агентов открывала застрявший в очереди прогон вместо
 * идущего и сообщала «высказалось 0 из 9» — про прогон, где работали агенты.
 *
 * Поэтому `nulls: "last"` явно, в обоих запросах. Порядок сортировки — не
 * подробность реализации, когда от него зависит, какой прогон человек видит.
 */
import { createPrismaClient, withTenant } from "@platform/db/prisma";

export async function latestCheckId(tenantId: string, objectCode: string): Promise<string | undefined> {
  const db = createPrismaClient(process.env["DATABASE_URL"]);

  try {
    const check = await withTenant(db, tenantId, (tx) =>
      tx.check.findFirst({
        where: { object: { code: objectCode } },
        orderBy: [{ startedAt: { sort: "desc", nulls: "last" } }, { createdAt: "desc" }],
        select: { id: true },
      }),
    );

    return check?.id;
  } finally {
    await db.$disconnect();
  }
}

/**
 * Прогон, который ИДЁТ ПРЯМО СЕЙЧАС.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ ПРОГОНА С АРТЕФАКТОМ. Артефакт появляется в конце, то есть
 * идущий прогон его не имеет по определению. Доска, выбиравшая «свежий с
 * артефактом», на двадцатой минуте нового прогона показывала ПРЕДЫДУЩИЙ — со
 * всеми его находками и датой недельной давности. Ошибка худшего вида: экран
 * выглядел полным и отвечал не на тот вопрос.
 *
 * Идущий прогон главнее завершённого именно поэтому: спрашивают про него.
 *
 * «ЖИВОЙ» — ЭТО СТАТУС ПЛЮС ЖИВАЯ ЗАДАЧА, А НЕ ОДИН СТАТУС
 *
 * Замерено на клиентском контуре: одиннадцать Проверок со статусом `queued`,
 * поставленных сквозными наборами в дни, когда воркера не было. Задач у них не
 * осталось, начаться они не могут никогда — а по статусу выглядят живыми. Доска,
 * выбиравшая их, показывала бы «прогон поставлен, ход ещё не начался» вечно.
 *
 * Поэтому условие — И статус, И задача в очереди либо в работе. Брошенный
 * прогон не идёт; он числится, и это разные вещи.
 */
export async function liveCheckId(
  tenantId: string,
  objectCode: string,
  /**
   * Только НАЧАВШИЙСЯ прогон, а не любой живой.
   *
   * Разница нашлась сквозным набором на клиентском контуре: там одиннадцать
   * Проверок, поставленных в дни без воркера, — задачи у них живые, начаться
   * они не могут, показать нечего. Доска, выбиравшая «любой живой», открывала
   * такую вместо прогона с результатами и сообщала «высказалось 0 из 9».
   *
   * Поэтому порядок у экранов такой: НАЧАВШИЙСЯ прогон (о нём и спрашивают,
   * пока он идёт) → свежий с артефактом (то, что сказали агенты) → просто
   * поставленный в очередь → просто последний. Стоящий в очереди попадает на
   * экран только тогда, когда показать больше нечего, — и экран честно говорит
   * «прогон поставлен, ход ещё не начался».
   */
  options: { readonly started?: boolean } = {},
): Promise<string | undefined> {
  const db = createPrismaClient(process.env["DATABASE_URL"]);

  try {
    const check = await withTenant(db, tenantId, (tx) =>
      tx.check.findFirst({
        where: {
          object: { code: objectCode },
          status: options.started === true
            ? { in: ["running", "awaiting_human"] }
            : { in: ["queued", "running", "awaiting_human"] },
          jobs: { some: { status: { in: ["queued", "running"] } } },
        },
        orderBy: [{ startedAt: { sort: "desc", nulls: "last" } }, { createdAt: "desc" }],
        select: { id: true },
      }),
    );

    return check?.id;
  } finally {
    await db.$disconnect();
  }
}

/**
 * Свежий прогон, У КОТОРОГО ЕСТЬ ЧТО ПОКАЗАТЬ.
 *
 * Доске агентов «последний прогон» не годится по умолчанию: последним часто
 * оказывается только что поставленный или пустой, и доска честно сообщала
 * «высказалось 0 из 9» — правда, из которой ничего не следует. Человек, открывая
 * агентов, имеет в виду «покажи, что они сказали».
 *
 * Отбор идёт по НАЛИЧИЮ АРТЕФАКТА обхода объекта, а не по наличию обзора внутри
 * него: обзор лежит в теле JSON, и фильтровать по нему в запросе нельзя. Это
 * приближение, и оно названо: прогон с артефактом, но без обзора, доска покажет
 * с оговоркой «собирать пока нечего», как это делает пакет.
 *
 * Возвращает `undefined`, только если у объекта нет ни одного прогона с
 * артефактом; вызывающий тогда берёт просто последний и говорит об этом.
 */
export async function latestCheckWithArtifact(
  tenantId: string,
  objectCode: string,
): Promise<string | undefined> {
  const db = createPrismaClient(process.env["DATABASE_URL"]);

  try {
    const artifact = await withTenant(db, tenantId, (tx) =>
      tx.artifact.findFirst({
        where: { operationId: "check-object", check: { object: { code: objectCode } } },
        orderBy: { producedAt: "desc" },
        select: { checkId: true },
      }),
    );

    return artifact?.checkId ?? undefined;
  } finally {
    await db.$disconnect();
  }
}
