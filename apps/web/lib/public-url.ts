/**
 * Внешний адрес запроса — для перенаправлений.
 *
 * ЗАЧЕМ
 *
 * `request.url` внутри контейнера — это АДРЕС, ПО КОТОРОМУ СЛУШАЕТ ПРОЦЕСС, а
 * не адрес, по которому к нему пришли: `http://0.0.0.0:3000/...`. Перенаправив
 * туда, мы отправляем браузер пользователя на несуществующий адрес.
 *
 * Найдено первым же входом в развёрнутый стек: `Location: http://0.0.0.0:3000/objects`.
 * На машине разработчика этого не видно — там процесс и слушает, и принимает по
 * одному адресу, поэтому ошибка проявляется ровно тогда, когда систему впервые
 * показывают.
 *
 * ЗАГОЛОВКАМ ДОВЕРЯЕМ ТОЛЬКО ДЛЯ АДРЕСА
 *
 * `Host` и `X-Forwarded-*` присылает клиент, и подделать их можно. Здесь они
 * определяют лишь то, КУДА вернуть браузер, — и подделавший перенаправит сам
 * себя. Ни одного решения о доступе на них не строится: арендатор берётся из
 * сессии, права — из точки политики.
 */

export function publicUrl(request: Request, path: string): URL {
  const forwardedHost = request.headers.get("x-forwarded-host");
  const host = forwardedHost ?? request.headers.get("host");

  if (host === null || host === "") {
    // Заголовка нет вовсе — остаётся адрес процесса. Это хуже, но честнее
    // выдуманного адреса.
    return new URL(path, request.url);
  }

  const forwardedProto = request.headers.get("x-forwarded-proto");
  const proto = forwardedProto ?? new URL(request.url).protocol.replace(":", "");

  return new URL(path, `${proto}://${host}`);
}
