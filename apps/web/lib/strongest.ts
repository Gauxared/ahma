/**
 * Три-пять сильных выводов — то, что показывают на встрече.
 *
 * ЗАЧЕМ ЭТО ОТДЕЛЬНЫЙ РАСЧЁТ
 *
 * Условие задачи дословно: «не нужно выдавать клиенту 100 выводов, нужны 3–5
 * сильных результатов». На курганском объекте система даёт 167 замечаний, из
 * них 20 критичных. Ни 167, ни 20 на встрече не читают.
 *
 * Отбор по важности этого не решает: «критично» — свойство замечания, а не
 * место в разговоре. Двадцать блокеров подряд — такой же список, как сто
 * шестьдесят семь, только короче.
 *
 * ПРАВИЛО ОТБОРА ВИДНО НА ЭКРАНЕ, И ЭТО ЧАСТЬ ТРЕБОВАНИЯ
 *
 * Перечень «самое важное», собранный неизвестно как, — это мнение системы, за
 * которое нельзя спросить. Поэтому правило объявлено здесь целиком, показано
 * рядом с перечнем и проверено гейтом.
 *
 * ЧЕГО ЭТОТ РАСЧЁТ НЕ ДЕЛАЕТ
 *
 * Не оценивает деньги под риском. `impact` у замечания — это стоимость ПОЗИЦИИ,
 * на которую агент сослался, а не потери: пять агентов об одной дорогой строке
 * несут одну и ту же сумму, а сумма всех величин по курганскому объекту — 509
 * млн ₽ против сметных 105 млн. Упорядочивать по ней можно, называть риском
 * нельзя, складывать нельзя.
 */
import type { ReviewFindingView } from "./check-read-model.js";

/** Сколько показываем. Верх — из условия задачи, а не из вкуса. */
export const STRONGEST_MAX = 5;

/**
 * Вес важности. Порядок тот же, что в шкале интерфейса; здесь он числом,
 * потому что сравнивать надо, а не показывать.
 */
const WEIGHT: Readonly<Record<string, number>> = {
  critical: 5,
  high: 4,
  medium: 3,
  low: 2,
  info: 1,
};

export interface Strongest {
  readonly finding: ReviewFindingView;
  /** Кто это сказал — именем, а не способностью. */
  readonly person: string;
  readonly capability: string;
}

/** Замечание с автором — вход отбора. */
export interface Candidate {
  readonly finding: ReviewFindingView;
  readonly person: string;
  readonly capability: string;
}

/**
 * Ключ позиции: ОТПЕЧАТОК ФАЙЛА, лист и строка.
 *
 * По нему отсекаются повторы. Без него пятёрка на курганском объекте
 * оказывается пятью мнениями об одной строке: несколько агентов ссылаются на
 * позицию 61 с суммой 21 383 323,11 ₽, и все поднимаются наверх вместе.
 *
 * ОТПЕЧАТОК, А НЕ ИМЯ ДОКУМЕНТА. Первая версия брала `finding.document` — и
 * правило не срабатывало ровно там, где нужнее всего: у объектных агентов это
 * поле ПУСТО (их предмет — объект, а не файл), и «#ЛСР#240» не совпадало с
 * «РИМ Курган_СОТВ_….xlsx#ЛСР#240». На экране это выглядело так: замечание
 * Виктора и замечание Людмилы об одной строке 240 стояли первым и вторым
 * пунктами перечня, который обещает пять РАЗНЫХ находок.
 *
 * Отпечаток называет файл однозначно и есть у обоих: его кладёт оболочка
 * агента вместе с координатой.
 */
function positionOf(finding: ReviewFindingView): string | null {
  const source = finding.source;
  if (source === null || source.row === null) return null;

  return `${source.contentHash ?? finding.document}#${source.sheet ?? ""}#${source.row}`;
}

/**
 * Отбор.
 *
 * 1. **Только с координатой.** Вывод, который нельзя показать в исходном файле,
 *    на встрече не работает: первое, что спросят, — «откуда». Замечание без
 *    координаты остаётся законным и читается на экране агента, но в пятёрку не
 *    идёт.
 * 2. **Сначала важность.** Блокер выше примечания при любой сумме.
 * 3. **Внутри важности — сумма позиции**, к которой относится замечание.
 * 4. **Одна позиция — одна находка.** Второе мнение о той же строке место в
 *    перечне не занимает.
 * 5. **Один автор — не больше двух находок.** Иначе разговор превращается в
 *    доклад одного агента, а ценность кросс-валидации в том, что видно
 *    нескольких.
 */
export function strongest(candidates: readonly Candidate[], limit = STRONGEST_MAX): readonly Strongest[] {
  const ranked = [...candidates]
    .filter((item) => positionOf(item.finding) !== null)
    .sort((left, right) => {
      const weight = (WEIGHT[right.finding.severity] ?? 0) - (WEIGHT[left.finding.severity] ?? 0);
      if (weight !== 0) return weight;

      // ноль-осознанно: КЛЮЧ СОРТИРОВКИ, а не значение. Находка без суммы
      // должна уходить в конец списка — именно это ноль здесь и делает;
      // в саму находку он не попадает и на экран не выводится.
      const amount = (right.finding.amount?.value ?? 0) - (left.finding.amount?.value ?? 0);
      if (amount !== 0) return amount;

      // Порядок при полном равенстве — по автору и тексту, а не «как пришло».
      // Перечень, меняющийся от прогона к прогону при тех же данных, нельзя
      // ни сравнить с предыдущим, ни переслать.
      return (
        left.capability.localeCompare(right.capability, "ru") ||
        left.finding.statement.localeCompare(right.finding.statement, "ru")
      );
    });

  const chosen: Strongest[] = [];
  const positions = new Set<string>();
  const perAuthor = new Map<string, number>();

  for (const item of ranked) {
    if (chosen.length >= limit) break;

    const position = positionOf(item.finding);
    if (position === null || positions.has(position)) continue;

    const already = perAuthor.get(item.capability) ?? 0;
    if (already >= 2) continue;

    positions.add(position);
    perAuthor.set(item.capability, already + 1);
    chosen.push(item);
  }

  return chosen;
}

/** Правило словами — показывается рядом с перечнем, а не прячется в код. */
