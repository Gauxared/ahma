/**
 * ИТОГ ЗАГРУЗКИ В АДРЕСЕ — против 502 при уже сохранённых файлах.
 *
 * НАЙДЕНО НА КЕЙСЕ ЗАКАЗЧИКА, а не набором.
 *
 * Загрузка комплекта «Новотэкс ЭС и ПС» — 53 файла, 62 МБ — вернула
 * **502 Bad Gateway**. В журнале nginx:
 *
 *   upstream sent too big header while reading response header from upstream
 *
 * Причина не в размере тела (`client_max_body_size 512m`) и не в таймауте
 * (`proxy_read_timeout 300s`, отказ на 77-й секунде). Перечень отклонённых
 * файлов уезжал в параметры адреса перенаправления, а русское имя файла в
 * процентной кодировке занимает по шесть байт на букву. Заголовок `Location`
 * перестал влезать в буфер nginx.
 *
 * ХУЖЕ САМОГО ОТКАЗА ТО, ЧТО ФАЙЛЫ СОХРАНИЛИСЬ. Обработчик доработал до конца,
 * партия легла на диск — и клиент получил 502, не узнав ни номера партии, ни
 * того, что загрузка вообще удалась. Молчаливый успех, выглядящий отказом:
 * человек грузит заново и получает вторую копию комплекта.
 *
 * ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ — что адрес ОГРАНИЧЕН по длине и что при этом не теряет
 * ответа на два разных вопроса: «что именно не взяли» (имена) и «сколько всего»
 * (число). Второе легко потерять, обрезав первое.
 */
import { describe, expect, it } from "vitest";

import { REJECTED_IN_URL, итогЗагрузкиВАдрес } from "./uploads.js";

/** Отклонённый файл с настоящим русским именем и настоящей причиной. */
function отклонён(n: number) {
  return {
    name: `ПЭС-2025-ЭМ ред.${n} Силовое электрооборудование и электроосвещение.pdf`,
    reason: "система не умеет читать .rtf: принимаются .xlsx, .xls, .pdf, .docx, .xml, .csv, .txt и архив .zip",
  };
}

function адрес(отклонённых: number): URL {
  const url = new URL("https://app.example.test/objects/BM-NVT/upload");

  итогЗагрузкиВАдрес(url, {
    batch: "2026-09-07T11-15-44-290Z",
    accepted: Array.from({ length: 49 }, (_, i) => i),
    rejected: Array.from({ length: отклонённых }, (_, i) => отклонён(i + 1)),
  });

  return url;
}

describe("итог загрузки в адресе", () => {
  it("на пятидесяти трёх файлах адрес остаётся В ПРЕДЕЛАХ буфера nginx", () => {
    /**
     * Умолчание `proxy_buffer_size` — 4 КБ, и в него должен уместиться ВЕСЬ
     * заголовок ответа, не только `Location`. Берём вдвое меньший запас: 2 КБ
     * на адрес оставляют место остальным заголовкам.
     */
    const длина = адрес(20).toString().length;

    expect(длина, `адрес ${длина} байт — заголовок не влезет в буфер, nginx ответит 502`).toBeLessThan(
      2048,
    );
  });

  it("РАЗМЕР ПОТЕРИ назван всегда, как бы ни урезали перечень", () => {
    /**
     * Инвариант здесь — не дословная фраза, а то, что «сколько не взяли»
     * доходит при любом урезании. Обрезать перечень и не сказать числа значило
     * бы соврать о размере потери: человек увидит три имени и решит, что не
     * взяли три.
     *
     * При двадцати файлах с длинными русскими именами перечень в бюджет не
     * влезает, и остаётся причина с числом — этого достаточно.
     */
    const url = адрес(20);

    expect(url.searchParams.get("не-взято"), "число отклонённых не передано").toBe("20");
    expect(url.searchParams.get("отклонено"), "в тексте не назван размер потери").toContain("20 шт.");
  });

  it("короткие имена ВЛЕЗАЮТ, и тогда файлы названы поимённо", () => {
    // Урезание — это запас на худший случай, а не поведение по умолчанию:
    // назвать файл поимённо полезнее, чем сказать «их было три».
    const url = new URL("https://app.example.test/objects/BM/upload");

    итогЗагрузкиВАдрес(url, {
      batch: "п",
      accepted: [1],
      rejected: [
        { name: "а.rtf", reason: "не читаем .rtf" },
        { name: "б.rtf", reason: "не читаем .rtf" },
        { name: "в.rtf", reason: "не читаем .rtf" },
        { name: "г.rtf", reason: "не читаем .rtf" },
      ],
    });

    const текст = url.searchParams.get("отклонено") ?? "";
    expect(текст).toContain("а.rtf");
    expect(текст, "остаток не назван").toContain(`и ещё ${4 - REJECTED_IN_URL}`);
    expect(текст.split("не читаем .rtf").length - 1, "причина повторена у каждого файла").toBe(1);
  });

  it("число отклонённых передаётся ВСЕГДА, даже когда все уместились", () => {
    // Иначе экран пересчитывает строки перечня — и ошибается, как только в
    // имени файла окажется разделитель.
    const url = адрес(2);

    expect(url.searchParams.get("не-взято")).toBe("2");
    expect(url.searchParams.get("отклонено"), "лишнее «и ещё 0»").not.toContain("и ещё");
  });

  it("партия и число принятых НЕ теряются из-за обрезки перечня", () => {
    /**
     * Главное в этом ответе — номер партии: без него прогон не запустить, и
     * загрузка становится бесполезной. Он обязан дойти при любом числе
     * отклонённых.
     */
    for (const сколько of [0, 3, 53, 300]) {
      const url = адрес(сколько);

      expect(url.searchParams.get("партия"), `партия потеряна при ${сколько} отклонённых`).toBe(
        "2026-09-07T11-15-44-290Z",
      );
      expect(url.searchParams.get("принято")).toBe("49");
    }
  });

  it("без отклонённых лишних параметров нет", () => {
    const url = адрес(0);

    expect(url.searchParams.get("отклонено")).toBeNull();
    expect(url.searchParams.get("не-взято")).toBeNull();
  });
});
