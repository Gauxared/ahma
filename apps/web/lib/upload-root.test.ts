/**
 * Корень хранения документов — против настройки, которая ничего не настраивает.
 *
 * НАЙДЕНО НА СЕРВЕРЕ, а не набором.
 *
 * `.env` объявлял `STROYINTELLECT_OBJECTS_PATH=/srv/stroyintellekt/objects`, а
 * документы заказчика ложились в `/opt/stroyintellekt/var/objects` — то есть
 * ВНУТРЬ каталога с кодом. Код читал третье имя, `SI_UPLOAD_ROOT`, которого не
 * было ни в одном файле окружения.
 *
 * Три имени одного, из которых работало то, что никто не задавал.
 *
 * Правило развёртывания требует обратного: документы монтируются и в поставку
 * не входят (ТЗ §11) — образ уезжает в реестр, а сметы заказчика там не место.
 *
 * Но хуже самого пути было ОБЕЩАНИЕ. Настройка, которую можно задать и которая
 * ни на что не влияет, — это ложь конфигурации: она выглядит работающей,
 * проверяется только развёртыванием и обнаруживается позже всего.
 */
import { afterEach, describe, expect, it } from "vitest";

import { uploadRoot } from "./uploads.js";

const ИМЯ = "STROYINTELLECT_OBJECTS_PATH";
const БЫЛО = process.env[ИМЯ];

afterEach(() => {
  if (БЫЛО === undefined) delete process.env[ИМЯ];
  else process.env[ИМЯ] = БЫЛО;
});

describe("корень хранения документов", () => {
  it("переменная окружения ДЕЙСТВУЕТ, а не только объявлена", () => {
    process.env[ИМЯ] = "/srv/stroyintellekt/objects";
    expect(uploadRoot()).toBe("/srv/stroyintellekt/objects");
  });

  it("без переменной остаётся умолчание рядом с приложением", () => {
    // Умолчание нужно локальной разработке: там монтировать нечего.
    delete process.env[ИМЯ];
    expect(uploadRoot().endsWith("var/objects")).toBe(true);
  });

  it("пустая строка — это НЕ заданный путь, а не корень файловой системы", () => {
    // `resolve("")` даёт текущий каталог, и документы заказчика легли бы куда
    // придётся. Пустое значение читается как «не задано».
    process.env[ИМЯ] = "   ";
    expect(uploadRoot().endsWith("var/objects")).toBe(true);
  });

  it("путь приводится к абсолютному", () => {
    // Относительный путь зависит от того, откуда запущен процесс: у systemd
    // рабочий каталог свой, и «./objects» указал бы в разные места у веба и
    // воркера — то есть загрузка и обход разошлись бы по разным папкам.
    process.env[ИМЯ] = "объекты";
    expect(uploadRoot().startsWith("/")).toBe(true);
  });
});
