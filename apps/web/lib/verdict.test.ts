/**
 * Вердикт агента: светофор — состояние, а не типографика.
 *
 * ЧТО ЗДЕСЬ ЗАЩИЩАЕТСЯ
 *
 * Модель ставит `🔴`, `🟡` или `🟢` в начало вердикта. Это единственное во всём
 * ответе агента, что читается не читая, и интерфейс это выбрасывал: знак
 * оставался внутри абзаца, где он ничем не отличается от прочей типографики.
 *
 * Два свойства, и оба легко потерять молча:
 *
 *  · знак снимается ТОЛЬКО с начала. Тот же знак встречается в середине фразы,
 *    и вынести его оттуда в состояние значит выдать оговорку внутри
 *    предложения за итог по смете;
 *  · отсутствие знака — ОТДЕЛЬНОЕ состояние, а не «зелёный по умолчанию».
 *    Из четырёх вердиктов сметчика по курганскому объекту знак есть у трёх.
 */
import { describe, expect, it } from "vitest";

import { verdictText, viewVerdict } from "./check-read-model.js";

describe("вердикт агента", () => {
  it("снимает светофор с начала и делает его состоянием", () => {
    expect(viewVerdict("ЛСР-1.xlsx", "🔴 принять только после расшифровки позиции.")).toEqual({
      subject: "ЛСР-1.xlsx",
      light: "красный",
      text: "принять только после расшифровки позиции.",
    });
  });

  it("различает жёлтый и зелёный", () => {
    expect(viewVerdict("", "🟡 принимаем с условием")?.light).toBe("жёлтый");
    expect(viewVerdict("", "🟢 принято")?.light).toBe("зелёный");
  });

  it("вердикт без знака не считается зелёным", () => {
    // Досчитать класс за агента было бы удобно и неверно: «критичных нет» и
    // «сметчик принял» — разные утверждения, и второе имеет право сказать
    // только сметчик.
    const разобрано = viewVerdict("ЛСР-1.xlsx", "Смета арифметически сходится: итог 14198884.54 ₽.");

    expect(разобрано?.light).toBeNull();
    expect(разобрано?.text).toBe("Смета арифметически сходится: итог 14198884.54 ₽.");
  });

  it("знак в середине фразы остаётся частью фразы", () => {
    const разобрано = viewVerdict("", "Принимать нельзя: риск 🔴 по срокам поставки.");

    expect(разобрано?.light).toBeNull();
    expect(разобрано?.text).toBe("Принимать нельзя: риск 🔴 по срокам поставки.");
  });

  it("пустой вердикт не становится вердиктом без текста", () => {
    // Иначе экран показал бы карточку «класс не объявлен» с пустым телом —
    // утверждение о том, что агент высказался, там где он промолчал.
    expect(viewVerdict("ЛСР-1.xlsx", "   ")).toBeUndefined();
  });

  it("суммы в вердикте не трогаются: разрядка — дело показа, не разбора", () => {
    // Выгрузки получают текст ровно таким, каким его написал агент: документ
    // заказчику не место для наших типографских правок.
    expect(viewVerdict("", "🟡 итог 14198884.54 ₽")?.text).toBe("итог 14198884.54 ₽");
  });

  it("склейка для выгрузок выводится из разложенного, а не наоборот", () => {
    const вердикты = [
      viewVerdict("ЛСР-1.xlsx", "🔴 не принимать"),
      viewVerdict("ЛСР-2.xlsx", "🟡 с условием"),
    ].filter((verdict) => verdict !== undefined);

    expect(verdictText(вердикты)).toBe("не принимать; с условием");
    // И обратно уже не восстановишь — именно поэтому склейка последняя, а не
    // первая: из строки «не принимать; с условием» связь с ЛСР-1 и ЛСР-2 не
    // выводится никак.
    expect(verdictText([])).toBe("");
  });
});
