"use server";

/**
 * Выбранный объект — серверная настройка, как свёрнутость рельса.
 *
 * ЗАЧЕМ ОН ПОНАДОБИЛСЯ
 *
 * Пять пунктов рельса из девяти вели на один и тот же адрес `/objects`, и
 * причина была не в небрежности: карточка объекта, загрузка, сравнение КП и
 * рабочий экран — ОБЪЕКТНЫЕ, у них нет статического адреса. Рельс не знал, о
 * каком объекте речь, и честного адреса дать не мог.
 *
 * В прототипе «Десктоп» этой проблемы нет, потому что там рельс объектный:
 * сверху стоит переключатель («ОСК Йошкар-Ола / Дом 8 Космонавтов»), а разделы
 * относятся к выбранному объекту. Здесь сделано то же.
 *
 * ПОЧЕМУ COOKIE, А НЕ АДРЕС
 *
 * Выбор объекта переживает переход между разделами и перезагрузку: человек
 * работает по одной стройке часами. Держать его в адресе значило бы тащить
 * шифр в каждую ссылку рельса и терять его при первом переходе на общий экран
 * (журнал, поиск). `Ф-ADR-010` разрешает серверную настройку ровно для такого.
 *
 * ЧЕМУ ЗДЕСЬ НЕЛЬЗЯ ВЕРИТЬ
 *
 * Значению cookie. Оно приходит от браузера, то есть извне: объект по этому
 * шифру мог быть удалён, переименован или принадлежать другому арендатору.
 * Поэтому cookie только ХРАНИТ выбор, а проверяет его чтение — `readChosenObject`
 * в `apps/web/lib/current-object.ts`, и проверяет по базе под арендатором.
 */
import { revalidatePath } from "next/cache";
import { cookies } from "next/headers";
import { redirect } from "next/navigation";

import { OBJECT_COOKIE } from "./object-cookie.js";

export async function chooseObject(form: FormData): Promise<void> {
  const code = String(form.get("объект") ?? "").trim();
  const jar = await cookies();

  // Пустое значение — это «снять выбор», а не «выбрать пустое». Без этой
  // ветки кнопка сброса записала бы шифр из пустой строки, и чтение искало бы
  // объект с пустым шифром — то есть всегда не находило бы, но по другой
  // причине, чем «не выбран».
  if (code === "") {
    jar.delete(OBJECT_COOKIE);
  } else {
    jar.set(OBJECT_COOKIE, code, {
      httpOnly: true,
      sameSite: "lax",
      path: "/",
      maxAge: 60 * 60 * 24 * 365,
    });
  }

  // Раскладка целиком: рельс есть на каждом экране, и счётчики зависят от
  // выбранного объекта.
  revalidatePath("/", "layout");

  /**
   * ВЫБОР ОБЪЕКТА ТЕПЕРЬ ВЕДЁТ НА ОБЪЕКТ.
   *
   * Пока виды объекта стояли пунктами рельса, переключателю было достаточно
   * записать выбор: адреса в рельсе менялись сами. Виды переехали во вкладки
   * карточки — и переключатель остался жестом без последствий: человек выбирал
   * стройку, экран перерисовывался тем же, и выбор выглядел не сработавшим. Я
   * сам на этом обманулся однажды с `defaultValue`, и это тот же класс:
   * действие, чей результат нельзя увидеть, читается как поломка.
   *
   * Снятие выбора никуда не ведёт: уходить с текущего экрана незачем.
   */
  if (code !== "") redirect(`/objects/${encodeURIComponent(code)}`);
}
