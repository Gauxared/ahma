/**
 * Вкладки объекта — ОДИН перечень на шесть экранов.
 *
 * ЧТО ЭТО ИСПРАВЛЯЕТ
 *
 * Карточка объекта, документы, сравнение предложений, рабочий экран Проверки,
 * доска агентов и пакет стояли шестью пунктами рельса. Все шесть — виды ОДНОГО
 * объекта, то есть листья, показанные корнями. У Домовея в рельсе нет ни одной
 * карточки: `/tickets/<id>` объявлена в `crmDetailRoutes` с полем `parentHref`
 * и получает только крошку, а переключение между видами одной сущности идёт
 * вкладками-ссылками.
 *
 * ПОРЯДОК — ПОРЯДОК РАБОТЫ, А НЕ АЛФАВИТ
 *
 * Паспорт → Документы → Сравнение КП → Проверка → Агенты → Пакет. Это шесть
 * шагов тракта в том же порядке, в каком их проходят: выбрал объект, загрузил и
 * разобрал, сравнил предложения, прогнал конвейер, прочитал кто что сказал,
 * забрал пакет. Порядок в системе был и раньше (`config/workflows`), а в
 * интерфейсе его не было ни одного следа.
 *
 * ЗАГРУЗКИ СРЕДИ ВКЛАДОК НЕТ НАМЕРЕННО
 *
 * Загрузка — ДЕЙСТВИЕ над документами, а не седьмой вид объекта. У Домовея
 * «+ Новый сотрудник» стоит кнопкой справа сверху на списке сотрудников, а не
 * вкладкой рядом с ним. Поэтому `/objects/<шифр>/upload` открывается кнопкой с
 * вкладки «Документы» и подсвечивает её же: пользователь не уходит из раздела,
 * он в нём действует.
 */
import type { Tab } from "@web/src/ui/kit/tabs.js";

/** Чем вкладка опознаётся: экран объявляет ключ, а не переписывает адрес. */
export type ObjectTabKey = "паспорт" | "документы" | "предложения" | "проверка" | "агенты" | "пакет";

/**
 * Сколько чего у объекта — необязательно и по частям.
 *
 * Экран считает то, что и так читает для себя: карточка знает число документов,
 * доска агентов — число высказавшихся. Требовать все шесть чисел от каждого
 * экрана значило бы шесть лишних запросов на каждый переход.
 */
export type ObjectTabCounts = Partial<Record<ObjectTabKey, number>>;

interface TabDefinition {
  readonly key: ObjectTabKey;
  readonly label: string;
  readonly path: (code: string) => string;
}

const DEFINITIONS: readonly TabDefinition[] = [
  { key: "паспорт", label: "Паспорт", path: (code) => `/objects/${code}` },
  { key: "документы", label: "Документы", path: (code) => `/objects/${code}/documents` },
  { key: "предложения", label: "Сравнение КП", path: (code) => `/objects/${code}/offers` },
  /**
   * «Проверка» ведёт на `latest`, а не на конкретный прогон.
   *
   * Идентификатор прогона вкладка знать не может и не должна: она ведёт на
   * ПОСЛЕДНЮЮ Проверку, а перенаправление на её адрес делает маршрут
   * `checks/latest`. Так же поступает и «Пакет».
   */
  { key: "проверка", label: "Проверка", path: (code) => `/objects/${code}/checks/latest` },
  { key: "агенты", label: "Агенты", path: (code) => `/objects/${code}/agents` },
  { key: "пакет", label: "Пакет", path: (code) => `/objects/${code}/package` },
];

/** Адрес одной вкладки: экран объявляет ключ и получает адрес отсюда. */
export function objectTabHref(code: string, key: ObjectTabKey): string {
  const definition = DEFINITIONS.find((item) => item.key === key);

  // Ключи перечислены типом, и промах здесь означал бы расхождение между типом
  // и таблицей. Молчаливая пустая строка дала бы ссылку на текущий адрес — то
  // есть вкладку, которая никуда не ведёт и выглядит рабочей.
  if (definition === undefined) throw new Error(`вкладка объекта «${key}» не объявлена в таблице`);

  return definition.path(encodeURIComponent(code));
}

/** Все вкладки объекта: подписи, адреса и — где известны — счётчики. */
export function objectTabs(code: string, counts: ObjectTabCounts = {}): readonly Tab[] {
  return DEFINITIONS.map((definition) => {
    const count = counts[definition.key];
    const base = { label: definition.label, href: definition.path(encodeURIComponent(code)) };

    // «Нет счётчика» и «счётчик равен undefined» — разные утверждения при
    // `exactOptionalPropertyTypes`, и второе типом запрещено.
    return count === undefined ? base : { ...base, count };
  });
}
