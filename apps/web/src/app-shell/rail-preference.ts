"use server";

/**
 * Свёрнутость рельса — серверное действие, а не обработчик формы.
 *
 * ПОЧЕМУ НЕ МАРШРУТ С РЕДИРЕКТОМ
 *
 * Первая версия была обычным `POST /api/rail`, который ставил cookie и отвечал
 * 303 на тот же адрес. Логика работала — сервер, получив cookie, отдавал
 * свёрнутый рельс, — но БРАУЗЕР ПОКАЗЫВАЛ ПРЕДЫДУЩИЙ ДОКУМЕНТ: переход на тот же
 * адрес после редиректа брался из кэша, и состояние отставало на одно нажатие.
 *
 * Замерено, а не предположено: `fetch('/objects')` сразу после записи cookie
 * возвращал разметку с новым состоянием, тогда как страница на экране оставалась
 * прежней. То есть виноват был не расчёт состояния, а показ.
 *
 * Серверное действие для этого и существует: оно пишет cookie и объявляет
 * раскладку устаревшей, после чего Next перерисовывает её сам. Клиентского кода
 * это не добавляет — обработчик остаётся на сервере.
 *
 * `Ф-ADR-010` соблюдён: настройка живёт в cookie, переживает перезагрузку и
 * одинакова на всех экранах.
 */
import { revalidatePath } from "next/cache";
import { cookies } from "next/headers";

import { RAIL_COOKIE, RAIL_NARROW, RAIL_WIDE } from "./rail-cookie.js";

export async function toggleRail(form: FormData): Promise<void> {
  const collapsed = String(form.get("свернуть") ?? "") === "да";
  const jar = await cookies();

  jar.set(RAIL_COOKIE, collapsed ? RAIL_NARROW : RAIL_WIDE, {
    httpOnly: true,
    sameSite: "lax",
    path: "/",
    maxAge: 60 * 60 * 24 * 365,
  });

  // Раскладка целиком: рельс есть на каждом экране, и устаревает он на каждом.
  revalidatePath("/", "layout");
}
