/**
 * Группы для рельса: рабочее сверху, неготовое — одной группой внизу.
 *
 * ЗАЧЕМ ЭТО ОТДЕЛЬНО ОТ `GROUPS`
 *
 * `GROUPS` — предметная карта: девять групп по областям, и в каждой рядом с
 * работающим разделом стоял неготовый с меткой «вне договора». Метки повторялись
 * двадцать раз и перекрикивали то, что открывается: рельс сообщал в основном о
 * том, чего нет.
 *
 * В Pulse рельс перечисляет ТОЛЬКО РАБОТАЮЩЕЕ, и это правильно: навигация
 * отвечает на «куда пойти», а не «что задумано». Поэтому здесь рабочие разделы
 * остаются по областям, а всё неготовое собрано в одну группу «В разработке» —
 * серым, без меток, с поводом в подсказке. Полная картина с поводами живёт на
 * карте поверхностей, где под каждый отведена строка.
 *
 * Предметная карта при этом не потеряна: оглавление по-прежнему строится по
 * `GROUPS`, и E2E сверяет, что рельс — её подмножество.
 */
export const RAIL_GROUPS: readonly SectionGroup[] = (() => {
  // Порядок подписей задан явно и не выводится из порядка предметных областей:
  // «Работа» обязана стоять первой, а какая область даст в неё пункт — вопрос
  // второй. Раздел, не назвавший `railGroup`, попадает под подпись своей
  // предметной области — так ведут себя будущие разделы, пока их не разложили.
  const order: string[] = [WORK_GROUP, ADMIN_GROUP];
  const ready = new Map<string, Section[]>();
  const pending: Section[] = [];
  let service: SectionGroup | undefined;

  for (const group of GROUPS) {
    // ВИДЫ ОБЪЕКТА В РЕЛЬС НЕ ПОПАДАЮТ ВОВСЕ — они вкладки его карточки.
    // Это не сокрытие: `detailOf` называет раздел, изнутри которого вид
    // открывается, а карта поверхностей показывает все шесть с их статусом.
    const own = group.sections.filter((section) => section.detailOf === undefined);
    const open = own.filter((section) => isOpen(section));

    pending.push(...own.filter((section) => !isOpen(section)));

    if (group.title === SERVICE_GROUP) {
      // Служебная группа собирается отдельно, чтобы встать ПОСЛЕ «В разработке»:
      // о самой системе читают последним, а не первым.
      if (open.length > 0) service = { title: group.title, sections: open };
      continue;
    }

    for (const section of open) {
      const title = section.railGroup ?? group.title;
      const bucket = ready.get(title);

      if (bucket === undefined) {
        ready.set(title, [section]);
        if (!order.includes(title)) order.push(title);
      } else {
        bucket.push(section);
      }
    }
  }

  return [
    ...order.flatMap((title) => {
      const sections = ready.get(title);
      return sections === undefined ? [] : [{ title, sections }];
    }),
    ...(pending.length === 0 ? [] : [{ title: "В разработке", sections: pending }]),
    ...(service === undefined ? [] : [service]),
  ];
})();

/**
 * Раздел открывается — одно правило на все три места, где его спрашивают.
 *
 * До появления объектных разделов правило было тождественно `kind === "готов"`,
 * и его переписывали в рельсе, в оглавлении и в сборке групп. С двумя видами
 * открываемости три копии разошлись бы немедленно: объектный раздел уехал бы в
 * «В разработке» на рельсе и остался бы «открывается» в оглавлении.
 */
export function isOpen(section: Section): boolean {
  return section.state.kind === "готов" || section.state.kind === "объектный";
}

/**
 * Адрес раздела при выбранном объекте.
 *
 * `undefined` означает «ссылкой быть не может»: либо раздел неготов, либо он
 * объектный, а объект не выбран. Вызывающий обязан в этом случае показать текст
 * с поводом, а не ссылку — ссылка, ведущая не туда, куда обещает, хуже
 * отсутствия ссылки.
 */
export function hrefOf(section: Section, objectCode: string | undefined): string | undefined {
  if (section.state.kind === "готов") return section.state.href;
  if (section.state.kind === "объектный" && objectCode !== undefined) return section.state.href(objectCode);
  return undefined;
}

/** Все разделы одним списком: для проверок и для оглавления. */
export const SECTIONS: readonly Section[] = GROUPS.flatMap((group) => group.sections);

/** Чем раздел опознаётся в рельсе: поверхность карты либо собственный ключ. */
export function keyOf(section: Section): string | undefined {
  return section.key ?? section.surface;
}

/**
 * Группа, в которой лежит раздел: нужна шапке для надзаголовка.
 *
 * Отвечает подписью РЕЛЬСА, а не предметной областью. У Домовея надзаголовок
 * равен подписи группы бокового меню (`resolveCrmRouteMeta` берёт
 * `sectionLabel` из навигации), и это не формальность: человек только что
 * нажал пункт под подписью «Работа» — увидеть над заголовком «Обзор» значит
 * усомниться, туда ли он попал.
 */
export function groupOf(active: string): SectionGroup | undefined {
  const group = GROUPS.find((item) => item.sections.some((section) => keyOf(section) === active));

  if (group === undefined) return undefined;

  const section = group.sections.find((item) => keyOf(item) === active);
  // ДЕТАЛЬ НАСЛЕДУЕТ ПОДПИСЬ У СВОЕГО РАЗДЕЛА. У Домовея надзаголовок карточки
  // заявки равен подписи группы, в которой стоит «Заявки», а не собственной:
  // карточка в меню не стоит вовсе, и называть её область отдельно значило бы
  // сослаться на подпись, которой в рельсе нет.
  const owner = section?.detailOf === undefined ? section : parentOf(section.detailOf);
  const title = owner?.railGroup ?? group.title;

  return title === group.title ? group : { title, sections: group.sections };
}

/**
 * Раздел, изнутри которого открывается деталь.
 *
 * Ищется по подписи, а не по ключу: `detailOf` называет раздел так, как он
 * подписан в рельсе («Реестр»), и это то же имя, которое человек только что
 * нажал. Промах молча возвращает `undefined` — надзаголовок тогда берётся из
 * предметной области, то есть хуже, но не неверно.
 */
function parentOf(label: string): Section | undefined {
  return SECTIONS.find((section) => section.label === label);
}

/**
 * Адрес раздела, изнутри которого открывается деталь.
 *
 * Нужен пути в шапке: у детали обязана быть обратная ссылка на список, иначе
 * выйти из карточки объекта можно только мимо реестра. Литерал `/objects` в
 * каркасе разошёлся бы с перечнем при первом переименовании адреса.
 */
export function parentHrefOf(section: Section): string | undefined {
  if (section.detailOf === undefined) return undefined;

  const parent = parentOf(section.detailOf);

  return parent === undefined ? undefined : hrefOf(parent, undefined);
}

export function sectionOf(active: string): Section | undefined {
  return SECTIONS.find((section) => keyOf(section) === active);
}

/**
 * Тон метки состояния.
 *
 * ЦВЕТ НЕ РАЗЛИЧАЕТ ВИДЫ НЕГОТОВНОСТИ — РАЗЛИЧАЕТ СЛОВО
 *
 * Первая версия давала «нет входов» тревожный тон, и на рельсе появлялось
 * восемь тревожных пятен: отсутствие сущности в модели данных — положение дел, а
 * не происшествие. Выделен только `строится`: единственное состояние, которое
 * изменится само.
 *
 * Функция одна на рельс и на оглавление намеренно. Одно и то же слово в двух
 * цветах читается как два разных состояния.
 */
export function stateTone(state: SectionState): "ok" | "info" | "plain" {
  switch (state.kind) {
    case "готов":
    // Объектный раздел работает — просто требует выбранного объекта. Тон тот
    // же, что у готового: неготовым он не является ни одной своей частью.
    case "объектный":
      return "ok";
    case "строится":
      return "info";
    default:
      return "plain";
  }
}

/**
 * Подпись состояния — одна на рельс и на оглавление.
 *
 * Сокращать её для рельса не пришлось: после укорачивания названий разделов
 * «вне договора» и «нет входов» умещаются рядом с названием при 240 px. Первая
 * попытка сократила их до «вне» и «нет данных» — и это было хуже цвета:
 * непонятное слово хуже понятного цвета, потому что его ещё и нельзя угадать.
 */
export function stateLabel(state: SectionState): string {
  switch (state.kind) {
    case "готов":
      return "готов";
    // Объектный раздел готов ровно так же — не хватает не системе, а выбора.
    // Компилятор поймал это сам: перечисление состояний закрытое, и новое
    // состояние нельзя добавить, забыв про подпись.
    case "объектный":
      return "по объекту";
    case "строится":
      return "строится";
    case "вне-договора":
      return "вне договора";
    case "нет-входов":
      return "нет входов";
  }
}
