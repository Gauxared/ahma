/**
 * Разделы приложения — ВИДИМАЯ ПРОЕКЦИЯ КАРТЫ ПОВЕРХНОСТЕЙ.
 *
 * ПОЧЕМУ ОДИН СПИСОК НА РЕЛЬС И НА ОГЛАВЛЕНИЕ
 *
 * До этого перечень готовых экранов жил литералами внутри главной страницы, а
 * навигации не было вовсе. Стоило появиться второму месту, где перечисляются
 * разделы, — и списки начали бы расходиться: рельс обещает то, чего нет в
 * оглавлении, оглавление знает про экран, которого нет в рельсе. Поэтому список
 * один, а рельс и оглавление — два его вида.
 *
 * ЧТО ЗДЕСЬ НЕ ХРАНИТСЯ
 *
 * Прав доступа нет. Пункт рельса не решает, можно ли смотреть: право проверяет
 * экран и отказывает отказом с названием недостающего права. Скрытый пункт
 * вместо отказа означал бы, что пользователь не может даже узнать о разделе.
 *
 * НАЗВАНИЯ КОРОТКИЕ, И ЭТО ТРЕБОВАНИЕ РАЗМЕТКИ
 *
 * Первая версия несла договорные формулировки целиком — «Смета против рынка»,
 * «Реестр исполнительной документации», «План-факт реализации». В рельсе 240 px
 * они ломались на две строки, и панель выглядела рваной. У прототипов заказчика
 * названия короткие («Пульт», «Финмодель», «Смета / ВОР», «Нормы») — и это не
 * небрежность, а то же ограничение, решённое до нас. Полная формулировка живёт
 * в карте поверхностей и в оглавлении, где под неё есть строка.
 */

/**
 * Состояние раздела.
 *
 * Три вида неготовности различаются, потому что различается ответ на вопрос
 * «когда будет»: `строится` — в этой вехе, `вне-договора` — по письменному
 * согласованию объёма, `нет-входов` — не раньше, чем в модели данных появится
 * названная сущность.
 */
export type SectionState =
  | { readonly kind: "готов"; readonly href: string }
  /**
   * Раздел ОБЪЕКТНЫЙ: его адрес существует только при выбранном объекте.
   *
   * Заведён потому, что без него пять пунктов рельса из девяти вели на один и
   * тот же `/objects` — карточка объекта, загрузка, сравнение КП и рабочий
   * экран не имеют статического адреса, и рельс, не знавший объекта, честного
   * адреса дать не мог. Вместо этого он давал реестр и делал вид, что ведёт
   * куда-то ещё.
   *
   * `href` получает шифр выбранного объекта. Объект не выбран — раздел не
   * ссылка, а текст с поводом: ссылка, ведущая не туда, куда обещает, хуже
   * отсутствия ссылки.
   */
  | { readonly kind: "объектный"; readonly href: (code: string) => string; readonly hint: string }
  | { readonly kind: "строится"; readonly reason: string }
  | { readonly kind: "вне-договора"; readonly reason: string }
  | { readonly kind: "нет-входов"; readonly reason: string };

export interface Section {
  readonly label: string;
  /**
   * Ключ раздела для подсветки, когда поверхности карты у него нет.
   *
   * Пульт и карта поверхностей — страницы САМОЙ СИСТЕМЫ, а не поверхности
   * договора: приписать им `S-NN` значило бы посчитать их в покрытии. Ключ
   * нужен только затем, чтобы страница могла объявить, где она в рельсе.
   */
  readonly key?: string;
  /** Иконка раздела. Обязательна: рельс без иконок читается как список ссылок. */
  readonly icon: LucideIcon;
  /**
   * Поверхность карты (`docs/roadmap-frontend.md` §2) — она же ключ, которым
   * страница объявляет, где она в системе.
   *
   * Пусто у того, что поверхностью не является: образец облика — показ облика, а
   * не экран системы, и приписывать ему `S-NN` значило бы посчитать его в
   * покрытии договора. Отдельного технического ключа у разделов нет намеренно:
   * во всех двадцати четырёх случаях он повторял бы `S-NN` слово в слово, а
   * повторённый литерал рано или поздно расходится.
   */
  readonly surface?: string;
  /** Договорный ли раздел: шесть экранов §25 против всего остального. */
  readonly contract: boolean;
  /**
   * Что считать рядом с названием, если это осмысленно.
   *
   * Счётчики в рельсе — приём Pulse, и там же его правило: НОЛЬ НЕ ПОКАЗЫВАЕТСЯ.
   * Ноль создаёт шум и ничего не сообщает, а непустое число сразу говорит, где
   * работа. Поэтому здесь только имя величины; само число приносит оболочка.
   */
  readonly counter?: "objects" | "documents" | "positions" | "pending" | "checks";
  /**
   * Полное название и способ открытия — то, чего не вмещает рельс.
   *
   * Карточка объекта, сравнение предложений и рабочий экран Проверки ведут на
   * реестр: собственного входа у них нет, они открываются изнутри пути. Без
   * этой приписки нажатие уводит «не туда», и это читается как ошибка.
   */
  readonly note?: string;
  /**
   * Чей это ВИД, если раздел — не раздел, а деталь.
   *
   * ПРИЁМ ВЗЯТ У ДОМОВЕЯ ЦЕЛИКОМ
   *
   * Там `/tickets/<id>` объявлена в `crmDetailRoutes` с полем `parentHref` и в
   * рельс не попадает никогда: пункт рельса — раздел системы, а карточка заявки
   * — её деталь. В рельсе Домовея нет ни одной карточки.
   *
   * У нас в рельсе стояли шесть штук: карточка объекта, документы, сравнение
   * предложений, рабочий экран, агенты и пакет. Все шесть — виды ОДНОГО
   * объекта, то есть листья, показанные корнями. Отсюда и «сделано не совсем
   * интуитивно понятно»: пользователь искал разделы системы, а находил
   * страницы одной стройки.
   *
   * Заполнено — раздел исчезает из рельса и остаётся вкладкой карточки
   * объекта. Из карты поверхностей он НЕ исчезает: поверхность существует, и
   * покрытие договора считается по ней, а не по рельсу.
   */
  readonly detailOf?: string;
  /**
   * Под какой подписью раздел стоит В РЕЛЬСЕ, если она не совпадает с
   * предметной областью.
   *
   * РЕЛЬС И КАРТА ГРУППИРУЮТ ПО РАЗНОМУ — И ЭТО НЕ НЕБРЕЖНОСТЬ
   *
   * Карта поверхностей группирует по ПРЕДМЕТУ: Смета, Деньги, Выполнение,
   * Подряд. Так устроен договор, и так её читают.
   *
   * Рельс у Домовея группирует по СТАДИИ ВНИМАНИЯ: Главная (что сейчас) ·
   * Работа (что я делаю) · Обзор (что смотрю) · Администрирование (что
   * настраиваю). Четыре подписи на четырнадцать пунктов.
   *
   * Я перенёс в рельс предметную группировку — и после переезда видов объекта
   * во вкладки получил ТРИ ГРУППЫ ПО ОДНОМУ ПУНКТУ: «Обзор → Пульт»,
   * «Объекты → Реестр», «Система → Журнал». Подпись над единственным пунктом
   * не сообщает ничего, а три таких подписи занимают столько же места, сколько
   * сами пункты. Замерено на живом экране, а не предположено.
   */
  readonly railGroup?: string;
  readonly state: SectionState;
}

export interface SectionGroup {
  readonly title: string;
  readonly sections: readonly Section[];
}

