/**
 * Состояние Проверки — СЛОВОМ ЧЕЛОВЕКА, а не значением перечисления.
 *
 * ЧТО ЗДЕСЬ ЗАКРЫВАЕТСЯ
 *
 * На рабочем экране прогона стояло `label={card.status}`, и клиент читал
 * «состояние queued». Это не мелочь перевода: экран прогона — то, что владелец
 * показывает на встрече, и английский идентификатор перечисления на нём
 * сообщает ровно одно — что показывают внутренности, а не продукт.
 *
 * Реестр объектов при этом словарь имел — свой, в своём файле. Третья копия
 * была бы гарантированным расхождением; вместо неё словарь один.
 *
 * НЕ ПУТАТЬ С СОСТОЯНИЕМ ЗАДАЧИ. У `Job` свой набор (`dead`, и `completed`
 * значит «выполнена», а не «завершена») и свой словарь. Свести их в один —
 * значит однажды показать «не удалась» там, где Проверка просто отменена.
 */
import type { PillTone } from "../kit/pill.js";

export interface StatusWord {
  readonly label: string;
  readonly tone: PillTone;
}

export const CHECK_STATUS: Readonly<Record<string, StatusWord>> = {
  queued: { label: "в очереди", tone: "plain" },
  running: { label: "выполняется", tone: "info" },
  awaiting_human: { label: "ждёт человека", tone: "warn" },
  completed: { label: "завершена", tone: "ok" },
  cancelled: { label: "отменена", tone: "plain" },
  failed: { label: "сбой", tone: "danger" },
};

/**
 * Слово о состоянии. Незнакомое значение НЕ прячется: оно показывается как
 * есть и помечается тревожным тоном — это значит, что в базе появилось
 * состояние, о котором интерфейс не знает, и молчать об этом хуже.
 */
export function checkStatusWord(status: string): StatusWord {
  return CHECK_STATUS[status] ?? { label: status, tone: "warn" };
}
