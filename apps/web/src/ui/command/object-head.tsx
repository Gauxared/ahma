/**
 * Шапка любого экрана объекта: имя объекта, вкладки, правый блок сведений.
 *
 * ЗАГОЛОВОК БЫЛ ДВОЙНЫМ, И ЭТО ВИДНО НА КАЖДОМ СКРИНШОТЕ
 *
 * Шапка каркаса писала «Проверка / АГЕНТЫ», а под ней страница ставила ещё раз
 * крупное «Агенты». Одно и то же слово дважды в двадцати пикселях друг от друга
 * — не «дублирование текста», а потеря единственного места, где можно сказать
 * ГЛАВНОЕ: на каком объекте пользователь находится.
 *
 * У Домовея это решено разделением уровней. Над справочником в шапке стоит
 * «СПРАВОЧНИКИ» (раздел), вкладки называют вид («Сотрудники 17»), а заголовок
 * блока данных называет данные («Все сотрудники · 17»). Три уровня, три разных
 * слова, ни одного повторения.
 *
 * Здесь то же самое:
 *
 *  - раздел — шапка каркаса («Объекты / КАРТОЧКА ОБЪЕКТА»);
 *  - **предмет — заголовок этого компонента: ИМЯ ОБЪЕКТА**;
 *  - вид — активная вкладка;
 *  - данные — заголовок карточки.
 *
 * Поэтому `title` здесь не принимается: имя объекта — единственное, что вправе
 * стоять заголовком на объектном экране. Экран, желающий назвать свой вид,
 * называет его вкладкой, а не вторым H1.
 */
import { objectTabHref, objectTabs, type ObjectTabCounts, type ObjectTabKey } from "@web/src/app-shell/object-tabs.js";
import { PageHead } from "@web/src/ui/kit/page.js";
import { Tabs } from "@web/src/ui/kit/tabs.js";
import type { ReactNode } from "react";

export function ObjectHead({
  code,
  name,
  active,
  counts,
  note,
  aside,
}: {
  readonly code: string;
  readonly name: string;
  /** Какой вид объекта открыт: экран объявляет ключ, адрес берётся из таблицы. */
  readonly active: ObjectTabKey;
  readonly counts?: ObjectTabCounts;
  /**
   * Что уточнить под именем объекта.
   *
   * По умолчанию — шифр: он короткий, опознаёт объект однозначно и нужен в
   * разговоре («по КРГ-1 приняли»). Экран может сказать больше — регион,
   * заказчика, — но не вместо шифра.
   */
  readonly note?: ReactNode;
  /** Правый блок: состояние прогона, свежесть, действие. */
  readonly aside?: ReactNode;
}) {
  return (
    <>
      <PageHead
        {...(aside === undefined ? {} : { aside })}
        note={note ?? `Шифр ${code}`}
        title={name}
      />
      <div className="toolbar">
        <Tabs
          active={objectTabHref(code, active)}
          label={`Разделы объекта ${code}`}
          tabs={objectTabs(code, counts ?? {})}
        />
      </div>
    </>
  );
}
