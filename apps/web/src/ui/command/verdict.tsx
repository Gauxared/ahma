/**
 * Вердикт агента — то, ради чего экран агента открывают.
 *
 * ЧТО ЗДЕСЬ БЫЛО НЕ ТАК
 *
 * Вердикты по четырём сметам склеивались в одну строку через `; ` и печатались
 * одним абзацем в колонке шириной триста сорок пикселей: полторы тысячи знаков
 * сплошной прозой, шестьдесят строк — выше экрана, то есть «липкая» панель
 * контекста не работала даже как панель. Прочитать это нельзя; можно только
 * пролистать.
 *
 * Хуже потери читаемости была потеря СВЯЗИ. Список предметов лежал рядом
 * отдельным полем, и по четырём вердиктам и четырём именам файлов установить,
 * какой вердикт о какой смете, было нельзя вовсе — а «по какой смете красный»
 * это первый вопрос на встрече.
 *
 * ЧТО ЗДЕСЬ ПОЯВИЛОСЬ И ЧЕГО НЕ ПРИДУМАНО
 *
 * Светофор `🔴 🟡 🟢` ставит сам агент, и это единственное в вердикте, что
 * читается не читая. Интерфейс его выбрасывал — знак оставался типографикой
 * внутри абзаца. Теперь он состояние: цвет, слово и место в начале строки.
 *
 * Класс, которого агент НЕ объявлял, назван неназванным. Досчитать его по
 * важности замечаний было бы удобно и неверно: «критичных нет» и «сметчик
 * принял» — разные утверждения, и второе имеет право сказать только сметчик.
 */
import type { ReactNode } from "react";

import type { AgentVerdictView, VerdictLight } from "@web/lib/check-read-model.js";
import { formatAmountsInProse } from "../value/format.js";
import { Pill, type PillTone } from "../kit/pill.js";

const LIGHT_TONE: Readonly<Record<VerdictLight, PillTone>> = {
  красный: "danger",
  жёлтый: "warn",
  зелёный: "ok",
};

/**
 * Слово рядом с цветом, и слово РАЗНОЕ по смыслу, а не название краски.
 *
 * «Красный» на пилюле сообщал бы только то, что и так видно цветом, — а спека
 * требует, чтобы цвет не был единственным сигналом. Значение светофора агенты
 * употребляют одинаково во всех девяти манифестах: красный запрещает принимать,
 * жёлтый разрешает с условием, зелёный принимает.
 */
const LIGHT_WORD: Readonly<Record<VerdictLight, string>> = {
  красный: "не принимать",
  жёлтый: "с условием",
  зелёный: "принять",
};

function Light({ light }: { readonly light: VerdictLight | null }): ReactNode {
  return light === null ? (
    <Pill label="класс не объявлен" tone="plain" title="Агент не поставил светофор — досчитывать его за него нельзя" />
  ) : (
    <Pill dot={light !== "красный"} label={LIGHT_WORD[light]} loud={light === "красный"} tone={LIGHT_TONE[light]} />
  );
}

/**
 * Развёрнутые вердикты — по одному блоку на предмет.
 *
 * Сеткой, а не столбиком: четыре вердикта по двести-триста знаков рядом
 * читаются одним взглядом, а в столбик тот же текст даёт полтора экрана
 * прокрутки. Колонка не уже 320 px — ниже этого проза ломается в лесенку.
 */
export function Verdicts({ verdicts }: { readonly verdicts: readonly AgentVerdictView[] }): ReactNode {
  return (
    <ul className="verdicts">
      {verdicts.map((verdict) => (
        <li className="verdict" key={`${verdict.subject}/${verdict.text.slice(0, 40)}`}>
          <span className="verdict__head">
            <Light light={verdict.light} />
            {/* Предмет — именем файла. У вывода об объекте целиком предмета нет,
                и подписывать его выдуманным именем значило бы назвать объект
                документом. */}
            <span className="verdict__subject">{verdict.subject === "" ? "объект целиком" : verdict.subject}</span>
          </span>
          <p className="verdict__text">{formatAmountsInProse(verdict.text)}</p>
        </li>
      ))}
    </ul>
  );
}

/**
 * Сводка светофоров — то, что имеет смысл держать на виду при прокрутке.
 *
 * В «липкой» панели контекста прозе места нет: она выше экрана и клеиться ей
 * некуда. А вот «по какой смете красный» — четыре короткие строки, и это
 * ровно тот вопрос, который задают, дойдя до сорок шестого замечания.
 */
export function VerdictLights({ verdicts }: { readonly verdicts: readonly AgentVerdictView[] }): ReactNode {
  return (
    <ul className="lights">
      {verdicts.map((verdict) => (
        <li className="lights__row" key={`${verdict.subject}/${verdict.text.slice(0, 40)}`}>
          <Light light={verdict.light} />
          <span className="lights__subject">{verdict.subject === "" ? "объект целиком" : verdict.subject}</span>
        </li>
      ))}
    </ul>
  );
}
