import type { ReactNode } from "react";

import { cn } from "../cn.js";

/**
 * Каркас рабочей страницы: ширина, поля, ритм между блоками.
 *
 * Заведён потому, что четыре экрана уже повторяли одну и ту же обёртку с
 * разными числами в отступах — а расхождение отступов между экранами читается
 * как небрежность быстрее, чем любая другая.
 */
export function Page({
  children,
  wide,
  className,
}: {
  readonly children: ReactNode;
  /** Широкая колонка для экранов с таблицами на всю ширину. */
  readonly wide?: boolean;
  readonly className?: string;
}) {
  return (
    <main
      className={cn(
        // `w-full` обязателен, а не для порядка. Каркас сделал `.pane`
        // flex-колонкой, и в ней `margin-inline: auto` перестаёт центрировать
        // растянутый блок — он ОТМЕНЯЕТ растяжение, и главная область
        // сжималась до ширины содержимого: журнал занимал 665 px из 1161.
        // Замерено, а не угадано: до каркаса `<main>` лежал в блочном потоке,
        // где `mx-auto` ведёт себя иначе.
        // ПОЛЯ И ЗАЗОР — ЧИСЛА ДОМОВЕЯ, И ШИРИНА ТОЖЕ ЕГО.
        //
        // Было `px-6 py-6` (24 px) и `max-w-[1280px]` с центровкой. На широком
        // экране это давало пустые поля по двести пикселей с каждой стороны:
        // содержимое стояло узкой колонкой посреди пустоты, а виджеты рядом
        // сжимались. У Домовея на рабочих экранах содержимое идёт ВО ВСЮ
        // ШИРИНУ области (`.crm-page-grid` с его `min(1180px)` там не
        // применяется — это оболочка форм, а не данных), поле 1,5rem, зазор
        // между блоками 12 px.
        //
        // Взято: поле 20 px, зазор 14 px, ширина полная. Ограничение ширины
        // осталось только у узких экранов — там длинная строка текста читается
        // хуже, и это единственная причина его держать.
        "flex w-full flex-col gap-3.5 px-5 py-5",
        wide === true ? "" : "mx-auto max-w-[68rem]",
        className,
      )}
    >
      {children}
    </main>
  );
}

/*
 * Хлебных крошек здесь больше нет.
 *
 * Путь переехал в шапку каркаса (`app-shell/shell.tsx`): он про место в системе,
 * а не про содержание экрана, и в шапке он один на все экраны. После переезда
 * `Crumbs` остался экспортом без применения — а «механизм без применения» в этом
 * проекте ловится гейтом, и правильно: неиспользуемый примитив выглядит как
 * рабочий и расходится с тем, что на экране.
 */

/** Шапка экрана: заголовок, подпись и правый блок под сведения или действия. */
export function PageHead({
  title,
  note,
  aside,
}: {
  readonly title: string;
  readonly note?: ReactNode;
  readonly aside?: ReactNode;
}) {
  return (
    <header className="flex flex-wrap items-start gap-x-8 gap-y-3">
      <div className="min-w-0">
        <h1 className="text-[24px] font-bold tracking-[-0.025em]">{title}</h1>
        {note === undefined ? null : <p className="meta m-0 mt-1">{note}</p>}
      </div>
      {aside === undefined ? null : <div className="ml-auto flex flex-wrap items-center gap-x-6 gap-y-2">{aside}</div>}
    </header>
  );
}
