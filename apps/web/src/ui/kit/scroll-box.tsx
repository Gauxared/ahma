/**
 * Список фиксированной высоты со своей прокруткой — и с доступом к ней.
 *
 * ЗАЧЕМ КОМПОНЕНТ, А НЕ КЛАСС `.dash-scroll`
 *
 * Классом это и было, в четырёх местах, и ни в одном не стояло `tabIndex`. То
 * есть до правых и нижних строк списка КЛАВИАТУРОЙ БЫЛО НЕ ДОБРАТЬСЯ вовсе —
 * WCAG 2.1.1, грубое нарушение.
 *
 * Дефект пролежал незамеченным, потому что `scrollable-region-focusable`
 * срабатывает, только когда область ДЕЙСТВИТЕЛЬНО прокручивается. На
 * демонстрационном контуре замечаний было мало, список помещался целиком, и
 * axe молчал. Первый же прогон с сотней замечаний сделал нарушение видимым.
 *
 * Ровно эта ошибка уже была починена у таблицы (`DataTable`) — и осталась
 * здесь, потому что правило жило в разметке, а не в одном месте. Теперь оно
 * одно.
 *
 * ИМЯ ОБЯЗАТЕЛЬНО. Область прокрутки, объявленная читалке без названия, —
 * «группа» посреди страницы: попасть в неё можно, понять, куда попал, нельзя.
 * Поэтому `label` не необязательный параметр.
 */
import type { ReactNode } from "react";

import { cn } from "../cn.js";

export interface ScrollBoxProps {
  /** Чем эта область является — произносится читалкой при входе в неё. */
  readonly label: string;
  readonly children: ReactNode;
  readonly className?: string;
}

export function ScrollBox({ label, children, className }: ScrollBoxProps) {
  return (
    // Остановка табуляции появляется и там, где прокрутки нет: узнать это
    // заранее сервер не может. Лишняя остановка — цена меньшая, чем
    // недостижимая строка, и она честная: читалка объявит область по названию.
    <div aria-label={label} className={cn("dash-scroll", className)} role="group" tabIndex={0}>
      {children}
    </div>
  );
}
