/**
 * Вкладки раздела — набор ссылок, у каждой свой адрес.
 *
 * ПОЧЕМУ ССЫЛКИ, А НЕ ПЕРЕКЛЮЧАТЕЛЬ
 *
 * Вкладки в Домовее (`DirectoryTabsToolbar`) — три `<Link>` на три маршрута.
 * Переключатель состояния дал бы один адрес на пять экранов: их нельзя
 * сохранить в закладки, нельзя дать ссылкой, нельзя открыть в новой вкладке
 * браузера, и «назад» вернул бы в другой раздел. У нас за один адрес на пять
 * экранов уже был справедливый выговор — повторять это внутри карточки объекта
 * значило бы починить рельс и сломать то же самое на уровень ниже.
 *
 * ЗАЧЕМ ВООБЩЕ
 *
 * Карточка объекта, документы, сравнение предложений, доска агентов, рабочий
 * экран и пакет — это ОДИН объект в шести видах, а стояли шестью пунктами
 * рельса. Пункт рельса — это раздел системы; здесь же были листья одного
 * объекта, показанные как корни. Вкладки возвращают их на свой уровень, не
 * отнимая у каждого адреса.
 */
import type { ReactElement } from "react";

export interface Tab {
  readonly label: string;
  readonly href: string;
  /**
   * Что считать рядом с названием.
   *
   * Ноль здесь ПОКАЗЫВАЕТСЯ, в отличие от рельса. Правило Pulse «ноль не
   * показывается» относится к навигации по всей системе, где ноль — шум среди
   * четырнадцати пунктов. На вкладке одного объекта «Агенты 0» отвечает на
   * вопрос «там уже что-то есть?» ДО нажатия, и это ответ, а не шум.
   */
  readonly count?: number;
}

export function Tabs({
  label,
  tabs,
  active,
}: {
  /** Чем набор вкладок называется для чтеца с экрана. */
  readonly label: string;
  readonly tabs: readonly Tab[];
  /** Адрес активной вкладки: сравнение точное, без совпадения по началу. */
  readonly active: string;
}): ReactElement {
  return (
    <nav aria-label={label} className="tabs">
      {tabs.map((tab) => {
        const on = tab.href === active;

        return (
          <a
            aria-current={on ? "page" : undefined}
            className={on ? "tabs__link tabs__link--on" : "tabs__link"}
            href={tab.href}
            key={tab.href}
          >
            {tab.label}
            {tab.count === undefined ? null : <span className="tabs__count">{tab.count}</span>}
          </a>
        );
      })}
    </nav>
  );
}
