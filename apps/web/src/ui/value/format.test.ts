/**
 * Суммы внутри прозы агента.
 *
 * ЗАЧЕМ ГЕЙТ У ТИПОГРАФСКОЙ ПРАВКИ
 *
 * Правило меняет ТЕКСТ, который написал агент, и меняет его регулярным
 * выражением. Такая правка опасна не тем, что не сработает, а тем, что
 * сработает не там: под «похоже на число» попадают шифры расценок
 * (`ГЭСНм08-03-572-06`), номера позиций и количества — а испорченный шифр хуже
 * неразмеченной суммы, потому что по нему не найти расценку.
 *
 * Поэтому проверяется прежде всего ГРАНИЦА: что правило НЕ трогает.
 */
import { describe, expect, it } from "vitest";

import { formatAmountsInProse, plural, pluralWord, СЛОВО } from "./format.js";

/** Разрядка `ru-RU` — неразрывный пробел, а не обычный. Сверяем по нему. */
const ПРОБЕЛ = " ";

describe("суммы в прозе агента", () => {
  it("разряжает сумму перед знаком рубля и ставит запятую в дробной части", () => {
    expect(formatAmountsInProse("итог 14198884.54 ₽, расхождение 0.00 ₽")).toBe(
      `итог 14${ПРОБЕЛ}198${ПРОБЕЛ}884,54 ₽, расхождение 0.00 ₽`,
    );
  });

  it("работает при шкале между числом и знаком", () => {
    expect(formatAmountsInProse("восстановлена из начисления 21415.26 тыс.₽")).toBe(
      `восстановлена из начисления 21${ПРОБЕЛ}415,26 тыс.₽`,
    );
  });

  it("не трогает шифр расценки", () => {
    // Шифр содержит группы цифр, и без якоря на знак рубля правило разорвало бы
    // его: `ГЭСНм08-03-572-06` перестал бы искаться поиском по документу.
    const текст = "шифр ГЭСНм08-03-572-06 и сумма 18038.61 ₽ повторяются в строках 48 и 148";

    expect(formatAmountsInProse(текст)).toBe(
      `шифр ГЭСНм08-03-572-06 и сумма 18${ПРОБЕЛ}038,61 ₽ повторяются в строках 48 и 148`,
    );
  });

  it("не трогает количество без знака рубля", () => {
    expect(formatAmountsInProse("блок ГЭСНм20-03-035: 198120 м при базовой 15240 м")).toBe(
      "блок ГЭСНм20-03-035: 198120 м при базовой 15240 м",
    );
  });

  it("не трогает короткие суммы", () => {
    // `Δ 7.52 ₽` в разрядке не нуждается, а замена точки на запятую в одном
    // месте при точке в соседнем — разнобой ради разнобоя.
    expect(formatAmountsInProse("Δ 7.52 ₽ при гранулярности шкалы 10 ₽")).toBe(
      "Δ 7.52 ₽ при гранулярности шкалы 10 ₽",
    );
  });

  it("не разряжает уже разряжённое повторно", () => {
    const готовое = `итог 14${ПРОБЕЛ}198${ПРОБЕЛ}884,54 ₽`;

    expect(formatAmountsInProse(готовое)).toBe(готовое);
  });

  it("не меняет ни одной цифры", () => {
    // Главное свойство: это разрядка, а не расчёт. Копейки те же, порядок тот
    // же — иначе показ начал бы спорить с расчётным модулем.
    const было = "НМЦК по объявленной ставке: 128491560.00 ₽ (база + НДС 20 %)";
    const стало = formatAmountsInProse(было);

    expect(стало.replace(/[^\d]/g, "")).toBe(было.replace(/[^\d]/g, ""));
  });
});

/**
 * Согласование числительного.
 *
 * ЛОМАЕТСЯ ОНО ТОЛЬКО НА КОНКРЕТНЫХ ЧИСЛАХ, и в этом вся опасность. Подпись
 * `${rows.length} партий` выглядит правильной при разработке на пяти партиях и
 * становится «1 партий» ровно у клиента, который загрузил первую. Проверка «на
 * экране есть число» такого не ловит.
 *
 * Продукт продаётся как инструмент, читающий документы внимательнее человека.
 * Несогласованное числительное в первой же подписи стоит дороже, чем кажется.
 */
describe("склонение числительного", () => {
  it("единственное — только у чисел, кончающихся на 1", () => {
    expect(plural(1, СЛОВО.партия)).toBe("1 партия");
    expect(plural(21, СЛОВО.партия)).toBe("21 партия");
    expect(plural(101, СЛОВО.партия)).toBe("101 партия");
  });

  it("2–4 берут свою форму", () => {
    expect(plural(2, СЛОВО.файл)).toBe("2 файла");
    expect(plural(3, СЛОВО.файл)).toBe("3 файла");
    expect(plural(4, СЛОВО.файл)).toBe("4 файла");
    expect(plural(22, СЛОВО.файл)).toBe("22 файла");
  });

  it("11–14 — исключение, и без него всё разваливается", () => {
    // Именно здесь ошибается наивное правило «смотрим последнюю цифру»:
    // получилось бы «11 партия», «12 партии», «13 партии», «14 партии».
    expect(pluralWord(11, СЛОВО.партия)).toBe("партий");
    expect(pluralWord(12, СЛОВО.партия)).toBe("партий");
    expect(pluralWord(13, СЛОВО.партия)).toBe("партий");
    expect(pluralWord(14, СЛОВО.партия)).toBe("партий");
    // А 111 и 112 — те же 11 и 12 по двум последним цифрам.
    expect(pluralWord(111, СЛОВО.партия)).toBe("партий");
  });

  it("ноль и множественное", () => {
    expect(plural(0, СЛОВО.замечание)).toBe("0 замечаний");
    expect(plural(5, СЛОВО.замечание)).toBe("5 замечаний");
    expect(plural(100, СЛОВО.замечание)).toBe("100 замечаний");
  });

  it("крупное число идёт с разрядкой, как остальные числа продукта", () => {
    // Иначе рядом стояли бы «14 198 884,54 ₽» и «2000 позиций» — разнобой в
    // одном абзаце заметнее, чем каждое из написаний по отдельности.
    expect(plural(2000, СЛОВО.позиция)).toBe(`2${ПРОБЕЛ}000 позиций`);
  });

  it("три формы у каждого слова из списка — разные", () => {
    // Русское словоизменение по одной форме не восстанавливается, и словарь,
    // где формы совпали, — это забытая строка, а не слово-исключение.
    for (const [имя, формы] of Object.entries(СЛОВО)) {
      const набор = new Set([формы.one, формы.few, формы.many]);
      expect(набор.size, `у слова «${имя}» формы совпали: ${JSON.stringify(формы)}`).toBe(3);
    }
  });
});
