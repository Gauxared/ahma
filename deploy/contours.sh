# КОНТУРЫ: ЧЕМ СТЕНД ОТЛИЧАЕТСЯ ОТ ПРОДА — В ОДНОМ МЕСТЕ.
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Отличий у двух контуров восемь: корень, ветка, порт,
# две службы, порт базы, имя базы, каталог документов. Разложенные по командам
# в README, они расходятся с действительностью на второй неделе — и расхождение
# обнаруживается тем, что выпуск стенда перезапускает боевые службы.
#
# Здесь они названы один раз, и все скрипты развёртывания берут их отсюда.
#
# ПОЧЕМУ У СТЕНДА ДРУГОЙ КЛАСТЕР БАЗЫ, А НЕ ПРОСТО ДРУГАЯ БАЗА РЯДОМ.
#
# Роль `stroyintellect_app`, под которой работает приложение и на которой держится
# RLS, в PostgreSQL принадлежит КЛАСТЕРУ, а не базе: одна роль — один пароль на
# все базы кластера. Поставь стенд в кластер прода — и строка подключения стенда
# открывает боевую базу. Отдельный кластер даёт стенду СВОИ роли со своими
# паролями: паролем стенда до боевых данных не дойти.
#
# ПОЧЕМУ ПРИ ЭТОМ И ИМЯ БАЗЫ ДРУГОЕ. Второй барьер против забытого параметра.
# Забыли `-p 5433` — на 5432 нет базы `stroyintellect_stage`, команда падает.
# Забыли `-d stroyintellect_stage` — на 5433 нет базы `stroyintellect`, команда
# падает. Оба промаха дают отказ, а не молчаливую запись в боевые данные.
#
# Подключение: . "$(dirname "$0")/contours.sh" && contour_load стенд|прод

# Имена переменных ЛАТИНИЦЕЙ — иначе bash разбирает присваивание как запуск
# команды и падает с «No such file or directory» (см. tooling/deploy-release.test.ts).
contour_load() {
  case "${1:-}" in
    prod)
      CONTOUR=prod
      CONTOUR_TITLE='прод — app.strintel.ru'
      ROOT=/opt/stroyintellekt
      BRANCH=main
      PORT=3000
      SERVICE_WEB=stroyintellekt-web
      # Воркер — ШАБЛОН systemd; экземпляры складываются как <база>@<номер>.
      SERVICE_WORKER=stroyintellekt-worker
      # ДВА ПОТОКА, И ЭТО ЧИСЛО СЧИТАНО.
      #
      # Проверку ставят до пяти человек, прогон экипажа идёт до часа: с одним
      # воркером второй человек ждёт не свою работу. Три потока на этой машине
      # не помещаются — 3 ГБ предела на поток, 3,2 ГБ на сборку выпуска, две
      # базы и два интерфейса, всего 11,7 ГБ и НЕТ подкачки.
      #
      # Больше двух даст не эта машина, а другая — либо снятие настоящего
      # предела: очередь пуста не потому, что потоков мало, а потому что прогон
      # ждёт модель.
      WORKERS=2
      PGPORT=5432
      PGDATABASE=stroyintellect
      OBJECTS=/srv/stroyintellekt/objects
      # Прод собирается в полную силу: он и есть то, ради чего сервер стоит.
      BUILD_PREFIX=''
      ;;
    stage)
      CONTOUR=stage
      CONTOUR_TITLE='стенд — stage.strintel.ru'
      ROOT=/opt/stroyintellekt-stage
      BRANCH=stage
      PORT=3100
      SERVICE_WEB=stroyintellekt-stage-web
      SERVICE_WORKER=stroyintellekt-stage-worker
      # Один поток: в остаток памяти после двух боевых второй не помещается.
      # Цена названа в deploy/stroyintellekt-stage-worker@.service.
      WORKERS=1
      PGPORT=5433
      PGDATABASE=stroyintellect_stage
      OBJECTS=/srv/stroyintellekt-stage/objects
      # СБОРКА СТЕНДА УСТУПАЕТ ПРОДУ ПРОЦЕССОР И ДИСК.
      #
      # Ядер на сервере четыре, и `next build` забирает их все на несколько
      # минут. Без уступки выпуск стенда — это замедление боевого сайта в те же
      # минуты: заказчик видит отклик хуже, а причина лежит в другом контуре.
      BUILD_PREFIX='nice -n 10 ionice -c 3'
      ;;
    *)
      echo "КОНТУР НЕ НАЗВАН. Ожидается: prod | stage" >&2
      echo "Имя контура обязательно: команда без имени однажды выполнилась бы на боевом." >&2
      return 2
      ;;
  esac

  SRC="$ROOT/src"
  RELEASES="$ROOT/releases"
  CURRENT="$ROOT/current"

  # Имена экземпляров воркера складываются ЗДЕСЬ, а не в каждом скрипте: два
  # места, считающие потоки самостоятельно, однажды разойдутся в счёте — и
  # выпуск перезапустит один поток из двух, оставив второй на старом коде.
  WORKER_UNITS=()
  for INSTANCE in $(seq 1 "$WORKERS"); do
    WORKER_UNITS+=("${SERVICE_WORKER}@${INSTANCE}")
  done
}
