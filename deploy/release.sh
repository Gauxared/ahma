#!/usr/bin/env bash
#
# ВЫПУСК: СБОРКА РЯДОМ, ПЕРЕКЛЮЧЕНИЕ ССЫЛКОЙ.
#
# Вызов: release.sh prod | release.sh stage
#
# ИМЯ КОНТУРА ОБЯЗАТЕЛЬНО. Скрипт без имени однажды выполнился бы на боевом
# контуре, когда его звали для стенда. Отличия контуров — в contours.sh.
#
# ЗАЧЕМ. `next build` переписывает `.next` НА МЕСТЕ, а работающий процесс
# читает оттуда же. Пока сборка идёт, живой сайт отдаёт 500:
#
#   Invariant: The client reference manifest for route "/objects/[code]"
#   does not exist
#
# Замерено 06.09.2026 на app.strintel.ru: около двух минут недоступности при
# каждом обновлении. Это не поломка сборки — это следствие того, что каталог
# переписывают под читателем.
#
# КАК УСТРОЕНО. Код каждого выпуска ложится в свой каталог `releases/<метка>`,
# собирается ТАМ, и только после успешной сборки ссылка `current` переводится
# на него. Службы работают из `current`, поэтому во время сборки они читают
# прежний выпуск и продолжают отвечать.
#
# ОТКУДА БЕРЁТСЯ КОД. Из ВЕТКИ репозитория: у прода — `main`, у стенда —
# `stage`. Сборочный каталог `$ROOT/src` — клон, который скрипт приводит к
# состоянию `origin/<ветка>` сам.
#
# Прежде код уезжал `rsync` с машины разработчика. Так на сервер попадало
# рабочее дерево, а не ветка: незакоммиченная правка уезжала молча, и ответить
# на вопрос «что именно стоит на проде» можно было только памятью. Теперь на
# вопрос отвечает файл `.release` в каталоге выпуска — ветка, хеш, дата.
#
# ЧЕГО ЭТО НЕ УБИРАЕТ. Перезапуск служб после переключения — секунды
# недоступности. Убрать и их можно только передачей сокета, и это отдельная
# задача; здесь снимаются ДВЕ МИНУТЫ, а не последние две секунды.
#
# ЧТО ЖИВЁТ ВНЕ ВЫПУСКОВ И ПОЧЕМУ:
#
#   .env            — ключ модели и пароли базы. Внутри выпуска он терялся бы
#                     при каждом переключении, и его пришлось бы копировать
#                     руками: лишний повод однажды забыть `chmod 600`.
#   node_modules    — общие. Установка в каждый выпуск стоит минут и гигабайтов
#                     ради зависимостей, которые меняются раз в неделю. Цена
#                     решения названа: при СМЕНЕ зависимостей нужен
#                     `pnpm install` до выпуска — иначе новый код встретит
#                     старые пакеты. Скрипт сверяет замок и предупреждает.
#   /srv/…/objects  — документы заказчика. К коду отношения не имеют.
set -euo pipefail

. "$(dirname "$(readlink -f "$0")")/contours.sh"
contour_load "${1:-}"

KEEP=${KEEP:-3}

STAMP=$(date -u +%Y%m%dT%H%M%SZ)
NEXT="$RELEASES/$STAMP"

echo "== выпуск $STAMP: $CONTOUR_TITLE"

if [ ! -f "$ROOT/.env" ]; then
  echo "НЕТ $ROOT/.env — окружение живёт вне выпусков и создаётся один раз" >&2
  exit 1
fi

# Проверка контура ДО сборки: окружение, указывающее на чужую базу, обязано
# остановить выпуск здесь, а не обнаружиться записью в боевые данные.
#
# Сверяется НЕ строка подключения, а метка, прочитанная из самой базы
# (`ALTER DATABASE … SET stroyintellect.contour`): строка говорит, куда
# собирались подключиться, метка — куда подключились.
ENV_PGPORT=$(sed -n 's|^DATABASE_URL=.*@[^:]*:\([0-9]*\)/.*|\1|p' "$ROOT/.env" | head -1)
ENV_PGDATABASE=$(sed -n 's|^DATABASE_URL=.*/\([A-Za-z0-9_]*\).*|\1|p' "$ROOT/.env" | head -1)

if [ "${ENV_PGPORT:-}" != "$PGPORT" ] || [ "${ENV_PGDATABASE:-}" != "$PGDATABASE" ]; then
  echo "ОКРУЖЕНИЕ НЕ ОТ ЭТОГО КОНТУРА." >&2
  echo "  contours.sh ждёт базу $PGDATABASE на порту $PGPORT," >&2
  echo "  в $ROOT/.env указана ${ENV_PGDATABASE:-?} на порту ${ENV_PGPORT:-?}." >&2
  exit 1
fi

MARK=$(sudo -u postgres psql -p "$PGPORT" -d "$PGDATABASE" -At \
  -c "select coalesce(current_setting('stroyintellect.contour', true), '')" 2>/dev/null || echo '')

if [ "$MARK" != "$CONTOUR" ]; then
  echo "БАЗА НЕ ПОМЕЧЕНА КОНТУРОМ «$CONTOUR» (прочитано: «${MARK:-нет метки}»)." >&2
  echo "  Метка ставится один раз при заведении контура:" >&2
  echo "  sudo -u postgres psql -p $PGPORT -c \"alter database $PGDATABASE set stroyintellect.contour = '$CONTOUR'\"" >&2
  exit 1
fi

mkdir -p "$RELEASES"

# НЕУДАВШИЙСЯ ВЫПУСК УБИРАЕТСЯ ЗА СОБОЙ.
#
# Хранится три выпуска, и откат — это переключение ссылки на прежний. Каталог
# неудачной сборки, оставленный на диске, считается выпуском наравне с рабочими
# и вытесняет из этих трёх настоящий — то есть отнимает откат. Двух неудач
# подряд хватило бы, чтобы откатываться стало некуда.
#
# После переключения ссылки каталог уже рабочий: тогда его не трогаем.
cleanup_failed_release() {
  local code=$?
  if [ "$code" -ne 0 ] && [ -d "$NEXT" ] && [ "$(readlink -f "$CURRENT" 2>/dev/null)" != "$NEXT" ]; then
    rm -rf "$NEXT"
    echo "== каталог неудачного выпуска убран; работает прежний: $(readlink -f "$CURRENT" 2>/dev/null || echo 'нет')" >&2
  fi
}
trap cleanup_failed_release EXIT

# ВЕТКА, А НЕ РАБОЧЕЕ ДЕРЕВО. Правка, сделанная на сервере руками, остановит
# выпуск: иначе она уехала бы в выпуск и пропала при следующем `reset`, а
# отличие сервера от репозитория никто бы не заметил.
#
# Сверяются ИЗМЕНЁННЫЕ ОТСЛЕЖИВАЕМЫЕ файлы: именно их затирает `reset --hard`.
# Неотслеживаемое `reset` не трогает, поэтому оно не повод отказать в выпуске —
# но в выпуск оно уедет вместе с исходником, и об этом сказано вслух.
if [ -n "$(git -C "$SRC" status --porcelain --untracked-files=no)" ]; then
  echo "В $SRC ИЗМЕНЕНЫ ФАЙЛЫ РЕПОЗИТОРИЯ:" >&2
  git -C "$SRC" status --short --untracked-files=no >&2
  echo "Сборочный каталог обязан быть копией ветки $BRANCH: обновление ветки затрёт эти правки." >&2
  echo "Правки — через репозиторий. Отказаться от них здесь: git -C $SRC checkout -- ." >&2
  exit 1
fi

UNTRACKED=$(git -C "$SRC" ls-files --others --exclude-standard)
if [ -n "$UNTRACKED" ]; then
  echo "!! В сборочном каталоге лежит НЕОТСЛЕЖИВАЕМОЕ — оно уедет в выпуск:" >&2
  echo "$UNTRACKED" | head -10 | sed 's|^|   |' >&2
fi

echo "== ветка $BRANCH из origin"
# СБОРОЧНЫЙ КАТАЛОГ ДЕРЖИТ ТОЛЬКО ВЕРШИНУ ВЕТКИ.
#
# Замерено 10.09.2026 с этого сервера: полный клон — 275 тысяч объектов на
# скорости около 215 КБ/с, двадцать минут на контур. Сборке нужен один коммит,
# а не история: клон сделан с `--depth 1`, и `fetch` обязан оставаться таким же,
# иначе первое же обновление затянет всё, чего избегали при клонировании.
if [ "$(git -C "$SRC" rev-parse --is-shallow-repository)" = 'true' ]; then
  git -C "$SRC" fetch --depth 1 --prune origin "$BRANCH"
else
  git -C "$SRC" fetch --prune origin "$BRANCH"
fi
git -C "$SRC" checkout --quiet -B "$BRANCH" "origin/$BRANCH"
git -C "$SRC" reset --hard --quiet "origin/$BRANCH"

COMMIT=$(git -C "$SRC" rev-parse --short HEAD)
SUBJECT=$(git -C "$SRC" log -1 --pretty=%s)
echo "   $COMMIT $SUBJECT"

# Исходник приезжает В НОВЫЙ каталог, а не поверх работающего.
# `reference-system/` (опорные базы ролей, версионируются) едет в выпуск;
# `reference-system-new/` (14 ГБ исходников заказчика) — нет и не должен.
# Ссылку на общие пакеты кладём внутрь выпуска: сборка ищет их по месту.
rsync -a --delete \
  --exclude node_modules --exclude .next --exclude .git --exclude var \
  --exclude .env --exclude reference-system-new \
  --exclude .venv --exclude .pytest_cache \
  "${SOURCE:-$SRC}/" "$NEXT/"

# ЗАМОК ЗАВИСИМОСТЕЙ СВЕРЯЕТСЯ С ПРЕЖНИМ ВЫПУСКОМ.
#
# Пакеты общие для всех выпусков — при СМЕНЕ зависимостей новый код встретит
# старые пакеты. Раньше об этом было написано в комментарии, а скрипт молчал:
# предупреждение существовало только в тексте. Теперь сверяется файл.
if [ -e "$CURRENT/pnpm-lock.yaml" ] && ! cmp -s "$CURRENT/pnpm-lock.yaml" "$NEXT/pnpm-lock.yaml"; then
  echo "!! ЗАМОК ЗАВИСИМОСТЕЙ ИЗМЕНИЛСЯ по сравнению с работающим выпуском." >&2
  echo "   Пакеты общие ($ROOT/node_modules) — новый код встретил бы старые." >&2
  echo "   Установка не делается сама: она меняет пакеты ПОД работающим выпуском," >&2
  echo "   и делать это вслепую посреди выпуска нельзя. Порядок такой:" >&2
  echo "     cp $SRC/package.json $SRC/pnpm-lock.yaml $ROOT/" >&2
  echo "     cd $ROOT && pnpm install --frozen-lockfile" >&2
  echo "     bash $SRC/deploy/release.sh $CONTOUR" >&2
  exit 1
fi

ln -sfn "$ROOT/node_modules" "$NEXT/node_modules"
ln -sfn "$ROOT/.env" "$NEXT/.env"

printf 'контур: %s\nветка: %s\nкоммит: %s\nзаголовок: %s\nвыпуск: %s\n' \
  "$CONTOUR" "$BRANCH" "$(git -C "$SRC" rev-parse HEAD)" "$SUBJECT" "$STAMP" > "$NEXT/.release"

echo "== сборка в $NEXT (старый выпуск продолжает отвечать)"
cd "$NEXT"
set -a; . "$ROOT/.env"; set +a
npx prisma generate >/dev/null
# shellcheck disable=SC2086
NODE_OPTIONS=--max-old-space-size=3072 $BUILD_PREFIX npx next build apps/web --webpack

# Миграции — ПОСЛЕ сборки и ДО переключения: собранный код уже проверен, а
# схема нужна ему с первой секунды работы.
npx prisma migrate deploy

echo "== переключение ссылки"
# `ln -sfn` на существующий симлинк-каталог создал бы ссылку ВНУТРИ него;
# `-T` заставляет обращаться с целью как с обычным именем.
ln -sfnT "$NEXT" "$CURRENT"

# ВОРКЕР НЕ ПЕРЕЗАПУСКАЕТСЯ ПОСРЕДИ ЧУЖОГО ПРОГОНА.
#
# Прогон экипажа идёт от получаса до часа и стоит десятки миллионов токенов.
# Перезапуск воркера обрывает его на середине: работа пропадает, а человек,
# который её ждёт, видит «прогон не завершился» без объяснения. Замерено
# 09.09.2026: владелец ждал свою Проверку в очереди, пока выпуск шёл рядом.
#
# Интерфейс при этом обновляется всегда: он не держит длинной работы, и его
# перезапуск стоит секунды. Воркер, занятый прогоном, доживает на прежнем
# выпуске и подхватит новый со следующей задачей — либо его перезапускают
# руками, когда прогон закончится.
#
# ПОТОКОВ НЕСКОЛЬКО — И ПЕРЕЗАПУСКАЮТСЯ ТОЛЬКО СВОБОДНЫЕ.
#
# Владелец аренды содержит номер потока (`<машина>/<номер>#<pid>`), поэтому
# занятый поток отличим от свободного. С двумя потоками это не мелочь: один
# может вести часовой прогон, второй — стоять пустым, и новый код обязан попасть
# в пустой сразу, а не ждать чужого прогона.
BUSY_OWNERS=$(sudo -u postgres psql -p "$PGPORT" -d "$PGDATABASE" -At -c \
  "select coalesce(\"leaseOwner\", '') from job where status = 'running'" 2>/dev/null || echo '')

sudo systemctl restart "$SERVICE_WEB"

# Владелец БЕЗ номера потока — это воркер, запущенный до перехода на шаблоны
# systemd. Какой это поток, сказать нечем, поэтому не перезапускается ни один:
# оборвать часовой прогон дороже, чем подождать его конца.
UNNUMBERED_BUSY=$(printf '%s\n' "$BUSY_OWNERS" | grep -c '^[^/]*#[0-9]*$' || true)

for UNIT in "${WORKER_UNITS[@]}"; do
  INSTANCE=${UNIT##*@}

  if [ "${UNNUMBERED_BUSY:-0}" -gt 0 ]; then
    echo "== $UNIT НЕ перезапущен: задачу ведёт воркер без номера потока"
    echo "   (запущен до перехода на шаблоны; после его прогона: sudo systemctl restart $UNIT)"
    continue
  fi

  if printf '%s\n' "$BUSY_OWNERS" | grep -q "/${INSTANCE}#"; then
    echo "== $UNIT НЕ перезапущен: он ведёт задачу"
    echo "   новый код поток подхватит после её конца: sudo systemctl restart $UNIT"
    continue
  fi

  sudo systemctl restart "$UNIT"
  echo "== $UNIT перезапущен"
done

# Проверка ПОСЛЕ переключения: выпуск, который не отвечает, надо увидеть здесь,
# а не от заказчика.
for _ in $(seq 1 30); do
  CODE=$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$PORT/" || true)
  [ "$CODE" = "200" ] && break
  sleep 2
done

if [ "${CODE:-000}" != "200" ]; then
  echo "ВЫПУСК НЕ ОТВЕЧАЕТ (http ${CODE:-000}). Откат: ln -sfnT <прежний> $CURRENT" >&2
  ls -1t "$RELEASES" | head -5 >&2
  exit 1
fi

echo "== выпуск $STAMP отвечает 200 на порту $PORT ($CONTOUR: $COMMIT)"

# Прежние выпуски держим: откат — это переключение ссылки, а не пересборка.
cd "$RELEASES"
ls -1t | tail -n "+$((KEEP + 1))" | xargs -r rm -rf
echo "== выпусков на диске: $(ls -1 "$RELEASES" | wc -l)"
