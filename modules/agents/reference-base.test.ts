/**
 * Опорная база — знание, которого у агента не было.
 *
 * Проверяется не «разбор читает xlsx», а три свойства, каждое из которых
 * определяет, соврёт агент или нет: статус нормы доходит до промпта; отсутствие
 * базы объявляется, а не замалчивается; объём базы не вытесняет саму смету.
 */
import { describe, expect, it } from "vitest";

import { parseReferenceSheet, renderReferenceBase } from "./reference-base.js";

const ЛИСТ = [
  ["2. СМЕТНО-НОРМАТИВНЫЕ БАЗЫ", "", "", "", ""],
  ["На чём считается. ФСНБ-2022 — текущая база.", "", "", "", ""],
  ["Шифр / норма", "Что регламентирует", "Действующая редакция", "Ключевая цифра", "Статус"],
  ["ТЕКУЩАЯ БАЗА", "ТЕКУЩАЯ БАЗА", "ТЕКУЩАЯ БАЗА", "ТЕКУЩАЯ БАЗА", "ТЕКУЩАЯ БАЗА"],
  ["ФСНБ-2022", "Федеральная сметно-нормативная база", "с 25.02.2023", "уровень цен 01.01.2022", "✅ действует"],
  ["РД-11-02-2006", "Состав и порядок ведения ИД", "ОТМЕНЁН приказом 344/пр", "", "❌ отменён"],
  ["", "", "", "", ""],
];

describe("разбор листа опорной базы", () => {
  const лист = parseReferenceSheet("2. Сметные базы", ЛИСТ);

  it("берёт строки знания после шапки", () => {
    const шифры = лист.rows.map((row) => row.code);
    expect(шифры).toContain("ФСНБ-2022");
    expect(шифры).toContain("РД-11-02-2006");
  });

  it("сохраняет СТАТУС нормы — ради него база и заводилась", () => {
    // Агент без статуса сошлётся на отменённый РД-11-02-2006 и будет звучать
    // убедительно. Это «Урок Д-6» самого легаси.
    const отменённая = лист.rows.find((row) => row.code === "РД-11-02-2006");
    expect(отменённая?.status).toBe("❌ отменён");
  });

  it("схлопывает объединённый заголовок раздела в одну строку", () => {
    // После разбора объединённая ячейка приезжает пятью одинаковыми колонками:
    // «ТЕКУЩАЯ БАЗА · ТЕКУЩАЯ БАЗА · …» впятеро раздувает блок ради одной строки.
    const заголовок = лист.rows.filter((row) => row.subject === "ТЕКУЩАЯ БАЗА");
    expect(заголовок).toHaveLength(1);
    expect(заголовок[0]!.code).toBe("");
  });

  it("сохраняет пояснение листа: оно несёт смысл, ради которого лист открывают", () => {
    expect(лист.rows.some((row) => row.subject.startsWith("На чём считается"))).toBe(true);
  });
});

describe("блок промпта", () => {
  const база = {
    source: "Опорная_база_Людмила.xlsx",
    contentHash: "хэш",
    sheets: [parseReferenceSheet("2. Сметные базы", ЛИСТ)],
  };

  it("предупреждает о статусе ДО перечня норм", () => {
    const текст = renderReferenceBase(база);

    expect(текст.indexOf("отменён — ссылаться нельзя")).toBeLessThan(
      текст.indexOf("ФСНБ-2022"),
    );
  });

  it("ТРЕБУЕТ ссылаться на базу, а не просто показывает её", () => {
    // Прогон с подключённой базой и без указания ею пользоваться дал две
    // нормативные ссылки на 157 замечаний: база доехала и осталась фоном.
    const текст = renderReferenceBase(база);

    expect(текст).toMatch(/подкрепляй ссылкой ОТСЮДА/u);
    expect(текст).toMatch(/не выдавай за проверенную/u);
  });

  it("называет источник: читатель должен знать, на что опирались", () => {
    expect(renderReferenceBase(база)).toContain("Опорная_база_Людмила.xlsx");
  });

  it("ОГРАНИЧИВАЕТ объём и говорит, сколько строк не показано", () => {
    // База ГИПа — 183 норматива. Целиком она вытеснит из окна саму смету, и
    // молча обрезать её значит скрыть, что агент видел не всё.
    const текст = renderReferenceBase(база, 1);

    expect(текст).toMatch(/и ещё строк базы: \d+ \(не показаны\)/u);
  });
});
