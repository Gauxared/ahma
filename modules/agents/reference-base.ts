/**
 * Опорная база агента — знание, на которое он опирается.
 *
 * ЧТО ЭТО ВОССТАНАВЛИВАЕТ
 *
 * В легаси у каждого из девяти агентов была своя книга на 8–17 листов: у
 * сметчика — методика, сметно-нормативные базы, индексы, накладные и лимитные;
 * у ГИПа — 183 нормативных документа по шестнадцати дисциплинам; у подрядчика —
 * скоринговая модель с весами. Формат листа единый:
 *
 *   Шифр / норма | Что регламентирует | Действующая редакция | Ключевая цифра | Статус
 *
 * И статусная модель, ради которой всё и заводилось: ✅ действует ·
 * ⚠️ проверить редакцию · 🆕 изменение 2025–2026 · ❌ отменён.
 *
 * При переносе агентов эти книги не переносились вовсе. Следствие видно на
 * прогоне: агент не может сказать «этот СП отменён», не может сверить позицию с
 * бенчмарком и не может проставить статус нормы на дату — ему нечем.
 *
 * ПОЧЕМУ ЭТО НЕ ВКЛЕИВАЕТСЯ В ПРОМПТ РУКАМИ
 *
 * Книга — документ заказчика, и по ТЗ §11 она монтируется, а не входит в
 * образ. Вклеенная в промпт копия устареет в тот день, когда заказчик поправит
 * свою книгу, и никто об этом не узнает: правка базы не изменит ни одного файла
 * в репозитории. Поэтому база ЧИТАЕТСЯ на прогоне, а её отпечаток идёт в
 * снапшот — правка базы меняет отпечаток Проверки.
 *
 * РЕЖИМ «БЕЗ БАЗЫ» — ПРАВИЛО САМОГО ЛЕГАСИ
 *
 * Дословно из промптов v9.6: «Нет → [БЕЗ БАЗЫ] (Ядро р.8)». Отсутствие базы
 * объявляется, а не замалчивается: агент без опоры отвечает общими знаниями
 * модели, и читатель обязан это знать (ADR-R-026).
 */

/** Строка опорной базы — как она лежит в книге легаси. */
export interface ReferenceRow {
  /** Шифр нормы либо название позиции знания. */
  readonly code: string;
  /** Что регламентирует и зачем агенту. */
  readonly subject: string;
  /** Действующая редакция либо срок. */
  readonly edition: string;
  /** Ключевая цифра или пункт. */
  readonly key: string;
  /** ✅ действует · ⚠️ проверить · 🆕 изменение · ❌ отменён. */
  readonly status: string;
}

export interface ReferenceSheet {
  readonly name: string;
  readonly rows: readonly ReferenceRow[];
}

export interface ReferenceBase {
  /** Имя файла книги — чтобы в отчёте было видно, на что опирались. */
  readonly source: string;
  readonly contentHash: string;
  readonly sheets: readonly ReferenceSheet[];
}

/**
 * Заголовки, по которым распознаётся шапка листа.
 *
 * Совпадение ищется по вхождению, а не по равенству: у разных агентов колонка
 * называется то «Что регламентирует / зачем Людмиле», то «Что регламентирует /
 * зачем Палычу». Требовать точного совпадения значило бы читать базу одного
 * агента и не читать базу другого.
 */
const HEADER_MARKERS = ["шифр", "норма", "что регламентирует", "статус"] as const;

function isHeader(cells: readonly string[]): boolean {
  const line = cells.join(" ").toLowerCase();
  return HEADER_MARKERS.filter((marker) => line.includes(marker)).length >= 2;
}

/**
 * Разбирает лист книги в строки знания.
 *
 * Строки до шапки — заголовок и пояснение листа; они не выбрасываются, а
 * становятся первой строкой с пустым статусом: пояснение «на чём считается»
 * несёт смысл, ради которого лист и открывают.
 */
export function parseReferenceSheet(name: string, rows: readonly (readonly string[])[]): ReferenceSheet {
  const out: ReferenceRow[] = [];
  let seenHeader = false;

  for (const cells of rows) {
    if (cells.every((cell) => cell.trim() === "")) continue;

    if (!seenHeader) {
      if (isHeader(cells)) {
        seenHeader = true;
        continue;
      }
      // Пояснение листа: одна содержательная колонка, остальные пусты.
      const filled = cells.filter((cell) => cell.trim() !== "");
      if (filled.length === 1 && filled[0]!.length > 12) {
        out.push({ code: "", subject: filled[0]!, edition: "", key: "", status: "" });
      }
      continue;
    }

    const [code = "", subject = "", edition = "", key = "", status = ""] = cells;
    if (code.trim() === "" && subject.trim() === "") continue;

    // Заголовок раздела в книге — объединённая ячейка, и после разбора она
    // приезжает пятью одинаковыми колонками. Печатать «ГЛАВНАЯ МЕТОДИКА ·
    // ГЛАВНАЯ МЕТОДИКА · …» значит впятеро раздуть блок ради одной строки.
    const distinct = new Set(cells.map((cell) => cell.trim()).filter((cell) => cell !== ""));
    if (distinct.size === 1) {
      out.push({ code: "", subject: [...distinct][0]!, edition: "", key: "", status: "" });
      continue;
    }

    out.push({
      code: code.trim(),
      subject: subject.trim(),
      edition: edition.trim(),
      key: key.trim(),
      status: status.trim(),
    });
  }

  return { name, rows: out };
}

/**
 * Опорная база в виде блока промпта.
 *
 * СТАТУС ПЕЧАТАЕТСЯ ВСЕГДА, И ЭТО ГЛАВНОЕ
 *
 * Правило легаси, названное «Урок Д-6»: ссылка на норму без проверки её
 * действия — ошибка. Норма с пометкой «❌ отменён» рядом с действующей — это и
 * есть то знание, которого у агента без базы нет: он сошлётся на отменённый
 * РД-11-02-2006 и будет звучать убедительно.
 *
 * `limit` ограничивает объём: база ГИПа — 183 норматива, и целиком она вытеснит
 * из окна саму смету. Отбираются строки с непустым статусом — то есть
 * нормативные, а не пояснительные.
 */
export function renderReferenceBase(base: ReferenceBase, limit = 120): string {
  const lines: string[] = [
    `ОПОРНАЯ БАЗА: ${base.source}`,
    "",
    "КАК ЕЮ ПОЛЬЗОВАТЬСЯ. Это твоя опора. Утверждение о норме, сроке или порядке",
    "подкрепляй ссылкой ОТСЮДА — с шифром и статусом: «Приказ 421/пр, действует».",
    "Норму, которой здесь нет, не выдавай за проверенную: скажи, что она вне базы.",
    "",
    "СТАТУС ОБЯЗАТЕЛЕН К УЧЁТУ: ❌ отменён — ссылаться нельзя, и ссылка на",
    "отменённую норму звучит так же убедительно, как на действующую;",
    "⚠️ — проверить редакцию на дату ответа.",
    "",
  ];

  let printed = 0;

  for (const sheet of base.sheets) {
    const significant = sheet.rows.filter((row) => row.code !== "" || row.status !== "");
    if (significant.length === 0) continue;

    lines.push(`— ${sheet.name} —`);

    for (const row of significant) {
      if (printed >= limit) {
        lines.push(`  … и ещё строк базы: ${significant.length - printed} (не показаны)`);
        return lines.join("\n");
      }

      lines.push(
        `  ${row.code || "—"} · ${row.subject}` +
          (row.edition === "" ? "" : ` · ${row.edition}`) +
          (row.key === "" ? "" : ` · ${row.key}`) +
          (row.status === "" ? "" : ` · ${row.status}`),
      );
      printed += 1;
    }

    lines.push("");
  }

  return lines.join("\n");
}
