/**
 * Тесты написаны до реализации. Техзаключение — продукт Денчика (ЧАСТЬ 2
 * промпта `Денчик_ГИП_v9.7.txt`):
 *
 *   ТВОЯ ЗОНА (Такт 0–1 — ВХОД всей цепочки): техзаключение = нормпрофиль
 *   объекта + геометрия от осей + нагрузки/балансы + БЛОК ДОПУЩЕНИЙ
 *
 * И правило Д-7 промпта:
 *
 *   ГРАНИЦА С ЛЮДМИЛОЙ: объём и геометрия — ты, цена и индекс — она.
 *   ВОР без твоего техзаключения = «объёмы без инженерного обоснования».
 */
import { describe, expect, it } from "vitest";

import { buildTechOpinion } from "./tech-opinion.js";
import type { TechOpinionInput } from "./tech-opinion.js";

/** Реверс курганского блока «вынос КС», посчитанный расчётным модулем. */
const КУРГАН: TechOpinionInput = {
  documentPath: "объект/ЭОМ.xlsx",
  groups: [
    {
      table: "ГЭСНм20-03-035",
      baseQuantity: "15.24",
      unit: "км",
      totalQuantity: "198.12",
      totalAmount: "64710398.29",
      flaggedAmount: "23123429.57",
      assumption:
        "базовая длина 15.24 км принята как самое частое значение в группе и НЕ сверена с осями РД",
      flagged: [
        { ordinal: "67", multiple: "4" },
        { ordinal: "64", multiple: "3" },
      ],
    },
  ],
  unjustifiedAmount: "64710398.29",
  hasDesignDocuments: false,
};

describe("техзаключение Денчика", () => {
  const заключение = buildTechOpinion(КУРГАН);

  it("возвращает ВОР-геометрию, а не утверждает объёмы", () => {
    // Промпт: «не выпускаешь ВОР — даёшь техзаключение ДЛЯ ВОР».
    // Продукт Денчика — обоснование объёмов, а не сами объёмы.
    expect(заключение.subject).toBe("вор-геометрия");
  });

  it("ВОЗВРАЩАЕТ ВОР на пересчёт, когда объёмы не обоснованы геометрией", () => {
    // «ВОР без твоего техзаключения = объёмы без инженерного обоснования».
    // Найден блок с кратностями >2 и без РД — обосновать нечем.
    expect(заключение.status).toBe("returned");
  });

  it("называет сумму необоснованного, а не только факт", () => {
    // ТЗ §5.2: влияние в рублях с основанием расчёта.
    expect(заключение.unjustifiedAmount).toBe("64710398.29");
  });

  it("даёт основание каждому флагу — шифр, кратность и деньги", () => {
    const флаг = заключение.findings.find((finding) => finding.statement.includes("кратность"));

    expect(флаг?.basis).toContain("ГЭСНм20-03-035");
    expect(флаг?.basis).toMatch(/база 15\.24/);
  });

  it("выносит допущения отдельным блоком, а не прячет в текст", () => {
    // Правило Д-7 промпта: «БЛОК ДОПУЩЕНИЙ — ОТДЕЛЬНО И ЯВНО. Допущения
    // не прячутся в текст».
    expect(заключение.assumptions.length).toBeGreaterThan(0);
    expect(заключение.assumptions.join(" ")).toContain("НЕ сверена с осями");
  });

  it("отмечает отсутствие рабочей документации как объявленную деградацию", () => {
    // Режим [БЕЗ БАЗЫ] промпта: работать можно, но сказать об этом обязан.
    expect(заключение.degradations).toContain("рабочая документация не разобрана: геометрия от осей недоступна");
  });

  it("готовит блок для Людмилы: что именно принять к ВОР", () => {
    // ЧАСТЬ 7 промпта: «▸ БЛОК ДЛЯ ЛЮДМИЛЫ» с конкретным указанием.
    expect(заключение.handoff.to).toBe("людмила");
    expect(заключение.handoff.payload).toContain("64710398.29");
    expect(заключение.handoff.priority).toBe("critical");
  });

  it("подтверждает ВОР, когда обосновывать нечего: флагов нет", () => {
    const чистая = buildTechOpinion({
      documentPath: "объект/чистая.xlsx",
      groups: [],
      unjustifiedAmount: "0.00",
      hasDesignDocuments: false,
    });

    expect(чистая.status).toBe("approved");
    expect(чистая.unjustifiedAmount).toBe("0.00");
  });

  it("с рабочей документацией не объявляет деградацию геометрии", () => {
    const сРД = buildTechOpinion({ ...КУРГАН, hasDesignDocuments: true });

    expect(сРД.degradations).not.toContain("рабочая документация не разобрана: геометрия от осей недоступна");
  });
});
