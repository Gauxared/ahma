/**
 * ПРАВИЛО ЦВЕТА — ОДНО НА ОБА ПУТИ, И ПРОВЕРЯЕТСЯ ОТДЕЛЬНО ОТ НИХ.
 *
 * Оба замеренных случая («🟢 арифметически принимаем» при четырёх и одной
 * находке уровня critical/high) пришли из КОНВЕЙЕРА, а не из экипажа. Почини мы
 * только экипаж — правка не задела бы ни одного из найденных прогонов. Поэтому
 * правило вынесено в домен и звучит одинаково с обеих сторон.
 */
import { describe, expect, it } from "vitest";

import { raiseVerdictColour } from "./verdict-colour.js";

describe("цвет вердикта по собственным находкам", () => {
  it("критическая находка делает зелёный красным", () => {
    const итог = raiseVerdictColour("🟢 принимаем", ["critical", "low"]);

    expect(итог).toContain("🔴");
    expect(итог).toContain("1 критических");
    expect(итог).toContain("принимаем");
  });

  it("важная находка делает зелёный жёлтым", () => {
    expect(raiseVerdictColour("🟢 принимаем", ["high"])).toContain("🟡");
  });

  it("мелкие находки цвет не двигают: иначе жёлтым станет каждый вердикт", () => {
    expect(raiseVerdictColour("🟢 принимаем", ["medium", "low", "info"])).toBe("🟢 принимаем");
  });

  it("жёлтый и красный не трогаем ни при каких находках", () => {
    expect(raiseVerdictColour("🟡 условно", ["critical"])).toBe("🟡 условно");
    expect(raiseVerdictColour("🔴 отказ", [])).toBe("🔴 отказ");
  });

  it("вердикт без значка остаётся как есть", () => {
    // Значка нет — цвет не заявлен, и подставлять его за агента мы не вправе.
    expect(raiseVerdictColour("вердикт не выдан", ["critical"])).toBe("вердикт не выдан");
  });
});
