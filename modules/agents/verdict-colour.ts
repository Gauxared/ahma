/** Насколько тревожна находка. Слова те же, что в схемах ответа агентов. */
const КРИТИЧНО = "critical";
const ВАЖНО = "high";

export function raiseVerdictColour(verdict: string, severities: readonly string[]): string {
  if (!verdict.includes("🟢")) return verdict;

  const критических = severities.filter((severity) => severity === КРИТИЧНО).length;
  const важных = severities.filter((severity) => severity === ВАЖНО).length;

  if (критических === 0 && важных === 0) return verdict;

  const цвет = критических > 0 ? "🔴" : "🟡";
  const счёт = критических > 0 ? `${критических} критических` : `${важных} важных`;

  return `${verdict.replace("🟢", цвет)} · ЦВЕТ ПОДНЯТ ПО СОБСТВЕННЫМ НАХОДКАМ (${счёт}); агент дал 🟢`;
}
