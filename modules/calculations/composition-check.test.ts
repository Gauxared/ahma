/**
 * Тесты написаны до реализации. Правила Д-3 и Д-4 промпта Денчика.
 *
 *   Д-3. СОСТАВ, А НЕ ТОЛЬКО ЦИФРЫ. Сверять количество объектов/систем/точек:
 *        план vs ТЗ. (ЧТЗ: 5 ИТП на плане против 7 зданий в ТЗ — флаг «5≠7».
 *        Пропавший ИТП = пропавшая мощность и деньги.)
 *
 *   Д-4. ПОЛНОТА СПЕЦИФИКАЦИИ. После расчёта — проверить, все ли позиции
 *        в спецификации. Отсутствие ≠ «не нужно». (ЧТЗ: Ø219, ~160 м,
 *        10–12 млн — выпала из перечня труб.)
 *
 * Оба правила про ОДНО: пропажа не видна в итоге. Смета сходится и без
 * потерянной позиции, потому что её просто нет ни в одном слагаемом.
 */
import { describe, expect, it } from "vitest";

import { checkComposition } from "./composition-check.js";
import type { CountedItem } from "./composition-check.js";

describe("сверка состава (Д-3)", () => {
  it("ловит расхождение числа однотипных единиц между разметками", () => {
    // Курганский аналог курса ЧТЗ «5 ИТП против 7 зданий».
    const отчёт = checkComposition([
      { group: "опоры", source: "смета", count: 127 },
      { group: "опоры", source: "ведомость", count: 134 },
    ]);

    expect(отчёт.mismatches).toHaveLength(1);
    expect(отчёт.mismatches[0]?.group).toBe("опоры");
    expect(отчёт.mismatches[0]?.counts).toEqual({ смета: 127, ведомость: 134 });
  });

  it("называет НЕДОБОР отдельно от избытка: это разные деньги", () => {
    // Недобор — пропавшая мощность и работа; избыток — переплата.
    // Свести их к «расхождению» значит потерять направление ошибки.
    const отчёт = checkComposition([
      { group: "насосы", source: "рд", count: 4 },
      { group: "насосы", source: "смета", count: 3 },
    ]);

    expect(отчёт.mismatches[0]?.kind).toBe("недобор");
    expect(отчёт.mismatches[0]?.missingFrom).toBe("смета");
  });

  it("молчит там, где числа совпадают", () => {
    const отчёт = checkComposition([
      { group: "опоры", source: "смета", count: 127 },
      { group: "опоры", source: "ведомость", count: 127 },
    ]);

    expect(отчёт.mismatches).toEqual([]);
  });

  it("не сверяет группу, встреченную в одной разметке: сравнивать не с чем", () => {
    // Отсутствие второй разметки — это не совпадение и не расхождение.
    // Объявить такую группу сошедшейся значит выдать незнание за проверку.
    const отчёт = checkComposition([{ group: "опоры", source: "смета", count: 127 }]);

    expect(отчёт.mismatches).toEqual([]);
    expect(отчёт.unverifiable).toEqual(["опоры"]);
  });
});

describe("полнота спецификации (Д-4)", () => {
  it("называет позиции, которых нет в смете, но которые есть в спецификации", () => {
    // ЧТЗ: Ø219 на 160 м и 10–12 млн выпала из перечня труб. Смета при этом
    // сошлась: потерянного слагаемого нет ни в одной сумме.
    const отчёт = checkComposition([
      { group: "труба Ø159", source: "спецификация", count: 1 },
      { group: "труба Ø159", source: "смета", count: 1 },
      { group: "труба Ø219", source: "спецификация", count: 1 },
    ]);

    expect(отчёт.unverifiable).toContain("труба Ø219");
  });

  it("не путает «нет позиции» с «нет потребности»", () => {
    // Прямая цитата Д-4: «Отсутствие ≠ „не нужно"». Поэтому отсутствующее
    // попадает в отчёт как требующее ответа, а не отбрасывается.
    const отчёт = checkComposition([{ group: "труба Ø219", source: "спецификация", count: 1 }]);

    expect(отчёт.unverifiable).toEqual(["труба Ø219"]);
    expect(отчёт.mismatches).toEqual([]);
  });
});
