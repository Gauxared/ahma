/**
 * Тесты написаны до реализации. Себестоимость по элементам и ₽/м² — ТЗ §6.4,
 * роадмап M4: «себестоимость по элементам и ₽/м²».
 *
 * ДВА РАЗНЫХ ВОПРОСА ПОД ОДНИМ ЗАГОЛОВКОМ
 *
 * «По элементам» отвечает на вопрос ИЗ ЧЕГО сложилась стоимость: материалы,
 * оплата труда, эксплуатация машин, накладные, сметная прибыль. «₽/м²» — на
 * вопрос ДОРОГО ЛИ, и он требует площади, которой в смете нет: площадь берётся
 * из паспорта объекта. Поэтому это две формулы, а не одна с двумя выходами.
 *
 * ГЛАВНАЯ ЛОВУШКА — ДОЛЯ ОТ ЧЕГО
 *
 * Смета почти никогда не разложена по элементам полностью: оборудование,
 * прочие затраты и НДС в разбивку не попадают. Если считать долю элемента от
 * ИТОГА сметы, доли не сложатся в единицу, и разбивка будет выглядеть неполной
 * без объяснения. Если считать от суммы объявленных элементов — сложатся, но
 * непокрытый остаток исчезнет из виду.
 *
 * Верно и то и другое одновременно: доля считается от суммы ОБЪЯВЛЕННЫХ
 * элементов, а непокрытый остаток называется отдельной величиной. Прятать его
 * в знаменатель — способ сделать неизвестное нулём (§9).
 */
import { describe, expect, it } from "vitest";

import { costPerSqm, costStructure } from "./cost-structure.js";

const ЭЛЕМЕНТЫ = [
  { element: "материалы" as const, amount: "50000000.00" },
  { element: "оплата труда" as const, amount: "20000000.00" },
  { element: "эксплуатация машин" as const, amount: "10000000.00" },
  { element: "накладные расходы" as const, amount: "15000000.00" },
  { element: "сметная прибыль" as const, amount: "5000000.00" },
];

describe("себестоимость по элементам затрат", () => {
  it("суммирует элементы и считает долю каждого", () => {
    const структура = costStructure({ elements: ЭЛЕМЕНТЫ, documentTotal: "100000000.00" });

    expect(структура.declaredTotal).toBe("100000000.00");
    expect(структура.items.find((item) => item.element === "материалы")?.share).toBe("0.5000");
  });

  it("доли объявленных элементов складываются в единицу", () => {
    const структура = costStructure({ elements: ЭЛЕМЕНТЫ, documentTotal: "100000000.00" });

    const сумма = структура.items.reduce((accumulator, item) => accumulator + Number(item.share), 0);

    expect(сумма).toBeCloseTo(1, 6);
  });

  it("НАЗЫВАЕТ непокрытый остаток, а не прячет его в знаменатель", () => {
    // Итог сметы 120 млн, по элементам разложено 100 млн: 20 млн — оборудование
    // и прочие затраты. Это не ошибка разбивки, но и не ноль.
    const структура = costStructure({ elements: ЭЛЕМЕНТЫ, documentTotal: "120000000.00" });

    expect(структура.uncovered).toBe("20000000.00");
    expect(структура.complete).toBe(false);
    expect(структура.note).toContain("не разложен");
  });

  it("признаёт разбивку полной, когда остатка нет", () => {
    const структура = costStructure({ elements: ЭЛЕМЕНТЫ, documentTotal: "100000000.00" });

    expect(структура.uncovered).toBe("0.00");
    expect(структура.complete).toBe(true);
  });

  it("не считает разбивку полной при отрицательном остатке", () => {
    // Сумма элементов больше итога — это расхождение источника, а не полнота.
    const структура = costStructure({ elements: ЭЛЕМЕНТЫ, documentTotal: "90000000.00" });

    expect(структура.complete).toBe(false);
    expect(структура.note).toContain("превышает");
  });

  it("отказывается считать доли без единого элемента", () => {
    const структура = costStructure({ elements: [], documentTotal: "100000000.00" });

    expect(структура.items).toEqual([]);
    expect(структура.note).toContain("разбивка отсутствует");
  });

  it("складывает повторы одного элемента, а не теряет их", () => {
    // Разбивка по нескольким сметам приносит «материалы» несколько раз.
    const структура = costStructure({
      elements: [
        { element: "материалы", amount: "30000000.00" },
        { element: "материалы", amount: "20000000.00" },
      ],
      documentTotal: "50000000.00",
    });

    expect(структура.items).toHaveLength(1);
    expect(структура.items[0]?.amount).toBe("50000000.00");
  });

  it("несёт след формулы: число объясняется без доступа к коду", () => {
    const структура = costStructure({ elements: ЭЛЕМЕНТЫ, documentTotal: "100000000.00" });

    expect(структура.trace.formulaId).toBe("calculation.cost-structure");
    expect(Object.keys(структура.trace.inputs)).toContain("материалы");
  });
});

describe("стоимость квадратного метра", () => {
  it("делит стоимость на площадь", () => {
    const показатель = costPerSqm({ cost: "100000000.00", area: "5000.00" });

    expect(показатель.value).toBe("20000.00");
    expect(показатель.computable).toBe(true);
  });

  it("НЕ считает показатель при нулевой площади", () => {
    // Деление на ноль даёт бесконечность, а не «очень дорого». Показатель
    // объявляется невычислимым (§9), и это видно в выгрузке.
    const показатель = costPerSqm({ cost: "100000000.00", area: "0.00" });

    expect(показатель.computable).toBe(false);
    expect(показатель.value).toBeUndefined();
    expect(показатель.reason).toContain("площадь");
  });

  it("НЕ подставляет площадь, которой нет", () => {
    const показатель = costPerSqm({ cost: "100000000.00" });

    expect(показатель.computable).toBe(false);
    expect(показатель.reason).toContain("не указана");
  });

  it("отказывается считать при отрицательной площади", () => {
    const показатель = costPerSqm({ cost: "100000000.00", area: "-1.00" });

    expect(показатель.computable).toBe(false);
  });

  it("несёт след формулы, когда показатель вычислен", () => {
    const показатель = costPerSqm({ cost: "100000000.00", area: "5000.00" });

    expect(показатель.trace?.formulaId).toBe("calculation.cost-per-sqm");
    expect(показатель.trace?.inputs.area).toBe("5000.00");
  });

  it("НЕ несёт следа, когда показатель не вычислен", () => {
    // След — объяснение полученного числа. Следа несуществующего числа быть
    // не может: он утверждал бы, что расчёт состоялся.
    const показатель = costPerSqm({ cost: "100000000.00" });

    expect(показатель.trace).toBeUndefined();
  });
});
