/**
 * Тесты написаны до реализации. Обратный расчёт срока — ТЗ §6.4, роадмап M4:
 * «крайний срок заказа, обратный расчёт срока».
 *
 * ЧЕМ ОТЛИЧАЕТСЯ ОТ ПРЯМОГО РАСЧЁТА
 *
 * Прямой отвечает «когда приедет, если заказать сегодня». Обратный — «когда
 * заказывать, чтобы успеть к дате потребности», и это другой вопрос: у него
 * ответ бывает В ПРОШЛОМ. Отрицательный запас — не ошибка расчёта, а найденный
 * срыв, и он обязан дойти до человека как находка.
 *
 * ЗАПАС СЧИТАЕТСЯ ОТ СЕГОДНЯ, А НЕ ОТ НАЧАЛА ЦЕПОЧКИ
 *
 * Вопрос звучит «сколько у нас ещё есть», а не «сколько было бы, если бы мы
 * начали вовремя». Поэтому дата отсчёта приходит аргументом: сегодняшний день
 * не берётся из системных часов внутри расчёта — иначе тот же прогон завтра
 * даст другой результат и перестанет быть воспроизводимым.
 */
import { describe, expect, it } from "vitest";

import { reverseDeadline } from "./deadline-reverse.js";

const ЭТАПЫ = [
  { stage: "согласование заявки", days: 5 },
  { stage: "изготовление", days: 45 },
  { stage: "доставка", days: 14 },
  { stage: "приёмка на объекте", days: 3 },
];

describe("обратный расчёт срока заказа", () => {
  it("считает дату заказа назад от даты потребности", () => {
    // 5 + 45 + 14 + 3 = 67 дней до 01.09.2026 → 26.06.2026.
    const итог = reverseDeadline({ neededBy: "2026-09-01", stages: ЭТАПЫ, today: "2026-05-01" });

    expect(итог.leadDays).toBe(67);
    expect(итог.orderBy).toBe("2026-06-26");
  });

  it("считает запас от СЕГОДНЯ до крайней даты заказа", () => {
    const итог = reverseDeadline({ neededBy: "2026-09-01", stages: ЭТАПЫ, today: "2026-05-01" });

    expect(итог.slackDays).toBe(56);
    expect(итог.status).toBe("в срок");
  });

  it("НАХОДИТ срыв, когда крайняя дата заказа уже прошла", () => {
    // Ответ в прошлом — не ошибка расчёта, а находка: заказывать надо было
    // раньше, и об этом обязан узнать человек.
    const итог = reverseDeadline({ neededBy: "2026-07-01", stages: ЭТАПЫ, today: "2026-06-01" });

    expect(итог.slackDays).toBeLessThan(0);
    expect(итог.status).toBe("срыв");
    expect(итог.note).toContain("просрочен");
  });

  it("объявляет крайний срок сегодняшним днём отдельным статусом", () => {
    // Запас ноль — не «в срок с запасом» и не «срыв»: заказывать надо сегодня.
    const итог = reverseDeadline({ neededBy: "2026-09-01", stages: ЭТАПЫ, today: "2026-06-26" });

    expect(итог.slackDays).toBe(0);
    expect(итог.status).toBe("крайний день");
  });

  it("называет самый долгий этап: сокращать имеет смысл его", () => {
    const итог = reverseDeadline({ neededBy: "2026-09-01", stages: ЭТАПЫ, today: "2026-05-01" });

    expect(итог.longestStage?.stage).toBe("изготовление");
    expect(итог.longestStage?.days).toBe(45);
  });

  it("отказывается считать без этапов, а не выдаёт дату потребности за дату заказа", () => {
    // Пустая цепочка дала бы «заказывать в день потребности» — арифметически
    // верно и практически ложно (§9).
    const итог = reverseDeadline({ neededBy: "2026-09-01", stages: [], today: "2026-05-01" });

    expect(итог.computable).toBe(false);
    expect(итог.note).toContain("этапы не заданы");
  });

  it("отвергает отрицательную длительность этапа", () => {
    expect(() =>
      reverseDeadline({
        neededBy: "2026-09-01",
        stages: [{ stage: "изготовление", days: -5 }],
        today: "2026-05-01",
      }),
    ).toThrow(/длительность/i);
  });

  it("несёт след с каждым этапом", () => {
    const итог = reverseDeadline({ neededBy: "2026-09-01", stages: ЭТАПЫ, today: "2026-05-01" });

    expect(итог.trace?.formulaId).toBe("calculation.deadline-reverse");
    expect(итог.trace?.inputs["изготовление"]).toBe("45");
  });

  it("не зависит от системных часов: тот же вход даёт тот же ответ", () => {
    // Дата отсчёта приходит аргументом. Возьми расчёт её из системных часов,
    // и вчерашний прогон перестал бы воспроизводиться.
    const первый = reverseDeadline({ neededBy: "2026-09-01", stages: ЭТАПЫ, today: "2026-05-01" });
    const второй = reverseDeadline({ neededBy: "2026-09-01", stages: ЭТАПЫ, today: "2026-05-01" });

    expect(первый).toEqual(второй);
  });
});
