/**
 * Тесты написаны до реализации. Классификация отклонений — ТЗ §5.2:
 *
 *   «Классификация выявленных отклонений: рыночное движение цен, особенность
 *    технического решения, ошибка в объёмах, завышение расценки, двойной учёт»
 *
 * ЗАЧЕМ КЛАССИФИКАЦИЯ, А НЕ ПРОСТО ЧИСЛО
 *
 * «Дороже оценки на 3 млн» не говорит, что делать. Пять категорий ТЗ — это
 * пять РАЗНЫХ следующих шагов:
 *
 *   рыночное движение   → обновить опорную базу, спорить не о чем;
 *   техническое решение → проверить, нужно ли оно; спор с проектировщиком;
 *   ошибка в объёмах    → вернуть подрядчику пересчёт, спор арифметический;
 *   завышение расценки  → переговоры о цене;
 *   двойной учёт        → снять позицию целиком, спор о факте.
 *
 * Отклонение без категории — это работа, переложенная обратно на человека.
 *
 * КАТЕГОРИЯ НЕ УГАДЫВАЕТСЯ, А ВЫВОДИТСЯ ИЗ ПРИЗНАКОВ
 *
 * Классификатор смотрит на то, что ИЗМЕРЕНО: совпадает ли объём, есть ли
 * повтор позиции, двигалась ли база, отличается ли состав работ. Где признаков
 * не хватает, категория не назначается — «не классифицировано» полноправный
 * исход, как и «не сопоставлено» в §5.2.
 */
import { describe, expect, it } from "vitest";

import { classifyDeviation } from "./deviation-class.js";

const БАЗА = {
  itemId: "щебень-40-70",
  estimateUnitPrice: "2500.00",
  offerUnitPrice: "2500.00",
  estimateQuantity: "1110",
  offerQuantity: "1110",
};

describe("пять категорий §5.2", () => {
  it("ОШИБКА В ОБЪЁМАХ, когда цена совпала, а объём разошёлся", () => {
    // Самая проверяемая категория: цена та же, объём другой. Спор
    // арифметический, а не переговорный.
    const итог = classifyDeviation({ ...БАЗА, offerQuantity: "2220" });

    expect(итог.category).toBe("ошибка в объёмах");
    expect(итог.impact).toBe("2775000.00");
  });

  it("ЗАВЫШЕНИЕ РАСЦЕНКИ, когда объём совпал, а цена выше", () => {
    const итог = classifyDeviation({ ...БАЗА, offerUnitPrice: "3500.00" });

    expect(итог.category).toBe("завышение расценки");
    expect(итог.impact).toBe("1110000.00");
  });

  it("РЫНОЧНОЕ ДВИЖЕНИЕ, когда база устарела и цена выросла в её сторону", () => {
    // Отличие от завышения — во внешнем свидетельстве: индекс за период
    // объясняет рост. Без него это завышение, а не рынок.
    const итог = classifyDeviation({
      ...БАЗА,
      offerUnitPrice: "2750.00",
      marketIndex: "1.10",
    });

    expect(итог.category).toBe("рыночное движение цен");
  });

  it("НЕ списывает на рынок рост, которого индекс не объясняет", () => {
    // Индекс +10%, а цена выше на 40%. Списать всё на рынок значит закрыть
    // глаза на тридцать процентов.
    const итог = classifyDeviation({
      ...БАЗА,
      offerUnitPrice: "3500.00",
      marketIndex: "1.10",
    });

    expect(итог.category).toBe("завышение расценки");
  });

  it("ДВОЙНОЙ УЧЁТ, когда та же работа встречается в предложении дважды", () => {
    // Спор здесь о факте, а не о цене: позиция снимается целиком.
    const итог = classifyDeviation({ ...БАЗА, duplicateOf: "поз. 1.7" });

    expect(итог.category).toBe("двойной учёт");
    expect(итог.remedy).toContain("снять");
  });

  it("двойной учёт ПЕРЕВЕШИВАЕТ прочие признаки", () => {
    // Позиция, учтённая дважды, не становится «завышением расценки» оттого,
    // что и цена в ней завышена: сначала снимают дубль.
    const итог = classifyDeviation({
      ...БАЗА,
      offerUnitPrice: "3500.00",
      duplicateOf: "поз. 1.7",
    });

    expect(итог.category).toBe("двойной учёт");
  });

  it("ОСОБЕННОСТЬ ТЕХНИЧЕСКОГО РЕШЕНИЯ, когда состав работ объявлен иным", () => {
    const итог = classifyDeviation({
      ...БАЗА,
      offerUnitPrice: "3500.00",
      compositionDiffers: "в предложении бетон B30F150 вместо B25F100",
    });

    expect(итог.category).toBe("особенность технического решения");
    expect(итог.basis).toContain("B30F150");
  });
});

describe("границы классификации", () => {
  it("НЕ классифицирует, когда отклонения нет", () => {
    const итог = classifyDeviation(БАЗА);

    expect(итог.category).toBe("отклонения нет");
    expect(итог.impact).toBe("0.00");
  });

  it("НЕ классифицирует, когда признаков не хватает", () => {
    // Разошлись и цена, и объём, и нет ни индекса, ни состава: по таким данным
    // категорию можно только угадать. Угаданная категория хуже отсутствующей —
    // по ней пойдут в переговоры.
    const итог = classifyDeviation({
      ...БАЗА,
      offerUnitPrice: "3500.00",
      offerQuantity: "2220",
    });

    expect(итог.category).toBe("не классифицировано");
    expect(итог.basis).toContain("и цена, и объём");
  });

  it("считает сумму влияния ВСЕГДА, даже без категории (§5.2)", () => {
    // «Выделение аномалий с указанием суммы влияния в рублях» — требование
    // отдельное от классификации. Сумма известна и тогда, когда причина нет.
    const итог = classifyDeviation({
      ...БАЗА,
      offerUnitPrice: "3500.00",
      offerQuantity: "2220",
    });

    expect(итог.impact).toBe("4995000.00");
  });

  it("сохраняет ЗНАК влияния: экономия — не то же, что перерасход", () => {
    const итог = classifyDeviation({ ...БАЗА, offerUnitPrice: "2000.00" });

    expect(Number(итог.impact)).toBeLessThan(0);
    expect(итог.category).toBe("предложение ниже оценки");
  });

  it("даёт основание и путь урегулирования на каждую категорию", () => {
    // Ровно то, чего требует реестр нарушений §10: без основания нарушение
    // нельзя предъявить, без пути урегулирования с ним нечего делать.
    const случаи = [
      { ...БАЗА, offerQuantity: "2220" },
      { ...БАЗА, offerUnitPrice: "3500.00" },
      { ...БАЗА, duplicateOf: "поз. 1.7" },
      { ...БАЗА, offerUnitPrice: "2750.00", marketIndex: "1.10" },
      { ...БАЗА, offerUnitPrice: "3500.00", compositionDiffers: "другой бетон" },
    ];

    for (const случай of случаи) {
      const итог = classifyDeviation(случай);

      expect(итог.basis.length).toBeGreaterThan(10);
      expect(итог.remedy.length).toBeGreaterThan(10);
    }
  });
});
