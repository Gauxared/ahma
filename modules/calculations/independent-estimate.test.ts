/**
 * Тесты написаны до реализации. Расчётно-аналитическая оценка — ТЗ §5.2,
 * роадмап M5:
 *
 *   «Независимая оценка: обучающий массив + опорная база + история АПРИ.
 *    ТЕСТ, КОТОРЫЙ ДОКАЗЫВАЕТ, ЧТО ЦЕНЫ ПОДРЯДЧИКОВ **НЕ** ИСПОЛЬЗУЮТСЯ КАК
 *    ЦЕЛЬ ОЦЕНКИ.»
 *
 * ЗАЧЕМ ЭТО ТРЕБОВАНИЕ СУЩЕСТВУЕТ
 *
 * ТЗ §5.2: «Система формирует собственную оценку стоимости по объекту и по
 * каждой значимой позиции НЕЗАВИСИМО от полученных предложений подрядчиков».
 *
 * Оценка, подсмотревшая в предложения, всегда окажется рядом с ними — и тем
 * самым подтвердит любую цену, включая завышенную. Она будет выглядеть
 * работающей ровно до того дня, когда все подрядчики сговорятся или ошибутся
 * одинаково. Именно тогда независимая оценка и нужна, и именно тогда её не
 * будет.
 *
 * ПОЧЕМУ НЕЗАВИСИМОСТЬ ДОКАЗЫВАЕТСЯ ТЕСТОМ, А НЕ КОММЕНТАРИЕМ
 *
 * Утечка цен в оценку — правка на одну строку, и выглядит она как улучшение
 * точности: «давайте учтём рынок». Комментарий такую правку не остановит.
 * Тест, меняющий ТОЛЬКО цены подрядчиков и требующий неизменной оценки,
 * останавливает.
 */
import { describe, expect, it } from "vitest";

import { estimateIndependently } from "./independent-estimate.js";
import type { PriceObservation } from "./independent-estimate.js";

/**
 * Опорная база: наблюдения по сопоставимым объектам, БЕЗ участия подрядчиков.
 *
 * Три наблюдения ОДНОГО периода — чтобы проверка медианы не смешивалась с
 * проверкой предпочтения периода. Для второй есть отдельный тест.
 */
const ОПОРНАЯ_БАЗА: readonly PriceObservation[] = [
  { itemId: "щебень-40-70", unitPrice: "2400.00", region: "УрФО", period: "2026-Q2", source: "опорная база" },
  { itemId: "щебень-40-70", unitPrice: "2600.00", region: "УрФО", period: "2026-Q2", source: "опорная база" },
  { itemId: "щебень-40-70", unitPrice: "2500.00", region: "УрФО", period: "2026-Q2", source: "история АПРИ" },
];

describe("независимость оценки от предложений подрядчиков", () => {
  it("НЕ меняется, когда меняются ВСЕ цены подрядчиков", () => {
    // Главный тест раздела. Меняется только то, что подрядчики предложили;
    // всё остальное — то же самое. Оценка обязана совпасть до копейки.
    const дёшево = estimateIndependently({
      itemId: "щебень-40-70",
      quantity: "1110",
      observations: ОПОРНАЯ_БАЗА,
      region: "УрФО",
      period: "2026-Q2",
      contractorOffers: ["1000.00", "1100.00", "1200.00"],
    });

    const дорого = estimateIndependently({
      itemId: "щебень-40-70",
      quantity: "1110",
      observations: ОПОРНАЯ_БАЗА,
      region: "УрФО",
      period: "2026-Q2",
      contractorOffers: ["9000.00", "9500.00", "10000.00"],
    });

    expect(дёшево.unitPrice).toBe(дорого.unitPrice);
    expect(дёшево.total).toBe(дорого.total);
  });

  it("НЕ меняется, когда предложений нет вовсе", () => {
    // Оценка существует до и без предложений: она — то, с чем их СРАВНИВАЮТ.
    const без = estimateIndependently({
      itemId: "щебень-40-70",
      quantity: "1110",
      observations: ОПОРНАЯ_БАЗА,
      region: "УрФО",
      period: "2026-Q2",
    });

    const с = estimateIndependently({
      itemId: "щебень-40-70",
      quantity: "1110",
      observations: ОПОРНАЯ_БАЗА,
      region: "УрФО",
      period: "2026-Q2",
      contractorOffers: ["9000.00"],
    });

    expect(без.unitPrice).toBe(с.unitPrice);
  });

  it("ОТКАЗЫВАЕТСЯ считать наблюдение, пришедшее от подрядчика, опорным", () => {
    // Попытка «обогатить» базу предложениями — самый естественный способ
    // потерять независимость, и выглядит он как улучшение полноты.
    const заражённая: readonly PriceObservation[] = [
      ...ОПОРНАЯ_БАЗА,
      {
        itemId: "щебень-40-70",
        unitPrice: "9000.00",
        region: "УрФО",
        period: "2026-Q2",
        source: "предложение подрядчика",
      },
    ];

    expect(() =>
      estimateIndependently({
        itemId: "щебень-40-70",
        quantity: "1110",
        observations: заражённая,
        region: "УрФО",
        period: "2026-Q2",
      }),
    ).toThrow(/подрядчик/i);
  });

  it("называет источники, на которых построена оценка (§5.2)", () => {
    // ТЗ прямо требует: «указание источников исходных числовых значений, на
    // которых построена оценка».
    const оценка = estimateIndependently({
      itemId: "щебень-40-70",
      quantity: "1110",
      observations: ОПОРНАЯ_БАЗА,
      region: "УрФО",
      period: "2026-Q2",
    });

    expect(оценка.sources).toContain("опорная база");
    expect(оценка.sources).toContain("история АПРИ");
  });
});

describe("построение оценки", () => {
  it("берёт медиану по сопоставимым наблюдениям", () => {
    // 2400 · 2500 · 2600 → медиана 2500.
    const оценка = estimateIndependently({
      itemId: "щебень-40-70",
      quantity: "1110",
      observations: ОПОРНАЯ_БАЗА,
      region: "УрФО",
      period: "2026-Q2",
    });

    expect(оценка.unitPrice).toBe("2500.00");
    expect(оценка.total).toBe("2775000.00");
  });

  it("даёт рекомендованный ДИАПАЗОН, а не одно число", () => {
    // §5.2 требует «рекомендованный диапазон цены и целевую цену». Одно число
    // без диапазона выглядит точнее, чем есть, и переговоры по нему ведут как
    // по факту.
    const оценка = estimateIndependently({
      itemId: "щебень-40-70",
      quantity: "1110",
      observations: ОПОРНАЯ_БАЗА,
      region: "УрФО",
      period: "2026-Q2",
    });

    expect(оценка.range.low).toBe("2400.00");
    expect(оценка.range.high).toBe("2600.00");
  });

  it("НЕ смешивает регионы", () => {
    // Цена щебня в УрФО и в Приморье — разные величины. §5.2: массив приведён
    // к сопоставимым единицам «по видам работ, конструктивам, РЕГИОНАМ и
    // периодам».
    const оценка = estimateIndependently({
      itemId: "щебень-40-70",
      quantity: "1",
      observations: [
        ...ОПОРНАЯ_БАЗА,
        { itemId: "щебень-40-70", unitPrice: "9900.00", region: "Приморье", period: "2026-Q2", source: "опорная база" },
      ],
      region: "УрФО",
      period: "2026-Q2",
    });

    expect(оценка.unitPrice).toBe("2500.00");
  });

  it("НЕ выдаёт оценку без наблюдений", () => {
    // Оценка «ноль рублей» или «средняя по всем позициям» — выдумка, которая
    // пойдёт в переговоры как факт (§9).
    const оценка = estimateIndependently({
      itemId: "неизвестная-позиция",
      quantity: "10",
      observations: ОПОРНАЯ_БАЗА,
      region: "УрФО",
      period: "2026-Q2",
    });

    expect(оценка.computable).toBe(false);
    expect(оценка.unitPrice).toBeUndefined();
    expect(оценка.reason).toContain("наблюден");
  });

  it("НЕ выдаёт оценку по одному наблюдению без пометки", () => {
    // Одно наблюдение — это цена одной сделки, а не оценка рынка. Выдать её
    // без оговорки значит назвать частный случай нормой.
    const оценка = estimateIndependently({
      itemId: "щебень-40-70",
      quantity: "1",
      observations: [ОПОРНАЯ_БАЗА[0]!],
      region: "УрФО",
      period: "2026-Q2",
    });

    expect(оценка.computable).toBe(true);
    expect(оценка.thin).toBe(true);
    expect(оценка.note).toContain("одно наблюдение");
  });

  it("ПРЕДПОЧИТАЕТ наблюдения своего периода прошлым", () => {
    // Цена прошлого квартала — не цена текущего. Смешать их значит усреднить
    // рынок по времени и получить число, не относящееся ни к одному моменту.
    const оценка = estimateIndependently({
      itemId: "щебень-40-70",
      quantity: "1",
      observations: [
        { itemId: "щебень-40-70", unitPrice: "1000.00", region: "УрФО", period: "2025-Q1", source: "опорная база" },
        { itemId: "щебень-40-70", unitPrice: "2500.00", region: "УрФО", period: "2026-Q2", source: "опорная база" },
      ],
      region: "УрФО",
      period: "2026-Q2",
    });

    expect(оценка.unitPrice).toBe("2500.00");
  });

  it("не отбрасывает соседние периоды, когда своих наблюдений нет", () => {
    // Полное отбрасывание оставило бы позицию без оценки при первом же
    // расширении горизонта. Соседние учитываются С ПОМЕТКОЙ: цифра есть, и
    // видно, что она заимствована.
    const оценка = estimateIndependently({
      itemId: "щебень-40-70",
      quantity: "1",
      observations: ОПОРНАЯ_БАЗА,
      region: "УрФО",
      period: "2026-Q3",
    });

    expect(оценка.computable).toBe(true);
    expect(оценка.note).toContain("другого периода");
  });

  it("несёт след формулы", () => {
    const оценка = estimateIndependently({
      itemId: "щебень-40-70",
      quantity: "1110",
      observations: ОПОРНАЯ_БАЗА,
      region: "УрФО",
      period: "2026-Q2",
    });

    expect(оценка.trace?.formulaId).toBe("calculation.independent-estimate");
  });
});

describe("граница между офертой и открытым прайсом", () => {
  it("ПРИНИМАЕТ опубликованный прайс завода как рыночное наблюдение", () => {
    // §5.2 запрещает строить оценку на «полученных предложениях подрядчиков» —
    // то есть на офертах по ЭТОМУ объекту. Опубликованный прайс завода
    // запретом не покрыт: это рыночное наблюдение, доступное кому угодно и
    // существующее независимо от нашего тендера.
    //
    // Запретить и его значило бы остаться без опорной базы вовсе и не выдать
    // оценку ни по одной позиции.
    const оценка = estimateIndependently({
      itemId: "арматура-а500",
      quantity: "18",
      observations: [
        { itemId: "арматура-а500", unitPrice: "61500.00", region: "УрФО", period: "2026-Q2", source: "открытый прайс ЕВРАЗ Маркет" },
        { itemId: "арматура-а500", unitPrice: "62600.00", region: "УрФО", period: "2026-Q2", source: "открытый прайс Промметалл" },
        { itemId: "арматура-а500", unitPrice: "50400.00", region: "УрФО", period: "2026-Q2", source: "открытый прайс Металлобаза-МСК" },
      ],
      region: "УрФО",
      period: "2026-Q2",
    });

    expect(оценка.computable).toBe(true);
    expect(оценка.unitPrice).toBe("61500.00");
  });

  it("ОТВЕРГАЕТ тендерное предложение, даже названное иначе", () => {
    // Оферта, поданная по этому объекту, остаётся офертой под любым названием.
    for (const источник of ["предложение подрядчика", "оферта ООО Ромашка", "тендерное предложение №4"]) {
      expect(() =>
        estimateIndependently({
          itemId: "арматура-а500",
          quantity: "18",
          observations: [
            { itemId: "арматура-а500", unitPrice: "99000.00", region: "УрФО", period: "2026-Q2", source: источник },
          ],
          region: "УрФО",
          period: "2026-Q2",
        }),
      ).toThrow(/независим/i);
    }
  });
});
