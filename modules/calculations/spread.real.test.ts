/**
 * Гейт M5 на НАСТОЯЩЕМ закупочном фоне объекта.
 *
 * Роадмап M5: «на реальном наборе ≥3 КП — разброс, аномалии, оценка,
 * рекомендованный диапазон».
 *
 * Источник — `Закупочный_фон_Рыба_Березовский_25-2-7-КР.xlsx`, лист
 * «Пул_поставщиков»: пять групп материалов, в каждой три-четыре поставщика с
 * ценами, собранными из открытых прайсов. Это настоящие цены настоящих заводов
 * Екатеринбурга и Берёзовского, а не выдуманный набор.
 *
 * ПОЧЕМУ ЭТО ЛУЧШЕ СИНТЕТИКИ
 *
 * Синтетический набор проверяет арифметику. Настоящий проверяет то, что
 * арифметикой не задаётся:
 *
 *  · часть поставщиков даёт «по запросу» вместо цены — и это НЕСОПОСТАВЛЕННЫЕ
 *    по §5.2, которые в расчёт разброса не входят;
 *  · часть даёт диапазон («5 150–5 300 ₽/м³») вместо числа;
 *  · часть даёт цену «от» — то есть нижнюю границу, а не цену;
 *  · в группе сэндвич-панелей ЦСКЗ даёт 1 750 ₽/м² против 3 886 и 3 987 у
 *    остальных — разница в 2,2 раза, и это либо другой товар, либо находка.
 *
 * ПАРСЕР ЗДЕСЬ НАМЕРЕННО НЕ ПИШЕТСЯ
 *
 * Разбор этого листа — разбор ОДНОЙ вёрстки, а не формата. Значения вынесены в
 * тест как данные с указанием строки источника: так видно, что взято, и
 * поддельные числа не спрячутся за кодом разбора.
 */
import { describe, expect, it } from "vitest";

import { spread } from "./spread.js";

/**
 * Группа сэндвич-панелей PIR 150. Строки 32–35 листа «Пул_поставщиков».
 *
 * «По запросу» у АМК-Групп — это отсутствие цены, а не ноль.
 */
const СЭНДВИЧ = {
  offers: [
    { source: "ЦСКЗ", amount: "1750.00" },
    { source: "Русбилдинг (РСБ96)", amount: "3886.00" },
    { source: "MCG", amount: "3987.00" },
  ],
  unmatched: [{ source: "АМК-Групп", reason: "цена «по запросу»: предложение не названо" }],
};

/** Арматура А400/А500С. Строки 18–21. */
const АРМАТУРА = {
  offers: [
    { source: "ЕВРАЗ Маркет", amount: "61500.00" },
    { source: "ПКП «Промметалл»", amount: "62600.00" },
    { source: "Металлобаза-МСК", amount: "50400.00" },
  ],
  unmatched: [{ source: "Металлобаза (СПК)", reason: "прайс от 05.06.26 без цены в источнике" }],
};

/** Бетон В20 F150. Строки 11–14. */
const БЕТОН = {
  offers: [
    { source: "Бетон АМ", amount: "5225.00" },
    { source: "БЕТОНГРУПП", amount: "5010.00" },
    { source: "БСК", amount: "3600.00" },
  ],
  unmatched: [{ source: "ЗБИ-Монолит", reason: "цена «по запросу»" }],
};

describe("гейт M5: разброс на настоящем закупочном фоне", () => {
  it("считает разброс по трём предложениям в каждой группе", () => {
    for (const группа of [СЭНДВИЧ, АРМАТУРА, БЕТОН]) {
      const итог = spread(группа);

      expect(итог.computable).toBe(true);
      expect(итог.comparable).toBe(3);
    }
  });

  it("НЕ включает «по запросу» в расчёт (§5.2)", () => {
    // Поставщик, не назвавший цену, — не поставщик с ценой ноль. Включить его
    // значит обрушить минимум и раздуть разброс.
    const итог = spread(СЭНДВИЧ);

    expect(итог.min).toBe("1750.00");
    expect(итог.unmatched).toHaveLength(1);
    expect(итог.note).toContain("АМК-Групп");
  });

  it("НАХОДИТ аномалию в сэндвич-панелях", () => {
    // ЦСКЗ даёт 1 750 ₽/м² против 3 886 и 3 987 у остальных. Это либо другой
    // товар (толщина, замок, покрытие), либо находка — и в обоих случаях
    // человек обязан посмотреть, а не получить усреднённое число.
    const итог = spread(СЭНДВИЧ);

    expect(итог.anomalies).toHaveLength(1);
    expect(итог.anomalies[0]?.source).toBe("ЦСКЗ");
  });

  it("даёт медиану, устойчивую к этой аномалии", () => {
    // Среднее по 1750 · 3886 · 3987 равно 3208 — числу, которого не предлагал
    // никто. Медиана 3886 — реально предложенная цена.
    const итог = spread(СЭНДВИЧ);

    expect(итог.median).toBe("3886.00");
  });

  it("даёт рекомендованный диапазон по каждой группе", () => {
    const арматура = spread(АРМАТУРА);

    expect(арматура.min).toBe("50400.00");
    expect(арматура.max).toBe("62600.00");
    expect(арматура.median).toBe("61500.00");
  });

  it("считает кратность разброса, а не только границы", () => {
    // По арматуре 62 600 / 50 400 = 1,24 — рынок сходится. По сэндвичу
    // 3 987 / 1 750 = 2,28 — сравнивать нечего, пока не выяснят, тот ли товар.
    expect(spread(АРМАТУРА).ratio).toBe("1.2421");
    expect(spread(СЭНДВИЧ).ratio).toBe("2.2783");
  });

  it("НАЗЫВАЕТ каждого несопоставленного поставщика поимённо", () => {
    // Иначе «трое из четырёх» читается как «четверо», и решение принимается
    // по неполной картине, выглядящей полной.
    for (const группа of [СЭНДВИЧ, АРМАТУРА, БЕТОН]) {
      const итог = spread(группа);

      for (const item of группа.unmatched) {
        expect(итог.note).toContain(item.source);
      }
    }
  });
});
