/**
 * Тесты написаны до реализации. Отклонение и разброс — ТЗ §6.4 и §5.2,
 * роадмап M4: «отклонение, разброс/медиана».
 *
 * ГЛАВНОЕ ТРЕБОВАНИЕ §5.2
 *
 *   «`не сопоставлено` — полноправный исход, а не ошибка; такие позиции по §5.2
 *    выделяются отдельно и В РАСЧЁТ РАЗБРОСА НЕ ВКЛЮЧАЮТСЯ.»
 *
 * Смысл в том, что подрядчик, не давший цену на позицию, — не подрядчик с
 * ценой ноль и не подрядчик со средней ценой. Включить его любым из этих
 * способов значит подделать разброс: в первом случае занизить минимум, во
 * втором — сузить разброс и спрятать несопоставимость.
 *
 * ПОЧЕМУ МЕДИАНА, А НЕ СРЕДНЕЕ
 *
 * Одно предложение с ошибкой в порядке величины сдвигает среднее и не сдвигает
 * медиану. §5.2 требует именно медиану — и требует называть аномалии отдельно,
 * а не растворять их в показателе.
 */
import { describe, expect, it } from "vitest";

import { deviation, spread } from "./spread.js";

describe("отклонение факта от базы", () => {
  it("считает относительное отклонение", () => {
    const итог = deviation({ actual: "110.00", base: "100.00" });

    expect(итог.absolute).toBe("10.00");
    expect(итог.relative).toBe("0.1000");
    expect(итог.computable).toBe(true);
  });

  it("сохраняет знак: экономия и перерасход различимы", () => {
    const итог = deviation({ actual: "90.00", base: "100.00" });

    expect(итог.absolute).toBe("-10.00");
    expect(итог.relative).toBe("-0.1000");
  });

  it("НЕ приравнивает относительное отклонение нулю при нулевой базе", () => {
    // Позиция, которой в базе не было, а в факте появилась: отклонение в
    // рублях есть, а «на сколько процентов» — вопрос без ответа. Ответить
    // нулём значит сказать «расхождения нет» (§9).
    const итог = deviation({ actual: "50.00", base: "0.00" });

    expect(итог.absolute).toBe("50.00");
    expect(итог.relative).toBeUndefined();
    expect(итог.computable).toBe(false);
    expect(итог.reason).toContain("база равна нулю");
  });

  it("несёт след формулы", () => {
    expect(deviation({ actual: "110.00", base: "100.00" }).trace?.formulaId).toBe("calculation.deviation");
  });
});

describe("разброс по предложениям", () => {
  const ПРЕДЛОЖЕНИЯ = [
    { source: "подрядчик-А", amount: "100.00" },
    { source: "подрядчик-Б", amount: "120.00" },
    { source: "подрядчик-В", amount: "140.00" },
  ];

  it("даёт минимум, максимум и медиану по сопоставимым", () => {
    const итог = spread({ offers: ПРЕДЛОЖЕНИЯ });

    expect(итог.min).toBe("100.00");
    expect(итог.max).toBe("140.00");
    expect(итог.median).toBe("120.00");
  });

  it("берёт медиану чётного набора как полусумму середины", () => {
    const итог = spread({
      offers: [
        { source: "а", amount: "100.00" },
        { source: "б", amount: "200.00" },
      ],
    });

    expect(итог.median).toBe("150.00");
  });

  it("считает разброс как отношение максимума к минимуму", () => {
    const итог = spread({ offers: ПРЕДЛОЖЕНИЯ });

    expect(итог.ratio).toBe("1.4000");
  });

  it("НЕ включает несопоставленные позиции в расчёт (§5.2)", () => {
    // Подрядчик без цены — не подрядчик с ценой ноль.
    const итог = spread({
      offers: ПРЕДЛОЖЕНИЯ,
      unmatched: [{ source: "подрядчик-Г", reason: "позиция не сопоставлена" }],
    });

    expect(итог.min).toBe("100.00");
    expect(итог.comparable).toBe(3);
    expect(итог.unmatched).toHaveLength(1);
  });

  it("НАЗЫВАЕТ несопоставленные, а не молчит о них", () => {
    const итог = spread({
      offers: ПРЕДЛОЖЕНИЯ,
      unmatched: [{ source: "подрядчик-Г", reason: "позиция не сопоставлена" }],
    });

    expect(итог.note).toContain("подрядчик-Г");
    expect(итог.note).toContain("НЕ входят");
  });

  it("отказывается считать разброс по одному предложению", () => {
    // Разброс одного значения равен единице — и это утверждение о согласии
    // рынка, которого не было. Одно предложение — не выборка.
    const итог = spread({ offers: [{ source: "а", amount: "100.00" }] });

    expect(итог.computable).toBe(false);
    expect(итог.reason).toContain("одно предложение");
    expect(итог.ratio).toBeUndefined();
  });

  it("отказывается считать разброс без единого сопоставимого предложения", () => {
    const итог = spread({
      offers: [],
      unmatched: [{ source: "а", reason: "нет цены" }],
    });

    expect(итог.computable).toBe(false);
    expect(итог.median).toBeUndefined();
  });

  it("не делит на ноль, если минимальное предложение нулевое", () => {
    const итог = spread({
      offers: [
        { source: "а", amount: "0.00" },
        { source: "б", amount: "100.00" },
      ],
    });

    expect(итог.median).toBe("50.00");
    expect(итог.ratio).toBeUndefined();
    expect(итог.reason).toContain("минимум равен нулю");
  });

  it("отмечает аномалию по отклонению от медианы, а не растворяет её", () => {
    // §5.2 требует называть аномалии с суммой влияния. Предложение,
    // отличающееся от медианы в разы, — находка, а не шум.
    const итог = spread({
      offers: [
        { source: "а", amount: "100.00" },
        { source: "б", amount: "110.00" },
        { source: "в", amount: "1000.00" },
      ],
      anomalyRatio: "2",
    });

    expect(итог.anomalies).toHaveLength(1);
    expect(итог.anomalies[0]?.source).toBe("в");
    expect(итог.anomalies[0]?.impact).toBe("890.00");
  });

  it("медиана устойчива к аномалии, в отличие от среднего", () => {
    // Проверка смысла выбора: одно предложение с ошибкой в порядке величины
    // не должно двигать показатель.
    const итог = spread({
      offers: [
        { source: "а", amount: "100.00" },
        { source: "б", amount: "110.00" },
        { source: "в", amount: "10000.00" },
      ],
    });

    expect(итог.median).toBe("110.00");
  });

  it("несёт след формулы с каждым учтённым предложением", () => {
    const итог = spread({ offers: ПРЕДЛОЖЕНИЯ });

    expect(итог.trace?.formulaId).toBe("calculation.spread");
    expect(Object.keys(итог.trace?.inputs ?? {})).toContain("подрядчик-А");
  });
});
