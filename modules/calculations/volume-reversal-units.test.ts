/**
 * МАСШТАБ ЕДИНИЦЫ: «1,5» В СОТНЯХ МЕТРОВ И «150» В МЕТРАХ — ОДНА ДЛИНА.
 *
 * ЧТО ЛОМАЛОСЬ. Линейные единицы лежали в одном множестве как равные, и объёмы
 * сравнивались числом к числу. Но расценки ГЭСН на трубопроводы и кабель
 * нормируются НА 100 МЕТРОВ, а участки дорог — на километры. В одной таблице
 * норм рядом стоят «1,5» и «150», означая одно и то же.
 *
 * ЦЕНА ОШИБКИ ДВУСТОРОННЯЯ И ОБА РАЗА МОЛЧАЛИВАЯ:
 *
 *  · базой становится меньшее число, и позиция в другой единице даёт кратность
 *    100 — флаг «объём завышен стократно» там, где завышения нет. Это возврат
 *    подрядчику, который нечем защитить, и репутация проверки;
 *  · базой становится позиция «в сотнях», и настоящая двукратная вставка
 *    превращается в дробь 0,02, выпадает из реверса — лишние метры проходят.
 *
 * ЧТО ПРОВЕРЯЕТСЯ ЗДЕСЬ: сравнение идёт по длине в метрах, а в отчёт попадает
 * объём КАК В СМЕТЕ — по нему читатель находит строку.
 */
import { describe, expect, it } from "vitest";

import { reverseVolumes } from "./volume-reversal.js";

/** Одна таблица норм, одна физическая длина 150 м, записанная двумя способами. */
const СМЕШАННЫЕ = [
  { ordinal: "1", basis: "ГЭСНм20-03-035-01", name: "Прокладка кабеля", unit: "100 м", quantity: "1.5", amount: "150000.00" },
  { ordinal: "2", basis: "ГЭСНм20-03-035-02", name: "Прокладка кабеля, второй участок", unit: "м", quantity: "150", amount: "150000.00" },
];

describe("масштаб линейной единицы", () => {
  it("одна длина в разных единицах не становится стократным превышением", () => {
    const отчёт = reverseVolumes(СМЕШАННЫЕ);
    const группа = отчёт.groups[0];

    expect(группа, "группа не собралась").toBeDefined();
    // Кратность единица: это одна и та же длина, а не «в сто раз больше».
    for (const позиция of группа!.positions) expect(позиция.multiple).toBe("1");
    expect(группа!.positions.some((p) => p.flagged), "выставлен флаг там, где превышения нет").toBe(false);
  });

  it("настоящая двукратная вставка находится и при смешанных единицах", () => {
    const отчёт = reverseVolumes([
      ...СМЕШАННЫЕ,
      { ordinal: "3", basis: "ГЭСНм20-03-035-03", name: "Вынос и возврат", unit: "м", quantity: "450", amount: "450000.00" },
    ]);
    const тройная = отчёт.groups[0]!.positions.find((p) => p.ordinal === "3");

    // 450 м против базы 150 м — тройная, и она выше порога Д-7.
    expect(тройная?.multiple).toBe("3");
    expect(тройная?.flagged).toBe(true);
  });

  it("в отчёт идёт объём как в смете, а масштаб назван в следе формулы", () => {
    const отчёт = reverseVolumes(СМЕШАННЫЕ);
    const сотниМетров = отчёт.groups[0]!.positions.find((p) => p.ordinal === "1");

    // Читатель ищет в смете «1.5», а не «150»: подменить число значило бы
    // отправить его искать строку, которой в документе нет.
    expect(сотниМетров?.quantity).toBe("1.5");
    // Но след объясняет, почему делили на 150: масштаб назван.
    expect(сотниМетров?.trace.inputs["unitScale"]).toBe("100");
    expect(сотниМетров?.trace.inputs["base"]).toBe("150");
  });

  it("сумма объёмов группы складывается по длине, а не по числам из колонки", () => {
    // «1,5» + «150» = 151,5 — это ни метры, ни сотни метров, а мусор, которым
    // потом сортируются группы отчёта.
    const группа = reverseVolumes(СМЕШАННЫЕ).groups[0]!;

    // База в сотнях метров, значит и сумма выражена в них: 150 + 150 = 300 м.
    expect(группа.totalQuantity).toBe("3");
    expect(группа.unit).toBe("100 м");
  });

  it("километры и метры сводятся так же", () => {
    // Базой становится самое частое значение: два участка по километру.
    const отчёт = reverseVolumes([
      { ordinal: "1", basis: "ГЭСН01-01-001-01", name: "Дорога", unit: "км", quantity: "1", amount: "1000000.00" },
      { ordinal: "3", basis: "ГЭСН01-01-001-03", name: "Дорога, участок 3", unit: "м", quantity: "1000", amount: "1000000.00" },
      { ordinal: "2", basis: "ГЭСН01-01-001-02", name: "Дорога, участок 2", unit: "м", quantity: "3000", amount: "3000000.00" },
    ]);
    const участок = отчёт.groups[0]!.positions.find((p) => p.ordinal === "2");

    expect(участок?.multiple).toBe("3");
  });
});
