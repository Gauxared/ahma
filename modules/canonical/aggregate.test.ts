/**
 * Тесты написаны до реализации. Декомпозиция и агрегация состава — ADR-R-013:
 *
 *   «декомпозиция и агрегация состава: одно КП свёртывает то, что другое
 *    разбивает»
 *
 * ЧТО ЭТО ЗА ЗАДАЧА
 *
 * Один подрядчик пишет «устройство подстилающего слоя из щебня — 1110 м³,
 * 2 664 000 ₽» одной строкой. Второй разбивает то же самое на «поставка щебня
 * фр. 40-70 — 1110 м³» и «укладка с трамбовкой — 1110 м³». Сравнивать их
 * построчно нельзя: у первого одна строка, у второго две, и любое построчное
 * сопоставление даст либо потерю, либо двойной счёт.
 *
 * §5.2 требует «сопоставление наименований, единиц измерения, объёмов И
 * СОСТАВА РАБОТ» — вот это и есть состав.
 *
 * ГЛАВНЫЙ ИНВАРИАНТ: ДЕНЬГИ НЕ ИСЧЕЗАЮТ И НЕ ПОЯВЛЯЮТСЯ
 *
 * Сумма по группе обязана в точности равняться сумме её строк. Агрегация,
 * теряющая копейку, теряет её из предложения подрядчика — то есть меняет то,
 * что он предложил. Это проверяется на каждой группе, а не подразумевается.
 *
 * ОБЪЁМЫ СКЛАДЫВАЮТСЯ ТОЛЬКО В ОДНОЙ РАЗМЕРНОСТИ
 *
 * «Поставка щебня, м³» и «укладка, м²» — не слагаемые. Сложить их значит
 * получить число без физического смысла, и это хуже отказа: у отказа виден
 * повод, у бессмысленного числа — нет.
 */
import { describe, expect, it } from "vitest";

import { aggregateByCanonical } from "./aggregate.js";

const РАЗБИТОЕ = [
  { line: "1.7a", canonicalId: "щебень-40-70", quantity: "1110", unit: "м3", amount: "1500000.00" },
  { line: "1.7b", canonicalId: "щебень-40-70", quantity: "1110", unit: "м3", amount: "1164000.00" },
];

const СВЁРНУТОЕ = [
  { line: "2.5", canonicalId: "щебень-40-70", quantity: "1110", unit: "м3", amount: "2664000.00" },
];

describe("агрегация состава", () => {
  it("сводит разбитые строки в одну группу", () => {
    const итог = aggregateByCanonical(РАЗБИТОЕ);

    expect(итог.groups).toHaveLength(1);
    expect(итог.groups[0]?.canonicalId).toBe("щебень-40-70");
    expect(итог.groups[0]?.lines).toHaveLength(2);
  });

  it("СУММА ГРУППЫ равна сумме её строк — до копейки", () => {
    // Агрегация, теряющая копейку, теряет её из предложения подрядчика, то
    // есть меняет то, что он предложил.
    const итог = aggregateByCanonical(РАЗБИТОЕ);

    expect(итог.groups[0]?.amount).toBe("2664000.00");
  });

  it("делает свёрнутое и разбитое СОПОСТАВИМЫМИ", () => {
    // Ради этого всё и затевается: два предложения, описавшие одну работу
    // по-разному, дают одинаковую группу.
    const разбито = aggregateByCanonical(РАЗБИТОЕ);
    const свёрнуто = aggregateByCanonical(СВЁРНУТОЕ);

    expect(разбито.groups[0]?.amount).toBe(свёрнуто.groups[0]?.amount);
    expect(разбито.groups[0]?.canonicalId).toBe(свёрнуто.groups[0]?.canonicalId);
  });

  it("НЕ складывает объёмы повторяющихся строк вслепую", () => {
    // 1110 + 1110 = 2220 м³ щебня — но щебень тот же самый: разбиение шло по
    // ВИДУ РАБОТ (поставка и укладка), а не по объёму. Сложить объёмы значит
    // удвоить материал.
    const итог = aggregateByCanonical(РАЗБИТОЕ);

    expect(итог.groups[0]?.quantity).toBe("1110");
    expect(итог.groups[0]?.quantityNote).toContain("совпадает");
  });

  it("СКЛАДЫВАЕТ объёмы, когда они относятся к разным участкам", () => {
    // Два участка по 555 м³ — это 1110 м³ работы. Отличие от предыдущего
    // случая в том, что объёмы РАЗНЫЕ, и значит строки описывают разные части,
    // а не разные виды работ над одной частью.
    const итог = aggregateByCanonical([
      { line: "1.1", canonicalId: "бетон-b30", quantity: "555", unit: "м3", amount: "1000000.00" },
      { line: "1.2", canonicalId: "бетон-b30", quantity: "444", unit: "м3", amount: "800000.00" },
    ]);

    expect(итог.groups[0]?.quantity).toBe("999");
  });

  it("ОТКАЗЫВАЕТСЯ складывать разные размерности", () => {
    // «Поставка щебня, м³» и «укладка, м²» — не слагаемые. Полученное число не
    // имело бы физического смысла, и это хуже отказа: у отказа виден повод.
    const итог = aggregateByCanonical([
      { line: "1.1", canonicalId: "щебень-40-70", quantity: "1110", unit: "м3", amount: "1500000.00" },
      { line: "1.2", canonicalId: "щебень-40-70", quantity: "3700", unit: "м2", amount: "1164000.00" },
    ]);

    expect(итог.groups[0]?.quantity).toBeUndefined();
    expect(итог.groups[0]?.quantityNote).toContain("размерност");
    // Деньги при этом суммируются: рубли остаются рублями.
    expect(итог.groups[0]?.amount).toBe("2664000.00");
  });

  it("приводит разные единицы ОДНОЙ размерности к общей", () => {
    // 1 км и 500 м — это 1500 м. Отказывать здесь незачем.
    const итог = aggregateByCanonical([
      { line: "1.1", canonicalId: "кабель", quantity: "1", unit: "км", amount: "100000.00" },
      { line: "1.2", canonicalId: "кабель", quantity: "500", unit: "м", amount: "50000.00" },
    ]);

    expect(итог.groups[0]?.quantity).toBe("1500");
    expect(итог.groups[0]?.unit).toBe("м");
  });

  it("сохраняет строки-источники в группе", () => {
    // Без них нельзя ни объяснить сумму, ни вернуться к исходному документу.
    const итог = aggregateByCanonical(РАЗБИТОЕ);

    expect(итог.groups[0]?.lines.map((line) => line.line)).toEqual(["1.7a", "1.7b"]);
  });

  it("выделяет несопоставленные строки ОТДЕЛЬНО (§5.2)", () => {
    // Строка без канонической позиции в группу не попадает и не исчезает:
    // §5.2 требует выделять такие отдельно.
    const итог = aggregateByCanonical([
      ...РАЗБИТОЕ,
      { line: "1.9", quantity: "160", unit: "м", amount: "300000.00" },
    ]);

    expect(итог.groups).toHaveLength(1);
    expect(итог.unmatched).toHaveLength(1);
    expect(итог.unmatched[0]?.line).toBe("1.9");
  });

  it("СУММА ВСЕГО равна сумме групп и несопоставленных", () => {
    // Главная проверка сохранения денег: ничто не потерялось и не удвоилось.
    const итог = aggregateByCanonical([
      ...РАЗБИТОЕ,
      { line: "1.9", quantity: "160", unit: "м", amount: "300000.00" },
    ]);

    expect(итог.total).toBe("2964000.00");
    expect(итог.matchedAmount).toBe("2664000.00");
    expect(итог.unmatchedAmount).toBe("300000.00");
  });

  it("на пустом наборе даёт нули и говорит об этом", () => {
    const итог = aggregateByCanonical([]);

    expect(итог.groups).toHaveLength(0);
    expect(итог.total).toBe("0.00");
    expect(итог.note).toContain("строк нет");
  });
});

describe("сравнение свёрнутого с разбитым", () => {
  it("даёт одинаковое число групп при разной детализации", () => {
    // Два предложения на одну работу: у одного две строки, у другого одна.
    // После агрегации — по одной группе у каждого.
    expect(aggregateByCanonical(РАЗБИТОЕ).groups).toHaveLength(1);
    expect(aggregateByCanonical(СВЁРНУТОЕ).groups).toHaveLength(1);
  });

  it("НАЗЫВАЕТ, какое предложение оказалось детальнее", () => {
    // Детализация — сама по себе сведение: подрядчик, разбивший работу,
    // показал её состав, и это довод в переговорах.
    const итог = aggregateByCanonical(РАЗБИТОЕ);

    expect(итог.groups[0]?.decomposed).toBe(true);
    expect(aggregateByCanonical(СВЁРНУТОЕ).groups[0]?.decomposed).toBe(false);
  });
});
