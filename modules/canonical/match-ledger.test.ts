/**
 * Тесты написаны до реализации. Подтверждение сопоставлений — ADR-R-013:
 *
 *   «confidence и объяснение на каждое сопоставление; неоднозначные требуют
 *    подтверждения человеком, ИСХОДНАЯ И ПОДТВЕРЖДЁННАЯ ВЕРСИИ ХРАНЯТСЯ ОБЕ»
 *
 * ЗАЧЕМ ХРАНИТЬ ОБЕ
 *
 * Через месяц спор пойдёт о цифре в сравнительной таблице, и вопрос будет
 * ровно один: система так решила или человек так поправил. Если подтверждение
 * ЗАМЕЩАЕТ исходное сопоставление, ответить нельзя — а от ответа зависит, чью
 * ошибку исправлять: алгоритма или сотрудника.
 *
 * Это тот же принцип, что у ревизий извлечения (`ExtractionLedger`), и
 * применён он к другому предмету: там правят ЧИСЛО, прочитанное из документа,
 * здесь — СВЯЗЬ между позицией КП и справочником.
 *
 * ЧЕЛОВЕК МОЖЕТ СКАЗАТЬ «НИ ОДИН»
 *
 * Подтверждение — не выбор из предложенного. Если верного кандидата в списке
 * нет, ответ «не сопоставлено» обязан быть доступен, иначе человека вынуждают
 * согласиться с лучшим из неправильных.
 */
import { describe, expect, it } from "vitest";

import { MatchLedger } from "./match-ledger.js";

const СОПОСТАВЛЕНИЕ = {
  offerLine: "2.9 устройство жб забора",
  outcome: "требует подтверждения" as const,
  candidateId: "забор",
  confidence: 0.55,
  explanation: "совпали значимые слова: забора; оценка 0.55",
};

describe("хранение обеих версий", () => {
  it("сохраняет исходное сопоставление системы", () => {
    const журнал = new MatchLedger();
    журнал.propose(СОПОСТАВЛЕНИЕ);

    const запись = журнал.get("2.9 устройство жб забора")!;

    expect(запись.proposed.candidateId).toBe("забор");
    expect(запись.confirmed).toBeUndefined();
  });

  it("подтверждение НЕ затирает исходное", () => {
    // Через месяц спор пойдёт о том, система так решила или человек поправил.
    const журнал = new MatchLedger();
    журнал.propose(СОПОСТАВЛЕНИЕ);
    журнал.confirm("2.9 устройство жб забора", {
      candidateId: "ограждение",
      by: "Людмила",
      at: "2026-08-31",
      reason: "в справочнике это ограждение, а не забор",
    });

    const запись = журнал.get("2.9 устройство жб забора")!;

    expect(запись.proposed.candidateId).toBe("забор");
    expect(запись.confirmed?.candidateId).toBe("ограждение");
  });

  it("действующим считается ПОДТВЕРЖДЁННОЕ, когда оно есть", () => {
    const журнал = new MatchLedger();
    журнал.propose(СОПОСТАВЛЕНИЕ);
    журнал.confirm("2.9 устройство жб забора", {
      candidateId: "ограждение",
      by: "Людмила",
      at: "2026-08-31",
      reason: "иная позиция справочника",
    });

    expect(журнал.effective("2.9 устройство жб забора")?.candidateId).toBe("ограждение");
  });

  it("человек может отвергнуть ВСЕ варианты", () => {
    // Подтверждение — не выбор из предложенного. Иначе человека вынуждают
    // согласиться с лучшим из неправильных.
    const журнал = new MatchLedger();
    журнал.propose(СОПОСТАВЛЕНИЕ);
    журнал.reject("2.9 устройство жб забора", {
      by: "Людмила",
      at: "2026-08-31",
      reason: "такой работы в справочнике нет",
    });

    const запись = журнал.get("2.9 устройство жб забора")!;

    expect(запись.confirmed?.candidateId).toBeUndefined();
    expect(журнал.effective("2.9 устройство жб забора")).toBeUndefined();
    expect(запись.proposed.candidateId).toBe("забор");
  });

  it("подтверждение требует причины", () => {
    // Решение человека без объяснения нельзя ни проверить, ни оспорить.
    const журнал = new MatchLedger();
    журнал.propose(СОПОСТАВЛЕНИЕ);

    expect(() =>
      журнал.confirm("2.9 устройство жб забора", {
        candidateId: "ограждение",
        by: "Людмила",
        at: "2026-08-31",
        reason: "  ",
      }),
    ).toThrow(/причин/i);
  });

  it("не подтверждает то, чего не предлагали", () => {
    const журнал = new MatchLedger();

    expect(() =>
      журнал.confirm("нет такой строки", {
        candidateId: "забор",
        by: "Людмила",
        at: "2026-08-31",
        reason: "почему бы нет",
      }),
    ).toThrow(/не найден/i);
  });
});

describe("что ждёт человека", () => {
  it("перечисляет ТОЛЬКО неподтверждённые неоднозначные", () => {
    // Уверенные сопоставления подтверждать не надо: иначе человек начнёт
    // подтверждать не глядя, и подтверждение обесценится — тот же довод, что
    // у ревизий извлечения.
    const журнал = new MatchLedger();
    журнал.propose(СОПОСТАВЛЕНИЕ);
    журнал.propose({
      offerLine: "2.4 устройство приямка",
      outcome: "сопоставлено",
      candidateId: "приямок",
      confidence: 1,
      explanation: "дословное совпадение",
    });

    expect(журнал.pending()).toHaveLength(1);
    expect(журнал.pending()[0]?.offerLine).toBe("2.9 устройство жб забора");
  });

  it("убирает из ожидания подтверждённое", () => {
    const журнал = new MatchLedger();
    журнал.propose(СОПОСТАВЛЕНИЕ);
    журнал.confirm("2.9 устройство жб забора", {
      candidateId: "забор",
      by: "Людмила",
      at: "2026-08-31",
      reason: "верно",
    });

    expect(журнал.pending()).toHaveLength(0);
  });

  it("НЕ ставит в очередь несопоставленное", () => {
    // «Не сопоставлено» — исход, а не вопрос к человеку: подтверждать нечего.
    // Такие позиции по §5.2 выделяются отдельным списком.
    const журнал = new MatchLedger();
    журнал.propose({
      offerLine: "2.9 забор",
      outcome: "не сопоставлено",
      confidence: 0.04,
      explanation: "ближайший кандидат набрал 0.04",
    });

    expect(журнал.pending()).toHaveLength(0);
    expect(журнал.unmatched()).toHaveLength(1);
  });
});

describe("готовность к расчёту", () => {
  it("НЕ готов, пока есть неподтверждённые неоднозначные", () => {
    // Считать разброс по неподтверждённым сопоставлениям значит считать по
    // догадкам и выдать результат как факт.
    const журнал = new MatchLedger();
    журнал.propose(СОПОСТАВЛЕНИЕ);

    const готовность = журнал.readiness();

    expect(готовность.ready).toBe(false);
    expect(готовность.reason).toContain("2.9");
  });

  it("готов, когда неоднозначных не осталось", () => {
    const журнал = new MatchLedger();
    журнал.propose(СОПОСТАВЛЕНИЕ);
    журнал.reject("2.9 устройство жб забора", {
      by: "Людмила",
      at: "2026-08-31",
      reason: "нет такой позиции",
    });

    expect(журнал.readiness().ready).toBe(true);
  });

  it("готов на пустом журнале, но говорит об этом", () => {
    // Ноль сопоставлений — не «всё подтверждено», а «нечего подтверждать».
    const журнал = new MatchLedger();

    expect(журнал.readiness().ready).toBe(true);
    expect(журнал.readiness().reason).toContain("сопоставлений нет");
  });
});
