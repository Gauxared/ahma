/**
 * Тесты написаны до реализации. Приведение русских слов к основе.
 *
 * ЗАЧЕМ ЭТО НУЖНО ИМЕННО ЗДЕСЬ
 *
 * Первая версия текстового сопоставления сравнивала слова точно — и провалилась
 * на настоящем КП. «Устройство ЖБ забора» против справочного «устройство
 * железобетонного забора»: даже подставив синоним «жб» → «железобетонный»,
 * получаем «железобетонный» против «железобетонного» и «забора» против
 * «забора» — одно слово из трёх не совпадает по одной букве окончания.
 *
 * Русский язык флективен, и почти каждое существительное в наименовании работ
 * стоит в косвенном падеже: «устройство слоЯ», «из щебнЯ», «толщиной 100мм».
 * Сравнение по точному совпадению слов на таком материале не работает в
 * принципе — это не настройка порога, а неверный способ сравнения.
 *
 * ПОЧЕМУ НЕ ОБРЕЗКА ПО ДЛИНЕ
 *
 * Обрезать каждое слово до пяти букв просто, но склеивает разное: «бетон» и
 * «бетономешалка» дали бы одну основу. Отсечение ИЗВЕСТНЫХ окончаний
 * ошибается реже и, главное, ошибается предсказуемо.
 *
 * ОСНОВА — ДЛЯ СРАВНЕНИЯ, А НЕ ДЛЯ ПОКАЗА
 *
 * «Устройств» человеку не показывают: в объяснении стоит исходное слово. Как и
 * с нормализацией, исходный текст остаётся исходным.
 */
import { describe, expect, it } from "vitest";

import { stemRussian } from "./stem.js";

describe("основа слова", () => {
  it("сводит падежи существительного к одной основе", () => {
    const формы = ["забор", "забора", "забору", "забором", "заборе", "заборы", "заборов"];
    const основы = new Set(формы.map(stemRussian));

    expect(основы.size).toBe(1);
  });

  it("сводит формы прилагательного", () => {
    const формы = ["железобетонный", "железобетонного", "железобетонная", "железобетонные"];
    const основы = new Set(формы.map(stemRussian));

    expect(основы.size).toBe(1);
  });

  it("сводит «слой» и «слоя»", () => {
    // Прямо из КП: «устройство подстилающего слоя».
    expect(stemRussian("слоя")).toBe(stemRussian("слой"));
  });

  it("сводит «щебень» и «щебня»", () => {
    // Беглая гласная: «щебень» → «щебня». Обрезка по длине здесь бессильна.
    expect(stemRussian("щебня")).toBe(stemRussian("щебень"));
  });

  it("НЕ склеивает разные слова", () => {
    // Обрезка до пяти букв дала бы «бетон» обоим.
    expect(stemRussian("бетон")).not.toBe(stemRussian("бетономешалка"));
    expect(stemRussian("демонтаж")).not.toBe(stemRussian("монтаж"));
  });

  it("не трогает короткие слова", () => {
    // У слова из трёх букв отсекать нечего: «жб», «шт», «мм».
    for (const слово of ["жб", "шт", "мм", "лоток"]) {
      expect(stemRussian(слово).length).toBeGreaterThanOrEqual(2);
    }
  });

  it("не трогает числа и латиницу", () => {
    expect(stemRussian("40")).toBe("40");
    expect(stemRussian("b30f150")).toBe("b30f150");
  });

  it("оставляет пустую строку пустой", () => {
    expect(stemRussian("")).toBe("");
  });

  it("сводит «подстилающего» и «подстилающий»", () => {
    expect(stemRussian("подстилающего")).toBe(stemRussian("подстилающий"));
  });

  it("сводит «фракция» и «фракции»", () => {
    expect(stemRussian("фракции")).toBe(stemRussian("фракция"));
  });

  it("сводит «существующей» и «существующего»", () => {
    // Из КП: «демонтаж существующей бетонной поверхности».
    expect(stemRussian("существующей")).toBe(stemRussian("существующего"));
  });
});
