/**
 * Приведение русских слов к основе — для сравнения наименований работ.
 *
 * ЗАЧЕМ
 *
 * Первая версия текстового сопоставления сравнивала слова точно и провалилась
 * на настоящем КП. «Устройство ЖБ забора» против справочного «устройство
 * железобетонного забора»: даже подставив синоним «жб» → «железобетонный»,
 * получаем «железобетонный» против «железобетонного» — одно слово из трёх не
 * совпадает по одной букве.
 *
 * Русский флективен, и почти каждое существительное в наименовании работ стоит
 * в косвенном падеже: «устройство слоЯ», «из щебнЯ», «демонтаж существующЕЙ
 * поверхностИ». Точное сравнение слов на таком материале не работает в
 * принципе — это не настройка порога, а неверный способ сравнения.
 *
 * ПОЧЕМУ НЕ ОБРЕЗКА ПО ДЛИНЕ
 *
 * Обрезать до пяти букв просто, но склеивает разное: «бетон» и «бетономешалка»
 * дали бы одну основу, а «демонтаж» и «монтаж» разошлись бы правильно только
 * случайно. Отсечение ИЗВЕСТНЫХ окончаний ошибается реже и ошибается
 * предсказуемо: список окончаний можно прочитать и оспорить.
 *
 * ЭТО НЕ ПОЛНАЯ МОРФОЛОГИЯ, И ЭТО СКАЗАНО ЯВНО
 *
 * Здесь нет словаря словоформ и нет разбора части речи. Задача уже: свести
 * падежные и родовые формы ОДНОГО слова к одной строке, чтобы два наименования
 * можно было сравнить. Омонимию и супплетивизм этот способ не берёт, и на
 * границе он ошибается — поэтому итог сопоставления несёт уверенность и
 * объяснение, а неоднозначное уходит человеку.
 *
 * ОСНОВА — ДЛЯ СРАВНЕНИЯ, А НЕ ДЛЯ ПОКАЗА
 *
 * «Устройств» человеку не показывают: в объяснении стоит исходное слово.
 */

/**
 * Окончания в порядке ОТ ДЛИННОГО К КОРОТКОМУ.
 *
 * Порядок обязателен, и это та же ловушка, что с шифрами ГЭСН/ГЭСНм: «ого»
 * начинается с «о», и, проверяя короткое первым, от «железобетонного» отсечёшь
 * только «о», получив «железобетонног».
 */
const ENDINGS: readonly string[] = [
  // Причастия и прилагательные
  "ующего", "ующей", "ующие", "ующих", "ующим", "ующая", "ующий",
  "ающего", "ающей", "ающие", "ающих", "ающим", "ающая", "ающий",
  "енного", "енной", "енные", "енных", "енным", "енная", "енный",
  "ованных", "ованные", "ованного", "ованный",
  "ого", "его", "ому", "ему", "ыми", "ими", "ая", "яя", "ые", "ие", "ый", "ий", "ой", "ей",
  "ом", "ем", "ых", "их", "ым", "им", "ую", "юю",
  // Существительные
  "ами", "ями", "ах", "ях", "ов", "ев", "ам", "ям",
  "а", "я", "ы", "и", "у", "ю", "е", "о", "ь", "й",
];

/**
 * Короче этого основу не режем.
 *
 * Три, а не четыре: «слой» и «слоя» дают основу «сло» длиной ровно три, и при
 * пороге в четыре обе формы остались бы нетронутыми и разными. Слово это в
 * наименованиях работ встречается постоянно — «устройство подстилающего слоя».
 *
 * Ниже трёх опускаться нельзя: двухбуквенная основа склеивает несвязанные
 * слова, и сопоставление начнёт находить сходство там, где его нет.
 */
const MIN_STEM = 3;

/** Беглые гласные: «щебень» → «щебн», «камень» → «камн». */
const FLEETING = /^(.*[бвгджзклмнпрстфхцчшщ])е([бвгджзклмнпрстфхцчшщ])$/;

const CYRILLIC = /[а-яё]/;

export function stemRussian(word: string): string {
  if (word === "" || !CYRILLIC.test(word)) {
    // Числа, латиница и шифры материалов («b30f150») остаются как есть:
    // отсечение окончаний к ним неприменимо, а порча их сломает сравнение
    // фракций и марок бетона.
    return word;
  }

  let stem = word;

  for (const ending of ENDINGS) {
    if (stem.length - ending.length >= MIN_STEM && stem.endsWith(ending)) {
      stem = stem.slice(0, -ending.length);
      break;
    }
  }

  // Беглая гласная применяется ПОСЛЕ отсечения: «щебня» → «щебн» уже совпадает
  // с «щебень» → «щебн» только через это правило.
  const fleeting = FLEETING.exec(stem);

  return fleeting === null ? stem : `${fleeting[1]}${fleeting[2]}`;
}
