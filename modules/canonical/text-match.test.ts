/**
 * Тесты написаны до реализации. Текстовый путь канонизации — ADR-R-013, ТЗ §5.2.
 *
 * Строки взяты из НАСТОЯЩЕГО КП подрядчика SLK по устройству бетонных площадок:
 * `reference-system-new/…/SLK СМУ-1/КП SLK.xlsx`. Шифров в нём нет вовсе —
 * только свободный текст, единица и объём. Это и есть случай, ради которого
 * текстовый путь существует.
 *
 * ТРИ ИСХОДА, А НЕ ДВА
 *
 * ТЗ §5.2: «несопоставимые позиции выделяются отдельно и в расчёт разброса не
 * включаются». Значит, исходов три: сопоставлено, НЕ сопоставлено, и —
 * отдельно — сопоставлено неоднозначно, что по ADR-R-013 требует подтверждения
 * человеком. Свести неоднозначное к сопоставленному значит принять решение за
 * человека и спрятать это; свести к несопоставленному — выбросить работу,
 * которую почти удалось сделать.
 *
 * ЕДИНИЦА — ЖЁСТКИЙ ЗАПРЕТ, А НЕ ВЕС В ФОРМУЛЕ
 *
 * «Устройство подстилающего слоя» в м³ и в м² — разные работы, как бы ни
 * совпадали наименования. Позволить сходству имён перевесить несовпадение
 * размерности значит сопоставить объём с площадью и посчитать по ним разброс.
 *
 * НЕОДНОЗНАЧНОСТЬ НЕ РАЗРЕШАЕТСЯ ВЫБОРОМ МАКСИМУМА
 *
 * Если два кандидата почти равны, «победитель» определяется третьим знаком
 * оценки — то есть шумом. Такой выбор выглядит решением и им не является.
 */
import { describe, expect, it } from "vitest";

import { matchByText } from "./text-match.js";
import type { TextCandidate } from "./text-match.js";

/** Позиции из настоящего КП SLK, приведённые к виду кандидатов справочника. */
const СПРАВОЧНИК: readonly TextCandidate[] = [
  { id: "щебень-40-70", name: "устройство подстилающего слоя из щебня фракция 40-70 мм", unit: "м3" },
  { id: "щебень-20-40", name: "устройство подстилающего слоя из щебня фракция 20-40 мм", unit: "м3" },
  { id: "песок-100", name: "устройство подстилающего слоя из песка толщиной 100 мм", unit: "м3" },
  { id: "бетон-b30", name: "устройство бетонного армированного покрытия из бетона B30F150", unit: "м3" },
  { id: "приямок", name: "устройство приямка", unit: "шт" },
  { id: "водоотвод", name: "устройство водоотводной системы водоприемный монолитный лоток", unit: "м" },
  { id: "демонтаж-бетона", name: "демонтаж существующей бетонной поверхности гидромолотом", unit: "м2" },
  { id: "забор", name: "устройство железобетонного забора", unit: "м" },
];

describe("сопоставление по тексту", () => {
  it("сопоставляет дословное совпадение", () => {
    const итог = matchByText(
      { name: "устройство приямка", unit: "шт" },
      СПРАВОЧНИК,
    );

    expect(итог.outcome).toBe("сопоставлено");
    expect(итог.match?.id).toBe("приямок");
  });

  it("сопоставляет через различие в написании и пунктуации", () => {
    // В КП написано «устройство подстилающего слоя из щебня,фракция 40- 70мм.»
    // — без пробела после запятой, с пробелом внутри диапазона, с точкой.
    const итог = matchByText(
      { name: "устройство подстилающего слоя из щебня,фракция 40- 70мм.,толщиной 300мм", unit: "м3" },
      СПРАВОЧНИК,
    );

    expect(итог.outcome).toBe("сопоставлено");
    expect(итог.match?.id).toBe("щебень-40-70");
  });

  it("РАЗЛИЧАЕТ фракции щебня, а не сваливает их в одну позицию", () => {
    // 40-70 и 20-40 отличаются двумя числами из десятка слов. Сопоставить их
    // друг с другом значит сложить разные материалы по разной цене.
    const итог = matchByText(
      { name: "устройство подстилающего слоя из щебня,фракция 20- 40мм.,толщиной 120мм", unit: "м3" },
      СПРАВОЧНИК,
    );

    expect(итог.match?.id).toBe("щебень-20-40");
  });

  it("НЕ сопоставляет при несовпадении размерности, как бы ни совпал текст", () => {
    // «Устройство подстилающего слоя» в м² — другая работа, чем в м³.
    const итог = matchByText(
      { name: "устройство подстилающего слоя из щебня фракция 40-70 мм", unit: "м2" },
      СПРАВОЧНИК,
    );

    expect(итог.outcome).toBe("не сопоставлено");
    expect(итог.explanation).toContain("размерност");
  });

  it("допускает разные единицы ОДНОЙ размерности", () => {
    // «пог.м» и «м» — одна размерность, и запрещать их сравнение незачем.
    const итог = matchByText(
      { name: "устройство железобетонного забора", unit: "пог.м" },
      СПРАВОЧНИК,
    );

    expect(итог.outcome).toBe("сопоставлено");
    expect(итог.match?.id).toBe("забор");
  });

  it("НЕ сопоставляет то, чего в справочнике нет", () => {
    // «Не сопоставлено» — полноправный исход §5.2, а не ошибка.
    const итог = matchByText(
      { name: "монтаж системы видеонаблюдения", unit: "шт" },
      СПРАВОЧНИК,
    );

    expect(итог.outcome).toBe("не сопоставлено");
    expect(итог.match).toBeUndefined();
  });

  it("ТРЕБУЕТ ПОДТВЕРЖДЕНИЯ при двух неразличимых кандидатах", () => {
    // Случай не выдуманный: в справочнике, собираемом из разных источников,
    // одна работа заводится дважды с переставленными словами. Обе записи для
    // сравнения одинаковы, и «победитель» определился бы порядком в массиве —
    // то есть тем, какой файл прочитали раньше.
    const дубли: readonly TextCandidate[] = [
      { id: "приямок-а", name: "устройство приямка", unit: "шт" },
      { id: "приямок-б", name: "приямка устройство", unit: "шт" },
    ];

    const итог = matchByText({ name: "устройство приямка", unit: "шт" }, дубли);

    expect(итог.outcome).toBe("требует подтверждения");
    expect(итог.alternatives).toHaveLength(2);
    expect(итог.explanation).toContain("шумом");
  });

  it("РАЗЛИЧАЕТ фракции щебня по числам, а не только по словам", () => {
    // Регрессия. Первая версия токенизации склеивала «70мм» в одно слово, и
    // оно не совпадало с «70» из справочной строки «40-70 мм». В итоге
    // «щебень 40-70» и «щебень 20-40» набирали ОДИНАКОВУЮ оценку 0.667:
    // различающее число терялось, и разные материалы по разной цене
    // становились одной позицией.
    //
    // Найдено на настоящем КП SLK. Правило: цифры отделяются от кириллицы, но
    // НЕ от латиницы — «B30F150» это марка бетона, и резать её нельзя.
    const сорок = matchByText(
      { name: "устройство подстилающего слоя из щебня,фракция 40- 70мм.,толщиной 300мм", unit: "м3" },
      СПРАВОЧНИК,
    );
    const двадцать = matchByText(
      { name: "устройство подстилающего слоя из щебня,фракция 20- 40мм.,толщиной 120мм", unit: "м3" },
      СПРАВОЧНИК,
    );

    expect(сорок.match?.id).toBe("щебень-40-70");
    expect(двадцать.match?.id).toBe("щебень-20-40");
    expect(сорок.outcome).toBe("сопоставлено");
    expect(двадцать.outcome).toBe("сопоставлено");
  });

  it("НЕ режет марку бетона на части", () => {
    // «B30F150» латиницей: разрезав её на «b», «30», «f», «150», мы сделали бы
    // все марки бетона похожими друг на друга.
    const итог = matchByText(
      { name: "устройство бетонного армированного покрытия из бетона B30F150 толщиной 200мм", unit: "м3" },
      СПРАВОЧНИК,
    );

    expect(итог.outcome).toBe("сопоставлено");
    expect(итог.match?.id).toBe("бетон-b30");
  });

  it("даёт уверенность и объяснение НА КАЖДЫЙ исход", () => {
    // ADR-R-013: «confidence и объяснение на каждое сопоставление». В том
    // числе на несопоставление: иначе непонятно, почему его не случилось.
    for (const запрос of [
      { name: "устройство приямка", unit: "шт" },
      { name: "монтаж системы видеонаблюдения", unit: "шт" },
    ]) {
      const итог = matchByText(запрос, СПРАВОЧНИК);

      expect(итог.confidence).toBeGreaterThanOrEqual(0);
      expect(итог.confidence).toBeLessThanOrEqual(1);
      expect(итог.explanation.length).toBeGreaterThan(10);
    }
  });

  it("объясняет сопоставление СОВПАВШИМИ СЛОВАМИ, а не числом", () => {
    // Человек подтверждает сопоставление, глядя на основание. «Уверенность
    // 0.87» основанием не является: по нему нельзя ни согласиться, ни возразить.
    const итог = matchByText(
      { name: "устройство подстилающего слоя из песка толщиной 100мм", unit: "м3" },
      СПРАВОЧНИК,
    );

    expect(итог.explanation).toContain("песка");
  });

  it("не сопоставляет по одному общему слову", () => {
    // «Устройство» есть почти в каждой строительной позиции. Совпадение по
    // нему одному — не сопоставление, а совпадение жанра.
    const итог = matchByText({ name: "устройство кровли", unit: "м2" }, СПРАВОЧНИК);

    expect(итог.outcome).toBe("не сопоставлено");
  });

  it("на пустом справочнике отвечает НЕ СОПОСТАВЛЕНО, а не падает", () => {
    const итог = matchByText({ name: "устройство приямка", unit: "шт" }, []);

    expect(итог.outcome).toBe("не сопоставлено");
    expect(итог.explanation).toContain("справочник пуст");
  });

  it("на пустом наименовании не сопоставляет", () => {
    // Пустое наименование совпадает со всем и ни с чем.
    const итог = matchByText({ name: "   ", unit: "шт" }, СПРАВОЧНИК);

    expect(итог.outcome).toBe("не сопоставлено");
  });
});

describe("синонимы предметной области", () => {
  it("сопоставляет через синоним, заданный СНАРУЖИ", () => {
    // Находка О-44: в договоре генподряда «пеня» не встречается ни разу, а
    // «неустойка» — восемь раз. Та же болезнь в КП: «жб» против
    // «железобетонный», «гидромолот» против «гидравлический молот».
    //
    // Словарь приходит аргументом, а не зашит в код: состав синонимов —
    // предметное знание клиента, а не свойство алгоритма (ADR-R-014).
    const итог = matchByText(
      { name: "устройство жб забора", unit: "м" },
      СПРАВОЧНИК,
      { synonyms: [["жб", "железобетонный"]] },
    );

    expect(итог.outcome).toBe("сопоставлено");
    expect(итог.match?.id).toBe("забор");
  });

  it("БЕЗ словаря тот же запрос не сопоставляется", () => {
    // Проверка того, что синонимы действительно работают, а не совпадение
    // получилось по другим словам.
    const итог = matchByText({ name: "устройство жб забора", unit: "м" }, СПРАВОЧНИК);

    expect(итог.outcome).not.toBe("сопоставлено");
  });
});
