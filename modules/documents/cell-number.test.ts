/**
 * Как читается число, показанное человеку.
 *
 * ЦЕНА ОШИБКИ ЗДЕСЬ — ТЫСЯЧА РАЗ, И ОНА ВЫГЛЯДИТ ЧИСЛОМ.
 *
 * Ошибка в другую сторону дешевле, но опаснее на вид: число, признанное
 * непрочитанным, роняет позицию, и на экране это «смета прочитана, позиций 0».
 * Замерено на курганской ЛСР в CSV: строгий шаблон давал НОЛЬ позиций из
 * сорока четырёх.
 *
 * Отдельно проверяется, что машинная запись НЕ ТРОГАЕТСЯ: книги Excel отдают
 * числа именно так, и любая правка этого правила задевает весь корпус.
 */
import { describe, expect, it } from "vitest";

import { cellNumber } from "./cell-number.js";

describe("машинная запись не меняется", () => {
  it("читает число из книги как есть", () => {
    expect(cellNumber("18038.61")).toBe("18038.61");
    expect(cellNumber("0")).toBe("0");
    expect(cellNumber("-12.5")).toBe("-12.5");
  });

  it("одна точка — ВСЕГДА десятичная, даже перед тремя цифрами", () => {
    // `18.038` — восемнадцать целых, а не восемнадцать тысяч. Книги отдают
    // числа так, и толкование точки как разрядной сдвинуло бы весь корпус.
    expect(cellNumber("18.038")).toBe("18.038");
    expect(cellNumber("0.001")).toBe("0.001");
  });
});

describe("русская запись: пробел в разрядах, запятая в дроби", () => {
  it("читает сумму из выгрузки Excel", () => {
    expect(cellNumber("18 038,61")).toBe("18038.61");
    expect(cellNumber("14 198 884,54")).toBe("14198884.54");
  });

  it("читает неразрывный и узкий пробел", () => {
    // Excel ставит именно неразрывный, а веб-выгрузки — узкий неразрывный.
    // Проверять только обычный пробел значило бы не проверять ничего.
    expect(cellNumber("18 038,61")).toBe("18038.61");
    expect(cellNumber("18 038,61")).toBe("18038.61");
  });

  it("читает запятую без разрядов", () => {
    expect(cellNumber("961,84")).toBe("961.84");
    expect(cellNumber("-4,5")).toBe("-4.5");
  });
});

describe("американская запись: запятая в разрядах, точка в дроби", () => {
  it("читает сумму с обоими знаками", () => {
    expect(cellNumber("18,038.61")).toBe("18038.61");
    expect(cellNumber("14,198,884.54")).toBe("14198884.54");
  });

  it("читает и обратный порядок знаков", () => {
    // `18.038,61` — европейская запись. Десятичный тот, что правее, и решать
    // тут нечего.
    expect(cellNumber("18.038,61")).toBe("18038.61");
  });

  it("читает разряды без дроби", () => {
    expect(cellNumber("14,198,884")).toBe("14198884");
  });
});

describe("единственный спорный случай: запятая и ровно три цифры", () => {
  it("считает запятую РАЗРЯДНОЙ, когда целая часть похожа на группу", () => {
    // `1,500` в деньгах — тысяча пятьсот: суммы в сметах всегда с двумя
    // знаками, трёхзначной дроби у них не бывает.
    expect(cellNumber("1,500")).toBe("1500");
    expect(cellNumber("961,312")).toBe("961312");
  });

  it("считает запятую ДЕСЯТИЧНОЙ при ведущем нуле — иначе ошибка в тысячу раз", () => {
    // `0,001` — количество «одна тысячная». Приняв запятую за разрядную, мы
    // получили бы `0001`, то есть единицу: тонна вместо килограмма, и число
    // при этом выглядит правдоподобным.
    expect(cellNumber("0,001")).toBe("0.001");
    expect(cellNumber("0,125")).toBe("0.125");
  });

  it("считает запятую ДЕСЯТИЧНОЙ, когда целая часть длиннее группы", () => {
    // Группа разрядов не бывает длиннее трёх цифр: `1234,567` — это дробь.
    expect(cellNumber("1234,567")).toBe("1234.567");
  });
});

describe("не число остаётся непрочитанным", () => {
  it("текст, пустота и мусор не превращаются в нули", () => {
    // Ноль вместо «не число» — худший исход: он складывается в итог и делает
    // сходимость ложно сошедшейся.
    for (const value of ["", "  ", "шт", "ФОТ", "—", "2%Г1.С:Г12.С", "н/д", undefined]) {
      expect(cellNumber(value), `«${value ?? "undefined"}» прочитано как число`).toBeUndefined();
    }
  });

  it("число с посторонними символами не читается", () => {
    // «1 234 руб.» — это подпись, а не значение: прочитав её, мы взяли бы
    // сумму из ячейки, которая суммой не является.
    expect(cellNumber("1 234 руб.")).toBeUndefined();
    expect(cellNumber("18 038,61 ₽")).toBeUndefined();
    expect(cellNumber("12,,5")).toBeUndefined();
  });
});
