/**
 * Число из ячейки — с разделителями разрядов и десятичной запятой.
 *
 * ЗАЧЕМ ЭТО ПОЯВИЛОСЬ
 *
 * Пока источником были только книги Excel, число приходило машинным:
 * `18038.61`. Оба разбора — ЛСР и ССРСС — проверяли его шаблоном
 * `/^-?\d+(?:\.\d+)?$/` и на этом заканчивали.
 *
 * Выгрузка в CSV пишет число ТАК, КАК ОНО ПОКАЗАНО ЧЕЛОВЕКУ: `18 038,61` в
 * русской локали, `18,038.61` в американской. Шаблон такое число не признаёт и
 * отвечает «не число», а вызывающий на этом теряет позицию.
 *
 * Замерено на курганской ЛСР: выгрузка той же сметы в CSV с русским форматом
 * чисел давала НОЛЬ позиций из сорока четырёх — «Всего по позиции» оставалось
 * без суммы. Это ровно тот исход, который выглядит успехом: смета «прочитана»,
 * и в ней ничего нет.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ МОДУЛЕМ
 *
 * Шаблон был записан ДВАЖДЫ — в разборе ЛСР и в разборе ССРСС. Две записи
 * одного правила расходятся молча: починив ЛСР, мы оставили бы сводный расчёт
 * терять числа, и расхождение между сметами и сводным вылезло бы как находка
 * системы, а не как её ошибка.
 *
 * ГДЕ ЗАПЯТАЯ ДЕСЯТИЧНАЯ, А ГДЕ РАЗРЯДНАЯ — РЕШАЕТСЯ, И РЕШЕНИЕ НАЗВАНО
 *
 * Однозначного ответа не существует: `1,500` — это и «одна тысяча пятьсот», и
 * «одна целая пять». Правила ниже разрешают неоднозначность так, чтобы
 * ошибиться было НЕЛЬЗЯ МОЛЧА: где решить невозможно, число остаётся
 * непрочитанным, и это видно.
 */

/** Число в машинной записи: точка как разделитель, возможен минус. */
const NUMERIC = /^-?\d+(?:\.\d+)?$/;

/**
 * Разделители разрядов, которые ПРОСТО УДАЛЯЮТСЯ.
 *
 * Все они — пробелы разной ширины плюс апостроф (швейцарская запись, приезжает
 * из некоторых систем). Ни один из них не бывает десятичным ни в одной локали,
 * поэтому решать тут нечего.
 */
const GROUPING = /[\s   ']/g;

/** Сжимает пробелы и убирает края — как `normalize` у листа. */
function trimmed(value: string | undefined): string {
  return (value ?? "").replace(/\s+/g, " ").trim();
}

/**
 * Разбито ли на группы разрядов ПО ФОРМЕ: одна-три цифры, дальше ровно по три.
 *
 * Проверять обязательно. Без этого `12,,5` считалось «числом с разрядными
 * запятыми» и превращалось в `125` — мусор, признанный числом и попадающий в
 * сумму. Поймано набором: правило «несколько запятых — все разрядные» верно
 * лишь для того, что и правда сгруппировано.
 */
function сгруппировано(text: string, separator: string): boolean {
  const escaped = separator === "." ? "\\." : separator;

  return new RegExp(`^-?\\d{1,3}(?:${escaped}\\d{3})+$`).test(text);
}

export function cellNumber(value: string | undefined): string | undefined {
  const text = trimmed(value).replace(GROUPING, "");

  // Уже машинное число — самый частый случай, и трогать его нельзя: одна точка
  // здесь ВСЕГДА десятичная, как её и читали книги. `18.038` — это восемнадцать
  // целых, а не восемнадцать тысяч.
  if (NUMERIC.test(text)) return text;

  const запятых = (text.match(/,/g) ?? []).length;
  const точек = (text.match(/\./g) ?? []).length;

  // Оба знака сразу — неоднозначности нет: десятичный тот, что ПРАВЕЕ, а
  // второй разрядный. Так записаны и `18,038.61`, и `18.038,61`.
  if (запятых > 0 && точек > 0) {
    const десятичный = text.lastIndexOf(",") > text.lastIndexOf(".") ? "," : ".";
    const разрядный = десятичный === "," ? "." : ",";

    const граница = text.lastIndexOf(десятичный);
    const целая = text.slice(0, граница);
    const дробная = text.slice(граница + 1);

    if (!сгруппировано(целая, разрядный)) return undefined;

    return проверить(`${целая.split(разрядный).join("")}.${дробная}`);
  }

  // Несколько запятых — все разрядные: десятичная бывает одна.
  if (запятых > 1) {
    return сгруппировано(text, ",") ? проверить(text.split(",").join("")) : undefined;
  }

  if (запятых === 1) {
    const [целая = "", дробная = ""] = text.split(",");

    // РОВНО ТРИ ЦИФРЫ ПОСЛЕ ЗАПЯТОЙ — ЕДИНСТВЕННЫЙ СПОРНЫЙ СЛУЧАЙ.
    //
    // Считаем разрядной, но только если целая часть выглядит группой: одна-три
    // цифры без ведущего нуля. Условие про ноль существенно: `0,001` — это
    // количество «одна тысячная», и приняв запятую за разрядную, мы получили бы
    // `0001`, то есть единицу — ошибку в тысячу раз, выглядящую как число.
    //
    // Деньги в сметах всегда с двумя знаками, поэтому спор задевает только
    // количества, а трёхзначная дробь без ведущего нуля («1,500 т») в них
    // пишется как «1,5».
    const разрядная = дробная.length === 3 && /^-?[1-9]\d{0,2}$/.test(целая);

    return проверить(разрядная ? целая + дробная : `${целая}.${дробная}`);
  }

  // Несколько точек — все разрядные. Одна точка сюда не доходит: её принял
  // первый шаг.
  if (точек > 1) {
    return сгруппировано(text, ".") ? проверить(text.split(".").join("")) : undefined;
  }

  return undefined;
}

/** Итог нормализации обязан быть числом: иначе это не число, а мусор. */
function проверить(text: string): string | undefined {
  return NUMERIC.test(text) ? text : undefined;
}
