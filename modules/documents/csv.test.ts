/**
 * CSV: что именно здесь может сломаться незаметно.
 *
 * Все три свойства проверяются потому, что нарушение каждого выглядит как
 * УСПЕХ, а не как ошибка:
 *
 *  · неверный разделитель даёт лист в одну колонку — «смета прочитана, позиций
 *    ноль», что неотличимо от пустой сметы;
 *  · неверная кодировка даёт кракозябры — шапка не находится, и итог тот же;
 *  · сдвиг нумерации строк даёт координату, которая указывает не туда, — а
 *    ссылка «откуда взято» и есть главное обещание продукта (§12.1д).
 */
import { describe, expect, it } from "vitest";

import { columnLetter, csvShape, csvSheet, decodeText, splitLine } from "./csv.js";
import { cell } from "./sheet.js";

/** Кириллица в `windows-1251`: так сохраняет CSV русский Excel. */
function в1251(text: string): Uint8Array {
  const карта: Record<string, number> = {};
  for (let code = 0xc0; code <= 0xff; code += 1) {
    карта[String.fromCharCode(0x410 + (code - 0xc0))] = code;
  }
  карта["ё"] = 0xb8;
  карта["Ё"] = 0xa8;

  return Uint8Array.from([...text].map((char) => карта[char] ?? char.charCodeAt(0)));
}

describe("кодировка определяется, а не назначается", () => {
  it("читает UTF-8", () => {
    expect(decodeText(new TextEncoder().encode("Устройство стяжки"))).toBe("Устройство стяжки");
  });

  it("читает windows-1251, а не выдаёт кракозябры", () => {
    // Назначь мы UTF-8, здесь вышло бы «Óñòðîéñòâî» — и шапка сметы не нашлась
    // бы, то есть файл «прочитался» бы в ноль позиций.
    expect(decodeText(в1251("Устройство стяжки"))).toBe("Устройство стяжки");
  });

  it("снимает метку порядка байтов, а не считает её частью первой ячейки", () => {
    const сbom = Uint8Array.from([0xef, 0xbb, 0xbf, ...new TextEncoder().encode("№;Наименование")]);

    // С меткой в начале первая ячейка была бы «﻿№», и поиск колонки «№»
    // по точному совпадению её не нашёл бы.
    expect(decodeText(сbom)).toBe("№;Наименование");
    expect(cell(csvSheet(decodeText(сbom)), 1, "A")).toBe("№");
  });
});

describe("разделитель", () => {
  it("точка с запятой у русского Excel", () => {
    const текст = "№;Наименование;Кол-во\n1;Стяжка;10\n2;Штукатурка;20";

    expect(csvShape(текст.split("\n")).delimiter).toBe(";");
  });

  it("запятая у веб-выгрузки", () => {
    const текст = "num,name,qty\n1,Стяжка,10\n2,Штукатурка,20";

    expect(csvShape(текст.split("\n")).delimiter).toBe(",");
  });

  it("не путает запятую в наименовании с разделителем", () => {
    // Запятых в файле больше, чем точек с запятой: счёт вхождений выбрал бы
    // запятую и разложил бы «Установка блоков» и «4 шт» по разным колонкам,
    // сдвинув все суммы вправо.
    const текст = [
      "№;Наименование;Сумма",
      "1;Установка блоков, серия БК-3, 4 шт;1000",
      "2;Кладка стен, толщина 380 мм;2000",
      "3;Монтаж перемычек, тип ПР-1, ПР-2;3000",
    ].join("\n");

    expect(csvShape(текст.split("\n")).delimiter).toBe(";");
    expect(cell(csvSheet(текст), 2, "B")).toBe("Установка блоков, серия БК-3, 4 шт");
  });

  it("шапка объекта сверху не сбивает ширину таблицы", () => {
    // У выгрузок первые строки — название объекта в одну ячейку. Считай мы
    // ширину по ПЕРВОЙ строке, вышла бы единица, и таблица была бы отвергнута.
    const текст = [
      "Объект: Курганский комбинат",
      "Смета № 02-01-01",
      "№;Наименование;Сумма",
      "1;Стяжка;1000",
      "2;Штукатурка;2000",
    ].join("\n");

    const форма = csvShape(текст.split("\n"));

    expect(форма.delimiter).toBe(";");
    expect(форма.columns).toBe(3);
  });
});

describe("кавычки", () => {
  it("разделитель внутри кавычек не делит ячейку", () => {
    expect(splitLine('1,"Стяжка, армированная",10', ",")).toEqual(["1", "Стяжка, армированная", "10"]);
  });

  it("удвоенная кавычка — это одна кавычка, а не конец поля", () => {
    expect(splitLine('1;"Блок ""БК-3""";10', ";")).toEqual(["1", 'Блок "БК-3"', "10"]);
  });
});

describe("координата в источнике", () => {
  it("номер строки — это номер строки ФАЙЛА, а не порядок непустых", () => {
    // Пустая строка внутри выгрузки — обычное дело (разрыв между разделами).
    // Выбросив её из нумерации, мы сослались бы на строку 3 там, где человек,
    // открыв файл, увидит на строке 3 пустоту, а нужную позицию — на четвёртой.
    const лист = csvSheet("№;Наименование\n1;Стяжка\n\n2;Штукатурка");

    expect(cell(лист, 4, "B")).toBe("Штукатурка");
    expect(лист.rows.has(3)).toBe(false);
  });

  it("колонки называются буквами, как в книге", () => {
    expect(columnLetter(0)).toBe("A");
    expect(columnLetter(25)).toBe("Z");
    // Двадцать шестая колонка — `AA`, а не `BA`: смета в тридцать колонок
    // встречается, и ошибка переноса дала бы ссылку на несуществующую ячейку.
    expect(columnLetter(26)).toBe("AA");
    expect(columnLetter(27)).toBe("AB");
  });

  it("пустая ячейка не занимает места, как и в книге", () => {
    const лист = csvSheet("1;;10");

    expect(лист.rows.get(1)?.has("B")).toBe(false);
    expect(cell(лист, 1, "C")).toBe("10");
  });
});
