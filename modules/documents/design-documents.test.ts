/**
 * Текст рабочей документации для агента.
 *
 * ЧТО ЗДЕСЬ ЗАЩИЩАЕТСЯ
 *
 * Три свойства, каждое из которых ломается молча:
 *
 * 1. **Колонтитул снимается, но не исчезает.** Он несёт шифр проекта и название
 *    раздела: один раз это сведение, тридцать три раза это шум. Снять его
 *    целиком значило бы отнять у агента название документа, который он читает.
 * 2. **Бюджет делится между подшивками, а не достаётся первой.** «ЭОМ» и «СОТ» —
 *    разные разделы проекта, и отдать один целиком вместо двух наполовину
 *    значит решить за агента, какой раздел важнее.
 * 3. **Сокращение объявляется.** Агент, получивший половину документации и не
 *    знающий об этом, отвечает так же уверенно, как получивший её целиком, — и
 *    его «в РД этого нет» становится утверждением о нашем бюджете, а не о
 *    проекте.
 */
import { describe, expect, it } from "vitest";

import { briefOf, briefToPrompt, condense } from "./design-documents.js";

/** Лист с колонтитулом: тот же текст сверху, разное содержание внизу. */
function лист(номер: number): string {
  return ["Запрещается без письменного разрешения собственника", "АО «Институт»", `содержание листа ${номер}`].join(
    "\n",
  );
}

describe("сжатие рабочей документации", () => {
  it("оставляет колонтитул один раз, а не тридцать три", () => {
    const текст = Array.from({ length: 33 }, (_, index) => лист(index)).join("\n");
    const сжато = condense(текст, 33);

    expect(сжато.split("\n").filter((line) => line.startsWith("Запрещается"))).toHaveLength(1);
    // И он не выброшен: шифр проекта и название раздела живут именно там.
    expect(сжато).toContain("Запрещается без письменного разрешения собственника");
  });

  it("не трогает содержание листов", () => {
    const текст = Array.from({ length: 33 }, (_, index) => лист(index)).join("\n");
    const сжато = condense(текст, 33);

    for (let index = 0; index < 33; index += 1) {
      expect(сжато, `содержание листа ${index} потеряно`).toContain(`содержание листа ${index}`);
    }
  });

  it("не считает колонтитулом строку, повторившуюся дважды на сорока страницах", () => {
    // Порог — треть страниц. Совпавшая пара строк чертежа не типографика.
    const текст = ["повтор", "повтор", ...Array.from({ length: 38 }, (_, i) => `строка ${i}`)].join("\n");

    expect(condense(текст, 40).split("\n").filter((line) => line === "повтор")).toHaveLength(2);
  });
});

describe("бюджет выжимки", () => {
  const длинный = { path: "РД/длинный.pdf", pages: 50, text: "д".repeat(50_000) };
  const короткий = { path: "РД/короткий.pdf", pages: 2, text: "к".repeat(1_000) };

  it("влезающее отдаётся целиком и не помечается обрезанным", () => {
    const brief = briefOf([короткий], 40_000);

    expect(brief.documents[0]?.text).toHaveLength(1_000);
    expect(brief.documents[0]?.truncated).toBe(false);
    expect(brief.shown).toBe(brief.chars);
  });

  it("короткая подшивка не вытесняется длинной", () => {
    // Иначе один длинный раздел съедает бюджет и второй не попадает вовсе.
    const brief = briefOf([длинный, короткий], 10_000);
    const виден = brief.documents.find((item) => item.path === короткий.path);

    expect(виден?.text).toHaveLength(1_000);
    expect(виден?.truncated).toBe(false);
  });

  it("остаток короткой достаётся длинной, а бюджет не превышается", () => {
    const brief = briefOf([длинный, короткий], 10_000);

    expect(brief.shown).toBe(10_000);
    expect(brief.documents.find((item) => item.path === длинный.path)?.text).toHaveLength(9_000);
  });

  it("обрезанное помечено, и замер источника сохранён", () => {
    const brief = briefOf([длинный], 1_000);
    const виден = brief.documents[0];

    expect(виден?.truncated).toBe(true);
    // Замер отвечает на вопрос «сколько мы НЕ показали».
    expect(виден?.chars).toBe(50_000);
    expect(виден?.text).toHaveLength(1_000);
  });
});

describe("выжимка в промпт", () => {
  it("объявляет неполноту словами, а не молчит о ней", () => {
    const строки = briefToPrompt(briefOf([{ path: "РД/а.pdf", pages: 50, text: "д".repeat(50_000) }], 1_000));

    expect(строки.join("\n")).toContain("показана ЧАСТЬ документации");
    // И называет границу механизма: чертежи мы не разбираем.
    expect(строки.join("\n")).toContain("Геометрия чертежей");
  });

  it("полную документацию неполной не объявляет", () => {
    const строки = briefToPrompt(briefOf([{ path: "РД/а.pdf", pages: 1, text: "коротко" }], 1_000));

    expect(строки.join("\n")).not.toContain("показана ЧАСТЬ");
    expect(строки.join("\n")).toContain("коротко");
  });

  it("без документации не пишет ничего", () => {
    // Пустой заголовок «РАБОЧАЯ ДОКУМЕНТАЦИЯ:» без содержания сообщал бы, что
    // она есть и пуста, а её просто нет.
    expect(briefToPrompt(briefOf([], 1_000))).toEqual([]);
  });
});
