/**
 * Тесты написаны до реализации. Ревизии извлечения — роадмап M4:
 *
 *   «Immutable `ExtractionRevision`, правка как новая ревизия, подтверждение по
 *    ХЭШУ ПРЕДМЕТА; сильный вердикт ЗАБЛОКИРОВАН до подтверждения критичных
 *    ревизий.»
 *
 * ЗАЧЕМ НЕИЗМЕНЯЕМОСТЬ
 *
 * Извлечённое значение правят руками: разбор взял из объединённой ячейки не то
 * число, единица измерения прочиталась как «шт» вместо «компл». Если правка
 * ЗАМЕНЯЕТ исходное значение, восстановить, что именно система прочитала в
 * документе, становится невозможно — а спор с подрядчиком идёт как раз об этом:
 * «в смете написано другое». Ответ «система читает так, человек исправил вот
 * на это, вот обе версии» — единственный, который защищает обе стороны.
 *
 * ПОЧЕМУ ПОДТВЕРЖДЕНИЕ ПРИВЯЗАНО К ХЭШУ
 *
 * Подтверждение — это подпись человека под конкретным значением. Если оно
 * переживает изменение предмета, то подписью прикрывают то, чего человек не
 * видел. Подтверждение, пережившее правку, ХУЖЕ отсутствия подтверждения:
 * отсутствие видно, а ложное подтверждение выглядит проверенным.
 *
 * ПОЧЕМУ СИЛЬНЫЙ ВЕРДИКТ БЛОКИРУЕТСЯ
 *
 * Сильный вердикт («смета проверена») опирается на числа. Если критичное число
 * поправлено руками и не подтверждено, вердикт опирается на правку, за которую
 * никто не расписался.
 */
import { describe, expect, it } from "vitest";

import { ExtractionLedger } from "./extraction-revision.js";

const ИСХОДНАЯ = {
  subject: "позиция-14/количество",
  value: "15.24",
  unit: "км",
  source: { document: "ЭОМ.xlsx", locator: "C14" },
  critical: true,
};

describe("неизменяемость ревизий", () => {
  it("правка создаёт НОВУЮ ревизию, не трогая исходную", () => {
    const журнал = new ExtractionLedger();
    const первая = журнал.extract(ИСХОДНАЯ);

    журнал.revise(первая.id, { value: "15.42", author: "Людмила", reason: "опечатка разбора" });

    expect(журнал.get(первая.id)?.value).toBe("15.24");
    expect(журнал.current(ИСХОДНАЯ.subject)?.value).toBe("15.42");
  });

  it("хранит цепочку ревизий целиком: спор идёт о том, что было в документе", () => {
    const журнал = new ExtractionLedger();
    const первая = журнал.extract(ИСХОДНАЯ);
    const вторая = журнал.revise(первая.id, { value: "15.42", author: "Людмила", reason: "опечатка" });
    журнал.revise(вторая.id, { value: "15.40", author: "Денчик", reason: "сверено по РД" });

    const история = журнал.history(ИСХОДНАЯ.subject);

    expect(история.map((r) => r.value)).toEqual(["15.24", "15.42", "15.40"]);
    expect(история[0]?.origin).toBe("разбор");
    expect(история[1]?.origin).toBe("правка");
  });

  it("правка требует причины: значение без объяснения нечем защитить", () => {
    const журнал = new ExtractionLedger();
    const первая = журнал.extract(ИСХОДНАЯ);

    expect(() => журнал.revise(первая.id, { value: "99", author: "Людмила", reason: "" })).toThrow(
      /причин/i,
    );
  });

  it("не даёт править ревизию, которая уже не последняя", () => {
    // Иначе две правки от разных людей разойдутся в две ветки, и «текущее
    // значение» станет вопросом порядка записи.
    const журнал = new ExtractionLedger();
    const первая = журнал.extract(ИСХОДНАЯ);
    журнал.revise(первая.id, { value: "15.42", author: "Людмила", reason: "опечатка" });

    expect(() => журнал.revise(первая.id, { value: "15.30", author: "Ваныч", reason: "иначе" })).toThrow(
      /не последн/i,
    );
  });
});

describe("подтверждение по хэшу предмета", () => {
  it("подтверждает конкретную ревизию", () => {
    const журнал = new ExtractionLedger();
    const первая = журнал.extract(ИСХОДНАЯ);

    журнал.confirm(первая.id, { by: "Денчик", at: "2026-08-31" });

    expect(журнал.get(первая.id)?.confirmedBy).toBe("Денчик");
  });

  it("ПЕРЕСТАЁТ считать предмет подтверждённым после правки", () => {
    // Подтверждение, пережившее правку, хуже его отсутствия: отсутствие видно,
    // а ложное подтверждение выглядит проверенным.
    const журнал = new ExtractionLedger();
    const первая = журнал.extract(ИСХОДНАЯ);
    журнал.confirm(первая.id, { by: "Денчик", at: "2026-08-31" });

    журнал.revise(первая.id, { value: "15.42", author: "Людмила", reason: "опечатка" });

    expect(журнал.isConfirmed(ИСХОДНАЯ.subject)).toBe(false);
  });

  it("оставляет подтверждение НА СТАРОЙ ревизии: подпись не отзывается задним числом", () => {
    // Человек действительно подтвердил то значение. Отменять его подпись —
    // переписывать историю; она просто перестаёт относиться к текущему предмету.
    const журнал = new ExtractionLedger();
    const первая = журнал.extract(ИСХОДНАЯ);
    журнал.confirm(первая.id, { by: "Денчик", at: "2026-08-31" });
    журнал.revise(первая.id, { value: "15.42", author: "Людмила", reason: "опечатка" });

    expect(журнал.get(первая.id)?.confirmedBy).toBe("Денчик");
  });

  it("считает предмет подтверждённым, когда подтверждена ПОСЛЕДНЯЯ ревизия", () => {
    const журнал = new ExtractionLedger();
    const первая = журнал.extract(ИСХОДНАЯ);
    const вторая = журнал.revise(первая.id, { value: "15.42", author: "Людмила", reason: "опечатка" });
    журнал.confirm(вторая.id, { by: "Денчик", at: "2026-08-31" });

    expect(журнал.isConfirmed(ИСХОДНАЯ.subject)).toBe(true);
  });

  it("не подтверждает предмет, которого не извлекали", () => {
    const журнал = new ExtractionLedger();

    expect(журнал.isConfirmed("позиция-99/количество")).toBe(false);
  });

  it("хэш ревизии меняется вместе со значением", () => {
    // Хэш и есть то, к чему привязано подтверждение.
    const журнал = new ExtractionLedger();
    const первая = журнал.extract(ИСХОДНАЯ);
    const вторая = журнал.revise(первая.id, { value: "15.42", author: "Людмила", reason: "опечатка" });

    expect(вторая.contentHash).not.toBe(первая.contentHash);
  });

  it("одинаковое содержание даёт одинаковый хэш", () => {
    const первый = new ExtractionLedger().extract(ИСХОДНАЯ);
    const второй = new ExtractionLedger().extract(ИСХОДНАЯ);

    expect(первый.contentHash).toBe(второй.contentHash);
  });
});

describe("блокировка сильного вердикта", () => {
  it("БЛОКИРУЕТ, пока критичная правка не подтверждена", () => {
    const журнал = new ExtractionLedger();
    const первая = журнал.extract(ИСХОДНАЯ);
    журнал.revise(первая.id, { value: "15.42", author: "Людмила", reason: "опечатка" });

    const итог = журнал.strongVerdictAllowed();

    expect(итог.allowed).toBe(false);
    expect(итог.blocking).toHaveLength(1);
    expect(итог.reason).toContain("позиция-14/количество");
  });

  it("РАЗРЕШАЕТ, когда критичная правка подтверждена", () => {
    const журнал = new ExtractionLedger();
    const первая = журнал.extract(ИСХОДНАЯ);
    const вторая = журнал.revise(первая.id, { value: "15.42", author: "Людмила", reason: "опечатка" });
    журнал.confirm(вторая.id, { by: "Денчик", at: "2026-08-31" });

    expect(журнал.strongVerdictAllowed().allowed).toBe(true);
  });

  it("НЕ требует подтверждения того, что система прочитала сама", () => {
    // Разбор без правки подтверждать не надо: подтверждают ВМЕШАТЕЛЬСТВО
    // человека, а не работу парсера. Иначе подтверждать пришлось бы каждую из
    // тысяч позиций, и подтверждение обесценилось бы.
    const журнал = new ExtractionLedger();
    журнал.extract(ИСХОДНАЯ);

    expect(журнал.strongVerdictAllowed().allowed).toBe(true);
  });

  it("не блокирует вердикт из-за НЕкритичной правки", () => {
    const журнал = new ExtractionLedger();
    const первая = журнал.extract({ ...ИСХОДНАЯ, subject: "шапка/исполнитель", critical: false });
    журнал.revise(первая.id, { value: "ООО Ромашка", author: "Настенька", reason: "опечатка" });

    expect(журнал.strongVerdictAllowed().allowed).toBe(true);
  });

  it("называет ВСЕ незакрытые предметы, а не первый попавшийся", () => {
    // Человек, увидевший один блокирующий предмет, подтвердит его и снова
    // упрётся в блокировку. Список нужен целиком с первого раза.
    const журнал = new ExtractionLedger();

    for (const subject of ["позиция-14/количество", "позиция-21/количество"]) {
      const revision = журнал.extract({ ...ИСХОДНАЯ, subject });
      журнал.revise(revision.id, { value: "1", author: "Людмила", reason: "правка" });
    }

    expect(журнал.strongVerdictAllowed().blocking).toHaveLength(2);
  });
});
