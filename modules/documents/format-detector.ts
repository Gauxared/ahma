/**
 * ZIP БЕЗ СИГНАТУРЫ В НАЧАЛЕ ФАЙЛА.
 *
 * ЗАМЕРЕНО НА ЭТАЛОННОМ КЕЙСЕ «ЙОШКАР-ОЛА» 09.09.2026: два приложения тендерной
 * документации — ПСД (31 файл: сметы и прайс-листы в PDF) и РД (вложенный архив
 * рабочей документации) — начинались НЕ с `PK\x03\x04`. Проверка сигнатуры по
 * началу файла объявляла их «неопознанными», и вместо 31 документа роль
 * получала 225 КБ «печатных последовательностей из двоичного файла».
 *
 * ТО ЕСТЬ ТЕРЯЛОСЬ САМОЕ ЦЕННОЕ В КОМПЛЕКТЕ, и терялось молча: файл «прочитан»,
 * знаки есть, формат назван. `unzip` и Python открывают такой архив без единой
 * жалобы — они ищут ЦЕНТРАЛЬНЫЙ КАТАЛОГ В КОНЦЕ, а не заголовок в начале.
 *
 * Так устроен формат: авторитетным перечнем записей является каталог в хвосте
 * (`PK\x05\x06`), и начало файла может занимать что угодно — префикс
 * самораспаковки, склейка, мусор от выгрузки. Поэтому и мы смотрим в хвост.
 */
export function zipTailSignature(bytes: Buffer): boolean {
  // Каталог заканчивается записью EOCD, за которой стоит комментарий длиной до
  // 65 535 байт: дальше этого окна искать бессмысленно.
  const окно = bytes.subarray(Math.max(0, bytes.length - 66_000));
  return окно.lastIndexOf(EOCD) !== -1;
}

function extensionOf(fileName: string): string {
  const dot = fileName.lastIndexOf(".");
  return dot === -1 ? "" : fileName.slice(dot + 1).toLowerCase();
}

