/**
 * ВЫГРУЗКА ГРАНД-СМЕТЫ С РУССКИМ КОРНЕМ ОПОЗНАЁТСЯ.
 *
 * ЧТО ЛОМАЛОСЬ. Признак формата проверялся выражением `/<Смета\b/i`. В
 * JavaScript граница слова `\b` считается ПО ASCII: между «а» в «<Смета» и
 * следующим «>» её нет, и условие не срабатывало НИКОГДА. Файл с русским
 * корневым элементом опознавался «просто XML» — то есть уходил к роли текстом
 * вместо разбора в позиции.
 *
 * МОЛЧАЛИВОСТЬ ЗДЕСЬ ПОЛНАЯ: формат назван, файл «прочитан», роль получила
 * содержимое. Не появляются только позиции — а их отсутствие на смете вне формы
 * 421/пр выглядит нормой.
 *
 * ТУ ЖЕ ЛОВУШКУ УЖЕ ЛОВИЛИ в разборе ГРАНД-Сметы (`grand-smeta.ts`, там про неё
 * есть комментарий) — и не заметили, что она осталась в детекторе. Правило,
 * усвоенное в одном месте, обязано быть проверено во всех.
 */
import { describe, expect, it } from "vitest";

import { detectFormat } from "./format-detector.js";

const xml = (корень: string): Buffer =>
  Buffer.from(`<?xml version="1.0" encoding="utf-8"?>\n<${корень} Название="ЛСР-02-01-01">\n  <Позиция/>\n</${корень}>\n`, "utf8");

describe("опознание выгрузки ГРАНД-Сметы", () => {
  it("русский корень «Смета» опознаётся, а не уходит в общий XML", () => {
    expect(detectFormat({ fileName: "ЛСР-02-01-01.xml", bytes: xml("Смета") }).format).toBe("grand-smeta-xml");
  });

  it("латинские корни опознавались и раньше — правка их не задела", () => {
    expect(detectFormat({ fileName: "смета.xml", bytes: xml("Document") }).format).toBe("grand-smeta-xml");
    expect(detectFormat({ fileName: "смета.xml", bytes: xml("GrandSmeta") }).format).toBe("grand-smeta-xml");
  });

  it("чужой XML остаётся обычным XML: признак не расширился до всего подряд", () => {
    expect(detectFormat({ fileName: "конфигурация.xml", bytes: xml("Настройки") }).format).toBe("xml");
  });
});
