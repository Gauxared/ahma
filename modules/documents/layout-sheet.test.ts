/**
 * ТЕКСТ PDF С РАСКЛАДКОЙ СТАНОВИТСЯ ЛИСТОМ.
 *
 * ЗАМЕР, ИЗ-ЗА КОТОРОГО ЭТОТ НАБОР НАПИСАН (09.09.2026, кейс «Благоустройство»,
 * локальный сметный расчёт на 36 страниц): просветы, посчитанные ПО ВСЕМУ
 * ДОКУМЕНТУ, не оставляли ни одного — страницы шире и уже друг друга (247, 266,
 * 275 знаков), титул и примечания идут сплошным текстом. Читатель молча
 * возвращал пустой лист. По странице просветов 15–24, то есть таблица видна.
 */
import { describe, expect, it } from "vitest";

import { layoutSheet } from "./layout-sheet.js";

const СТРАНИЦА = [
  "                    ЛОКАЛЬНЫЙ СМЕТНЫЙ РАСЧЁТ № 02-01-01",
  "",
  " №      Обоснование        Наименование работ      Ед.      Кол-во     Всего, руб.",
  " 1      ГЭСН09-01-015      Монтаж конструкций      т        6,25       625 905,00",
  " 2      ФССЦ-01.7.15       Болты с гайками         кг       128,40     11 830,00",
  " 3      ГЭСН06-01-001      Устройство основания    м3       340,10     1 049 030,00",
].join("\n");

describe("лист из текста с раскладкой", () => {
  const sheet = layoutSheet(СТРАНИЦА, "Смета.pdf");

  it("колонки находятся по просветам, а не по догадке о ширине", () => {
    const строка = sheet.rows.get(4);

    expect(строка?.get("A")).toBe("1");
    expect(строка?.get("B")).toBe("ГЭСН09-01-015");
    expect(строка?.get("C")).toBe("Монтаж конструкций");
    expect(строка?.get("D")).toBe("т");
    expect(строка?.get("E")).toBe("6,25");
    expect(строка?.get("F")).toBe("625 905,00");
  });

  it("одиночный пробел колонку не режет: он стоит между словами", () => {
    // «Болты с гайками» — одна ячейка, а не три.
    expect(sheet.rows.get(5)?.get("C")).toBe("Болты с гайками");
  });

  it("номер строки листа — номер строки текста: по нему человек находит место", () => {
    expect(sheet.rows.get(3)?.get("C")).toBe("Наименование работ");
  });
});

describe("документ из нескольких страниц", () => {
  /**
   * Вторая страница той же сметы НАБРАНА УЖЕ первой: так выходит при сканировании
   * и при разной ширине полей. Колонка «Всего» стоит на другом знаке, но на той
   * же доле ширины — и обязана попасть в ту же колонку листа.
   */
  const ДОКУМЕНТ = [
    СТРАНИЦА,
    [
      " №    Обоснование    Наименование работ   Ед.    Кол-во   Всего, руб.",
      " 4    ГЭСН08-02-001  Кладка стен          м3     212,00   3 480 500,00",
      " 5    ГЭСН07-05-016  Монтаж перемычек     шт     96,00    148 200,00",
      " 6    ГЭСН09-03-014  Окраска фасада       м2     1800,00  441 000,00",
    ].join("\n"),
  ].join("\f");

  const sheet = layoutSheet(ДОКУМЕНТ, "Смета.pdf");

  it("страницы сводятся в один лист со сквозной нумерацией строк", () => {
    // Строки первой страницы — 1…6, второй — начиная с седьмой.
    expect(sheet.rows.get(4)?.get("C")).toBe("Монтаж конструкций");
    expect([...sheet.rows.keys()].some((row) => row > 6)).toBe(true);
  });

  it("колонка узкой страницы попадает туда же, куда колонка широкой", () => {
    const вторая = [...sheet.rows.entries()].find(([, cells]) => cells.get("C") === "Кладка стен");

    expect(вторая?.[1].get("A")).toBe("4");
    expect(вторая?.[1].get("E")).toBe("212,00");
    expect(вторая?.[1].get("F")).toBe("3 480 500,00");
  });
});

describe("там, где таблицы нет", () => {
  it("сплошная проза листом не притворяется", () => {
    const проза = [
      "Настоящий проект разработан на основании технического задания заказчика.",
      "Работы выполняются в две смены с соблюдением требований охраны труда.",
    ].join("\n");

    expect(layoutSheet(проза, "Записка.pdf").rows.size).toBe(0);
  });

  it("пустой текст даёт пустой лист, а не выдуманную строку", () => {
    expect(layoutSheet("", "Скан.pdf").rows.size).toBe(0);
  });
});
