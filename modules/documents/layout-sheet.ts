/**
 * ТАБЛИЦА ИЗ ТЕКСТА С СОХРАНЁННОЙ РАСКЛАДКОЙ — PDF СТАНОВИТСЯ ЛИСТОМ.
 *
 * ЗАЧЕМ. Смета, присланная в PDF, не давала ни одной позиции: у PDF нет
 * «книги», есть страницы с текстом. Текст шёл ролям, и это лучше молчания, но
 * координаты строки, шифра, объёма и суммы у него не было — то есть не было ни
 * сходимости, ни поиска дублей, ни таблицы на экране.
 *
 * НА ЧЁМ ЭТО СТАЛО ВОЗМОЖНО. `pdftotext -layout` (poppler) расставляет пробелы
 * так, как текст стоит на странице: колонки остаются колонками. Замерено на
 * кейсе «Благоустройство» 09.09.2026: прежний текстовый слой давал по одному
 * значению на строку (125 486 знаков без структуры), раскладка — 462 240 знаков
 * со строками сметы целиком.
 *
 * КАК НАХОДЯТСЯ КОЛОНКИ. Не по догадке о ширине, а по ПРОСВЕТАМ: позиция, где
 * ни у одной табличной строки страницы нет знака, — граница колонок. Так же их
 * видит человек: колонки разделены пустотой, идущей сверху вниз.
 *
 * ПРОСВЕТЫ СЧИТАЮТСЯ ПО СТРАНИЦЕ, А НЕ ПО ДОКУМЕНТУ. Замерено на том же кейсе:
 * по всему документу просветов не остаётся НИ ОДНОГО — страницы шире и уже друг
 * друга (247, 266, 275 знаков), титул и примечания идут сплошным текстом, и
 * любая колонка оказывается кем-нибудь закрыта. По странице просветов 15–24, то
 * есть таблица видна. Это не мелочь раскладки: считая по документу, читатель
 * молча возвращал пустой лист на смете из тридцати шести страниц.
 *
 * КАК СТРАНИЦЫ СВОДЯТСЯ В ОДИН ЛИСТ. Колонки сопоставляются по ДОЛЕ ШИРИНЫ, а
 * не по номеру знака: одна и та же колонка на соседних страницах скана стоит на
 * 118-м и на 126-м знаке, но обе — на 47 % ширины. Эталон берётся со страницы, у
 * которой табличных строк больше всего: она и есть тело сметы. Так вся смета
 * оказывается одним листом с общими колонками, а не тридцатью шестью обрывками.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Никакого распознавания: нет текста — нет и листа. Пустой лист
 * значит «таблицы не видно», а не «таблица пуста» (ТЗ §9, §14).
 */
import type { Sheet } from "./sheet.js";

/** Ширина просвета, признающая границу колонок. Один пробел — пробел в тексте. */
const GAP = 2;

/** Сколько табличных строк нужно странице, чтобы её просветы что-то значили. */
const MIN_TABLE_LINES = 3;

/** Буква колонки по номеру с единицы: 1 → A, 27 → AA. Как в книгах Excel. */
function буква(номер: number): string {
  let результат = "";
  let n = номер;

  while (n > 0) {
    const остаток = (n - 1) % 26;
    результат = String.fromCharCode(65 + остаток) + результат;
    n = Math.floor((n - остаток) / 26);
  }

  return результат;
}

/**
 * Похожа ли строка на строку таблицы: есть широкие разрывы между кусками
 * текста. Сплошной абзац таких разрывов не имеет, и по нему колонок не найти.
 */
function табличная(line: string): boolean {
  return line.trim().split(/\s{2,}/u).filter((кусок) => кусок !== "").length >= 3;
}

/** Колонка страницы: отрезок знаков и его середина в долях ширины страницы. */
interface Колонка {
  readonly от: number;
  readonly до: number;
  readonly доля: number;
}

/** Колонки одной страницы по её просветам. */
function колонкиСтраницы(lines: readonly string[]): readonly Колонка[] {
  const табличные = lines.filter((line) => табличная(line));
  if (табличные.length < MIN_TABLE_LINES) return [];

  const ширина = табличные.reduce((max, line) => Math.max(max, line.length), 0);
  if (ширина === 0) return [];

  const занято = new Uint8Array(ширина);

  for (const line of табличные) {
    for (let i = 0; i < line.length && i < ширина; i += 1) {
      if (line[i] !== " " && line[i] !== "\t") занято[i] = 1;
    }
  }

  const отрезки: [number, number][] = [];
  let начало: number | undefined;
  let пусто = 0;

  for (let i = 0; i < ширина; i += 1) {
    if (занято[i] === 1) {
      // Просвет закрывает колонку, только если он ШИРОКИЙ: одиночный пробел
      // стоит между словами наименования, и резать по нему нельзя.
      if (начало !== undefined && пусто >= GAP) {
        отрезки.push([начало, i - пусто]);
        начало = i;
      } else if (начало === undefined) {
        начало = i;
      }
      пусто = 0;
    } else {
      пусто += 1;
    }
  }

  // Последняя колонка идёт до конца строки: за правой границей стоят суммы.
  if (начало !== undefined) отрезки.push([начало, Number.MAX_SAFE_INTEGER]);

  return отрезки.map(([от, до]) => ({
    от,
    до,
    доля: (от + Math.min(до, ширина)) / 2 / ширина,
  }));
}

/** Страница текста: её строки и номер первой из них в документе. */
interface Страница {
  readonly lines: readonly string[];
  readonly перваяСтрока: number;
}

function страницы(text: string): readonly Страница[] {
  const результат: Страница[] = [];
  let номер = 1;

  for (const page of text.replace(/\r\n?/gu, "\n").split("\f")) {
    const lines = page.split("\n");
    результат.push({ lines, перваяСтрока: номер });
    номер += lines.length;
  }

  return результат;
}

/**
 * Лист из текста с раскладкой.
 *
 * Номер строки листа — НОМЕР СТРОКИ ТЕКСТА во всём документе, а не порядковый
 * номер позиции: по нему человек находит место, и он же уходит координатой
 * находки. Номер сквозной через страницы — иначе координата «строка 42»
 * указывала бы на тридцать шесть разных мест.
 */
export function layoutSheet(text: string, name: string): Sheet {
  const pages = страницы(text);
  const rows = new Map<number, ReadonlyMap<string, string>>();

  const разметка = pages.map((page) => ({ page, колонки: колонкиСтраницы(page.lines) }));

  // Эталон — страница с наибольшим числом колонок среди самых «табличных».
  // Именно она несёт тело сметы; титул и примечания колонок почти не дают.
  const эталон = разметка.reduce<readonly Колонка[]>(
    (лучшие, { колонки }) => (колонки.length > лучшие.length ? колонки : лучшие),
    [],
  );

  if (эталон.length < 2) return { name, rows };

  for (const { page, колонки } of разметка) {
    // У страницы без своих колонок (титул, сплошной текст) режущих границ нет.
    // Её строки уходят в первую колонку целиком: терять их нельзя, а разрезать
    // чужими границами — значит рвать предложение посередине слова.
    const границы = колонки.length >= 2 ? колонки : undefined;

    page.lines.forEach((line, индекс) => {
      if (line.trim() === "") return;

      const ячейки = new Map<string, string>();

      if (границы === undefined) {
        ячейки.set("A", line.trim());
      } else {
        for (const колонка of границы) {
          const текст = line
            .slice(колонка.от, колонка.до === Number.MAX_SAFE_INTEGER ? undefined : колонка.до)
            .trim();
          if (текст === "") continue;

          // Колонка страницы приписывается ближайшей по ДОЛЕ ШИРИНЫ колонке
          // эталона: скан смещает знаки, но не смещает вёрстку.
          const номер = ближайшая(эталон, колонка.доля);
          const было = ячейки.get(буква(номер + 1));
          ячейки.set(буква(номер + 1), было === undefined ? текст : `${было} ${текст}`);
        }
      }

      if (ячейки.size > 0) rows.set(page.перваяСтрока + индекс, ячейки);
    });
  }

  return { name, rows };
}

function ближайшая(эталон: readonly Колонка[], доля: number): number {
  let номер = 0;
  let расстояние = Number.POSITIVE_INFINITY;

  эталон.forEach((колонка, индекс) => {
    const d = Math.abs(колонка.доля - доля);
    if (d < расстояние) {
      расстояние = d;
      номер = индекс;
    }
  });

  return номер;
}
