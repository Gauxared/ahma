describe("подтверждение арифметикой", () => {
  /**
   * У ТЕКСТА PDF ЯЧЕЕК НЕТ: границы колонок восстановлены по просветам, а сам
   * текст бывает распознан со скана. Замерено на кейсе «Благоустройство»:
   * разбор такого текста дал 334 «позиции» с объёмом 625905 там, где в
   * документе 6,25905. Выдуманная цифра хуже отсутствующей — она выглядит
   * фактом, и в строительной смете стоит миллионы.
   */
  const ИСКАЖЁННАЯ = sheetFrom("PDF", [
    [1, { A: "№", B: "Наименование работ", C: "Ед.", D: "Количество", E: "Цена", F: "Сумма" }],
    [2, { A: "1", B: "Монтаж павильона", C: "т", D: "625905", E: "59.61", F: "1 049,03" }],
    [3, { A: "2", B: "Болты с гайками", C: "кг", D: "0", E: "11.8307", F: "488 3^0,74" }],
    [4, { A: "3", B: "Трибуна с навесом", C: "компл", D: "9", E: "877 020", F: "2S0;32" }],
  ]);

  it("без требования арифметики разбор состоится: у книги ячейки точны", () => {
    const документ = parseAnyEstimate(ИСКАЖЁННАЯ);
    expect(документ.sections.flatMap((section) => section.positions)).toHaveLength(3);
  });

  it("с требованием — отказ, и он называет замер, а не «не получилось»", () => {
    expect(() => parseAnyEstimate(ИСКАЖЁННАЯ, { требоватьАрифметику: true })).toThrow(/сошлось на 0 строках/u);
  });

  it("честная таблица требование проходит", () => {
    const документ = parseAnyEstimate(КОНТРАКТ, { требоватьАрифметику: true });
    expect(документ.sections.flatMap((section) => section.positions)).toHaveLength(3);
  });
});

