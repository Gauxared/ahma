import { describe, expect, it } from "vitest";

import { sheetFrom } from "../sheet.js";
import { parseAnyEstimate } from "./any-estimate.js";

/** Смета контракта по 44-ФЗ: своя вёрстка, шапка в одну строку. */
const КОНТРАКТ = sheetFrom("Смета контракта", [
  [1, { A: "СМЕТА КОНТРАКТА (ЛОКАЛЬНАЯ)" }],
  [3, { A: "№ п/п", B: "Наименование работ и затрат", C: "Ед. изм.", D: "Кол-во", E: "Цена за ед., руб.", F: "Сумма, руб." }],
  [4, { A: "1", B: "2", C: "3", D: "4", E: "5", F: "6" }],
  [5, { A: "", B: "Раздел 1. Земляные работы" }],
  [6, { A: "1", B: "Разработка грунта экскаватором", C: "м3", D: "1 250,00", E: "412,50", F: "515 625,00" }],
  [7, { A: "2", B: "Уплотнение грунта катком", C: "м3", D: "1 250,00", E: "88,40", F: "110 500,00" }],
  [8, { B: "Итого по разделу 1", F: "626 125,00" }],
  [9, { A: "", B: "Раздел 2. Дорожная одежда" }],
  [10, { A: "3", B: "Устройство основания из щебня", C: "м2", D: "4 300,00", E: "946,00", F: "4 067 800,00" }],
  [11, { B: "ВСЕГО по смете", F: "4 693 925,00" }],
]);

describe("смета своей вёрстки", () => {
  const документ = parseAnyEstimate(КОНТРАКТ);
  const позиции = документ.sections.flatMap((section) => section.positions);

  it("разбирается: три позиции вместо нуля", () => {
    expect(документ.form).toBe("any-layout");
    expect(позиции).toHaveLength(3);
  });

  it("сумма берётся из колонки суммы, а не из цены", () => {
    const грунт = позиции.find((позиция) => позиция.name.includes("экскаватором"));

    expect(грунт?.total).toBe("515625.00");
    expect(грунт?.unitCost).toBe("412.50");
    expect(грунт?.quantity).toBe("1250.00");
    expect(грунт?.unit).toBe("м3");
  });

  it("строка нумерации колонок позицией не становится", () => {
    expect(позиции.some((позиция) => позиция.name === "2")).toBe(false);
  });

  it("разделы читаются по заголовкам, а итог раздела остаётся при разделе", () => {
    expect(документ.sections.map((section) => section.name)).toEqual([
      "Раздел 1. Земляные работы",
      "Раздел 2. Дорожная одежда",
    ]);
    expect(документ.sections[0]?.declaredTotal).toBe("626125.00");
  });

  it("«ВСЕГО по смете» — итог документа, а не работа", () => {
    expect(документ.declaredTotal).toBe("4693925.00");
    expect(позиции.some((позиция) => позиция.name.startsWith("ВСЕГО"))).toBe(false);
  });

  it("выбор колонок назван словами: человек должен видеть, что мы прочли", () => {
    const сказано = документ.issues.map((issue) => issue.message).join(" ");

    expect(сказано).toContain("разобрана по шапке колонок");
    expect(сказано).toContain("сумма F");
    expect(сказано).toContain("сошлось на 3 строках из 3");
  });
});

