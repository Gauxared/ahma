describe("многоэтажная шапка", () => {
  /**
   * Шапка в два этажа — обычное дело: «Стоимость, руб.» стоит над «на единицу |
   * всего». Прочитанная порознь, верхняя строка объявила бы одной колонкой то,
   * что в документе две.
   */
  const КНИГА = sheetFrom("Ведомость", [
    [1, { A: "№ п/п", B: "Наименование работ", C: "Ед. изм.", D: "Кол-во", E: "Стоимость, руб.", F: "" }],
    [2, { E: "на единицу", F: "всего" }],
    [3, { A: "1", B: "Окраска фасада", C: "м2", D: "1 800,00", E: "245,00", F: "441 000,00" }],
    [4, { A: "2", B: "Грунтовка фасада", C: "м2", D: "1 800,00", E: "62,00", F: "111 600,00" }],
  ]);

  it("нижний этаж уточняет верхний: цена и сумма различены", () => {
    const документ = parseAnyEstimate(КНИГА);
    const позиции = документ.sections.flatMap((section) => section.positions);

    expect(позиции).toHaveLength(2);
    expect(позиции[0]?.unitCost).toBe("245.00");
    expect(позиции[0]?.total).toBe("441000.00");
  });
});

describe("смета без цен", () => {
  it("объёмы есть, денег нет — и это свойство документа, а не ноль", () => {
    const вор = sheetFrom("ВОР", [
      [1, { A: "№", B: "Наименование работ", C: "Ед. изм.", D: "Количество" }],
      [2, { A: "1", B: "Кладка стен из газобетона", C: "м3", D: "348,50" }],
      [3, { A: "2", B: "Устройство перемычек", C: "шт", D: "96,00" }],
    ]);

    const документ = parseAnyEstimate(вор);
    const позиции = документ.sections.flatMap((section) => section.positions);

    expect(позиции).toHaveLength(2);
    expect(документ.withoutPrices).toBe(true);
    // Ноль здесь соврал бы о стоимости объекта: неизвестное не становится нулём.
    expect(позиции[0]?.total).toBeUndefined();
    expect(позиции[0]?.quantity).toBe("348.50");
  });
});
