/**
 * Структура затрат из шапки сметы.
 *
 * Три вывода эталонного разбора опираются ровно на эти четыре числа, и замер
 * против эталона промахивался по всем трём, пока шапка не читалась. Поэтому
 * проверяется не «разбор находит числа», а то, что он не находит их там, где их
 * нет: слова «оборудование» и «прочие затраты» встречаются и ниже шапки — в
 * названиях разделов и позиций.
 */
import { describe, expect, it } from "vitest";

import type { Sheet } from "../sheet.js";

import { parseCostElements } from "./cost-elements.js";

function лист(rows: readonly (readonly string[])[]): Sheet {
  return {
    name: "ЛСР",
    rows: new Map(
      rows.map((cells, index) => [
        index + 1,
        new Map(cells.map((value, column) => [String.fromCharCode(65 + column), value])),
      ]),
    ),
  };
}

const ШАПКА = [
  ["Сметная стоимость", "14198.88", "тыс.руб."],
  ["в том числе:"],
  ["строительных работ", "0", "тыс.руб."],
  ["монтажных работ", "11086.18", "тыс.руб."],
  ["оборудования", "2222.04", "тыс.руб."],
  ["прочих затрат", "890.67", "тыс.руб."],
  ["№ п/п", "Обоснование", "Наименование работ и затрат"],
];

describe("шапка сметы", () => {
  const элементы = parseCostElements(лист(ШАПКА));

  it("приводит тысячи к рублям", () => {
    expect(элементы.total).toBe("14198880.00");
    expect(элементы.assembly).toBe("11086180.00");
    expect(элементы.equipment).toBe("2222040.00");
    expect(элементы.other).toBe("890670.00");
    expect(элементы.scale).toBe("thousands");
  });

  it("НОЛЬ отличает от отсутствия", () => {
    // «строительных работ 0» — утверждение документа: их в смете нет.
    // Отсутствие строки было бы незнанием, и это разные вещи (ТЗ §9).
    expect(элементы.construction).toBe("0.00");
    expect(элементы.labour).toBeUndefined();
  });
});

describe("итоги по смете — точный источник", () => {
  const ИТОГИ = [
    ...ШАПКА,
    ["Итоги по разделу 1 Оборудование :"],
    ["     Монтажные работы", "11086178.75"],
    ["          в том числе:"],
    ["               материалы", "265427.50"],
    ["     Оборудование", "2222036.29"],
    ["Всего по разделу 1", "14198884.54"],
    ["Итоги по смете:"],
    ["     Всего прямые затраты (справочно)", "5372294.14"],
    ["          в том числе:"],
    ["               Материалы", "265427.50"],
    ["     Монтажные работы", "11086178.75"],
    ["          в том числе:"],
    ["               материалы", "265427.50"],
    ["               накладные расходы", "4057158.61"],
    ["               сметная прибыль", "2080854.33"],
    ["     Оборудование", "2222036.29"],
    ["     Прочие затраты", "890669.50"],
    ["ВСЕГО по смете", "14198884.54"],
    ["     справочно:"],
    ["          Оборудование, отсутствующее в ФРСН", "1386844.61"],
  ];

  const элементы = parseCostElements(лист(ИТОГИ));

  it("предпочитает точные рубли округлённым тысячам шапки", () => {
    // Шапка даёт 2 222 040 (гранулярность 10 ₽), итоги — 2 222 036,29.
    expect(элементы.equipment).toBe("2222036.29");
    expect(элементы.from).toBe("итоги-разделов");
  });

  it("НЕ складывает блок раздела с блоком сметы", () => {
    // Обе строки «Оборудование» несут одно и то же число. Сложить их значит
    // удвоить смету, и ошибка невидима: сумма остаётся правдоподобной.
    expect(элементы.equipment).toBe("2222036.29");
    expect(элементы.other).toBe("890669.50");
  });

  it("берёт материалы из строки работ, а не из справочной разбивки", () => {
    // «Всего прямые затраты (справочно)» несёт те же материалы. Сложить оба
    // вхождения — удвоить материалы; пропустить оба — обнулить их.
    expect(элементы.materials).toBe("265427.50");
  });

  it("читает оборудование вне ФРСН — то, что не подтверждено нормативом", () => {
    expect(элементы.outsideRegistry).toBe("1386844.61");
  });

  it("читает накладные и сметную прибыль — «жирок» сметы", () => {
    expect(элементы.overhead).toBe("4057158.61");
    expect(элементы.profit).toBe("2080854.33");
  });
});

describe("чего разбор НЕ берёт", () => {
  it("останавливается на заголовке таблицы", () => {
    // Ниже шапки «оборудование» — это название раздела, а «прочих затрат» —
    // наименование позиции. Прочитать их как итог по элементу значило бы
    // принять стоимость одной строки за итог сметы.
    const элементы = parseCostElements(
      лист([
        ...ШАПКА,
        ["Раздел 1. Оборудование", "999999.99"],
        ["прочих затрат по разделу", "888888.88"],
      ]),
    );

    expect(элементы.equipment).toBe("2222040.00");
    expect(элементы.other).toBe("890670.00");
  });

  it("на листе без шапки не выдумывает итог", () => {
    const элементы = parseCostElements(лист([["№ п/п", "Обоснование"], ["1", "ГЭСН"]]));

    expect(элементы.total).toBeUndefined();
    expect(элементы.equipment).toBeUndefined();
  });

  it("без единиц измерения тысячи не домысливаются", () => {
    const элементы = parseCostElements(
      лист([["Сметная стоимость", "14198.88"], ["№ п/п", "Обоснование"]]),
    );

    expect(элементы.scale).toBe("rubles");
    expect(элементы.total).toBe("14198.88");
  });
});
