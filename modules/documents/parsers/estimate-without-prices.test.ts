/**
 * СМЕТА БЕЗ СТОИМОСТНОЙ ЧАСТИ — против потери ста восьмидесяти семи фактов.
 *
 * НАЙДЕНО НА ПАКЕТЕ ЗАКАЗЧИКА, а не набором.
 *
 * Пакет «Устройство фундаментов линии 720» (Нижний Тагил, ИТЦ/07-373-24-КЖ):
 * одиннадцать книг, автор — сметчик заказчика, изменены 11.08.2026. Обход
 * заканчивался словами «нечего проверять, смет 0, позиций 0».
 *
 * Разбор находил форму, находил разделы — и отбрасывал КАЖДУЮ позицию с
 * замечанием «строка „Всего по позиции“ без суммы». В этих сметах денег нет
 * вовсе: у позиций есть шифр ГЭСН/ФСБЦ, наименование, единица и объём, а
 * ценовые колонки пусты. За весь лист в них двенадцать чисел, и это нумерация
 * шапки.
 *
 * ЧЕГО ЖДЁТ ЗАКАЗЧИК — сказано его собственным эталоном выхода по этому же
 * кейсу (`ЦИМ_Нижний_Тагил_фундаменты_линии_720.xlsx`):
 *
 *  · лист «06·Позиции_ЛСР» — 187 строк, колонки «ЛСР · Класс · Код ·
 *    Наименование · Ед. · Кол-во». ДЕНЕЖНОЙ КОЛОНКИ В НЁМ НЕТ;
 *  · лист «04·Находки», находка №1, красная: «Сметы БЕЗ ЦЕН. Все ЛСР содержат
 *    только коды ГЭСН/ФСБЦ и объёмы; денежных колонок нет. Построчный аудит
 *    расценок/индексов/двойного счёта невозможен» — вес «блокирует проверку
 *    86,78 млн».
 *
 * То есть отсутствие цен — это ГЛАВНАЯ НАХОДКА объекта, а не причина молчать.
 * Позиции при этом перечисляются все.
 *
 * ЧТО ЗДЕСЬ РАЗДЕЛЯЕТСЯ
 *
 * Позиция без итога в смете, где деньги ЕСТЬ, — дефект строки: там сумма
 * должна быть и её нет. Позиция без итога в смете, где денег НЕТ НИГДЕ, —
 * свойство документа. Одинаково обойтись с ними нельзя: в первом случае молча
 * оставить позицию значило бы спрятать дыру, во втором отбросить её значило бы
 * потерять факт, который заказчик ждёт в отчёте.
 *
 * Ноль рублей не подставляется ни в каком случае: сумма неизвестна, а не равна
 * нулю, и сходимость, сложившая такие нули, соврала бы о стоимости объекта.
 */
import { describe, expect, it } from "vitest";

import { parseLsr } from "./grand-smeta.js";
import { sheetFrom } from "../sheet.js";

/**
 * Вёрстка снята с настоящей книги пакета: шапка «№ п/п» в строке 41,
 * подзаголовок в 43, нумерация колонок в 44, данные с 45.
 */
function лист(строки: readonly [number, Record<string, string>][]) {
  return sheetFrom("Конструкции железобетонные. Фун", [
    [41, { A: "№ п/п", B: "Обоснование", C: "Наименование работ и затрат", H: "Единица измерения" }],
    [
      43,
      {
        A: "№ п/п",
        I: "на единицу измерения",
        J: "коэффициенты",
        K: "всего с учетом коэффициентов",
        L: "на единицу измерения в базисном уровне цен",
        M: "индекс",
        P: "всего",
      },
    ],
    [44, { A: "1", B: "2", C: "3", H: "4", I: "5", J: "6", K: "7", L: "8", M: "9", P: "12" }],
    ...строки,
  ]);
}

const РАЗДЕЛ: [number, Record<string, string>] = [45, { A: "Раздел 1. Фундамент Фм e" }];

const ПОЗИЦИЯ_1: [number, Record<string, string>] = [
  46,
  {
    A: "1",
    B: "ГЭСН08-01-002-02",
    C: "Устройство основания под фундаменты: щебеночного",
    H: "м3",
    I: "25.2",
    J: "1",
  },
];

const ПОЗИЦИЯ_2: [number, Record<string, string>] = [
  49,
  {
    A: "2",
    B: "ФСБЦ-02.2.05.04-2090",
    C: "Щебень из плотных горных пород для строительных работ М 800, фракция 20-40 мм",
    H: "м3",
    I: "27.72",
    J: "1",
  },
];

describe("смета без стоимостной части", () => {
  it("позиции СОХРАНЯЮТСЯ: шифр, наименование, единица и объём — это факты", () => {
    const документ = parseLsr(
      лист([
        РАЗДЕЛ,
        ПОЗИЦИЯ_1,
        [47, { C: "Итого прямые затраты" }],
        [48, { C: "Всего по позиции" }],
        ПОЗИЦИЯ_2,
        [50, { C: "Всего по позиции" }],
        [106, { C: "ВСЕГО по смете" }],
      ]),
    );

    const позиции = документ.sections.flatMap((раздел) => раздел.positions);

    expect(позиции.length, "позиции отброшены — 187 фактов пакета теряются").toBe(2);
    expect(позиции[0]?.basis).toBe("ГЭСН08-01-002-02");
    expect(позиции[0]?.code).toEqual({ system: "ГЭСН", code: "08-01-002-02" });
    expect(позиции[0]?.unit).toBe("м3");
    expect(позиции[0]?.quantity).toBe("25.2");
    expect(позиции[1]?.basis).toBe("ФСБЦ-02.2.05.04-2090");
  });

  it("объём берётся, даже когда колонка «всего с учётом коэффициентов» пуста", () => {
    /**
     * ЗАМЕРЕНО НА КНИГАХ ПАКЕТА, а не выведено из формы.
     *
     * В книге «Фундамент Фм e» из двадцати позиций колонка K заполнена у
     * ЧЕТЫРЁХ; в книге «Восстановление полов» — ни у одной. При этом I («на
     * единицу измерения») и J («коэффициенты») заполнены у всех, и там, где K
     * всё-таки написана, она в точности равна I при коэффициенте 1.
     *
     * Разбор читал только K — и оставлял без объёма девятнадцать позиций из
     * двадцати. Позиция без объёма в смете без цен пуста совсем: ни денег, ни
     * количества, один шифр.
     *
     * Эталон заказчика подтверждает правило: в листе «06·Позиции_ЛСР» у
     * ГЭСН01-01-020-02 стоит 6.175 — это значение I, а K в книге пуста.
     */
    const документ = parseLsr(
      лист([РАЗДЕЛ, ПОЗИЦИЯ_1, [48, { C: "Всего по позиции" }], [106, { C: "ВСЕГО по смете" }]]),
    );

    expect(документ.sections[0]?.positions[0]?.quantity, "объём потерян: в книге он в колонке I").toBe(
      "25.2",
    );
  });

  it("коэффициент не равен единице — объём считается, а не берётся сырым", () => {
    // Иначе объём был бы занижен ровно во столько раз, во сколько написан
    // коэффициент, и молча: число на месте, оно просто не то.
    const документ = parseLsr(
      лист([
        РАЗДЕЛ,
        [46, { A: "1", B: "ГЭСН08-01-002-02", C: "Устройство основания", H: "м3", I: "10", J: "1.15" }],
        [48, { C: "Всего по позиции" }],
        [106, { C: "ВСЕГО по смете" }],
      ]),
    );

    expect(документ.sections[0]?.positions[0]?.quantity).toBe("11.5");
  });

  it("написанная колонка «всего с учётом коэффициентов» ГЛАВНЕЕ расчёта", () => {
    // Документ сам сказал итоговый объём — спорить с ним нельзя: округления
    // ГРАНД-Сметы наши, а число там их.
    const документ = parseLsr(
      лист([
        РАЗДЕЛ,
        [46, { A: "1", B: "ГЭСН08-01-002-02", C: "Устройство основания", H: "м3", I: "10", J: "1.15", K: "11.49" }],
        [48, { C: "Всего по позиции" }],
        [106, { C: "ВСЕГО по смете" }],
      ]),
    );

    expect(документ.sections[0]?.positions[0]?.quantity).toBe("11.49");
  });

  it("сумма ОТСУТСТВУЕТ, а не равна нулю", () => {
    // Ноль сложится в сходимости и соврёт о стоимости объекта; «неизвестно»
    // сложить нельзя, и это правильный ответ.
    const документ = parseLsr(
      лист([РАЗДЕЛ, ПОЗИЦИЯ_1, [48, { C: "Всего по позиции" }], [106, { C: "ВСЕГО по смете" }]]),
    );

    const позиция = документ.sections[0]?.positions[0];
    expect(позиция?.total, "подставлен ноль вместо «неизвестно»").toBeUndefined();
  });

  it("документ НАЗВАН сметой без цен — это находка, а не тишина", () => {
    const документ = parseLsr(
      лист([РАЗДЕЛ, ПОЗИЦИЯ_1, [48, { C: "Всего по позиции" }], [106, { C: "ВСЕГО по смете" }]]),
    );

    expect(
      документ.withoutPrices,
      "документ не помечен: обход скажет «нечего проверять» вместо главной находки объекта",
    ).toBe(true);

    const замечание = документ.issues.find((i) => /без стоимостной части/i.test(i.message));
    expect(замечание, "нет замечания о смете без цен").toBeDefined();

    /**
     * ЗАМЕЧАНИЕ НЕ БЛОКИРУЮЩЕЕ — и это проверяется, а не подразумевается.
     *
     * `blocking` означает «разбор не удался», и обход по нему ОТКАЗЫВАЕТ
     * документу целиком: экран заказчика показывал ровно это — десять смет со
     * штампом «ОТКАЗ» и ни одной позиции. Но разбор удался: двести тридцать
     * одна позиция прочитана. Серьёзность находки задаёт обход, а не разбор.
     */
    expect(
      замечание?.severity,
      "разбор объявлен неудавшимся — обход откажет документу и выбросит все прочитанные позиции",
    ).toBe("warning");
    expect(
      документ.issues.some((i) => i.severity === "blocking"),
      "среди замечаний осталось блокирующее: документ уйдёт в отказ",
    ).toBe(false);
  });

  it("замечание сказано ОДИН раз на документ, а не по разу на строку", () => {
    /**
     * На книге пакета таких строк тридцать и больше. Повторённое построчно,
     * замечание занимает пол-экрана и вытесняет всё остальное — это уже
     * наблюдалось на экране заказчика.
     */
    const документ = parseLsr(
      лист([
        РАЗДЕЛ,
        ПОЗИЦИЯ_1,
        [48, { C: "Всего по позиции" }],
        ПОЗИЦИЯ_2,
        [50, { C: "Всего по позиции" }],
        [51, { A: "3", B: "ГЭСН06-01-001-01", C: "Устройство бетонной подготовки", H: "100 м3", I: "0.119" }],
        [52, { C: "Всего по позиции" }],
        [106, { C: "ВСЕГО по смете" }],
      ]),
    );

    const построчные = документ.issues.filter((i) => /без суммы/i.test(i.message));
    expect(построчные.length, "замечание повторено построчно").toBe(0);

    const про_документ = документ.issues.filter((i) => /без стоимостной части/i.test(i.message));
    expect(про_документ.length).toBe(1);
  });

  it("в смете С ДЕНЬГАМИ пропущенный итог остаётся дефектом СТРОКИ", () => {
    /**
     * Обратная ошибка, и она хуже первой: приняв всякую позицию без суммы, мы
     * спрятали бы настоящую дыру в оценённой смете. Здесь деньги в документе
     * есть — значит у этой позиции сумма должна быть, и её отсутствие
     * по-прежнему блокирующее.
     */
    const документ = parseLsr(
      лист([
        РАЗДЕЛ,
        ПОЗИЦИЯ_1,
        [48, { C: "Всего по позиции", P: "132 450,10" }],
        ПОЗИЦИЯ_2,
        [50, { C: "Всего по позиции" }],
        [106, { C: "ВСЕГО по смете", P: "132 450,10" }],
      ]),
    );

    expect(документ.withoutPrices, "смета с деньгами помечена как смета без цен").toBe(false);

    const позиции = документ.sections.flatMap((раздел) => раздел.positions);
    expect(позиции.length, "позиция без суммы принята в оценённой смете").toBe(1);
    expect(позиции[0]?.total).toBe("132450.10");

    const построчное = документ.issues.find((i) => /без суммы/i.test(i.message));
    expect(построчное, "пропущенный итог перестал быть дефектом строки").toBeDefined();
    expect(построчное?.row).toBe(50);
  });

  it("итог документа тоже отсутствует, а не равен нулю", () => {
    const документ = parseLsr(
      лист([РАЗДЕЛ, ПОЗИЦИЯ_1, [48, { C: "Всего по позиции" }], [106, { C: "ВСЕГО по смете" }]]),
    );

    expect(документ.declaredTotal).toBeUndefined();
  });
});
