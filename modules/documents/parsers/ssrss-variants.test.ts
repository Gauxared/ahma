/**
 * СВОДНЫЙ РАСЧЁТ, ОФОРМЛЕННЫЙ ИНАЧЕ, — та же форма, другие мелочи.
 *
 * Форма 421/пр государственная, но внутри неё составитель волен выбрать шкалу
 * и систему шифров. Пакет Нижнего Тагила отличается от курганского и тем, и
 * другим — и по каждому отличию разбор отказывал или ошибался.
 *
 * ШКАЛА — против ошибки ровно в тысячу раз.
 *
 * НАЙДЕНО НА ПАКЕТЕ ЗАКАЗЧИКА, а не набором.
 *
 * Сводный расчёт пакета «Устройство фундаментов линии 720» отвергался целиком:
 * «не найдена шапка „Сметная стоимость, тыс. руб.“ — документ не похож на
 * сводный сметный расчёт по Приложению № 6». Между тем это ровно он: та же
 * форма 421/пр, та же структура глав, те же шифры ЛСР в обосновании.
 *
 * Отличие одно — суммы номинированы В РУБЛЯХ: шапка говорит «Сметная
 * стоимость, руб.». Форма это допускает, и составитель вправе так сделать.
 *
 * ЦЕНА ОШИБКИ ЗДЕСЬ НЕ «НЕ РАСПОЗНАЛИ»
 *
 * Пока разбор требовал тысяч, документ просто не читался — обидно, но заметно.
 * Стоит начать читать его, не различая шкалу, и станет хуже: сверка «сумма ЛСР
 * против сводного» умножит рубли на тысячу и объявит расхождение в 999 раз
 * больше самой стоимости объекта. Число при этом будет выглядеть посчитанным.
 *
 * Поэтому шкала — СВОЙСТВО ИСТОЧНИКА, прочитанное из шапки, а не умолчание.
 */
import { describe, expect, it } from "vitest";

import { parseSsrss } from "./ssrss.js";
import { sheetFrom } from "../sheet.js";

/** Вёрстка снята с настоящих книг: шапка в 21–23, нумерация в 24, данные с 25. */
function лист(единица: string) {
  return sheetFrom("Сводный сметный расчет", [
    [21, { A: "№ п/п", B: "Обоснование", C: "Наименование глав", D: `Сметная стоимость, ${единица}` }],
    [22, { A: "№ п/п", B: "Обоснование", C: "Наименование глав", D: "Строительных", H: "всего" }],
    [24, { A: "1", B: "2", C: "3", D: "4", H: "8" }],
    // Заголовок главы — объединённая ячейка: текст повторён во всех колонках.
    // Так он выглядит в настоящем документе, и разбор опознаёт его именно так.
    [
      25,
      Object.fromEntries(
        ["A", "B", "C", "D", "E", "F", "G", "H"].map((c) => [c, "Глава 2. Основные объекты строительства"]),
      ),
    ],
    [26, { A: "1", B: "НТ-05-02-01", C: "Конструкции железобетонные", D: "1000.00", H: "1200.00" }],
    [27, { B: "Итого по Главам 1-9", C: "Итого по Главам 1-9", H: "1200.00" }],
  ]);
}

describe("шкала сводного сметного расчёта", () => {
  it("расчёт В РУБЛЯХ распознаётся, а не отвергается как чужая форма", () => {
    const документ = parseSsrss(лист("руб."));

    expect(документ.scale, "рублёвый сводный расчёт прочитан как тысячи — ошибка в 1000 раз").toBe(
      "rubles",
    );
    expect(документ.objects.length, "объекты не найдены").toBeGreaterThan(0);
  });

  it("расчёт В ТЫСЯЧАХ читается по-прежнему", () => {
    // Курганский комплект — в тысячах, и правка не должна стоить работающего
    // случая: там сверка со шкалой держится именно на множителе 1000.
    const документ = parseSsrss(лист("тыс. руб."));

    expect(документ.scale).toBe("thousands");
    expect(документ.objects.length).toBeGreaterThan(0);
  });

  it("шапка без слова «стоимость» по-прежнему НЕ считается сводным расчётом", () => {
    // Расширение не должно превратиться в «читаем что угодно»: документ другой
    // формы обязан отвергаться, иначе разбор выдаст мусор за факты.
    expect(() =>
      parseSsrss(
        sheetFrom("Ведомость", [
          [21, { A: "№ п/п", B: "Обоснование", C: "Наименование", D: "Количество" }],
          [24, { A: "1", B: "2", C: "3", D: "4" }],
        ]),
      ),
    ).toThrow(/не похож на сводный/iu);
  });

  it("шифр объекта с буквенным префиксом — это ОБЪЕКТ, а не начисление", () => {
    /**
     * НАЙДЕНО НА ПАКЕТЕ ЗАКАЗЧИКА.
     *
     * Курганский сводный расчёт ссылается на сметы шифрами «05-02», и разбор
     * требовал ровно двух групп цифр. В Нижнем Тагиле шифры свои — «НТ-05-02-01».
     *
     * Не совпав с шаблоном, такая строка уходила в НАЧИСЛЕНИЯ — то есть объект
     * капитального строительства учитывался как накрутка на итог. Это не «не
     * распозналось»: это разложилось неверно и молча.
     */
    const документ = parseSsrss(лист("руб."));

    expect(документ.objects.map((o) => o.basis), "объект уехал в начисления").toContain("НТ-05-02-01");
    expect(документ.accruals.map((a) => a.basis)).not.toContain("НТ-05-02-01");
  });

  it("ссылка на приказ остаётся НАЧИСЛЕНИЕМ, а не становится объектом", () => {
    // Обратная ошибка: расширив шаблон шифра, легко записать в объекты
    // непредвиденные затраты — и завысить состав стройки на строку, которой
    // никакой сметы не соответствует.
    const документ = parseSsrss(
      sheetFrom("Сводный сметный расчет", [
        [21, { A: "№ п/п", B: "Обоснование", C: "Наименование глав", D: "Сметная стоимость, руб." }],
        [24, { A: "1", B: "2", C: "3", D: "4", H: "8" }],
        [
          25,
          Object.fromEntries(
            ["A", "B", "C", "D", "E", "F", "G", "H"].map((c) => [c, "Глава 9. Прочие работы и затраты"]),
          ),
        ],
        [26, { A: "5", B: "Приказ от 4.08.2020 № 421/пр п.179", C: "Непредвиденные затраты", H: "2099.53" }],
      ]),
    );

    expect(документ.objects).toHaveLength(0);
    expect(документ.accruals.map((a) => a.name)).toContain("Непредвиденные затраты");
  });

  it("объекты без сумм — НЕ провал разбора, если итоги по главам прочитаны", () => {
    /**
     * НАЙДЕНО НА ЖИВОМ ПРОГОНЕ, а не чтением кода.
     *
     * Сводный расчёт пакета Нижнего Тагила перечисляет объекты без сумм — ровно
     * как и его ЛСР, — но итоги по главам в нём ЕСТЬ: «Итого по Главам 1-9»
     * 86 778 920,38 ₽. Это НМЦК объекта, и эталон заказчика опирается именно на
     * неё («блокирует проверку 86,78 млн»).
     *
     * Разбор при этом отвечал блокирующим «не найдено ни одного объекта
     * капитального строительства», обход отказывал документу — и НМЦК, которая
     * лежала в двух строках ниже, до экрана не доходила.
     *
     * Та же развязка, что в ЛСР: разбор не удался только тогда, когда не
     * прочитано НИЧЕГО.
     */
    const документ = parseSsrss(
      sheetFrom("Сводный сметный расчет", [
        [21, { A: "№ п/п", B: "Обоснование", C: "Наименование глав", D: "Сметная стоимость, руб." }],
        [24, { A: "1", B: "2", C: "3", D: "4", H: "8" }],
        [
          25,
          Object.fromEntries(
            ["A", "B", "C", "D", "E", "F", "G", "H"].map((c) => [c, "Глава 2. Основные объекты"]),
          ),
        ],
        [26, { A: "1", B: "НТ-05-02-01", C: "Конструкции железобетонные" }],
        [27, { A: "2", B: "НТ-05-02-02", C: "Фундамент Фм c" }],
        [44, { B: "Итого по Главам 1-9", C: "Итого по Главам 1-9", H: "86778920.38" }],
      ]),
    );

    expect(
      документ.issues.filter((i) => i.severity === "blocking"),
      "разбор объявлен провалившимся — обход откажет документу и потеряет НМЦК",
    ).toHaveLength(0);

    expect(документ.totals.find((t) => t.scope === "chapters:1-9")?.total).toBe("86778920.38");

    const предупреждение = документ.issues.find((i) => /без сумм/i.test(i.message));
    expect(предупреждение, "молчание о том, что объекты перечислены без сумм").toBeDefined();
    expect(предупреждение?.severity).toBe("warning");
  });

  it("пустой документ ПО-ПРЕЖНЕМУ провал: ни объектов, ни итогов", () => {
    // Развязка не должна превратиться в «всё принимаем»: если не прочитано
    // ничего, сказать об этом обязаны блокирующим замечанием.
    const документ = parseSsrss(
      sheetFrom("Сводный сметный расчет", [
        [21, { A: "№ п/п", B: "Обоснование", C: "Наименование глав", D: "Сметная стоимость, руб." }],
        [24, { A: "1", B: "2", C: "3", D: "4", H: "8" }],
      ]),
    );

    expect(документ.issues.some((i) => i.severity === "blocking")).toBe(true);
  });
});
