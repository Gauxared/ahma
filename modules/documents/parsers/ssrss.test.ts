/**
 * Тесты написаны до реализации.
 *
 * Разметка взята из настоящего файла «Сводный сметный расчет - ССРСС по
 * Методике 2020» курганского комплекта, форма по Приложению № 6 приказа
 * Минстроя № 421/пр.
 */
import { describe, expect, it } from "vitest";

import { sheetFrom } from "../sheet.js";

import { parseSsrss, SsrssParseError } from "./ssrss.js";

/**
 * Строки заголовков глав в источнике повторяют один и тот же текст во ВСЕХ
 * колонках — это объединённая ячейка. Разметка воспроизведена как есть.
 */
function chapterHeader(row: number, title: string): [number, Record<string, string>] {
  return [row, { A: title, B: title, C: title, D: title, E: title, F: title, G: title, H: title }];
}

const SAMPLE = sheetFrom("ССРСС", [
  [21, { A: "№ п/п", B: "Обоснование", C: "Наименование глав", D: "Сметная стоимость, тыс. руб." }],
  [22, { A: "№ п/п", B: "Обоснование", C: "Наименование глав", D: "Строительных", E: "монтажных работ", F: "оборудования", G: "прочих затрат", H: "всего" }],
  [24, { A: "1", B: "2", C: "3", D: "4", E: "5", F: "6", G: "7", H: "8" }],
  chapterHeader(25, "Глава 5. Объекты транспортного хозяйства"),
  [26, { A: "7", B: "05-02", C: "Система видеонаблюдения", E: "11086.18", F: "2222.04", G: "890.67", H: "14198.89" }],
  [27, { A: "8", B: "05-01", C: "Система электроснабжения", D: "20957.05", E: "68575.52", H: "89532.57" }],
  [28, { B: "Итого по Главе 5. \"Объекты транспортного хозяйства\"", C: "Итого по Главе 5.", D: "20957.05", E: "79661.7", F: "2222.04", G: "890.67", H: "103731.46" }],
  [30, { B: "Итого по Главам 1-7", C: "Итого по Главам 1-7", D: "20957.05", H: "103731.46" }],
  chapterHeader(33, "Глава 9. Прочие работы и затраты"),
  [34, { A: "2", B: "09-01", C: "Пусконаладочные работы(ПНР)", G: "890.67", H: "890.67" }],
  [35, { A: "1", B: "09-02", C: "Спец проверка и Специсследование(СП и СИ)", G: "354.58", H: "354.58" }],
  [36, { B: "Итого по Главе 9. \"Прочие работы и затраты\"", C: "Итого по Главе 9.", G: "1245.25", H: "1245.25" }],
  [37, { B: "Итого по Главам 1-9", C: "Итого по Главам 1-9", D: "20957.05", E: "79661.7", F: "2222.04", G: "2135.92", H: "104976.71" }],
  [41, { A: "5", B: "Приказ от 4.08.2020 № 421/пр п.179", C: "Непредвиденные затраты", D: "419.14", E: "1593.23", F: "44.44", G: "42.72", H: "2099.53" }],
  [42, { D: "2%Г1.С:Г12.С", E: "2%Г1.М:Г12.М", F: "2%Г1.О:Г12.О", G: "2%Г1.П:Г12.П" }],
  [44, { B: "Итого с учетом \"Непредвиденные затраты\"", C: "Итого", D: "21376.19", E: "81254.93", F: "2266.48", G: "2178.64", H: "107076.24" }],
]);

describe("разбор сводного сметного расчёта (Приложение № 6)", () => {
  const document = parseSsrss(SAMPLE);

  it("объявляет шкалу источника, а не догадывается о ней", () => {
    // Вся форма номинирована в ТЫС. РУБ. Считать её рублями — ошибка в 1000 раз.
    expect(document.scale).toBe("thousands");
  });

  it("извлекает объекты капитального строительства с их шифрами", () => {
    expect(document.objects.map((object) => object.basis)).toEqual([
      "05-02",
      "05-01",
      "09-01",
      "09-02",
    ]);
  });

  it("не принимает заголовок главы за объект", () => {
    // Заголовок «Глава 5…» повторён во всех колонках объединённой ячейкой.
    // Наивный разбор по непустому A завёл бы его как позицию.
    const names = document.objects.map((object) => object.name);
    expect(names.some((name) => name.startsWith("Глава"))).toBe(false);
    expect(document.objects).toHaveLength(4);
  });

  it("не принимает строку нумерации колонок за объект", () => {
    // Под шапкой идёт строка A=1, B=2 … H=8. По форме она неотличима от
    // объекта: номер в A, непустые B и C, число в «всего».
    expect(document.objects.some((object) => object.row === 24)).toBe(false);
  });

  it("не принимает строку с формулой начисления за данные", () => {
    // Строка 42 несёт «2%Г1.С:Г12.С» в числовых колонках — это пояснение
    // к начислению, а не сумма.
    expect(document.objects.some((object) => object.row === 42)).toBe(false);
  });

  it("не считает начисление объектом капитального строительства", () => {
    // «Непредвиденные затраты» берутся процентом от суммы объектов и входят
    // в итог ПОСЛЕ неё. Учесть их как объект — значит задвоить.
    expect(document.objects.some((object) => object.name.includes("Непредвиденные"))).toBe(false);

    expect(document.accruals).toHaveLength(1);
    expect(document.accruals[0]?.name).toBe("Непредвиденные затраты");
    expect(document.accruals[0]?.total).toBe("2099.53");
  });

  it("берёт итог объекта из колонки «всего»", () => {
    const видеонаблюдение = document.objects.find((object) => object.basis === "05-02");

    expect(видеонаблюдение?.total).toBe("14198.89");
    expect(видеонаблюдение?.equipment).toBe("2222.04");
    expect(видеонаблюдение?.construction).toBeUndefined();
  });

  it("собирает накопительные итоги по главам", () => {
    const итоги = Object.fromEntries(document.totals.map((total) => [total.scope, total.total]));

    expect(итоги["chapters:1-9"]).toBe("104976.71");
    expect(итоги["chapters:1-7"]).toBe("103731.46");
    expect(итоги["chapter:5"]).toBe("103731.46");
    expect(итоги["chapter:9"]).toBe("1245.25");
  });

  it("отличает итог по главам от итога с непредвиденными затратами", () => {
    // Смешать их — значит сравнить сумму ЛСР с суммой, куда уже вошли 2%.
    const итоги = Object.fromEntries(document.totals.map((total) => [total.scope, total.total]));

    expect(итоги["with-contingency"]).toBe("107076.24");
    expect(итоги["chapters:1-9"]).not.toBe(итоги["with-contingency"]);
  });

  it("отказывает на документе, который не является ССРСС", () => {
    const чужой = sheetFrom("не тот", [[1, { A: "Локальный сметный расчёт" }]]);

    expect(() => parseSsrss(чужой)).toThrow(SsrssParseError);
  });
});
