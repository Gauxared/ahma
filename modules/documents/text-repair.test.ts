/**
 * СБИТАЯ КОДИРОВКА ШРИФТА PDF — ЭТО ПОТЕРЯ ТЕКСТА, А НЕ ЕГО ВИД.
 *
 * Замерено 09.09.2026 на кейсе «Дноуглубление»: «Раздел ПД №9_СМ_Расч_Изм.2_.pdf»
 * отдавал 5 383 знака из 53 363 в виде «ɋɈɋɌȺȼ ɉɊɈȿɄɌɇɈɃ ȾɈɄɍɆȿɇɌȺɐɂɂ». Роль
 * читала это как шум, а система считала документ прочитанным: знаки пришли,
 * длина большая. Именно так выглядит молчаливая потеря.
 */
import { describe, expect, it } from "vitest";

import { restoreShiftedCyrillic, shiftedLetters } from "./text-repair.js";

describe("кириллица, съехавшая в латиницу", () => {
  it("возвращается на место целым предложением", () => {
    expect(restoreShiftedCyrillic("ɋɈɋɌȺȼ ɉɊɈȿɄɌɇɈɃ ȾɈɄɍɆȿɇɌȺɐɂɂ")).toBe("СОСТАВ ПРОЕКТНОЙ ДОКУМЕНТАЦИИ");
  });

  it("чинится и строчная: сдвиг у всей азбуки один", () => {
    expect(restoreShiftedCyrillic("ɉɨɹɫɧɢɬɟɥɶɧɚɹ ɡɚɩɢɫɤɚ")).toBe("Пояснительная записка");
  });

  it("кавычки чинятся вместе с буквами — они съехали тем же шрифтом", () => {
    expect(restoreShiftedCyrillic("ɈɈɈ©ȽȿɈɂɁɈɅª")).toBe("ООО«ГЕОИЗОЛ»");
  });

  it("нормальный русский текст не трогается", () => {
    const текст = "Локальный сметный расчёт № 02-01-01 (с) 2026";
    expect(restoreShiftedCyrillic(текст)).toBe(текст);
  });

  it("одиночный чужой знак не считается сбитой кодировкой", () => {
    // Иначе знак авторского права в нормальном документе стал бы кавычкой.
    const текст = "© ООО «Стройинтеллект», лист ɂ";
    expect(shiftedLetters(текст)).toBe(1);
    expect(restoreShiftedCyrillic(текст)).toBe(текст);
  });
});
