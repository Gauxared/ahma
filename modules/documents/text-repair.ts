/**
 * КИРИЛЛИЦА, СЪЕХАВШАЯ В ЛАТИНИЦУ, — ВОССТАНОВЛЕНИЕ ТЕКСТА PDF.
 *
 * ЧТО ЗАМЕРЕНО 09.09.2026. В кейсе «Дноуглубление» сметный раздел проектной
 * документации отдавал текст вида
 *
 *   «ɋɈɋɌȺȼ ɉɊɈȿɄɌɇɈɃ ȾɈɄɍɆȿɇɌȺɐɂɂ»
 *
 * вместо «СОСТАВ ПРОЕКТНОЙ ДОКУМЕНТАЦИИ». Это не скан и не сбой чтения: в
 * документе подмножество шрифта с собственной кодировкой, и таблица ToUnicode
 * у него сдвинута. Каждая буква приезжает на 0x1D6 ниже своего места — ровно
 * на столько, сколько отделяет кириллицу от расширенной латиницы.
 *
 * СКОЛЬКО ЭТО СТОИЛО. «Раздел ПД №9_СМ_Расч_Изм.2_.pdf» — 5 383 знака из
 * 53 363, то есть каждая десятая буква документа. «Раздел ПД №9_СМ_ЛС» и
 * «…_ОС» — столько же. Роль читала этот текст как набор символов без смысла и
 * не могла сказать, что в нём написано; система молчала, потому что знаки
 * пришли и длина текста была большой. Потеря выглядела успехом.
 *
 * ПОЧЕМУ ЭТО МОЖНО ЧИНИТЬ БЕЗ ДОГАДОК. Сдвиг ПОСТОЯННЫЙ и проверяем: «С»
 * (U+0421) приходит как U+024B, «о» (U+043E) — как U+0268, разница одна и та
 * же. Обратный сдвиг — не распознавание, а снятие известного смещения.
 *
 * ПОЧЕМУ ЭТО БЕЗОПАСНО. Диапазон U+023A–U+027B — расширенная латиница и знаки
 * МФА (ɺ, ɷ, ɂ). В строительной документации на русском их не бывает: встретив
 * их пачкой, мы видим не текст, а сбитую кодировку. Одиночный такой знак
 * оставляется как есть — чинится только то, что пришло словами.
 */

/** Расстояние между кириллицей и тем местом, куда её сдвинула таблица шрифта. */
const СДВИГ = 0x1d6;

/** Границы сдвинутого диапазона: «А» (U+0410) → U+023A, «я» (U+044F) → U+0279, «ё» → U+027B. */
const ОТ = 0x023a;
const ДО = 0x027b;

/**
 * Сколько сдвинутых знаков считать сбитой кодировкой, а не текстом.
 *
 * Восемь — это слово. Одиночная ɂ в чертёжной надписи может быть и знаком, а
 * восемь подряд идущих — это всегда испорченная строка.
 */
const СЛОВО = 8;

/** Сдвинуты ли и кавычки: «…» приезжают как ©…ª в тех же документах. */
const КАВЫЧКИ: ReadonlyMap<string, string> = new Map([
  ["©", "«"],
  ["ª", "»"],
]);

/** Сколько знаков текста лежит в сдвинутом диапазоне. */
export function shiftedLetters(text: string): number {
  let сколько = 0;

  for (const знак of text) {
    const код = знак.codePointAt(0) ?? 0;
    if (код >= ОТ && код <= ДО) сколько += 1;
  }

  return сколько;
}

/**
 * Возвращает кириллицу на место. Текст без сдвига возвращается тем же объектом:
 * подавляющее большинство документов чинить не нужно, и лишней работы не будет.
 */
export function restoreShiftedCyrillic(text: string): string {
  if (shiftedLetters(text) < СЛОВО) return text;

  let результат = "";

  for (const знак of text) {
    const код = знак.codePointAt(0) ?? 0;

    if (код >= ОТ && код <= ДО) {
      результат += String.fromCodePoint(код + СДВИГ);
      continue;
    }

    // Кавычки чинятся ТОЛЬКО в документе, где сдвиг уже доказан буквами: знак
    // авторского права сам по себе законен, и трогать его без причины нельзя.
    результат += КАВЫЧКИ.get(знак) ?? знак;
  }

  return результат;
}
