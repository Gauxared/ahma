/**
 * ИТОГОВАЯ СТРОКА — НЕ ПОЗИЦИЯ.
 *
 * Правило одно на всю систему и живёт отдельно от обоих читателей по той же
 * причине, что и `cell-number.ts`: строку «Всего с НДС» одинаково встречают и
 * роль, выписавшая её из документа, и разбор, прочитавший книгу колонками.
 * Написанное дважды, правило разошлось бы, и один путь считал бы итог работой,
 * а другой — итогом. Замерено на прогоне 16: пятнадцать таких строк из ста
 * сорока четырёх, включая «Всего с НДС 413 072 947 ₽».
 *
 * Строка не отбрасывается — она помечается: число остаётся видимым человеку и
 * пригодным для сверки сходимости, но в денежные своды не идёт.
 *
 * `\b` ЗДЕСЬ НЕ ГОДИТСЯ: в JavaScript граница слова считается по ASCII, и после
 * кириллического «итого» её просто нет — правило молча не срабатывало.
 * Границу задаёт «дальше не буква» в юникодном смысле.
 */
const ИТОГОВАЯ = /^\s*(итого|итог|всего|в том числе|в т\.ч\.)(?!\p{L})/iu;

/** Начинается ли наименование как итог документа, раздела или подраздела. */
export function isTotalRow(name: string): boolean {
  return ИТОГОВАЯ.test(name);
}
