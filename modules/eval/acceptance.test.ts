/**
 * Тесты написаны до реализации. Приёмка по агентам — ТЗ §12.2.
 *
 * Требование: **≥80% пунктов чек-листа по каждому агенту**. Именно «по
 * каждому», а не в среднем: агент, провалившийся в одиночку, не принимается,
 * даже если остальные восемь идеальны. Средняя оценка по девяти скрыла бы
 * ровно того, кто не работает.
 *
 * Роадмап, ADR-R-001: «Вариант „один промпт с девятью линзами" контрактно
 * непринимаем: нечем закрывать §12.2».
 */
import { describe, expect, it } from "vitest";

import { evaluateAgent, evaluateAll, ACCEPTANCE_THRESHOLD } from "./acceptance.js";
import type { AgentChecklist } from "./acceptance.js";

const ЧЕКЛИСТ: AgentChecklist = {
  agent: "денчик",
  items: [
    { id: "д-7-реверс", requirement: "реверс объёма линейных позиций выполнен" },
    { id: "д-7-флаги", requirement: "кратность >2 помечена стоп-флагом" },
    { id: "допущения", requirement: "блок допущений вынесен отдельно" },
    { id: "основания", requirement: "у каждого вывода есть основание" },
    { id: "деградации", requirement: "недоступное объявлено, а не умолчано" },
  ],
};

describe("приёмка одного агента (§12.2)", () => {
  it("держит порог договора: восемьдесят процентов", () => {
    expect(ACCEPTANCE_THRESHOLD).toBe(0.8);
  });

  it("принимает агента ровно на пороге", () => {
    // Четыре из пяти — 80%. Договор говорит «≥80%», значит порог входит.
    const итог = evaluateAgent(ЧЕКЛИСТ, {
      "д-7-реверс": true,
      "д-7-флаги": true,
      допущения: true,
      основания: true,
      деградации: false,
    });

    expect(итог.share).toBe(0.8);
    expect(итог.passed).toBe(true);
  });

  it("не принимает агента чуть ниже порога", () => {
    const итог = evaluateAgent(ЧЕКЛИСТ, {
      "д-7-реверс": true,
      "д-7-флаги": true,
      допущения: true,
      основания: false,
      деградации: false,
    });

    expect(итог.share).toBe(0.6);
    expect(итог.passed).toBe(false);
  });

  it("НЕОТВЕЧЕННЫЙ пункт считается непройденным, а не пропускается", () => {
    // Иначе чек-лист из одного отвеченного пункта дал бы 100%: чем меньше
    // проверили, тем лучше результат. Это худший из возможных стимулов.
    const итог = evaluateAgent(ЧЕКЛИСТ, { "д-7-реверс": true });

    expect(итог.share).toBe(0.2);
    expect(итог.unanswered).toHaveLength(4);
  });

  it("называет проваленные пункты поимённо", () => {
    const итог = evaluateAgent(ЧЕКЛИСТ, { "д-7-реверс": false, "д-7-флаги": true });

    expect(итог.failed.map((item) => item.id)).toEqual(["д-7-реверс"]);
  });

  it("пустой чек-лист не принимается: проверять было нечего", () => {
    // Ноль из нуля — это не сто процентов. Агент без чек-листа не проверен,
    // и объявить его принятым значит принять непроверенное.
    const итог = evaluateAgent({ agent: "пустой", items: [] }, {});

    expect(итог.passed).toBe(false);
    expect(итог.share).toBe(0);
  });
});

describe("приёмка всех агентов", () => {
  const второй: AgentChecklist = {
    agent: "людмила",
    items: [
      { id: "сходимость", requirement: "сходимость 0 ₽" },
      { id: "шифры", requirement: "позиции сопоставлены по шифру" },
    ],
  };

  it("принимает набор, только если КАЖДЫЙ агент прошёл", () => {
    // §12.2 требует «по каждому агенту», а не в среднем.
    const итог = evaluateAll(
      [ЧЕКЛИСТ, второй],
      {
        денчик: { "д-7-реверс": true, "д-7-флаги": true, допущения: true, основания: true, деградации: true },
        людмила: { сходимость: true, шифры: false },
      },
    );

    expect(итог.byAgent.find((agent) => agent.agent === "денчик")?.passed).toBe(true);
    expect(итог.byAgent.find((agent) => agent.agent === "людмила")?.passed).toBe(false);
    expect(итог.passed).toBe(false);
  });

  it("не усредняет: один провал не тонет в чужих успехах", () => {
    const итог = evaluateAll(
      [ЧЕКЛИСТ, второй],
      {
        денчик: { "д-7-реверс": true, "д-7-флаги": true, допущения: true, основания: true, деградации: true },
        людмила: { сходимость: false, шифры: false },
      },
    );

    // Средняя доля была бы (1.0 + 0) / 2 = 50% и выглядела бы «почти».
    expect(итог.failedAgents).toEqual(["людмила"]);
  });

  it("агент без ответов вовсе не считается пройденным", () => {
    const итог = evaluateAll([ЧЕКЛИСТ, второй], { денчик: {} });

    expect(итог.failedAgents).toContain("денчик");
    expect(итог.failedAgents).toContain("людмила");
  });
});
