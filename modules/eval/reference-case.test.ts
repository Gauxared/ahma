/**
 * Замер против эталона — инструмент, которому предстоит судить нашу работу.
 *
 * Поэтому проверяется в первую очередь не то, что он засчитывает совпадение, а
 * то, что он НЕ засчитывает: замер, который нельзя провалить, не измеряет
 * ничего. Заказчик работы усомнился именно в этом, и сомнение верное — такой
 * инструмент обязан быть проверен со стороны отказа.
 */
import { describe, expect, it } from "vitest";

import { measureAgainstReference } from "./reference-case.js";
import type { ReferenceCase } from "./reference-case.js";

const ЭТАЛОН: ReferenceCase = {
  id: "проба",
  object: "объект",
  reference: "эталон",
  expectations: [
    {
      id: "вынос-кс",
      claim: "блок не обоснован РД",
      amount: "64710398.29",
      source: "03_Сметный_анализ, README",
      about: ["ГЭСНм20-03-035", "вынос"],
    },
  ],
};

describe("чего замер НЕ засчитывает", () => {
  it("пустой прогон — промах, а не успех", () => {
    const мера = measureAgainstReference(ЭТАЛОН, { amounts: [], text: "" });

    expect(мера.reproduced).toBe(0);
    expect(мера.results[0]!.kind).toBe("не воспроизведено");
    expect(мера.score).toBe("0.00");
  });

  it("совпало ЧИСЛО без предмета — частично, а не воспроизведено", () => {
    // Совпадение сумм бывает случайным: 64 710 398 могло попасть в отчёт по
    // другому поводу. Засчитывать такое полностью значит завышать паритет.
    const мера = measureAgainstReference(ЭТАЛОН, {
      amounts: ["64710398.29"],
      text: "итог по объекту",
    });

    expect(мера.results[0]!.kind).toBe("частично");
    expect(мера.results[0]!.note).toMatch(/может быть случайным/u);
  });

  it("назван ПРЕДМЕТ без суммы — частично: вывод не оценён в рублях", () => {
    const мера = measureAgainstReference(ЭТАЛОН, {
      amounts: ["123.00"],
      text: "блок ГЭСНм20-03-035 вызывает вопросы",
    });

    expect(мера.results[0]!.kind).toBe("частично");
    expect(мера.results[0]!.note).toMatch(/не оценён в рублях/u);
  });

  it("число ВНЕ допуска не считается тем же числом", () => {
    // 64,7 млн и 66,0 млн — разные величины, и выдать одну за другую значит
    // объявить воспроизведённым то, что не воспроизведено.
    const мера = measureAgainstReference(ЭТАЛОН, {
      amounts: ["66020127.59"],
      text: "блок ГЭСНм20-03-035 не подтверждён",
    });

    expect(мера.results[0]!.kind).toBe("частично");
    expect(мера.results[0]!.matched).toBeUndefined();
  });
});

describe("что замер засчитывает", () => {
  it("число И предмет — воспроизведено, с расхождением в отчёте", () => {
    const мера = measureAgainstReference(ЭТАЛОН, {
      amounts: ["64710398.29"],
      text: "блок ГЭСНм20-03-035: объём не подтверждён рабочей документацией",
    });

    expect(мера.results[0]!.kind).toBe("воспроизведено");
    expect(мера.results[0]!.note).toBe("совпало точно");
    expect(мера.score).toBe("100.00");
  });

  it("берёт БЛИЖАЙШЕЕ из нескольких кандидатов", () => {
    const мера = measureAgainstReference(ЭТАЛОН, {
      amounts: ["64890000.00", "64710398.29", "64500000.00"],
      text: "вынос контактной сети",
    });

    expect(мера.results[0]!.matched).toBe("64710398.29");
  });

  it("допускает расхождение шкалы и НАЗЫВАЕТ его", () => {
    // Сводный расчёт номинирован в тысячах: расхождение в рубль неизбежно и
    // должно быть видно, а не спрятано.
    const мера = measureAgainstReference(
      { ...ЭТАЛОН, expectations: [{ ...ЭТАЛОН.expectations[0]!, amount: "2141524.73" }] },
      { amounts: ["2141526.00"], text: "вынос" },
    );

    expect(мера.results[0]!.kind).toBe("воспроизведено");
    expect(мера.results[0]!.note).toMatch(/расхождением 0\.000/u);
  });
});

describe("доля", () => {
  it("частичное стоит половины полного", () => {
    const два: ReferenceCase = {
      ...ЭТАЛОН,
      expectations: [
        ЭТАЛОН.expectations[0]!,
        { ...ЭТАЛОН.expectations[0]!, id: "второе", amount: "100.00", about: ["второе"] },
      ],
    };

    const мера = measureAgainstReference(два, {
      amounts: ["64710398.29", "100.00"],
      text: "вынос контактной сети",
    });

    // Первое — полностью, второе — число без предмета, то есть половина.
    expect(мера.reproduced).toBe(1);
    expect(мера.partial).toBe(1);
    expect(мера.score).toBe("75.00");
  });
});
