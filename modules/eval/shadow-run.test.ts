/**
 * Тесты написаны до реализации. Теневой прогон — ADR-R-020 и роадмап M3:
 *
 *   «Теневой прогон против небольшой локальной модели — регулярно, ДАЖЕ ПОКА
 *    НЕ ПРОХОДИТ. Метрика „разрыв внешняя ↔ целевая модель" ведётся с этого
 *    момента; перевод в контур разрешён по ЗАКРЫТИЮ РАЗРЫВА, а не по
 *    наступлению срока.»
 *
 * Смысл в последней фразе. Разрыв, который начинают мерить в день переезда,
 * измеряют один раз и под давлением срока. Разрыв, который ведут с самого
 * начала, показывает тренд — и говорит, сближаются модели или расходятся.
 */
import { describe, expect, it } from "vitest";

import { compareRuns, gapTrend } from "./shadow-run.js";

describe("разрыв между внешней и целевой моделью", () => {
  it("совпадение по всем пунктам даёт нулевой разрыв", () => {
    const разрыв = compareRuns({
      reference: { agent: "денчик", passedItems: ["а", "б", "в"] },
      shadow: { agent: "денчик", passedItems: ["а", "б", "в"] },
    });

    expect(разрыв.gap).toBe(0);
    expect(разрыв.closed).toBe(true);
  });

  it("считает разрыв долей пунктов, потерянных целевой моделью", () => {
    const разрыв = compareRuns({
      reference: { agent: "денчик", passedItems: ["а", "б", "в", "г"] },
      shadow: { agent: "денчик", passedItems: ["а", "б"] },
    });

    expect(разрыв.gap).toBe(0.5);
    expect(разрыв.lost).toEqual(["в", "г"]);
  });

  it("НЕ считает разрывом то, что целевая модель нашла ДОПОЛНИТЕЛЬНО", () => {
    // Локальная модель может закрыть пункт, который внешняя пропустила.
    // Это не разрыв: разрыв — то, что мы ПОТЕРЯЕМ при переезде.
    const разрыв = compareRuns({
      reference: { agent: "денчик", passedItems: ["а", "б"] },
      shadow: { agent: "денчик", passedItems: ["а", "б", "в"] },
    });

    expect(разрыв.gap).toBe(0);
    expect(разрыв.gained).toEqual(["в"]);
  });

  it("пустой эталон не даёт нулевого разрыва: мерить не с чем", () => {
    // Ноль потерянных из нуля — это не «разрыв закрыт», а «не измеряли».
    const разрыв = compareRuns({
      reference: { agent: "денчик", passedItems: [] },
      shadow: { agent: "денчик", passedItems: [] },
    });

    expect(разрыв.closed).toBe(false);
    expect(разрыв.note).toContain("не измерялся");
  });
});

describe("тренд разрыва", () => {
  it("называет сближение, когда разрыв уменьшается", () => {
    expect(gapTrend([0.5, 0.4, 0.2]).direction).toBe("сближаются");
  });

  it("называет расхождение, когда разрыв растёт", () => {
    // Это тревога: целевая модель отстаёт всё сильнее, и срок переезда
    // становится нереальным раньше, чем наступит.
    expect(gapTrend([0.2, 0.3, 0.5]).direction).toBe("расходятся");
  });

  it("называет застой, когда разрыв не меняется", () => {
    expect(gapTrend([0.3, 0.3, 0.3]).direction).toBe("без изменений");
  });

  it("по одному замеру тренда нет, и он не выдумывается", () => {
    const тренд = gapTrend([0.3]);

    expect(тренд.direction).toBe("недостаточно замеров");
    expect(тренд.note).toContain("одного замера");
  });

  it("считает, сколько замеров до закрытия при текущем темпе", () => {
    // Прогноз — не обещание, а ответ на вопрос «успеваем ли к сроку».
    const тренд = gapTrend([0.5, 0.4, 0.3]);

    expect(тренд.runsToClose).toBe(3);
  });

  it("не прогнозирует закрытие при расхождении", () => {
    const тренд = gapTrend([0.2, 0.3, 0.5]);

    expect(тренд.runsToClose).toBeUndefined();
  });
});
