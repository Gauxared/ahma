/**
 * Заключение агента — то, что клиент уносит с встречи.
 *
 * ПОЧЕМУ ЭТОТ НАБОР ПОЯВИЛСЯ ПОЗДНО И ЧТО ОН НАШЁЛ
 *
 * Сборщик девяти документов пакета не был покрыт ничем. Обнаружилось это при
 * сверке с эталонным выходом `reference-system/output-1`: в наших книгах не
 * оказалось ПОРУЧЕНИЙ — «что проверить человеку». Это графа формы результата и
 * одно из обещаний брифа; на прогоне эталонного входа таких поручений было
 * семьдесят два, и ни одно не доезжало до выгруженного документа.
 *
 * Пропуск такого рода не виден ни на одном экране: экран показывает поручения,
 * а книга — нет, и расходятся они молча.
 *
 * ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ
 *
 * Не «книга собралась», а состав: лист поручений есть ВСЕГДА, пустой отличён от
 * отсутствующего, и лист «Чего здесь нет» не молчит о границах.
 */
import { describe, expect, it } from "vitest";

import { buildAgentReport, type AgentReportSource } from "./agent-report.js";

function источник(parts: Partial<AgentReportSource> = {}): AgentReportSource {
  return {
    title: "02 Инженерное заключение",
    capability: "tech_opinion",
    role: "ГИП",
    objectName: "ЖДПП Зауралье",
    objectCode: "KRG-1",
    verdict: "🔴 не принимать",
    subjects: ["ЛСР-1.xlsx"],
    findings: [{ severity: "critical", statement: "позиция 89 не расшифрована", basis: "блок «НЕРАСШИФРОВАННЫЕ»" }],
    errors: [],
    tasks: [],
    sheets: [],
    requiredSheets: [],
    artifactId: "a1",
    inputHashes: ["h1"],
    producedAt: "2026-09-06",
    generatorVersion: "1.0.0",
    ...parts,
  };
}

const имена = (source: AgentReportSource): readonly string[] =>
  buildAgentReport(source).sheets.map((sheet) => sheet.name);

describe("состав книги заключения", () => {
  it("резюме несёт НАХОДКИ, а не только их счёт", () => {
    /**
     * Сверка с эталонным `02_Инженерное_заключение`: его первый лист — вердикт
     * и «ТОП-НАХОДКИ (в порядке денежного веса и риска)», десять строк с фактом
     * и адресатом. Наш был карточкой учёта: сорок четыре замечания, из них
     * восемь критичных, артефакт такой-то.
     *
     * Человек, открывший книгу, видел числа и НИ ОДНОЙ НАХОДКИ: они лежали
     * листом дальше.
     */
    const книга = buildAgentReport(
      источник({
        findings: [
          { severity: "medium", statement: "мелочь на большие деньги", basis: "поз. 3", amount: { text: "12 000 000,00", value: 12_000_000 } },
          { severity: "critical", statement: "критично, но без суммы", basis: "поз. 7" },
        ],
      }),
    );

    const резюме = JSON.stringify(книга.sheets[0]);

    expect(резюме).toContain("мелочь на большие деньги");
    expect(резюме).toContain("критично, но без суммы");
    expect(резюме).toContain("12 000 000,00");
  });

  it("порядок находок — сначала деньги, потом важность", () => {
    // «Критично на 12 миллионов» и «критично без суммы» разного веса, и порядок
    // выдачи модели тут не судья. Замечание без суммы уходит вниз, а не
    // приравнивается к нулю рублей (§9).
    const книга = buildAgentReport(
      источник({
        findings: [
          { severity: "critical", statement: "без суммы", basis: "б" },
          { severity: "low", statement: "дешёвое", basis: "б", amount: { text: "1 000,00", value: 1000 } },
          { severity: "low", statement: "дорогое", basis: "б", amount: { text: "9 000 000,00", value: 9_000_000 } },
        ],
      }),
    );

    const строки = JSON.stringify(книга.sheets[0]);
    const место = (что: string) => строки.indexOf(что);

    expect(место("дорогое")).toBeLessThan(место("дешёвое"));
    expect(место("дешёвое")).toBeLessThan(место("без суммы"));
  });

  it("замечание без суммы не выдаётся за бесплатное", () => {
    const книга = buildAgentReport(
      источник({ findings: [{ severity: "high", statement: "нет опоры в РД", basis: "б" }] }),
    );

    expect(JSON.stringify(книга.sheets[0])).toContain("величина не определена");
    expect(JSON.stringify(книга.sheets[0])).not.toContain("0,00 ₽");
  });

  it("резюме без замечаний блока находок не заводит", () => {
    // Заголовок «Главное» над пустотой читается как «главного не нашлось» —
    // утверждение, которого агент не делал.
    expect(JSON.stringify(buildAgentReport(источник({ findings: [] })).sheets[0])).not.toContain("Главное");
  });

  it("поручения — отдельный лист, а не приложение к замечаниям", () => {
    expect(имена(источник())).toContain("04_Поручения");
  });

  it("лист поручений есть и когда поручений нет", () => {
    // Отсутствие листа читается как «поручений не предусмотрено», пустой лист с
    // объяснением — как «агент их не выдал». Второе правда, и оно полезнее.
    const книга = buildAgentReport(источник({ tasks: [] }));
    const лист = книга.sheets.find((sheet) => sheet.name === "04_Поручения");

    expect(лист).toBeDefined();
    expect(JSON.stringify(лист)).toContain("не выдал ни одного поручения");
  });

  it("поручение несёт вопрос, адресата и срок", () => {
    const книга = buildAgentReport(
      источник({
        tasks: [{ question: "сверить объём кабеля с журналом", owner: "ГИП", dueBy: "2026-09-20" }],
      }),
    );
    const лист = JSON.stringify(книга.sheets.find((sheet) => sheet.name === "04_Поручения"));

    expect(лист).toContain("сверить объём кабеля с журналом");
    expect(лист).toContain("ГИП");
    expect(лист).toContain("2026-09-20");
  });

  it("поручение без адресата НЕ выдаётся за адресованное", () => {
    // Пустая ячейка читается как «кому угодно». Поручение без адресата —
    // не поручение (§9), и книга обязана это произнести.
    const книга = buildAgentReport(источник({ tasks: [{ question: "проверить", owner: "", dueBy: "" }] }));
    const лист = JSON.stringify(книга.sheets.find((sheet) => sheet.name === "04_Поручения"));

    expect(лист).toContain("адресат не назван агентом");
    expect(лист).toContain("срок не назван агентом");
  });

  it("отказ агента — свой лист, и он появляется только при отказе", () => {
    expect(имена(источник())).not.toContain("05_Отказы");
    expect(имена(источник({ errors: ["модель не ответила"] }))).toContain("05_Отказы");
  });

  it("книга называет границу: чего в ней нет и почему", () => {
    const лист = JSON.stringify(buildAgentReport(источник()).sheets.at(-1));

    expect(лист).toContain("Чего в этом документе нет");
    expect(лист).toContain("След формулы");
  });

  it("предметные листы попадают в книгу как есть — с названием и колонками агента", () => {
    /**
     * Названия листов НЕ ЗАДАНЫ конфигурацией, и это главное свойство.
     * Эталонный пакет снят с одного объекта: его «КС_геометрия» бессмысленна
     * для жилого дома, а агент, обязанный такой лист заполнить, начнёт его
     * выдумывать.
     */
    const книга = buildAgentReport(
      источник({
        sheets: [
          {
            id: "ks-geometry",
            title: "Контактная сеть: смета против физики",
            purpose: "объём сметы сверяется с геометрией трассы",
            columns: ["Параметр", "Значение", "Ед.", "Источник"],
            rows: [["длина участка", "15 240", "м", "РД, лист 8"]],
          },
        ],
      }),
    );

    const лист = книга.sheets.find((sheet) => sheet.name.includes("ks-geometry"));

    expect(лист, "предметный лист не попал в книгу").toBeDefined();
    const текст = JSON.stringify(лист);
    expect(текст).toContain("Контактная сеть: смета против физики");
    expect(текст).toContain("объём сметы сверяется с геометрией трассы");
    expect(текст).toContain("РД, лист 8");
  });

  it("нумерация сквозная при любом числе предметных листов", () => {
    // Номер листа — навигация. При трёх предметных листах замечания обязаны
    // стать «05», а не остаться «02»: заказчик ищет их по порядку.
    const лист = (id: string) => ({
      id,
      title: id,
      purpose: "п",
      columns: ["А"],
      rows: [["1"]],
    });

    const имена3 = имена(источник({ sheets: [лист("a"), лист("b"), лист("c")] }));

    expect(имена3[0]).toBe("01_Вердикт");
    expect(имена3.slice(1, 4).every((n) => /^0[234]_/.test(n))).toBe(true);
    expect(имена3).toContain("05_Замечания");
    expect(имена3).toEqual([...имена3].sort((a, b) => a.localeCompare(b, "ru")));
  });

  it("НЕ ДАННЫЙ обязательный лист называется пробелом, а не молчит", () => {
    // Отличать надо от предметного листа, которого нет: тот отсутствует потому,
    // что на объекте нет предмета. Каркас роли — то, на что агент отвечает
    // всегда, и его молчание означает «не ответил».
    const книга = buildAgentReport(
      источник({ requiredSheets: [{ id: "convergence", title: "Сходимость" }], sheets: [] }),
    );

    expect(JSON.stringify(книга.sheets.at(-1))).toContain("Сходимость");
    expect(JSON.stringify(книга.sheets.at(-1))).toContain("пробел, а не отсутствие предмета");
  });

  it("данный обязательный лист пробелом не называется", () => {
    const книга = buildAgentReport(
      источник({
        requiredSheets: [{ id: "convergence", title: "Сходимость" }],
        sheets: [{ id: "convergence", title: "Сходимость", purpose: "п", columns: ["А"], rows: [["0 ₽"]] }],
      }),
    );

    expect(JSON.stringify(книга.sheets.at(-1))).not.toContain("пробел, а не отсутствие предмета");
  });

  it("имя листа книги укладывается в предел Excel и не содержит запрещённых знаков", () => {
    // `id` приходит от модели и содержать может что угодно. Excel режет имя на
    // 31 знаке молча: два длинных названия схлопнулись бы в одно, и книга не
    // открылась бы вовсе.
    const книга = buildAgentReport(
      источник({
        sheets: [
          { id: "очень/длинное:название[листа]*которое*не*влезает", title: "т", purpose: "п", columns: ["А"], rows: [["1"]] },
        ],
      }),
    );

    for (const имя of книга.sheets.map((sheet) => sheet.name)) {
      expect(имя.length, `имя листа «${имя}» длиннее предела Excel`).toBeLessThanOrEqual(31);
      expect(имя, `имя листа «${имя}» содержит запрещённый знак`).not.toMatch(/[:\\/?*[\]]/);
    }
  });

  it("листы идут по порядку номеров в имени", () => {
    // Номер в имени листа — навигация: книга, где «06» стоит перед «04»,
    // читается как собранная наспех.
    const порядок = имена(источник({ errors: ["сбой"], tasks: [{ question: "q", owner: "o", dueBy: "d" }] }));

    expect(порядок).toEqual([...порядок].sort((a, b) => a.localeCompare(b, "ru")));
  });
});
