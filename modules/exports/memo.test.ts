/**
 * Тесты написаны до реализации. Записка — ТЗ §10, третья из четырёх выгрузок:
 *
 *   «Записка (Word) | Паспорт объекта, разделы по агентам, сводный вывод»
 *
 * ЧЕМ ЗАПИСКА ОТЛИЧАЕТСЯ ОТ ОСТАЛЬНЫХ ТРЁХ
 *
 * Три другие выгрузки — таблицы: их читает тот, кто уже знает, что ищет.
 * Записку читает руководитель, которому нужно принять решение, не открывая
 * смет. Значит, у неё есть обязанность, которой нет у таблиц: СКАЗАТЬ ВЫВОД
 * ПЕРВЫМ, а не спрятать его после девяти разделов.
 *
 * ПУСТОЙ РАЗДЕЛ АГЕНТА — ЭТО СОДЕРЖАНИЕ
 *
 * Агент, который не отработал, обязан быть в записке с пометкой, а не
 * отсутствовать. Отсутствие раздела читается как «этой темы нет у объекта»;
 * пометка «не выполнено» читается как «эту тему никто не смотрел». Это разные
 * вещи, и вторая — риск, о котором руководитель должен знать.
 *
 * СВОДНЫЙ ВЫВОД НЕ БЫВАЕТ СИЛЬНЕЕ СВОИХ РАЗДЕЛОВ
 *
 * Если хоть один агент дал отказ или блокирующую находку, «всё в порядке» в
 * шапке — ложь. Вывод выводится из разделов, а не пишется отдельно.
 */
import { describe, expect, it } from "vitest";

import { buildMemo } from "./memo.js";

const ПАСПОРТ = {
  objectName: "Курган, электроснабжение",
  customer: "ПАО «АПРИ»",
  documentCount: 7,
  checkedAt: "2026-08-31",
  total: "104976702.48",
};

const РАЗДЕЛ = {
  agent: "Денчик",
  role: "ГИП",
  status: "выполнен" as const,
  findings: ["объём блока ГЭСНм20-03-035 не подтверждён РД — 64 710 398,29 ₽"],
  conclusion: "объём принять нельзя до сверки с осями РД",
};

describe("записка (§10)", () => {
  it("несёт паспорт объекта", () => {
    const записка = buildMemo({ passport: ПАСПОРТ, sections: [РАЗДЕЛ] });
    const текст = записка.blocks.map((b) => ("text" in b ? b.text : "")).join(" ");

    expect(текст).toContain("Курган, электроснабжение");
    expect(текст).toContain("ПАО «АПРИ»");
  });

  it("СТАВИТ сводный вывод ПЕРЕД разделами", () => {
    // Записку читает тот, кто решает, не открывая смет. Вывод после девяти
    // разделов — это вывод, которого не прочтут.
    const записка = buildMemo({ passport: ПАСПОРТ, sections: [РАЗДЕЛ] });

    const выводIndex = записка.blocks.findIndex((b) => "text" in b && b.text.includes("СВОДНЫЙ ВЫВОД"));
    const разделIndex = записка.blocks.findIndex((b) => "text" in b && b.text.includes("Денчик"));

    expect(выводIndex).toBeGreaterThanOrEqual(0);
    expect(выводIndex).toBeLessThan(разделIndex);
  });

  it("даёт раздел на каждого агента", () => {
    const записка = buildMemo({
      passport: ПАСПОРТ,
      sections: [РАЗДЕЛ, { ...РАЗДЕЛ, agent: "Людмила", role: "Сметчик" }],
    });
    const текст = записка.blocks.map((b) => ("text" in b ? b.text : "")).join(" ");

    expect(текст).toContain("Денчик");
    expect(текст).toContain("Людмила");
  });

  it("ВКЛЮЧАЕТ раздел агента, который не отработал, с пометкой", () => {
    // Отсутствие раздела читается как «этой темы нет у объекта». Пометка «не
    // выполнено» читается как «эту тему никто не смотрел» — разные вещи.
    const записка = buildMemo({
      passport: ПАСПОРТ,
      sections: [{ ...РАЗДЕЛ, agent: "Ваныч", role: "Эконом", status: "не выполнен", findings: [], conclusion: "" }],
    });
    const текст = записка.blocks.map((b) => ("text" in b ? b.text : "")).join(" ");

    expect(текст).toContain("Ваныч");
    expect(текст).toContain("не выполнен");
  });

  it("НЕ выносит сильный вывод, когда есть невыполненный раздел", () => {
    const записка = buildMemo({
      passport: ПАСПОРТ,
      sections: [
        { ...РАЗДЕЛ, findings: [], conclusion: "замечаний нет" },
        { ...РАЗДЕЛ, agent: "Ваныч", role: "Эконом", status: "не выполнен", findings: [], conclusion: "" },
      ],
    });

    expect(записка.verdict.strong).toBe(false);
    expect(записка.verdict.reason).toContain("Ваныч");
  });

  it("НЕ выносит сильный вывод при находках", () => {
    // «Всё в порядке» над разделом с находкой на 64 миллиона — ложь.
    const записка = buildMemo({ passport: ПАСПОРТ, sections: [РАЗДЕЛ] });

    expect(записка.verdict.strong).toBe(false);
    expect(записка.verdict.findingsCount).toBe(1);
  });

  it("выносит сильный вывод, когда все отработали и находок нет", () => {
    const записка = buildMemo({
      passport: ПАСПОРТ,
      sections: [{ ...РАЗДЕЛ, findings: [], conclusion: "замечаний нет" }],
    });

    expect(записка.verdict.strong).toBe(true);
  });

  it("НЕ выносит сильный вывод на пустом наборе разделов", () => {
    // Ноль разделов — это «никто не смотрел», а не «замечаний нет».
    const записка = buildMemo({ passport: ПАСПОРТ, sections: [] });

    expect(записка.verdict.strong).toBe(false);
    expect(записка.verdict.reason).toContain("ни один агент");
  });

  it("перечисляет находки в сводном выводе, а не только внутри разделов", () => {
    // Руководитель, дочитавший до вывода, обязан увидеть, о чём спор.
    const записка = buildMemo({ passport: ПАСПОРТ, sections: [РАЗДЕЛ] });
    // Границей берётся заголовок разделов, а не имя агента: имя встречается и
    // в сводных находках, и срез по нему отрезал бы ровно то, что проверяется.
    const вывод = записка.blocks
      .slice(
        записка.blocks.findIndex((b) => "text" in b && b.text.includes("СВОДНЫЙ ВЫВОД")),
        записка.blocks.findIndex((b) => "text" in b && b.text.includes("Разделы по агентам")),
      )
      .map((b) => ("text" in b ? b.text : ""))
      .join(" ");

    expect(вывод).toContain("64 710 398,29 ₽");
  });

  it("разделяет разряды НЕРАЗРЫВНЫМ пробелом", () => {
    // Обычный пробел позволил бы Word перенести «104 976» и «702,48» на разные
    // строки, и сумма в записке превратилась бы в два числа. Для документа,
    // которым обосновывают решение на сто миллионов, это не придирка.
    const записка = buildMemo({ passport: ПАСПОРТ, sections: [] });
    const текст = записка.blocks.map((b) => ("text" in b ? b.text : "")).join(" ");

    expect(текст).toContain("104\u00A0976\u00A0702,48 ₽");
  });

  it("не теряет заголовки: у каждого блока есть уровень", () => {
    const записка = buildMemo({ passport: ПАСПОРТ, sections: [РАЗДЕЛ] });

    for (const блок of записка.blocks) {
      if (блок.kind === "heading") expect([1, 2, 3]).toContain(блок.level);
    }
  });
});

describe("причина, по которой раздел не закрыт", () => {
  it("печатает вывод неотработавшего агента, а не только пометку", () => {
    // «Агент не отработал» руководителю нечего делать: он не знает, ждать ли,
    // или чего-то не хватает от него самого. Причина превращает пометку в
    // поручение.
    const memo = buildMemo({
      passport: ПАСПОРТ,
      sections: [
        {
          agent: "Ваныч",
          role: "Эконом",
          status: "не выполнен",
          findings: [],
          conclusion: "Финмодель не строится: себестоимость не задана (--costs).",
        },
      ],
    });

    const text = memo.blocks.map((block) => ("text" in block ? block.text : "")).join("\n");

    expect(text).toContain("Тема объекта НЕ проверена");
    expect(text).toContain("себестоимость не задана");
  });

  it("не печатает пустую строку, когда причины нет", () => {
    const memo = buildMemo({
      passport: ПАСПОРТ,
      sections: [
        { agent: "Палыч", role: "ПТО", status: "не выполнен", findings: [], conclusion: "   " },
      ],
    });

    const paragraphs = memo.blocks.filter(
      (block) => "text" in block && block.text.trim() === "",
    );

    expect(paragraphs).toHaveLength(0);
  });
});
