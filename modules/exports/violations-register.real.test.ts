/**
 * Реестр собирается на НАСТОЯЩЕЙ находке курганского объекта.
 *
 * Синтетическая строка доказывает, что колонки на месте. Она не доказывает
 * того, ради чего реестр существует: что найденное системой нарушение можно
 * ПРЕДЪЯВИТЬ — с суммой, с основанием и с понятным следующим шагом.
 *
 * Здесь берётся находка, совпавшая с эталонным приёмом заказчика: блок
 * ГЭСНм20-03-035 на 64 710 398,29 ₽, объём которого не подтверждён рабочей
 * документацией (правило Д-7 Денчика, кратность больше двух).
 */
import { describe, expect, it } from "vitest";

import { buildViolationsRegister } from "./violations-register.js";

describe("реестр на курганской находке", () => {
  it("предъявляет блок реверса объёма со всеми пятью полями", () => {
    const реестр = buildViolationsRegister({
      objectName: "Курган, ЭОМ",
      violations: [
        {
          position: "блок ГЭСНм20-03-035 (6 позиций), 198.12 км",
          kind: "объём не подтверждён рабочей документацией",
          amount: "64710398.29",
          basis:
            "Д-7: сметный объём кратен базовой длине 15.24 км с кратностью более двух; " +
            "базовая длина принята по самому частому значению в группе и НЕ сверена с осями РД (Д-1)",
          remedy:
            "вернуть блок подрядчику, запросить расчёт объёма по осям РД; " +
            "до сверки объём остаётся допущением, сильный вердикт не выносится",
          document: "РИМ Курган_ЭОМ__ЭОМ испр. - ЛСР по Методике 2020 _РМ_.xlsx",
        },
      ],
    });

    expect(реестр.incomplete).toHaveLength(0);
    expect(реестр.totalAmount).toBe("64710398.29");

    // Основание и путь урегулирования — не пожелания, а то, с чем человек
    // пойдёт к подрядчику. Проверяется, что они дошли до ячеек.
    const строка = реестр.sheets[0]!.rows[1]!;
    const текст = строка.map((c) => (c.kind === "text" ? c.value : "")).join(" | ");

    expect(текст).toContain("Д-7");
    expect(текст).toContain("осям РД");
  });

  it("держит сумму находки в маркированной числовой ячейке (§12.1д)", () => {
    const реестр = buildViolationsRegister({
      objectName: "Курган, ЭОМ",
      violations: [
        {
          position: "блок ГЭСНм20-03-035",
          kind: "объём не подтверждён РД",
          amount: "64710398.29",
          basis: "Д-7",
          remedy: "возврат позиции",
          document: "ЭОМ.xlsx",
        },
      ],
    });

    const сумма = реестр.sheets[0]!.rows[1]![2]!;

    expect(сумма.kind).toBe("number");
    expect(сумма.kind === "number" && сумма.marker).toBeTruthy();
  });
});
