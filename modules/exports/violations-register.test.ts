/**
 * Тесты написаны до реализации. Реестр нарушений — ТЗ §10, вторая из четырёх
 * договорных выгрузок:
 *
 *   «Реестр нарушений (Excel) | Позиция, характер нарушения, сумма, основание,
 *    путь урегулирования»
 *
 * ПЯТЬ КОЛОНОК — ЭТО ПЯТЬ ОБЯЗАТЕЛЬСТВ, А НЕ ФОРМАТ
 *
 * ТЗ перечисляет их не для красоты таблицы. Нарушение без СУММЫ нельзя
 * приоритизировать: непонятно, стоит ли из-за него спорить. Без ОСНОВАНИЯ его
 * нельзя предъявить: подрядчик спросит «на каком пункте», и ответа не будет.
 * Без ПУТИ УРЕГУЛИРОВАНИЯ реестр остаётся списком претензий, с которым служба
 * заказчика не знает, что делать.
 *
 * Поэтому строка без любого из пяти полей в реестр не попадает — она попадает в
 * отдельный список неполных находок. Выдать нарушение без основания значит
 * подставить того, кто пойдёт с ним к подрядчику.
 *
 * §12.1в МЕРЯЕТ ПОЛНОТУ ЭТОГО РЕЕСТРА
 *
 * «Полнота реестра нарушений относительно ручного расчёта Заказчика — не менее
 * 70%». Значит, потерянная находка стоит дороже лишней: лишнюю снимут на
 * разборе, потерянная не попадёт в измерение вовсе.
 */
import { describe, expect, it } from "vitest";

import { buildViolationsRegister } from "./violations-register.js";

const НАРУШЕНИЕ = {
  position: "поз. 14, ГЭСНм20-03-035-01",
  kind: "объём не подтверждён РД" as const,
  amount: "64710398.29",
  basis: "Д-7: кратность объёма базовой длине больше двух",
  remedy: "вернуть позицию подрядчику, запросить расчёт объёма по осям РД",
  document: "ЭОМ.xlsx",
};

describe("реестр нарушений (§10)", () => {
  it("несёт пять договорных колонок", () => {
    const реестр = buildViolationsRegister({ objectName: "Курган", violations: [НАРУШЕНИЕ] });
    const шапка = реестр.sheets[0]!.rows[0]!.map((cell) =>
      cell.kind === "text" ? cell.value : "",
    );

    for (const колонка of ["Позиция", "Характер нарушения", "Сумма", "Основание", "Путь урегулирования"]) {
      expect(шапка.some((имя) => имя.includes(колонка))).toBe(true);
    }
  });

  it("сортирует по сумме: спорят сначала о крупном", () => {
    const реестр = buildViolationsRegister({
      objectName: "Курган",
      violations: [
        { ...НАРУШЕНИЕ, position: "мелкое", amount: "1000.00" },
        { ...НАРУШЕНИЕ, position: "крупное", amount: "5000000.00" },
      ],
    });

    const первая = реестр.sheets[0]!.rows[1]!;

    expect(первая[0]).toMatchObject({ value: "крупное" });
  });

  it("НЕ включает нарушение без основания: его нечем предъявить", () => {
    const реестр = buildViolationsRegister({
      objectName: "Курган",
      violations: [{ ...НАРУШЕНИЕ, basis: "" }],
    });

    expect(реестр.incomplete).toHaveLength(1);
    expect(реестр.incomplete[0]?.missing).toContain("основание");
  });

  it("НЕ включает нарушение без пути урегулирования", () => {
    // Иначе реестр остаётся списком претензий, с которым служба заказчика не
    // знает, что делать.
    const реестр = buildViolationsRegister({
      objectName: "Курган",
      violations: [{ ...НАРУШЕНИЕ, remedy: "" }],
    });

    expect(реестр.incomplete[0]?.missing).toContain("путь урегулирования");
  });

  it("НАЗЫВАЕТ неполные находки, а не выбрасывает их", () => {
    // §12.1в меряет полноту: потерянная находка дороже лишней, потому что
    // лишнюю снимут на разборе, а потерянная не попадёт в измерение вовсе.
    const реестр = buildViolationsRegister({
      objectName: "Курган",
      violations: [{ ...НАРУШЕНИЕ, basis: "", remedy: "" }],
    });

    expect(реестр.incomplete[0]?.position).toBe(НАРУШЕНИЕ.position);
    expect(реестр.incomplete[0]?.missing).toHaveLength(2);
  });

  it("считает итог по сумме нарушений", () => {
    const реестр = buildViolationsRegister({
      objectName: "Курган",
      violations: [
        { ...НАРУШЕНИЕ, amount: "1000.00" },
        { ...НАРУШЕНИЕ, position: "вторая", amount: "2000.50" },
      ],
    });

    expect(реестр.totalAmount).toBe("3000.50");
  });

  it("НЕ включает неполные находки в итог: сумма обязана сходиться со строками", () => {
    const реестр = buildViolationsRegister({
      objectName: "Курган",
      violations: [
        { ...НАРУШЕНИЕ, amount: "1000.00" },
        { ...НАРУШЕНИЕ, position: "неполная", amount: "9999.00", basis: "" },
      ],
    });

    expect(реестр.totalAmount).toBe("1000.00");
  });

  it("каждое число несёт маркер статуса источника (§12.1д)", () => {
    const реестр = buildViolationsRegister({ objectName: "Курган", violations: [НАРУШЕНИЕ] });

    for (const row of реестр.sheets[0]!.rows) {
      for (const cell of row) {
        if (cell.kind === "number") expect(cell.marker).toBeTruthy();
      }
    }
  });

  it("на пустом наборе даёт книгу с честной пометкой, а не пустой файл", () => {
    // Пустой реестр читается как «нарушений нет». Если проверка не проводилась,
    // это ложь, и лист обязан сказать, что именно проверено.
    const реестр = buildViolationsRegister({ objectName: "Курган", violations: [] });

    expect(реестр.sheets[0]!.rows.length).toBeGreaterThan(1);
    const текст = реестр.sheets[0]!.rows.flat().map((c) => (c.kind === "text" ? c.value : "")).join(" ");
    expect(текст).toContain("нарушений не найдено");
  });

  it("экранирует наименование позиции из чужого документа", () => {
    const реестр = buildViolationsRegister({
      objectName: "Курган",
      violations: [{ ...НАРУШЕНИЕ, position: '=HYPERLINK("http://зло")' }],
    });

    const ячейка = реестр.sheets[0]!.rows[1]![0]!;

    expect(ячейка.kind === "text" && ячейка.value.startsWith("'")).toBe(true);
  });
});
