export async function checkObject(
  objectPath: string,
  ports: CheckObjectPorts,
): Promise<CheckObjectBody> {
  /**
   * Отчёт о ходе, который не может ни упасть, ни промолчать.
   *
   * Сбой доставки запоминается и попадает в тело: обход доводится до вердикта,
   * а расхождение экрана с фактом становится объяснимым.
   */
  const progressLost: string[] = [];

  const report = async (event: CheckProgress): Promise<void> => {
    /**
     * ГРАНИЦА ТАКТА — ЕДИНСТВЕННОЕ МЕСТО, ГДЕ СПРАШИВАЮТ ОБ ОСТАНОВКЕ.
     *
     * Здесь, а не отдельным вызовом перед каждым тактом: такты объявляются
     * ровно этим отчётом, и второй список мест «где спросить» разошёлся бы с
     * первым при добавлении такта.
     *
     * Бросается ДО доставки отчёта: сообщать экрану о начале такта, который не
     * начнётся, — значит расходиться с фактом.
     */
    if (event.kind === "этап") {
      const причина = ports.stopRequested?.();
      if (причина !== undefined) throw new CheckStopped(причина);
    }

    if (ports.progress === undefined) return;

    try {
      await ports.progress(event);
    } catch (error) {
      progressLost.push(`${event.kind}: ${(error as Error).message}`);
    }
  };

  await report({ kind: "этап", phase: "обход папки" });

  const discovered = await ports.discover(objectPath);
  const documents: DocumentOutcome[] = [];

  await report({ kind: "обход", documents: discovered.length });

  const summaryDocument =
    ports.checkSummary === undefined
      ? undefined
      : discovered.find((document) => document.kind === "ссрсс");

  /** Разобранный документ — событие: счётчик на экране двигается по факту. */
  const reportDocument = async (outcome: DocumentOutcome): Promise<void> =>
    report({
      kind: "документ",
      path: outcome.path,
      status: outcome.status,
      done: documents.length,
      total: discovered.length,
    });

  for (const document of discovered) {
    if (document === summaryDocument) continue;

    if (document.kind !== "лср") {
      /**
       * Прочитанное объявляется прочитанным.
       *
       * Текстовый слой у документа есть — значит обход его открыл, разобрал на
       * страницы и отдал агентам. Называть это «не поддержан» значит называть
       * сделанную работу несделанной.
       */
      const прочитан = document.text !== undefined && document.text.text.trim() !== "";

      documents.push({
        path: document.path,
        kind: document.kind,
        // Причина от поиска точнее общей: он видел содержимое файла.
        reason: прочитан
          ? "позиций из него не извлекают: это не сметный расчёт. Текст и листы переданы агентам"
          : (document.reason ?? SKIP_REASON[document.kind]),
        status: прочитан ? "прочитан" : "не поддержан",
        ...(прочитан
          ? {
              readout: {
                pages: document.text!.pages,
                chars: document.text!.text.length,
                ...(ports.sheetsOf === undefined ? {} : { sheets: ports.sheetsOf(document.path) }),
              },
            }
          : {}),
      });
      await reportDocument(documents[documents.length - 1]!);
      continue;
    }

    try {
      const check = await ports.checkDocument(document);
      documents.push({
        path: document.path,
        kind: document.kind,
        status: "проверен",
        positions: check.positions,
        byCode: check.byCode,
        converged: check.converged,
        delta: check.delta,
        documentTotal: check.documentTotal,
      });
    } catch (error) {
      // Отказ разбора — это результат проверки, а не повод её прервать:
      // остальные сметы объекта должны быть проверены, а отказ — предъявлен.
      //
      // НО ОТКАЗ РАЗБОРА — НЕ ОТКАЗ ЧТЕНИЯ. Книга своей вёрстки, ведомость в
      // `.csv`, калькуляция — позиций из них не извлечь, и извлекать нельзя:
      // выдуманная позиция хуже отсутствующей. Содержимое при этом читается и
      // уходит агентам текстом. Молчать об этом значит дать человеку прочесть
      // «отказ» как «файл выброшен» — а он прочитан и назван в замечаниях.
      const знаков = ports.charsOf?.(document.path) ?? 0;

      /**
       * ФОРМА НЕ ТА — ЭТО НЕ ОТКАЗ РАЗБОРА, и разделить их обязательно.
       *
       * `LsrParseError` бросается ровно в двух случаях: не найдена шапка
       * «№ п/п» и не найден подзаголовок «всего». Оба означают одно: мы
       * попробовали прочесть книгу как смету 421/пр и этой формы в ней нет.
       * Значит это не смета — и «отказом разбора» называть это нельзя.
       *
       * Всё остальное (строки не сходятся, суммы потеряны) — отказ, и он
       * остаётся отказом: дыра в настоящей смете не должна спрятаться под
       * вывеской «просто не смета».
       */
      const формаНеТа = error instanceof NotAnEstimate;

      documents.push({
        path: document.path,
        kind: формаНеТа ? "книга-не-смета" : document.kind,
        status: формаНеТа ? "прочитан" : "отказ",
        reason:
          формаНеТа
            ? `книга прочитана, но это не локальный сметный расчёт: ${(error as Error).message}` +
              (знаков > 0 ? ". Содержимое передано агентам текстом" : "")
            : знаков > 0
            ? `${(error as Error).message}. Содержимое прочитано и передано агентам текстом`
            : (error as Error).message,
        ...(знаков > 0
          ? {
              readout: {
                pages: 1,
                chars: знаков,
                ...(ports.sheetsOf === undefined ? {} : { sheets: ports.sheetsOf(document.path) }),
              },
            }
          : {}),
      });
    }

    await reportDocument(documents[documents.length - 1]!);
  }

  const reviews: DocumentReviewOutcome[] = [];

  // Агенты идут ПАРАЛЛЕЛЬНО, но с потолком (Д5).
  //
  // Замер: одно обращение к модели — около сорока секунд. Четыре агента на
  // четырёх сметах это шестнадцать обращений, то есть одиннадцать минут
  // последовательно. Норматив §11 для режима «стандарт» — не более часа, и на
  // объекте вчетверо крупнее курганского в него бы уже не уложились.
  //
  // Но и без потолка нельзя: `Promise.all` на ста файлах — двести
  // одновременных обращений, и это не выдержит ни провайдер, ни память
  // воркера. Потолок объявлен числом и приходит портом.
  //
  // Порядок замечаний СОХРАНЯЕТСЯ: `mapWithLimit` кладёт результат по индексу
  // задачи, а не в порядке завершения. Отчёт, меняющий порядок от прогона к
  // прогону, нельзя сравнить с предыдущим.
  const reviewTasks = (ports.reviewers ?? []).flatMap((reviewer) =>
    discovered
      .filter((document) => document.kind === "лср")
      .map((document) => ({
        reviewer,
        document,
        outcome: documents.find((candidate) => candidate.path === document.path),
      }))
      .filter((task) => task.outcome?.status === "проверен"),
  );

  if (reviewTasks.length > 0) {
    await report({ kind: "этап", phase: "агенты по сметам" });
  }

  const limit = ports.concurrency ?? AGENT_CONCURRENCY;

  reviews.push(
    ...(await mapWithLimit(
      reviewTasks,
      limit,
      async ({ reviewer, document, outcome }): Promise<DocumentReviewOutcome> => {
        // Начало и конец сообщаются РАЗДЕЛЬНО, потому что различать «работает»
        // и «не запускался» обязательно: агенты идут параллельно, и без начала
        // экран показывал бы восемь незапущенных агентов там, где работают все
        // восемь. Порядок замечаний это не меняет: `Promise.all` возвращает
        // результаты в порядке задач, а события — в порядке завершения.
        await report({
          kind: "агент-начал",
          capability: reviewer.capability,
          subject: document.path,
          scope: "документ",
        });

        const spoke = async (result: DocumentReviewOutcome): Promise<DocumentReviewOutcome> => {
          await report({ kind: "агент-высказался", scope: "документ", outcome: result });
          return result;
        };

        try {
          const result = await reviewer.review(document, {
            path: document.path,
            positions: outcome!.positions ?? 0,
            byCode: outcome!.byCode ?? 0,
            unmatched: (outcome!.positions ?? 0) - (outcome!.byCode ?? 0),
            converged: outcome!.converged ?? false,
            /**
             * ПУСТО ОСТАЁТСЯ ПУСТЫМ — И ЭТО ИСТОЧНИК ВСЕЙ ЦЕПОЧКИ.
             *
             * Отсюда `delta` и `documentTotal` расходятся по экрану, гейтам,
             * реестру нарушений и книге, которую заказчик уносит. Подставленный
             * здесь `"0.00"` означал ниже по течению «расхождение ноль», то
             * есть ДОКАЗАННУЮ сходимость сметы, у которой стоимостной части нет
             * вовсе. Одно значение — пять неверных утверждений.
             */
            delta: outcome!.delta,
            documentTotal: outcome!.documentTotal,
          });

          return await spoke({
            path: document.path,
            capability: reviewer.capability,
            verdict: result.verdict,
            findings: result.findings,
            ...(result.depthViolations === undefined
              ? {}
              : { depthViolations: result.depthViolations }),
            // Открытые вопросы едут вместе с замечаниями: графа «что проверить
            // человеку» — восьмая графа формы результата, и терять её здесь
            // значит терять у всех девяти агентов сразу.
            ...(result.openQuestions === undefined ? {} : { openQuestions: result.openQuestions }),
            ...(result.sections === undefined ? {} : { sections: result.sections }),
        ...(result.toolCalls === undefined ? {} : { toolCalls: result.toolCalls }),
        ...(result.run === undefined ? {} : { run: result.run }),
          });
        } catch (error) {
          // Отказ ОДНОГО агента на ОДНОЙ смете не прерывает ни остальные сметы,
          // ни остальных агентов, но и не прячется: он попадает в отчёт и
          // проваливает гейт агента.
          return await spoke({
            path: document.path,
            capability: reviewer.capability,
            findings: [],
            error: (error as Error).message,
          });
        }
      },
    )),
  );


  let summary: SummaryOutcome | undefined;

  if (summaryDocument !== undefined && ports.checkSummary !== undefined) {
    await report({ kind: "этап", phase: "сводный расчёт" });

    const estimates = documents
      .filter((document) => document.status === "проверен")
      .map((document) => ({
        path: document.path,
        positions: document.positions ?? 0,
        byCode: document.byCode ?? 0,
        unmatched: (document.positions ?? 0) - (document.byCode ?? 0),
        converged: document.converged ?? false,
        /**
         * «0.00» ЗДЕСЬ ПОДСТАВЛЯТЬ НЕЛЬЗЯ — а стояло именно оно.
         *
         * Написано было тогда, когда итог был у каждой сметы, и `?? "0.00"`
         * читалось как формальность. С появлением смет без стоимостной части
         * эта формальность стала подлогом: десять неизвестных итогов
         * превращались в десять нулей, сверка складывала их в 0 ₽ и объявляла
         * «Δ 86 778 920,38 ₽ ВНЕ гранулярности — требует разбора». То есть
         * система предъявляла расхождение размером во ВСЮ стоимость объекта,
         * которого на самом деле не считала.
         *
         * Ирония в том, что ровно об этом предупреждает комментарий десятью
         * строками ниже — про ноль слагаемых. Тот случай закрыли, этот нет.
         */
        delta: document.delta,
        documentTotal: document.documentTotal,
      }));

    // Ноль слагаемых — не ноль рублей. Если ни одна смета не проверена, сумма
    // смет равна нулю, и сравнение её со сводным расчётом даёт «расхождение»
    // размером во весь ССРСС. Это не расхождение, а отсутствие предмета сверки,
    // и называть его надо так (ТЗ §9: неизвестное не превращается в ноль).
    if (estimates.length === 0) {
      summary = {
        path: summaryDocument.path,
        error:
          "сверка не выполнена: ни одна смета не проверена, сверять не с чем",
      };
      documents.push({
        path: summaryDocument.path,
        kind: summaryDocument.kind,
        status: "не поддержан",
        reason: "сверять нечего: ни одна смета объекта не проверена",
      });
    } else {
      try {
        summary = await ports.checkSummary(summaryDocument, estimates);
        documents.push({
          path: summaryDocument.path,
          kind: summaryDocument.kind,
          status: "сверен",
          reason: `эталон сверки: ${summary.label}`,
        });
      } catch (error) {
        summary = {
          path: summaryDocument.path,
          error: (error as Error).message,
        };
        documents.push({
          path: summaryDocument.path,
          kind: summaryDocument.kind,
          status: "отказ",
          reason: (error as Error).message,
        });
      }
    }

    await reportDocument(documents[documents.length - 1]!);
  }

  if ((ports.objectReviewers ?? []).length > 0) {
    await report({ kind: "этап", phase: "объектные агенты" });
  }

  // Объектные агенты — ПОСЛЕ обхода и сводного расчёта: им нужен готовый итог.
  // Между собой они тоже идут параллельно.
  reviews.push(
    ...(await mapWithLimit(
      ports.objectReviewers ?? [],
      limit,
      async (reviewer): Promise<DocumentReviewOutcome> => {
        await report({
          kind: "агент-начал",
          capability: reviewer.capability,
          subject: objectPath,
          scope: "объект",
        });

        const spoke = async (result: DocumentReviewOutcome): Promise<DocumentReviewOutcome> => {
          await report({ kind: "агент-высказался", scope: "объект", outcome: result });
          return result;
        };

        try {
          const result = await reviewer.review({
            objectPath,
            ...(summary !== undefined && "declaredRubles" in summary
              ? { declaredTotal: summary.declaredRubles }
              : {}),
            documents,
          });

          return await spoke({
            path: objectPath,
            scope: "объект",
            capability: reviewer.capability,
            verdict: result.verdict,
            findings: result.findings,
            ...(result.depthViolations === undefined
              ? {}
              : { depthViolations: result.depthViolations }),
            ...(result.openQuestions === undefined ? {} : { openQuestions: result.openQuestions }),
            ...(result.sections === undefined ? {} : { sections: result.sections }),
        ...(result.toolCalls === undefined ? {} : { toolCalls: result.toolCalls }),
        ...(result.run === undefined ? {} : { run: result.run }),
          });
        } catch (error) {
          // Отказ объектного агента не отменяет разбор смет, но и не прячется.
          return await spoke({
            path: objectPath,
            scope: "объект",
            capability: reviewer.capability,
            findings: [],
            error: (error as Error).message,
          });
        }
      },
    )),
  );


  if ((ports.synthesisReviewers ?? []).length > 0) {
    await report({ kind: "этап", phase: "синтез" });
  }

  // Синтез — ТРЕТЬЯ фаза: агент читает замечания остальных, и запустить его
  // вместе с ними значило бы дать ему пустой список.
  for (const reviewer of ports.synthesisReviewers ?? []) {
    await report({
      kind: "агент-начал",
      capability: reviewer.capability,
      subject: objectPath,
      scope: "синтез",
    });

    try {
      const result = await reviewer.review({
        objectPath,
        ...(summary !== undefined && "declaredRubles" in summary
          ? { declaredTotal: summary.declaredRubles }
          : {}),
        documents,
        reviews: [...reviews],
      });

      const outcome: DocumentReviewOutcome = {
        path: objectPath,
        scope: "объект",
        capability: reviewer.capability,
        verdict: result.verdict,
        findings: result.findings,
        ...(result.depthViolations === undefined
          ? {}
          : { depthViolations: result.depthViolations }),
        ...(result.openQuestions === undefined ? {} : { openQuestions: result.openQuestions }),
        ...(result.sections === undefined ? {} : { sections: result.sections }),
        ...(result.toolCalls === undefined ? {} : { toolCalls: result.toolCalls }),
        ...(result.run === undefined ? {} : { run: result.run }),
      };

      reviews.push(outcome);
      await report({ kind: "агент-высказался", scope: "синтез", outcome });
    } catch (error) {
      const outcome: DocumentReviewOutcome = {
        path: objectPath,
        scope: "объект",
        capability: reviewer.capability,
        findings: [],
        error: (error as Error).message,
      };

      reviews.push(outcome);
      await report({ kind: "агент-высказался", scope: "синтез", outcome });
    }
  }

  await report({ kind: "этап", phase: "итог" });

  const checked = documents.filter(
    (document) => document.status === "проверен",
  );
  const failed = documents.filter(
    (document) => document.status === "отказ" && document.kind === "лср",
  );
  const skipped = documents.filter(
    (document) => document.status === "не поддержан",
  );

  /**
   * Позиции, выписанные ролями, СЧИТАЮТСЯ ОТДЕЛЬНЫМ ЧИСЛОМ.
   *
   * Складывать их с разобранными молча нельзя: у них разный уровень доверия, и
   * одна цифра «позиций 148» скрыла бы, что половину назвала модель. Но и
   * прятать их, как было до 09.09.2026, нельзя — тогда свод говорит «ноль» там,
   * где в базе полсотни строк.
   */
  const накоплено = await ports.collectedPositions?.();

  const totals = {
    documents: documents.length,
    checked: checked.length,
    skipped: skipped.length,
    failed: failed.length,
    positions: checked.reduce(
      // ноль-осознанно: складываются СЧЁТЧИКИ позиций проверенных смет.
      (sum, document) => sum + (document.positions ?? 0),
      0,
    ),
    // ноль-осознанно: счётчик сопоставленных по шифру, не деньги.
    byCode: checked.reduce((sum, document) => sum + (document.byCode ?? 0), 0),
    unmatched: checked.reduce(
      (sum, document) =>
        sum + ((document.positions ?? 0) - (document.byCode ?? 0)),
      0,
    ),
    // ноль-осознанно: счётчик позиций, названных ролями; ноль означает, что
    // ролей не звали либо они позиций не нашли, и это видно рядом с `positions`.
    agentPositions: накоплено?.byAgent ?? 0,
  };

  const diverged = checked.filter((document) => document.converged !== true);

  let review: ReviewSummary | undefined;

  const gates: Gate[] = [
    {
      id: "обход",
      name: "все сметы объекта прочитаны",
      passed: failed.length === 0,
      detail:
        failed.length === 0
          ? `прочитано смет: ${checked.length}`
          : `не прочитано: ${перечислить(failed.map((document) => document.path))}`,
    },
    {
      id: "§12.1б",
      name: "сходимость внутри ЛСР равна 0 ₽",
      passed: checked.length > 0 && diverged.length === 0,
      detail:
        checked.length === 0
          ? "сверять нечего"
          : diverged.length === 0
            ? `сошлось смет: ${checked.length}`
            : /**
               * «НЕ СОШЛОСЬ» И «СВЕРЯТЬ НЕЧЕГО» — РАЗНОЕ, и в одной строке они
               * противоречат друг другу: читатель не поймёт, разошлось у него
               * или не считалось. Ведущее слово выбирается по тому, есть ли
               * хоть одно ПОСЧИТАННОЕ расхождение.
               */
              `${diverged.every((document) => document.delta === undefined) ? "сверять нечего" : "не сошлось"}: ` +
              всеОдинаково(
                diverged.map((document) => ({
                  имя: document.path,
                  причина:
                    document.delta === undefined ? "в смете нет стоимостной части" : `Δ ${document.delta} ₽`,
                })),
              ),
    },
    {
      id: "§12.1а",
      name: "позиции извлечены полностью",
      // Ручной сверки у нас нет, и выдавать за неё долю сопоставленных позиций
      // нельзя. Но сходимость 0 ₽ доказывает, что ни одна позиция не потеряна
      // ПО СУММАМ: пропущенная позиция дала бы расхождение с итогом раздела.
      // Это проверяемое утверждение, в отличие от «95% против ручной сверки».
      passed: checked.length > 0 && diverged.length === 0,
      detail:
        checked.length === 0
          ? "проверять нечего"
          : /**
             * ПОЛНОТА ПОДТВЕРЖДАЕТСЯ СХОДИМОСТЬЮ — а её могло не быть.
             *
             * Текст «полнота подтверждена сходимостью сумм» печатался всегда,
             * в том числе на пакете, где сумм нет вовсе и сходимость не
             * считалась. Утверждение о подтверждении там, где ничего не
             * подтверждали, — худший род неправды: он выглядит как результат
             * проверки.
             */
            `позиций ${totals.positions}, ` +
            (diverged.length === 0
              ? "полнота подтверждена сходимостью сумм"
              : diverged.every((document) => document.delta === undefined)
                ? "полнота НЕ подтверждена: сумм в сметах нет, сходимостью проверить нечем"
                : "полнота НЕ подтверждена: сходимость не сошлась") +
            `; с нормативным шифром ${totals.byCode}, без шифра ${totals.unmatched}`,
    },
  ];

  if (summary !== undefined) {
    gates.push({
      id: "ЛСР→ССРСС",
      name: "сумма смет сходится со сводным расчётом в пределах шкалы",
      passed: summary.error === undefined && summary.explainedByScale === true,
      detail:
        summary.error !== undefined
          ? summary.explainedByScale === undefined &&
            summary.delta === undefined
            ? `сверять нечего: ${summary.error}`
            : `сводный расчёт не разобран: ${summary.error}`
          : summary.explainedByScale === true
            ? `${summary.label}: ${summary.declaredThousands} тыс.₽, ` +
              `Δ ${summary.delta} ₽ при гранулярности шкалы ${summary.granularity} ₽ — ` +
              "объясняется округлением источника"
            : `${summary.label}: Δ ${summary.delta} ₽ ВНЕ гранулярности ` +
              `${summary.granularity} ₽ — требует разбора`,
    });
  }

  if (
    (ports.reviewers ?? []).length +
      (ports.objectReviewers ?? []).length +
      (ports.synthesisReviewers ?? []).length >
    0
  ) {
    const bySeverity: Record<string, number> = {};
    for (const outcome of reviews) {
      for (const finding of outcome.findings) {
        bySeverity[finding.severity] = (bySeverity[finding.severity] ?? 0) + 1;
      }
    }

    const failedReviews = reviews.filter(
      (outcome) => outcome.error !== undefined,
    );

    review = {
      requested: true,
      documents: reviews,
      findings: reviews.reduce(
        (sum, outcome) => sum + outcome.findings.length,
        0,
      ),
      bySeverity,
      failed: failedReviews.length,
    };

    // Смет и обзоров РАЗНОЕ количество: каждую смету смотрит каждый агент.
    // Написать «сметы обозрены: 8» при четырёх сметах и двух агентах значит
    // сказать неправду о размере проверенного.
    // Объект — не смета. Считать его в «сметах» значит завысить размер
    // проверенного ровно на одну строку и сделать это незаметно.
    const reviewedDocuments = new Set(
      reviews.filter((outcome) => outcome.scope !== "объект").map((outcome) => outcome.path),
    ).size;
    const agents = new Set(
      reviews.map((outcome) => outcome.capability).filter((value) => value !== undefined),
    ).size;

    gates.push({
      id: "агент",
      name: "все агенты отработали по всем сметам",
      /**
       * НОЛЬ СМЕТ — ЭТО НЕ «ВСЕ ОТРАБОТАЛИ».
       *
       * Замечено на экране заказчика: объект, где ни одна смета не разобралась,
       * показывал этот гейт ПРОЙДЕННЫМ — «смет 0, агентов 8, замечаний 63».
       * Пустая истина: «все» из ничего верно и бессмысленно, а зелёная отметка
       * рядом с тремя красными читается как «эта часть в порядке».
       *
       * Правило то же, что у §12.1б и §12.1а строкой выше: проверять было
       * нечего — гейт не пройден.
       */
      passed: reviewedDocuments > 0 && failedReviews.length === 0,
      detail:
        reviewedDocuments === 0
          ? `смет по форме 421/пр не разобрано ни одной — проверять этим гейтом было нечего. ` +
            `РОЛИ ПРИ ЭТОМ ОТРАБОТАЛИ: агентов ${agents}, замечаний ${review.findings}, ` +
            `позиций выписано ${накоплено?.byAgent ?? 0}. Их результат смотрите в заключениях и позициях объекта`
          : failedReviews.length === 0
          ? `смет ${reviewedDocuments}, агентов ${agents}, замечаний ${review.findings}`
          : `не обозрено: ${failedReviews
              .slice(0, 5)
              .map((outcome) => `${имяФайла(outcome.path)} (${outcome.error})`)
              .join("; ")}${failedReviews.length > 5 ? ` и ещё ${failedReviews.length - 5}` : ""}`,
    });
  }

  // ДВОЙНОЙ СЧЁТ МЕЖДУ СМЕТАМИ.
  //
  // Каждая смета может сходиться до рубля, сумма смет — сходиться со сводным
  // расчётом, все внутренние проверки быть зелёными, — и объект при этом
  // оплачивается дважды за одну работу. Увидеть это можно только сопоставив
  // сметы между собой, и до сих пор этого не делал никто.
  //
  // Гейт НЕ падает от находки: законный случай существует (две очереди с
  // одинаковым составом и ценой). Он предъявляет находку человеку, а решение
  // оставляет ему — как это делает эталонный разбор.
  if (ports.crossEstimateCheck !== undefined && checked.length > 1) {
    const cross = await ports.crossEstimateCheck();

    gates.push({
      id: "межсметный-дубль",
      name: "сметы сопоставлены между собой на двойной счёт",
      /**
       * СОПОСТАВЛЕНО НОЛЬ — ЭТО НЕ «ПОВТОРОВ НЕТ».
       *
       * Двойной счёт ищется по совпадению шифра И суммы. В пакете без
       * стоимостной части сумм нет ни у одной позиции, сопоставлять нечем — и
       * гейт показывал ЗЕЛЁНОЕ «повторов расценки с той же суммой нет».
       *
       * Формально верно, по смыслу — обещание проверки, которой не было.
       * Правило то же, что у §12.1б и «агента»: не проверяли — не пройден.
       */
      passed: cross.comparedDocuments > 0,
      detail:
        cross.comparedDocuments === 0
          ? "сверять нечего: двойной счёт ищется по совпадению шифра И суммы, " +
            "а сумм в этих сметах нет — сопоставлять нечем"
          : cross.duplicates.length === 0
          ? `сопоставлено смет ${cross.comparedDocuments}, повторов расценки с той же суммой нет`
          : `ТРЕБУЕТ ПРОВЕРКИ: повторов ${cross.duplicates.length}, под вопросом ${cross.excess} ₽ — ` +
            cross.duplicates
              .slice(0, 3)
              .map(
                (entry) =>
                  // Где найден повтор — часть находки, а не подробность: «одна
                  // работа в двух сметах» и «одна работа дважды в одной смете»
                  // — разный разговор с подрядчиком и разное исправление.
                  `${entry.basis} «${entry.name}» ${entry.amount} ₽ (${entry.scope}) в ` +
                  entry.occurrences.map((o) => `${o.document} поз. ${o.ordinal}`).join(" и "),
              )
              .join("; "),
    });
  }

  // СТАВКА НДС ПРОТИВ ДЕЙСТВУЮЩЕЙ.
  //
  // Смета составлена по одной ставке, работы выполняются по другой. При твёрдой
  // цене разницу несёт подрядчик, и она не видна ни в одной внутренней
  // проверке: смета сходится, сводный расчёт сходится, ставка в документе своя
  // собственная и никем не оспаривается.
  //
  // Гейт не падает: расхождение ставок — это не ошибка сметчика, а изменение
  // закона. Он предъявляет цену вопроса.
  if (ports.checkVat !== undefined) {
    const vat = await ports.checkVat();

    if (vat !== undefined) {
      gates.push({
        id: "ндс",
        name: "ставка НДС сверена с действующей на дату Проверки",
        passed: true,
        detail: vat.applicable
          ? `ставка сметы ${vat.declaredRate}, действующая ${vat.currentRate}: ` +
            `разрыв ${vat.gap} ₽. ${vat.note}`
          : `ставка сметы ${vat.declaredRate} совпадает с действующей — разрыва нет`,
      });
    }
  }

  // РЕВЕРС ОБЪЁМА (правило Д-7).
  //
  // Блок, чей сметный объём кратен базовой длине с кратностью выше двух, — это
  // либо шаблонная вставка, либо объём, которого на объекте нет. Ни одна
  // внутренняя проверка его не поймает: смета с ним сходится до рубля.
  //
  // Гейт не падает: кратность — признак, а не доказательство. Он предъявляет
  // сумму, по которой нужно решение.
  if (ports.reverseVolume !== undefined) {
    const reversal = await ports.reverseVolume();

    if (reversal.groups.length > 0) {
      gates.push({
        id: "объём-по-рд",
        name: "объём блоков сверен с базовой длиной (правило Д-7)",
        passed: true,
        detail:
          `ТРЕБУЕТ СВЕРКИ С РД: ${reversal.flaggedAmount} ₽ — ` +
          reversal.groups
            .slice(0, 3)
            .map(
              (group) =>
                `блок ${group.table}: ${group.totalQuantity} ${group.unit} при базовой ` +
                `${group.baseQuantity} ${group.unit}, ${group.positions} позиций, ${group.totalAmount} ₽`,
            )
            .join("; "),
      });
    }
  }

  // СТРУКТУРА ЗАТРАТ ОБЪЕКТА.
  //
  // Разложение по элементам объявляет сама смета в блоке «в том числе». Оно
  // отвечает на вопросы, которых по позициям не задать: сколько в объекте
  // оборудования, а сколько монтажа. Эталонный разбор именно отсюда увидел, что
  // оборудования в смете 2,22 млн, а «железа» проекта в нём нет.
  if (ports.costStructure !== undefined && checked.length > 0) {
    const structure = await ports.costStructure();

    gates.push({
      id: "структура-затрат",
      name: "структура затрат объекта прочитана из шапок смет",
      // Гейт падает, только если ни одной шапки прочитать не удалось: тогда
      // разложения нет вовсе, и молчать об этом нельзя.
      passed: structure.unread.length < checked.length,
      detail:
        structure.unread.length >= checked.length
          ? /**
             * НИ ОДНОЙ ШАПКИ НЕ ПРОЧИТАНО — и печатать при этом «итог 0.00 ₽:
             * строительные 0.00, монтажные 0.00…» значит выдать незнание за
             * измеренный ноль. Ровно этот выдуманный ноль запрещён ТЗ §9, и
             * ровно он стоял здесь на пакете без стоимостной части.
             */
            `структура затрат не прочитана ни у одной из ${checked.length} смет: ` +
            "в них нет стоимостной части, разложение по видам затрат брать неоткуда"
          : `итог ${structure.total} ₽: строительные ${structure.construction}, ` +
        `монтажные ${structure.assembly}, оборудование ${structure.equipment}, ` +
        `прочие ${structure.other}, материалы ${structure.materials}, ` +
        `НР+СП ${structure.overheadAndProfit}` +
        (structure.outsideRegistry === "0.00"
          ? ""
          : `, оборудование вне ФРСН ${structure.outsideRegistry}`) +
        structure.byDocument
          .map(
            (row) =>
              `; ${row.document}: монтаж ${row.assembly}, оборудование ${row.equipment}, ` +
              `прочие ${row.other}`,
          )
          .join("") +
        (structure.unread.length === 0
          ? ""
          : `; шапка не прочитана у ${structure.unread.length}: ${перечислить(structure.unread)}`),
    });
  }

  /**
   * «НЕЧЕГО ПРОВЕРЯТЬ» — ТОЛЬКО КОГДА ДЕЙСТВИТЕЛЬНО НЕЧЕГО.
   *
   * Прежде вердикт зависел ровно от одного: разобрана ли хоть одна смета формы
   * 421/пр. На комплекте владельца (DG-2) таких смет нет, а роли дали 85
   * находок, 40 из них критические, и 50 позиций — и экран всё равно сообщал
   * «нечего проверять».
   *
   * Это худший вид неправды в этой системе: не ошибка в цифре, а отрицание
   * работы, которая сделана. Теперь «нечего проверять» означает, что не было
   * НИ разбора смет, НИ заключений ролей.
   */
  const рольСказала = (review?.findings ?? 0) > 0 || (накоплено?.byAgent ?? 0) > 0;

  const verdict: Verdict =
    checked.length === 0 && !рольСказала
      ? "нечего проверять"
      : gates.every((gate) => gate.passed)
        ? "принято"
        : "не принято";

  // Поле именно ОТСУТСТВУЕТ, когда обзор не запрашивали, а не равно undefined:
  // «обзор не запрашивали» и «обзор дал пусто» — разные вещи (ADR-R-014).
  return {
    objectPath,
    documents,
    totals,
    gates,
    ...(review === undefined ? {} : { review }),
    ...(summary === undefined ? {} : { summary }),
    // Пусто — поля нет: «сбоев доставки не было» и «поле не заполняли» —
    // разные утверждения, и пустой массив стёр бы разницу.
    ...(progressLost.length === 0 ? {} : { progressLost }),
    verdict,
  };
}
