/**
 * Тесты написаны до реализации. Имена файлов взяты из настоящей папки объекта
 * `reference-system/input-1/`.
 */
import { describe, expect, it } from "vitest";

import { classifyDocument } from "./classify-document.js";

describe("определение вида документа объекта", () => {
  it("узнаёт сводный сметный расчёт по названию государственной формы", () => {
    expect(classifyDocument("Сводный сметный расчет - ССРСС по Методике 2020 _РИМ_.xlsx")).toBe("ссрсс");
    expect(classifyDocument("ССРСС.xlsx")).toBe("ссрсс");
  });

  it("считает рабочей документацией всё, что не книга Excel", () => {
    expect(classifyDocument("КУРГАН_СОТ_07.04.2025.pdf")).toBe("рабочая-документация");
    expect(classifyDocument("КУРГАН ЭОМ 07.04.2025.pdf")).toBe("рабочая-документация");
  });

  it("пробует как ЛСР любую книгу, не опознанную как другая форма", () => {
    // Имя ненадёжно, содержание — надёжно. Книга с необычным именем должна
    // дойти до разбора и провалиться громко, а не быть пропущенной молча.
    expect(classifyDocument("РИМ Курган_СОТВ_ испр. - ЛСР по Методике 2020 _РМ_.xlsx")).toBe("лср");
    expect(classifyDocument("смета без опознавательных знаков.xlsx")).toBe("лср");
  });

  it("не считает документом временные файлы Excel", () => {
    // Excel держит рядом с открытой книгой файл-замок «~$имя.xlsx».
    // Разбор такого файла — гарантированный отказ на пустом месте.
    expect(classifyDocument("~$РИМ Курган_СОТВ_.xlsx")).toBe("неизвестный");
  });

  it("не зависит от регистра и разделителей в названии формы", () => {
    expect(classifyDocument("сводный сметный расчёт.xlsx")).toBe("ссрсс");
  });
});
