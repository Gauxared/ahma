/**
 * Определение вида документа в папке объекта.
 *
 * Правило разделения: по ИМЕНИ опознаётся только то, что имеет название
 * государственной формы («сводный сметный расчёт», ССРСС) — такие имена
 * устойчивы. Всё остальное, что является книгой Excel, отправляется на разбор
 * как ЛСР, и вид подтверждается СОДЕРЖАНИЕМ.
 *
 * Почему не наоборот: имя файла ненадёжно. Книга с необычным именем должна
 * дойти до разбора и провалиться громко, попав в отчёт со статусом «отказ», а
 * не быть пропущенной по несовпадению имени. Пропуск сметы даёт зелёный
 * вердикт на неполном обходе — то, что запрещено инвариантом ТЗ §9.
 */
import type { DocumentKind } from "./check-object.js";

/**
 * Формат, определённый по содержимому, если он уже известен.
 *
 * Имя файла остаётся первым признаком — оно отвечает на вопрос «какая это
 * ФОРМА»: ССРСС узнаётся по названию государственной формы. Содержимое
 * отвечает на другой вопрос — «можно ли это вообще прочитать», — и ответ на
 * него ГЛАВНЕЕ: книга, которую не открыть, не станет ЛСР оттого, что названа
 * сметой.
 */
export interface ContentFormat {
  readonly supported: boolean;
  readonly reason?: string;
  /**
   * Формат, определённый по содержимому.
   *
   * Появился в Д1б и сместил границу в правильную сторону: до него «книга ли
   * это» решало расширение `.xlsx`, и смета в старом двоичном формате
   * становилась рабочей документацией по имени файла. Теперь книгу узнаёт
   * содержимое, а имя отвечает только на вопрос «какая это ФОРМА» — ССРСС
   * узнаётся по названию государственной формы.
   */
  readonly format?: string;
}

/**
 * Окончания записаны как `[а-яё]*`, а не `\w*`: в JavaScript `\w` — это
 * `[A-Za-z0-9_]`, кириллица в него не входит, и `сводн\w*` не взяло бы «сводный».
 */
const SSRSS = /ссрсс|сводн[а-яё]*\s+сметн[а-яё]*\s+расч[её]т/i;

/**
 * Форматы, от которых ЖДУТ позиций, даже если читателя у них нет.
 *
 * Разница между «не разобран» и «рабочая документация» — в ожидании: выгрузка
 * ГРАНД-Сметы в XML это смета, которую мы не прочитали, а чертёж в PDF —
 * документ, от которого позиций никто не ждёт. Свести их к одному значило бы
 * либо потерять непрочитанную смету, либо объявить каждый чертёж пробелом.
 */
const ПРЕТЕНДУЮТ_НА_КНИГУ: ReadonlySet<string> = new Set([
  "xlsx",
  "xls",
  "grand-smeta-xml",
  "ole2",
  "zip-архив",
]);
/** Файл-замок, который Excel держит рядом с открытой книгой. */
const LOCK = /^~\$/;
const WORKBOOK = /\.xlsx$/i;

/**
 * ФОРМАТЫ, КОТОРЫЕ ПРИНЯТЫ НА ВХОДЕ И НЕ ИМЕЮТ РАЗБОРА.
 *
 * Это самая опасная щель, какая бывает у обхода: файл прошёл дверь загрузки,
 * попал в папку объекта, посчитался в числе документов — и молча стал «рабочей
 * документацией», то есть не сметой. Сто смет в старом формате `.xls` давали
 * бы «документов 100, позиций 0» и вердикт по пустому обходу.
 *
 * Пока адаптера нет, такой файл — «не разобран» С НАЗВАННОЙ ПРИЧИНОЙ. Это
 * третье состояние помимо «разобрано» и «отвергнуто на двери», и оно
 * допустимо ровно потому, что названо: человек видит, что файл принят и НЕ
 * прочитан, и решает сам.
 *
 * Ключ здесь — расширение, а не содержимое, намеренно. Содержимое уже
 * проверено детектором формата и попало в `format.supported`; здесь речь о
 * другом: формат опознан и поддержки разбора у него нет.
 */
/**
 * Причина, по которой формат принят и не разобран. Пусто — разбор возможен.
 *
 * СПИСОК РАЗБИРАЕМЫХ ФОРМАТОВ ПРИХОДИТ ПАРАМЕТРОМ, А НЕ ЖИВЁТ ЗДЕСЬ. Здесь он
 * жил, и это была третья истина о том, что система умеет читать: реестр
 * читателей книг знал одно, `ParserRegistry` — другое, а этот список — третье.
 * Он и разошёлся: строка про XML утверждала, что «адаптер ГРАНД-Сметы написан,
 * но не подключён», — а его не существовало вовсе, и утверждение переехало
 * оттуда в план демо, где прожило неделю.
 *
 * Теперь перечень собирается из тех реестров, которые действительно читают
 * файлы, и разойтись с реальностью ему нечем.
 */
export function awaitingParser(
  format: string | undefined,
  parsable: readonly string[],
): string | undefined {
  if (format === undefined) return undefined;
  if (parsable.includes(format)) return undefined;

  // СПРАШИВАЕТСЯ ТОЛЬКО У ТЕХ, ОТ КОГО ЖДУТ ПОЗИЦИЙ.
  //
  // Поймано гейтом: без этого условия курганский чертёжный комплект получал
  // причину «формат pdf опознан, но разбора у него нет». На экране это
  // читалось бы как пробел — «документ принят и не прочитан», — тогда как PDF
  // рабочей документации прочитан целиком и позиций в нём нет по существу.
  // Причина, отвечающая не на тот вопрос, хуже отсутствия причины.
  if (!ПРЕТЕНДУЮТ_НА_КНИГУ.has(format)) return undefined;

  return (
    `формат ${format} опознан по содержимому, но разбора у него нет: ` +
    `файл принят и НЕ прочитан. Разбираются: ${parsable.join(", ")}`
  );
}

export function classifyDocument(
  fileName: string,
  format?: ContentFormat,
  /** Форматы книг, которые система читает. Пусто — решает расширение имени. */
  parsable: readonly string[] = [],
): DocumentKind {
  if (LOCK.test(fileName)) return "неизвестный";

  // Нечитаемое содержимое перекрывает имя: файл, который не открыть, не станет
  // сметой оттого, что назван сметой, и не станет чертежом оттого, что не
  // назван сметой. Он именно НЕ РАЗОБРАН, и причина известна.
  if (format !== undefined && !format.supported) return "не-разобран";

  // КНИГУ УЗНАЁТ СОДЕРЖИМОЕ, а расширение остаётся запасным сигналом — для
  // вызовов, где формат не определяли (тесты разбора, дверь загрузки).
  const книга =
    format?.format === undefined ? WORKBOOK.test(fileName) : parsable.includes(format.format);

  // Принято на входе и разбора не имеет — «не разобран», а НЕ «рабочая
  // документация». Разница в том, ждёт ли кто-то от файла позиций.
  //
  // Спрашивается ТОЛЬКО у форматов, которые притязают на роль книги: у PDF и
  // docx читателя книги нет и быть не должно — они рабочая документация, а не
  // непрочитанная смета.
  if (!книга && format?.format !== undefined && ПРЕТЕНДУЮТ_НА_КНИГУ.has(format.format)) {
    return "не-разобран";
  }

  if (!книга) return "рабочая-документация";

  if (SSRSS.test(fileName)) return "ссрсс";

  return "лср";
}
