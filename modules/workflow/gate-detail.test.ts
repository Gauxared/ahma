/**
 * ПОЯСНЕНИЯ К ГЕЙТАМ — против экрана, где вместо ответа лежит дамп путей.
 *
 * НАЙДЕНО НА ЭКРАНЕ ЗАКАЗЧИКА, а не набором.
 *
 * На объекте с десятью сметами гейт «все сметы объекта прочитаны» показывал:
 *
 *   не прочитано: /opt/stroyintellekt/var/objects/22222222-2222-2222-2222-
 *   222222222222/NT-03/2026-09-06T16-23-13-414Z/Конструкции железобетонные.
 *   Демонтаж железобетонных полов - ЛСР по Методике 2020 (РИМ).xlsx, /opt/…
 *
 * — и так десять раз, на треть экрана. Читателю это говорит ровно то же, что
 * список из десяти имён файлов, но занимает в пять раз больше места и прячет
 * имена внутри одинаковых префиксов.
 *
 * ХУЖЕ ЧИТАЕМОСТИ: В ПУТИ ЕДЕТ ВНУТРЕННЕЕ УСТРОЙСТВО. Каталог развёртывания,
 * идентификатор арендатора и метка партии — то, что заказчику видеть незачем, а
 * при показе третьей стороне и вовсе не следует. Идентификатор арендатора в
 * тексте на экране — это утечка, пусть и мелкая.
 *
 * ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ: пояснение гейта называет ФАЙЛЫ, а не пути, и не
 * растёт бесконечно с числом файлов.
 */
import { describe, expect, it } from "vitest";

import { всеОдинаково, имяФайла, перечислить } from "./gate-detail.js";

describe("пояснение к гейту", () => {
  it("называет файл, а не путь до него", () => {
    const путь =
      "/opt/stroyintellekt/var/objects/22222222-2222-2222-2222-222222222222/NT-03/" +
      "2026-09-06T16-23-13-414Z/Конструкции железобетонные. Фундамент Фм e - ЛСР по Методике 2020 (РИМ).xlsx";

    expect(имяФайла(путь)).toBe("Конструкции железобетонные. Фундамент Фм e - ЛСР по Методике 2020 (РИМ).xlsx");
  });

  it("в пояснении НЕТ ни каталога развёртывания, ни идентификатора арендатора", () => {
    const пути = [
      "/opt/stroyintellekt/var/objects/22222222-2222-2222-2222-222222222222/NT-03/п/А.xlsx",
      "/srv/stroyintellekt/objects/11111111-1111-1111-1111-111111111111/TUN-2/п/Б.xlsx",
    ];

    const текст = перечислить(пути);

    expect(текст, "в тексте остался путь файловой системы").not.toContain("/");
    expect(текст, "в тексте остался идентификатор арендатора").not.toMatch(/[0-9a-f]{8}-[0-9a-f]{4}/u);
    expect(текст).toContain("А.xlsx");
    expect(текст).toContain("Б.xlsx");
  });

  it("длинный список ОБРЕЗАЕТСЯ, и остаток назван числом", () => {
    // Десять имён подряд читаются не лучше десяти путей. Но молча отбросить
    // половину значило бы соврать о размере проблемы.
    const пути = Array.from({ length: 10 }, (_, i) => `/о/п/смета-${i + 1}.xlsx`);

    const текст = перечислить(пути);

    expect(текст).toContain("смета-1.xlsx");
    expect(текст).toContain("смета-5.xlsx");
    expect(текст, "остаток не назван").toContain("и ещё 5");
    expect(текст, "показано больше пяти имён").not.toContain("смета-6.xlsx");
  });

  it("короткий список показывается целиком, без «и ещё 0»", () => {
    expect(перечислить(["/о/п/один.xlsx", "/о/п/два.xlsx"])).toBe("один.xlsx, два.xlsx");
  });

  it("пустой список даёт пустую строку, а не «и ещё 0»", () => {
    expect(перечислить([])).toBe("");
  });

  it("имя без каталога остаётся собой", () => {
    // Не всякий источник — путь: у документа из архива имя приходит голым.
    expect(имяФайла("смета.xlsx")).toBe("смета.xlsx");
  });

  it("десять одинаковых причин сводятся в одну", () => {
    /**
     * НАЙДЕНО НА ЭКРАНЕ ПОСЛЕ ПЕРВОЙ ПРАВКИ, и это тот же дефект в новом месте.
     *
     * Гейт §12.1б на пакете без цен показывал:
     *
     *   не сошлось: <файл> (сверять нечего: нет стоимостной части); <файл>
     *   (сверять нечего: нет стоимостной части); … и ещё 5
     *
     * Два изъяна сразу. Первый: причина у всех десяти ОДНА, и повторённая
     * десять раз она не добавляет ничего, кроме длины. Второй хуже — «не
     * сошлось» и «сверять нечего» противоречат друг другу в одной строке:
     * читатель не поймёт, разошлось у него или не считалось.
     */
    const причина = всеОдинаково([
      { имя: "/о/п/А.xlsx", причина: "нет стоимостной части" },
      { имя: "/о/п/Б.xlsx", причина: "нет стоимостной части" },
      { имя: "/о/п/В.xlsx", причина: "нет стоимостной части" },
    ]);

    expect(причина, "причина не свёрнута").toBe("нет стоимостной части — во всех 3");
    expect(причина.split("нет стоимостной части").length - 1, "причина повторена").toBe(1);
  });

  it("разные причины НЕ схлопываются — их перечисляют по файлам", () => {
    // Сведение одинаковых не должно превратиться в потерю разных: это были бы
    // две разные проблемы, показанные как одна.
    const причина = всеОдинаково([
      { имя: "/о/п/А.xlsx", причина: "нет стоимостной части" },
      { имя: "/о/п/Б.xlsx", причина: "Δ 1250.40 ₽" },
    ]);

    expect(причина).toContain("А.xlsx");
    expect(причина).toContain("Б.xlsx");
    expect(причина).toContain("Δ 1250.40 ₽");
  });

  it("одна запись остаётся собой", () => {
    expect(всеОдинаково([{ имя: "/о/п/А.xlsx", причина: "Δ 10.00 ₽" }])).toBe("А.xlsx (Δ 10.00 ₽)");
  });
});
