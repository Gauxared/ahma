/**
 * Как гейт называет документы в своём пояснении.
 *
 * НАЙДЕНО НА ЭКРАНЕ ЗАКАЗЧИКА: пояснение «не прочитано» выводило десять
 * абсолютных путей подряд — треть экрана одинаковых префиксов, внутри которых
 * терялись собственно имена файлов.
 *
 * Путь несёт то, чего читателю знать не нужно и что показывать не следует:
 * каталог развёртывания, идентификатор арендатора, метку партии загрузки.
 * Отвечает же на вопрос «какие документы» только последний сегмент.
 */

/** Сколько имён показывать, прежде чем свернуть остаток в число. */
const ПОКАЗАТЬ = 5;

/**
 * Имя файла из пути. Разделитель — только `/`: пути внутри системы
 * посикс-овые, а имя файла заказчика вполне может содержать обратный слэш.
 */
export function имяФайла(путь: string): string {
  const последний = путь.split("/").pop();
  return последний === undefined || последний === "" ? путь : последний;
}

/**
 * Перечисление документов для пояснения гейта.
 *
 * Обрезается, но остаток НАЗЫВАЕТСЯ: молча показать пять из десяти значило бы
 * соврать о размере проблемы — а размер здесь и есть главное, что читают.
 */
export function перечислить(пути: readonly string[]): string {
  if (пути.length === 0) return "";

  const имена = пути.map(имяФайла);
  const показанные = имена.slice(0, ПОКАЗАТЬ).join(", ");
  const остаток = имена.length - ПОКАЗАТЬ;

  return остаток > 0 ? `${показанные} и ещё ${остаток}` : показанные;
}

/** Документ и то, что о нём сказано. */
export interface СПричиной {
  readonly имя: string;
  readonly причина: string;
}

/**
 * Перечисление «файл — причина», свёрнутое, когда причина у всех одна.
 *
 * НАЙДЕНО НА ЭКРАНЕ: гейт §12.1б на пакете без цен выводил десять раз подряд
 * «(сверять нечего: нет стоимостной части)» — по разу на файл. Причина у всех
 * одна, и повторённая она не добавляет ничего, кроме длины; имена же файлов
 * при этом тонут в одинаковых хвостах.
 *
 * Свёрнутая форма отвечает на вопрос сразу: что случилось и со сколькими.
 */
export function всеОдинаково(записи: readonly СПричиной[]): string {
  if (записи.length === 0) return "";

  const причины = new Set(записи.map((запись) => запись.причина));

  if (причины.size === 1 && записи.length > 1) {
    return `${записи[0]!.причина} — во всех ${записи.length}`;
  }

  const показанные = записи
    .slice(0, ПОКАЗАТЬ)
    .map((запись) => `${имяФайла(запись.имя)} (${запись.причина})`)
    .join("; ");
  const остаток = записи.length - ПОКАЗАТЬ;

  return остаток > 0 ? `${показанные} и ещё ${остаток}` : показанные;
}
