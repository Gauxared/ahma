/**
 * Область знания прогона (ADR-R-024, ADR-R-026).
 *
 * Лёгкий фильтр «какие источники разрешены в этом прогоне», а НЕ снимок состава
 * опорной базы. Тяжёлый вариант — фиксировать весь состав — делал бы каждое
 * расширение базы событием, затрагивающим прошлые прогоны; воспроизводимость
 * обеспечивается контентной адресацией (ADR-R-027), а не этим фильтром.
 *
 * КАК ЭТО РАБОТАЕТ БЕЗ НОВОЙ МАШИНЕРИИ
 *
 * Источник вне области объявляется в реестре способностей выключенным. Дальше
 * всё происходит само: обязательная способность не разрешается — операция не
 * стартует и называет недостающее; необязательная — операция идёт и записывает
 * деградацию в артефакт.
 *
 * Ровно это требует ADR-R-024: «Ручных проверок „а есть ли раздел 04" в коде
 * операций нет». Проверка «а разрешён ли источник» была бы такой же ручной
 * проверкой, только в другом месте.
 *
 * ДВА РАЗНЫХ «НИЧЕГО»
 *
 * Область не задана — ограничения нет, разрешено всё. Область задана пустой —
 * запрещено всё, и первая же операция честно откажет. Свести их к одному
 * значению значило бы дать флагу `--scope ""` молча ничего не делать.
 */

export interface KnowledgeScope {
  /** Ограничения нет: прогон видит всё, что есть в сборке. */
  readonly unrestricted: boolean;
  readonly allows: (sourceId: string) => boolean;
  /**
   * Какие из имеющихся источников выключены этой областью.
   *
   * Список «что выключено» — и есть объявленная деградация: без него
   * отсутствие результата выглядит свойством данных, а не следствием настройки.
   */
  readonly excludedFrom: (available: readonly string[]) => readonly string[];
  /** Что было перечислено. `undefined`, если ограничения нет. */
  readonly allowed: readonly string[] | undefined;
}

export function knowledgeScope(allowed: readonly string[] | undefined): KnowledgeScope {
  if (allowed === undefined) {
    return {
      unrestricted: true,
      allows: () => true,
      excludedFrom: () => [],
      allowed: undefined,
    };
  }

  const set = new Set(allowed);

  return {
    unrestricted: false,
    allows: (sourceId) => set.has(sourceId),
    // Только то, что в сборке ЕСТЬ и при этом не разрешено. Имя, которого в
    // сборке нет, исключённым не является — его просто не существует.
    excludedFrom: (available) => available.filter((sourceId) => !set.has(sourceId)),
    allowed,
  };
}

/**
 * Разбирает область из значения флага.
 *
 * `undefined` (флаг не задан) и `""` (задан пустым) РАЗНЫЕ: первое снимает
 * ограничение, второе запрещает всё.
 */
export function parseScope(value: string | undefined): readonly string[] | undefined {
  if (value === undefined) return undefined;

  return value
    .split(",")
    .map((item) => item.trim())
    .filter((item) => item !== "");
}
