/**
 * КНИГА, КОТОРАЯ НЕ СМЕТА, НЕ НАЗЫВАЕТСЯ СМЕТОЙ.
 *
 * НАЙДЕНО БЕНЧМАРКОМ НА КЕЙСАХ ЗАКАЗЧИКА, а не набором.
 *
 * Классификатор устроен так: книга, чьё имя не похоже на сводный расчёт,
 * объявляется «лср». Понятия «книга, но не смета» в системе не было — и вот что
 * из этого вышло на настоящих комплектах:
 *
 *  · «Новотэкс ЭС и ПС»: девятнадцать файлов `_spec.xls` от ЭТМ из подкаталога
 *    «Счета» — счета и спецификации поставщика — стали девятнадцатью «ЛСР».
 *    Экран сообщил «19 смет», из которых 19 отказались в разборе;
 *  · «Дагестан дороги»: «график выполнения» и «ведомость объёмов» тоже стали
 *    сметами и тоже отказались.
 *
 * ЧЕМ ЭТО ХУЖЕ ПРОСТОГО НЕУДОБСТВА. Система утверждает о документе то, чего не
 * проверяла: «это локальный сметный расчёт, и он не читается». Первая половина
 * — выдумка, вторая — следствие выдумки. Читатель делает вывод, что у него в
 * комплекте девятнадцать битых смет, тогда как смет там нет вовсе.
 *
 * ЧТО РАЗДЕЛЯЕТСЯ ЗДЕСЬ — два разных исхода разбора:
 *
 *  · ФОРМА НЕ ТА: нет шапки «№ п/п», нет подзаголовка «всего». Мы попробовали
 *    прочесть книгу как смету 421/пр и этой формы в ней не нашли. Значит это
 *    не смета, и отказом разбора это называть нельзя;
 *  · ФОРМА ТА, НО БИТАЯ: шапка на месте, а строки не сходятся. Вот это отказ, и
 *    он должен остаться отказом — иначе дыра в настоящей смете спрячется под
 *    вывеской «просто не смета».
 */
import { describe, expect, it } from "vitest";

import { checkObject, NotAnEstimate, type CheckObjectPorts } from "./check-object.js";

function порты(overrides: Partial<CheckObjectPorts> = {}): CheckObjectPorts {
  return {
    discover: async () => [{ path: "/о/ЭТМ 502_spec.xls", kind: "лср" as const }],
    charsOf: () => 4200,
    ...overrides,
  } as unknown as CheckObjectPorts;
}

describe("книга, которая не смета", () => {
  it("форма не распознана — вид становится «книга-не-смета», а не «лср»", async () => {
    const итог = await checkObject(
      "/о",
      порты({
        checkDocument: async () => {
          throw new NotAnEstimate(
            "Спецификация: в подзаголовке таблицы не найдена колонка «всего» — раскладка формы не распознана",
          );
        },
      }),
    );

    const документ = итог.documents[0];
    expect(документ?.kind, "счёт поставщика назван локальным сметным расчётом").toBe(
      "книга-не-смета",
    );
  });

  it("это НЕ отказ разбора: отказ означал бы битую смету", async () => {
    /**
     * Разница видна на счётчиках экрана. «Отказов разбора: 19» читается как
     * «девятнадцать смет не удалось прочесть» — то есть как проблема комплекта.
     * А проблемы нет: смет в комплекте не было.
     */
    const итог = await checkObject(
      "/о",
      порты({
        checkDocument: async () => {
          throw new NotAnEstimate("КГ 0-7: не найдена шапка таблицы");
        },
      }),
    );

    expect(итог.documents[0]?.status, "форма не та — а объявлено отказом разбора").not.toBe("отказ");
    expect(итог.totals.failed, "непрочитанной сметой посчитано то, что сметой не является").toBe(0);
  });

  it("содержимое всё равно прочитано и названо прочитанным", async () => {
    // Книга уходит агентам текстом (это сделано раньше). Промолчать об этом
    // значит дать прочесть «не смета» как «файл выброшен».
    const итог = await checkObject(
      "/о",
      порты({
        checkDocument: async () => {
          throw new NotAnEstimate("Спецификация: не найдена шапка таблицы");
        },
      }),
    );

    expect(итог.documents[0]?.reason).toMatch(/прочитано|передано агентам/iu);
    expect(итог.documents[0]?.readout?.chars).toBe(4200);
  });

  it("БИТАЯ СМЕТА остаётся отказом — иначе дыра спрячется", async () => {
    /**
     * Обратная ошибка, и она дороже первой. Смета формы 421/пр, чьи строки не
     * сходятся, — это находка: в ней потеряны позиции или суммы. Назвать её
     * «просто не сметой» значило бы снять с неё все проверки и не сказать
     * читателю ничего.
     */
    const итог = await checkObject(
      "/о",
      порты({
        discover: async () => [{ path: "/о/ЛСР-1.xlsx", kind: "лср" as const }],
        checkDocument: async () => {
          throw new Error("строка «Всего по позиции» без суммы (строка 45)");
        },
      }),
    );

    expect(итог.documents[0]?.status, "битая смета перестала быть отказом").toBe("отказ");
    expect(итог.documents[0]?.kind).toBe("лср");
    expect(итог.totals.failed).toBe(1);
  });

  it("РЕЕСТР говорит то же, что результат", async () => {
    /**
     * НАЙДЕНО ПОВТОРНЫМ ПРОГОНОМ НА КЕЙСЕ ЗАКАЗЧИКА: первая версия этой правки
     * изменила результат обхода и НЕ изменила запись в базе. Вид в реестр
     * пишется при обходе ПАПКИ, до разбора, — то есть по догадке о имени файла.
     * На экране «Документы объекта» девятнадцать счетов поставщика так и
     * остались «лср», хотя отчёт уже называл их не сметами.
     *
     * Расхождение экрана с результатом — худший исход правки: она выглядит
     * сделанной и не сделана. Поэтому вид документа проверяется В ОБОИХ местах,
     * а не в одном.
     *
     * Здесь проверяется договор обхода: вид в результате взят у документа, и
     * если порт назвал книгу не сметой, никакая часть системы не имеет права
     * называть её сметой.
     */
    const итог = await checkObject(
      "/о",
      порты({
        checkDocument: async () => {
          throw new NotAnEstimate("Спецификация: не найдена шапка таблицы");
        },
      }),
    );

    const виды = new Set(итог.documents.map((документ) => документ.kind));

    expect(виды.has("лср"), "документ остался сметой хотя бы в одном месте").toBe(false);
    expect(виды.has("книга-не-смета")).toBe(true);
  });
});
