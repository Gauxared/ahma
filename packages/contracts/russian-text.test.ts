/**
 * Тесты написаны до реализации. Нормализация русского текста.
 *
 * ЧТО ЭТО ЗА ЛОВУШКА И ГДЕ ОНА НАШЛАСЬ
 *
 * В настоящем договоре генерального подряда АПРИ слово «расчет» встречается
 * 34 раза, «расчёт» — НИ РАЗУ. При этом буква ё в документе есть: пять раз, в
 * других словах. То есть документ смешивает написания непоследовательно.
 *
 * Агент, ищущий в договоре «расчёт», не нашёл бы ничего — при том, что слово
 * стоит в тексте 34 раза. Это ровно тот молчаливый пропуск, ради предотвращения
 * которого система и строится: ответ «условий о расчётах в договоре нет»
 * выглядит как результат работы.
 *
 * ЧТО ЕЩЁ ЛОМАЕТ ПОИСК ПО ДОКУМЕНТАМ
 *
 * Неразрывные пробелы из Word, мягкие переносы, разные виды дефисов и кавычек.
 * Всё это невидимо глазом и различимо для сравнения строк, поэтому сводится к
 * одному виду ДО сравнения, а не после неудачи.
 *
 * НОРМАЛИЗАЦИЯ — ДЛЯ СРАВНЕНИЯ, А НЕ ДЛЯ ХРАНЕНИЯ
 *
 * Исходный текст остаётся исходным: по нему цитируют документ. Нормализованный
 * вид — ключ поиска, и подменять им оригинал значит менять текст источника.
 */
import { describe, expect, it } from "vitest";

import { normalizeRussian, russianIncludes } from "./russian-text.js";

describe("нормализация", () => {
  it("сводит ё к е", () => {
    expect(normalizeRussian("расчёт")).toBe(normalizeRussian("расчет"));
  });

  it("сводит Ё к е вместе с регистром", () => {
    expect(normalizeRussian("РАСЧЁТ")).toBe("расчет");
  });

  it("сводит неразрывный пробел к обычному", () => {
    // Word ставит их сам, и глазом они неотличимы.
    expect(normalizeRussian("104 976")).toBe("104 976");
  });

  it("выбрасывает мягкий перенос", () => {
    // Мягкий перенос невидим и разрывает слово для сравнения строк.
    expect(normalizeRussian("рас­чет")).toBe("расчет");
  });

  it("сводит виды дефисов к одному", () => {
    for (const дефис of ["‐", "‑", "‒", "–", "—", "−"]) {
      expect(normalizeRussian(`ГЭСН${дефис}20`)).toBe("гэсн-20");
    }
  });

  it("сводит виды кавычек к одному", () => {
    for (const пара of [["«", "»"], ["“", "”"], ["„", "“"], ['"', '"']]) {
      expect(normalizeRussian(`ООО ${пара[0]}Ромашка${пара[1]}`)).toBe('ооо "ромашка"');
    }
  });

  it("схлопывает повторные пробелы и переводы строк", () => {
    expect(normalizeRussian("кабель   ВВГнг\n\n  5х16")).toBe("кабель ввгнг 5х16");
  });

  it("обрезает края", () => {
    expect(normalizeRussian("  кабель  ")).toBe("кабель");
  });

  it("НЕ трогает цифры и латиницу", () => {
    expect(normalizeRussian("ВВГнг(А)-LS 5х16 мм²")).toBe("ввгнг(а)-ls 5х16 мм²");
  });

  it("оставляет пустую строку пустой", () => {
    expect(normalizeRussian("")).toBe("");
  });
});

describe("поиск с нормализацией", () => {
  it("находит «расчёт» в тексте, где написано «расчет»", () => {
    // Тот самый случай из договора генподряда.
    expect(russianIncludes("порядок расчетов по договору", "расчёт")).toBe(true);
  });

  it("находит и в обратную сторону", () => {
    expect(russianIncludes("порядок расчётов по договору", "расчет")).toBe(true);
  });

  it("не находит того, чего нет", () => {
    // Нормализация не должна делать поиск всеядным: она убирает различия
    // написания, а не различия слов.
    expect(russianIncludes("порядок расчетов", "гарантия")).toBe(false);
  });

  it("не считает совпадением пустой запрос", () => {
    // Пустая строка содержится в любой — и «нашли» превратилось бы в «всегда
    // нашли», то есть в бесполезный ответ.
    expect(russianIncludes("любой текст", "")).toBe(false);
    expect(russianIncludes("любой текст", "   ")).toBe(false);
  });

  it("находит через неразрывный пробел", () => {
    expect(russianIncludes("гарантийное удержание", "гарантийное удержание")).toBe(true);
  });
});
