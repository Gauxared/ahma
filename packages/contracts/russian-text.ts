/**
 * Нормализация русского текста для сравнения и поиска.
 *
 * ГДЕ НАШЛАСЬ ЛОВУШКА
 *
 * В настоящем договоре генерального подряда АПРИ слово «расчет» встречается
 * 34 раза, «расчёт» — НИ РАЗУ. При этом буква ё в документе есть: пять раз, в
 * других словах. Документ смешивает написания непоследовательно, как почти
 * любой документ на русском.
 *
 * Агент, ищущий в договоре «расчёт», не нашёл бы ничего — при том, что слово
 * стоит там 34 раза. Ответ «условий о расчётах в договоре нет» выглядел бы как
 * результат работы. Это ровно тот молчаливый пропуск, ради предотвращения
 * которого система и строится.
 *
 * ЧТО ЕЩЁ ЛОМАЕТ СРАВНЕНИЕ
 *
 * Неразрывные пробелы, которые Word ставит сам; мягкие переносы; шесть видов
 * дефиса; четыре пары кавычек. Всё это неотличимо глазом и различимо для
 * сравнения строк, поэтому сводится к одному виду ДО сравнения, а не после
 * неудачного поиска.
 *
 * НОРМАЛИЗАЦИЯ — ДЛЯ СРАВНЕНИЯ, А НЕ ДЛЯ ХРАНЕНИЯ
 *
 * Исходный текст остаётся исходным: по нему цитируют документ и по нему сверяют
 * смету. Нормализованный вид — ключ поиска. Подменить им оригинал значит
 * изменить текст источника, чего система не делает нигде.
 */

/** Мягкий перенос: невидим и разрывает слово для сравнения. */
const SOFT_HYPHEN = /­/g;

/** Шесть видов дефиса и минуса, сводимые к обычному. */
const HYPHENS = /[‐‑‒–—−]/g;

/** Кавычки всех видов — к прямой двойной. */
const QUOTES = /[«»“”„‟‘’‚‛]/g;

/** Пробельные символы, включая неразрывный и узкий неразрывный. */
const SPACES = /[\s   ]+/g;

/**
 * Приводит текст к виду, пригодному для сравнения.
 *
 * Регистр, ё, переносы, дефисы, кавычки и пробелы — к одному виду. Цифры и
 * латиница не трогаются: `ВВГнг(А)-LS 5х16` обязан остаться узнаваемым.
 */
export function normalizeRussian(value: string): string {
  return value
    .replace(SOFT_HYPHEN, "")
    .replace(HYPHENS, "-")
    .replace(QUOTES, '"')
    .replace(SPACES, " ")
    .trim()
    .toLowerCase()
    // ё складывается ПОСЛЕ приведения регистра: иначе пришлось бы обрабатывать
    // обе буквы отдельно.
    .replace(/ё/g, "е");
}

/**
 * Содержит ли текст искомое с точностью до написания.
 *
 * Пустой запрос совпадением НЕ считается: пустая строка содержится в любой, и
 * «нашли» превратилось бы в «всегда нашли» — ответ, по которому нельзя принять
 * решение.
 */
export function russianIncludes(haystack: string, needle: string): boolean {
  const query = normalizeRussian(needle);

  return query !== "" && normalizeRussian(haystack).includes(query);
}
