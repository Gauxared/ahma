/**
 * Сборка отказывается запускаться с незадекларированным адресом модели.
 *
 * ADR-R-014, R-017: «любая ошибка конфигурации ОСТАНАВЛИВАЕТ сборку».
 *
 * ПОЧЕМУ ЭТО ПРОВЕРЯЕТСЯ НА СТАРТЕ, А НЕ ПРИ ПЕРВОМ ВЫЗОВЕ
 *
 * Ошибка конфигурации, обнаруженная при первой проверке объекта, — это отказ в
 * работе посреди работы: пользователь загрузил документы, дождался очереди и
 * получил «выход наружу не разрешён». Обнаруженная на старте, она означает, что
 * стенд просто не поднялся, и об этом узнал тот, кто его разворачивал.
 *
 * ЧТО ИМЕННО ЗАЩИЩАЕТСЯ
 *
 * Не от злоумышленника, а от тихой подмены провайдера: правки
 * STROYINTELLECT_MODEL_BASE_URL достаточно, чтобы сметы заказчика поехали в
 * другую компанию, и в конфигурации проекта это никак не отразилось бы.
 * Теперь смена провайдера требует правки манифеста маршрута — то есть файла,
 * который читают и рецензируют.
 */
import { describe, expect, it } from "vitest";

import { bootstrap } from "./bootstrap.js";

const БАЗА = {
  STROYINTELLECT_MODEL_ID: "м-1",
  STROYINTELLECT_MODEL_API_KEY: "ключ",
};

describe("сборка и egress", () => {
  it("ОТКАЗЫВАЕТСЯ собираться с незадекларированным адресом модели", () => {
    expect(() =>
      bootstrap({ env: { ...БАЗА, STROYINTELLECT_MODEL_BASE_URL: "https://чужой.example/v1" } }),
    ).toThrow(/не разрешён ни одним маршрутом/);
  });

  it("объясняет, где объявляется назначение", () => {
    // Сообщение об отказе, не говорящее что делать, превращает отказ в загадку.
    expect(() =>
      bootstrap({ env: { ...БАЗА, STROYINTELLECT_MODEL_BASE_URL: "https://чужой.example/v1" } }),
    ).toThrow(/model-routes\.json/);
  });

  it("ОТКАЗЫВАЕТСЯ собираться с http-адресом модели", () => {
    expect(() =>
      bootstrap({
        env: { ...БАЗА, STROYINTELLECT_MODEL_BASE_URL: "http://api.anthropic.com/v1" },
      }),
    ).toThrow(/https/);
  });

  it("собирается с задекларированным адресом", () => {
    const platform = bootstrap({
      env: { ...БАЗА, STROYINTELLECT_MODEL_BASE_URL: "https://api.anthropic.com/v1" },
    });

    expect(platform.egressGateway).toBeDefined();
  });

  it("собирается без модели вовсе: шлюз не требует её наличия", () => {
    // Детерминированная часть проверки работает без модели (§12.1а, §12.1б).
    // Шлюз не должен превращать её отсутствие в отказ запуска.
    const platform = bootstrap({ env: {} });

    expect(platform.egressGateway).toBeDefined();
    expect(platform.drainEgressLog()).toEqual([]);
  });
});
