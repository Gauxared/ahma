import { describe, expect, it } from "vitest";

import { parseCrewText } from "./crew-text.js";

/** Ответ в формате эталонной системы: так отвечал сметчик легаси. */
const ОТВЕТ = `
ВЕРДИКТ: 🟡 принимаем с условиями. Завышение ≈ 4,1 млн (8,5%).

ТОП-ОШИБКИ (в рублях):
1. Двойной счёт: разработка грунта учтена в ФЕР 01-01-013-07 И отдельно как «перемещение» — эффект 2 300 000 ₽. ✅ ФАКТ [ИСТОЧНИК: ФСНБ-2022, опорная база, действует]
2. НР 142% вместо норматива 95% по виду работ — эффект 1 200 000 ₽. ✅ ФАКТ [ИСТОЧНИК: Приказ № 812/пр, 2026-09-09, действует]
3. Цена щебня 1 180 руб/м³ при сметной 740 — эффект ≈ 600 000 ₽. ⚠ ПРЕДПОЛОЖЕНИЕ [ИСТОЧНИК: прайс поставщика, 2026-09-01, старше 90 дней]

❌ НЕИЗВЕСТНОЕ: объёмы по выторфовке — нет техзаключения, от Денчика, срок: до торга

## Сходимость сметы
| Показатель | Значение, ₽ | Статус |
|---|---|---|
| Итого по позициям | 48 200 000,00 | ✅ |
| Заявлено в шапке | 48 200 000,00 | ✅ |

## Ведомость объёмов работ
| Вид работ | Ед. изм. | Количество | Сумма, ₽ | Откуда объём |
|---|---|---|---|---|
| Разработка грунта экскаватором | м3 | 12 500,00 | 9 030 636,54 | ЛСР-02 · строка 84 |
| Щебень фракции 40-70 | м3 | 1 250,50 | 1 629 401,50 | ЛСР-02 · строка 91 |

🚨 АЛЕРТ Сметчик | 2026-09-09
Ситуация: цена битума в смете вдвое ниже рынка
Денежный эффект: 2 400 000 ₽, статья «материалы»
Документ-обоснование: в работе
Нужно решение Артемия: да — фиксировать ли цену с АБЗ

▸ БЛОК ДЛЯ ВАНЫЧА ───────────────────────────
Себестоимость по материалам 31 200 000 ₽ без НДС.
Снятия по позициям 1–2: 3 500 000 ₽. Срок: до 2026-09-10.
─────────────────────────────────────────────
Скопируйте этот блок в чат Ваныча.

НЕ ПРИНИМАЮ инженерный реестр Денчика. Не хватает: подтверждения объёмов по чертежам. Срок — 2026-09-10.

СЛЕДУЮЩИЙ ТАКТ: Ваныч считает финмодель на скорректированной себестоимости.
УРОК: встретил смету без расшифровки НР → требуй расчёт по видам работ, потому что норматив 142% скрывает завышение.
`;

describe("разбор свободного ответа роли", () => {
  const output = parseCrewText(ОТВЕТ);

  it("текст роли сохраняется целиком: он и есть её документ", () => {
    // Разбор добавляет системе экран и пакет; он не заменяет собой результат.
    expect(output.text).toContain("ТОП-ОШИБКИ (в рублях)");
    expect(output.text.length).toBeGreaterThan(1000);
  });

  it("вердикт берётся со значком, как велит Ядро р.4", () => {
    expect(output.verdict).toContain("🟡");
    expect(output.verdict).toContain("Завышение");
  });

  it("находки — строки с тегом источника, с суммой и статусом", () => {
    expect(output.findings.length).toBeGreaterThanOrEqual(3);

    const двойной = output.findings.find((f) => f.statement.includes("Двойной счёт"));
    expect(двойной?.impactRub).toBe("2300000");
    expect(двойной?.sourceStatus).toBe("факт");
    expect(двойной?.basis).toContain("ФСНБ-2022");

    const щебень = output.findings.find((f) => f.statement.includes("щебня"));
    expect(щебень?.sourceStatus).toBe("предположение");
  });

  it("«❌ НЕИЗВЕСТНОЕ» становится открытым вопросом с адресатом и сроком", () => {
    expect(output.openQuestions).toHaveLength(1);
    expect(output.openQuestions[0]?.question).toContain("выторфовке");
    expect(output.openQuestions[0]?.owner).toContain("Денчика");
    expect(output.openQuestions[0]?.dueBy).toContain("до торга");
  });

  it("«БЛОК ДЛЯ» становится передачей смежнику, а рамка блока в данные не попадает", () => {
    expect(output.handoffs).toHaveLength(1);
    expect(output.handoffs[0]?.to).toBe("ВАНЫЧА");
    expect(output.handoffs[0]?.subject).toContain("31 200 000");
    // Линия-разделитель и «Скопируйте…» — оформление, а не содержание.
    expect(output.handoffs[0]?.subject).not.toContain("────");
    expect(output.handoffs[0]?.subject).not.toContain("Скопируйте");
  });

  it("«🚨 АЛЕРТ» разбирается по строкам своего формата", () => {
    expect(output.alerts).toHaveLength(1);
    expect(output.alerts[0]?.situation).toContain("битума");
    expect(output.alerts[0]?.moneyEffect).toContain("2 400 000");
    expect(output.alerts[0]?.decision).toContain("АБЗ");
  });

  it("«НЕ ПРИНИМАЮ» становится возвратом работы смежнику", () => {
    expect(output.returns).toHaveLength(1);
    expect(output.returns[0]?.missing).toContain("объёмов по чертежам");
    expect(output.returns[0]?.dueBy).toContain("2026-09-10");
  });

  it("таблицы Markdown становятся листами документа", () => {
    const названия = output.sections.map((s) => s.title);
    expect(названия).toContain("Сходимость сметы");
    expect(названия).toContain("Ведомость объёмов работ");

    const сходимость = output.sections.find((s) => s.title === "Сходимость сметы");
    expect(сходимость?.columns).toEqual(["Показатель", "Значение, ₽", "Статус"]);
    expect(сходимость?.rows).toHaveLength(2);
  });

  it("строки с шифром, объёмом и суммой становятся позициями", () => {
    // Позиция — то, у чего есть обоснование либо единица с количеством и
    // суммой. Реестр рисков и таблица сроков позициями не становятся.
    expect(output.positions.length).toBeGreaterThanOrEqual(2);

    const грунт = output.positions.find((p) => p.name.includes("грунта"));
    expect(грунт?.unit).toBe("м3");
    expect(грунт?.quantity).toBe("12500.00");
    expect(грунт?.amountRub).toBe("9030636.54");
    // Координата — из колонки «откуда объём»: по ней читатель открывает строку.
    expect(грунт?.row).toBe(84);
  });

  it("следующий такт и урок читаются своими строками", () => {
    expect(output.nextTakt).toContain("Ваныч считает финмодель");
    expect(output.lesson).toContain("расчёт по видам работ");
  });

  it("пустой ответ не выдаётся за структуру", () => {
    const пусто = parseCrewText("   ");

    expect(пусто.verdict).toBe("");
    expect(пусто.findings).toHaveLength(0);
    expect(пусто.sections).toHaveLength(0);
  });
});
