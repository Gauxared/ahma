/**
 * СВОБОДНЫЙ ОТВЕТ РОЛИ → СТРУКТУРА ДЛЯ ЭКРАНА И ПАКЕТА.
 *
 * ПОЧЕМУ СХЕМЫ БОЛЬШЕ НЕТ. Роль отвечала строгим JSON из шестнадцати
 * обязательных полей. Схема решала за неё, ЧТО сказать: поле есть — заполни,
 * даже если по этому объекту сказать нечего. Владелец 09.09.2026: «пусть агент
 * отвечает свободно». В эталонной системе так и было — агент выдавал документ
 * по форме СВОЕГО промпта, и форму эту задавала роль, а не оркестратор.
 *
 * ЧТО ВЗАМЕН. Роль пишет тем форматом, которому её учит собственный промпт и
 * Ядро: вердикт со значком, заключение строками, находки со статусом источника,
 * «▸ БЛОК ДЛЯ [ИМЯ]», «❌ НЕИЗВЕСТНОЕ», «🚨 АЛЕРТ», таблицы. Разбор читает
 * ИМЕННО ЭТИ маркеры — не выдуманные нами, а те, что записаны в Ядре и в
 * промптах ролей, то есть те, которые роль пишет и так.
 *
 * ГЛАВНОЕ ПРАВИЛО ЭТОГО МОДУЛЯ: ТЕКСТ РОЛИ НЕ ПРОПАДАЕТ. Что бы ни удалось
 * разобрать, полный ответ сохраняется целиком и доходит до человека. Разбор
 * добавляет системе возможность показать находки на экране и собрать пакет —
 * он не является условием того, что работа засчитана. Пустой разбор при
 * непустом ответе означает «структуру не распознали», а не «роль ничего не
 * сказала», и это видно по длине текста рядом.
 */
import type { CrewFinding, CrewOutput, CrewPosition, CrewReturn, Handoff } from "./crew-output.js";
import type { ReviewSection } from "@modules/workflow/check-object.js";
import { cellNumber } from "@modules/documents/cell-number.js";

/** Значок вердикта: им Ядро р.4 велит начинать ответ. */
const ВЕРДИКТ = /(🟢|🟡|🔴)/u;

/** «▸ БЛОК ДЛЯ ВАНЫЧА ─────» — протокол передачи Ядра р.2. */
const БЛОК_ДЛЯ = /^\s*[▸►>]?\s*БЛОК\s+ДЛЯ\s+([^\n─—\-|]+?)\s*[─—\-]*\s*$/imu;

/** «❌ НЕИЗВЕСТНОЕ — нужны данные: от кого и к какому сроку» (Ядро р.7). */
const НЕИЗВЕСТНОЕ = /^\s*❌\s*(?:НЕИЗВЕСТНОЕ\s*[—:-]?\s*)?(.+)$/u;

/** «🚨 АЛЕРТ <роль> | <дата>» (Ядро). */
// `\b` после кириллицы не работает (граница слова в JS считается по ASCII):
// между «Т» и пробелом её нет. Тот же класс уже ловили в детекторе форматов.
const АЛЕРТ = /^\s*🚨\s*АЛЕРТ(?!\p{L})(.*)$/u;

/** «НЕ ПРИНИМАЮ …», «ВОЗВРАЩАЮ …» — возврат работы смежнику. */
const ВОЗВРАТ = /^\s*(?:🔴\s*)?(?:ВОЗВРАЩАЮ|НЕ\s+ПРИНИМАЮ)(?!\p{L})\s*[:.]?\s*(.*)$/imu;

/** «[ИСТОЧНИК: документ, дата, статус]» — Ядро р.7. */
const ИСТОЧНИК = /\[ИСТОЧНИК:([^\]]+)\]/u;

/** Строка таблицы Markdown: `| ячейка | ячейка |`. */
const СТРОКА_ТАБЛИЦЫ = /^\s*\|(.+)\|\s*$/u;

/** Разделитель шапки таблицы: `|---|---|`. */
const РАЗДЕЛИТЕЛЬ = /^\s*\|[\s:|-]+\|\s*$/u;

/** Заголовок Markdown: `## Сходимость сметы` — им роль называет свои листы. */
const ЗАГОЛОВОК = /^\s{0,3}#{1,6}\s+(.+?)\s*#*\s*$/u;

/** Важность по словам статуса источника и по значку. */
function важность(строка: string): CrewFinding["severity"] {
  const t = строка.toLowerCase();

  if (строка.includes("🔴") || t.includes("критич") || t.includes("блокер")) return "critical";
  if (строка.includes("🚨") || t.includes("риск") || t.includes("завышен") || t.includes("не принима")) return "high";
  if (строка.includes("⚠") || t.includes("предположение")) return "medium";
  if (строка.includes("❌")) return "medium";
  return "info";
}

/** Первая сумма в рублях из строки — десятичной строкой либо пусто. */
function рубли(строка: string): string {
  const m = строка.match(/(-?\d[\d\s   ']*(?:[.,]\d+)?)\s*(?:₽|руб)/iu);
  return m === null ? "" : (cellNumber(m[1] ?? "") ?? "");
}

/** Ячейки строки таблицы Markdown. */
function ячейки(строка: string): readonly string[] {
  const m = строка.match(СТРОКА_ТАБЛИЦЫ);
  if (m === null) return [];

  return (m[1] ?? "").split("|").map((cell) => cell.trim());
}

/**
 * Таблицы Markdown → листы документа роли.
 *
 * Идентификатор листа берётся из ближайшего заголовка над таблицей: роль
 * называет лист по-человечески («## Сходимость сметы»), а не кодом. Ключ для
 * каркаса подставляется отдельно — по совпадению названия с манифестом; когда
 * совпадения нет, лист остаётся предметным, и это законно.
 */
function листы(строки: readonly string[]): readonly ReviewSection[] {
  const out: ReviewSection[] = [];
  let заголовок = "";
  let текущая: string[][] = [];
  let шапка: readonly string[] = [];

  const закрыть = (): void => {
    if (шапка.length === 0 || текущая.length === 0) {
      текущая = [];
      шапка = [];
      return;
    }

    out.push({
      id: заголовок === "" ? `лист_${out.length + 1}` : заголовок.toLowerCase().replace(/\s+/gu, "_").slice(0, 60),
      title: заголовок === "" ? `Таблица ${out.length + 1}` : заголовок,
      purpose: "лист документа роли",
      columns: [...шапка],
      rows: текущая.map((строка) => [...строка]),
    });

    текущая = [];
    шапка = [];
  };

  for (const строка of строки) {
    const шапкаМ = строка.match(ЗАГОЛОВОК);
    if (шапкаМ !== null) {
      закрыть();
      заголовок = шапкаМ[1] ?? "";
      continue;
    }

    if (РАЗДЕЛИТЕЛЬ.test(строка)) continue;

    const cells = ячейки(строка);
    if (cells.length === 0) {
      закрыть();
      continue;
    }

    if (шапка.length === 0) шапка = cells;
    else текущая.push([...cells]);
  }

  закрыть();
  return out;
}

/**
 * Позиции из таблиц: строка с шифром расценки и суммой — позиция.
 *
 * Признак сознательно узкий. Роль пишет много таблиц — реестр рисков, сроки,
 * параметры расчёта, — и объявлять позицией каждую строку значило бы засыпать
 * счёт объекта мусором. Позиция здесь — то, у чего есть ОБОСНОВАНИЕ (шифр) или
 * единица измерения вместе с количеством и суммой.
 */
function позиции(таблицы: readonly ReviewSection[]): readonly CrewPosition[] {
  const ШИФР = /\b(ФЕР|ГЭСН|ФССЦ|ФСЭМ|ТЕР|ТСН)[мрп]?[\s-]?\d{2}-\d{2}-\d{3}/iu;
  const out: CrewPosition[] = [];

  for (const лист of таблицы) {
    const индекс = (слова: readonly string[]): number =>
      лист.columns.findIndex((колонка) => слова.some((слово) => колонка.toLowerCase().includes(слово)));

    const кНаименованию = индекс(["наимен", "работ", "позиц", "ресурс"]);
    const кСумме = индекс(["сумм", "стоимост", "всего", "₽"]);
    const кЕдинице = индекс(["ед."]);
    const кКоличеству = индекс(["кол-во", "количеств", "объ[её]м"]);
    const кОткуда = индекс(["откуда", "источник", "документ", "строка"]);

    if (кНаименованию < 0 || кСумме < 0) continue;

    for (const строка of лист.rows) {
      const имя = строка[кНаименованию] ?? "";
      const сумма = рубли(строка[кСумме] ?? "") || (cellNumber(строка[кСумме] ?? "") ?? "");
      const шифр = строка.find((ячейка) => ШИФР.test(ячейка)) ?? "";

      if (имя.trim() === "") continue;
      if (шифр === "" && (кЕдинице < 0 || кКоличеству < 0)) continue;
      if (сумма === "" && (строка[кКоличеству] ?? "") === "") continue;

      const откуда = кОткуда < 0 ? "" : (строка[кОткуда] ?? "");
      const строкаДокумента = откуда.match(/строк[аи]?\s*(\d+)/iu)?.[1] ?? откуда.match(/\b(\d{1,5})\b\s*$/u)?.[1] ?? "0";

      out.push({
        document: откуда.split("·")[0]?.trim() ?? "",
        sheet: "",
        row: Number.parseInt(строкаДокумента, 10),
        ordinal: String(out.length + 1),
        section: лист.title,
        name: имя,
        code: (шифр.match(ШИФР)?.[0] ?? "").trim(),
        unit: кЕдинице < 0 ? "" : (строка[кЕдинице] ?? ""),
        quantity: кКоличеству < 0 ? "" : (cellNumber(строка[кКоличеству] ?? "") ?? ""),
        amountRub: сумма,
      });
    }
  }

  return out;
}

/**
 * Разбор свободного ответа роли.
 *
 * Ничего не требует и ни на чём не настаивает: чего в тексте нет, того нет в
 * структуре. Полный текст возвращается в `text` и сохраняется рядом — по нему
 * человек читает документ роли так, как она его написала.
 */
export function parseCrewText(raw: string): CrewOutput & { readonly text: string } {
  const текст = raw.trim();
  const строки = текст.split("\n");

  const вердиктСтрока = строки.find((строка) => ВЕРДИКТ.test(строка))?.trim() ?? "";

  const findings: CrewFinding[] = [];
  const openQuestions: { question: string; owner: string; dueBy: string }[] = [];
  const handoffs: Handoff[] = [];
  const alerts: { situation: string; moneyEffect: string; document: string; decision: string }[] = [];
  const returns: CrewReturn[] = [];
  const summary: string[] = [];

  let адресатБлока: string | undefined;
  let телоБлока: string[] = [];

  const закрытьБлок = (): void => {
    if (адресатБлока !== undefined && телоБлока.length > 0) {
      handoffs.push({
        to: адресатБлока,
        subject: телоБлока.join(" ").slice(0, 600),
        disputed: телоБлока.find((строка) => строка.includes("⚠") || строка.includes("❌")) ?? "",
        needed: телоБлока.find((строка) => /срок|до \d|нужн/iu.test(строка)) ?? "",
      });
    }

    адресатБлока = undefined;
    телоБлока = [];
  };

  for (const [индекс, строка] of строки.entries()) {
    const блок = строка.match(БЛОК_ДЛЯ);
    if (блок !== null) {
      закрытьБлок();
      адресатБлока = (блок[1] ?? "").trim();
      continue;
    }

    if (адресатБлока !== undefined) {
      // Рамка блока в эталонном формате — из символов линии; она не данные.
      if (/^[\s─—_=-]+$/u.test(строка) || /^Скопируйте/iu.test(строка.trim())) {
        if (телоБлока.length > 0) закрытьБлок();
        continue;
      }
      if (строка.trim() !== "") телоБлока.push(строка.trim());
      continue;
    }

    const неизвестное = строка.match(НЕИЗВЕСТНОЕ);
    if (неизвестное !== null) {
      const вопрос = (неизвестное[1] ?? "").trim();
      openQuestions.push({
        question: вопрос,
        owner: вопрос.match(/от\s+([^,;.]+)/iu)?.[1]?.trim() ?? "",
        dueBy: вопрос.match(/срок[:\s]+([^,;.]+)/iu)?.[1]?.trim() ?? "",
      });
    }

    const алерт = строка.match(АЛЕРТ);
    if (алерт !== null) {
      const хвост = строки.slice(индекс + 1, индекс + 5).join(" ");
      alerts.push({
        situation: хвост.match(/Ситуация:\s*([^\n]+?)(?:Денежный|Документ|$)/iu)?.[1]?.trim() ?? (алерт[1] ?? "").trim(),
        moneyEffect: хвост.match(/Денежный эффект:\s*([^\n]+?)(?:Документ|Нужно|$)/iu)?.[1]?.trim() ?? "",
        document: хвост.match(/Документ[^:]*:\s*([^\n]+?)(?:Нужно|$)/iu)?.[1]?.trim() ?? "",
        decision: хвост.match(/Нужно решение[^:]*:\s*([^\n]+)/iu)?.[1]?.trim() ?? "",
      });
    }

    const возврат = строка.match(ВОЗВРАТ);
    if (возврат !== null) {
      const хвост = (возврат[1] ?? "") + " " + строки.slice(индекс + 1, индекс + 3).join(" ");
      returns.push({
        to: хвост.match(/^\s*([А-ЯЁ][а-яё]+)/u)?.[1] ?? "",
        notAccepted: (возврат[1] ?? "").trim(),
        missing: хвост.match(/не хватает[:\s]+([^.]+)/iu)?.[1]?.trim() ?? "",
        dueBy: хвост.match(/срок[:\s—-]+([^.]+)/iu)?.[1]?.trim() ?? "",
      });
    }

    // Находка — строка со статусом источника либо с денежным эффектом.
    if (ИСТОЧНИК.test(строка) || /✅ ФАКТ|⚠ ПРЕДПОЛОЖЕНИЕ/u.test(строка)) {
      const утверждение = строка.replace(ИСТОЧНИК, "").replace(/^[\s\d.)•·—-]+/u, "").trim();
      if (утверждение !== "") {
        findings.push({
          severity: важность(строка),
          statement: утверждение.slice(0, 600),
          basis: строка.match(ИСТОЧНИК)?.[0] ?? "",
          document: "",
          row: 0,
          impactRub: рубли(строка),
          sourceStatus: строка.includes("✅") ? "факт" : строка.includes("❌") ? "неизвестное" : "предположение",
        });
      }
    }

    // «ЗАКЛЮЧЕНИЕ — 4 СТРОКИ»: нумерованные строки сразу после заголовка.
    if (/^\s*\d[.)]\s+\S/u.test(строка) && summary.length < 6 && findings.length === 0) {
      summary.push(строка.trim());
    }
  }

  закрытьБлок();

  const sections = листы(строки);

  return {
    text: текст,
    verdict: вердиктСтрока,
    summary,
    findings,
    positions: позиции(sections),
    sections,
    openQuestions,
    handoffs,
    returns,
    assumptions: [],
    alerts,
    nextTakt: текст.match(/СЛЕДУЮЩИЙ ТАКТ[:\s—-]+([^\n]+)/iu)?.[1]?.trim() ?? "",
    lesson: текст.match(/УРОК[^:\n]*:\s*([^\n]+)/iu)?.[1]?.trim() ?? "",
  };
}
