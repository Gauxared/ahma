/**
 * Экипаж: такты, ворота и передача между ролями (spec-demo-stage-1 А3, А4, А6).
 *
 * ОРКЕСТРАТОР НЕ ВЫБИРАЕТ РОЛЬ «ПО РЕЛЕВАНТНОСТИ» — ОН ИСПОЛНЯЕТ DAG С
 * ПРЕДУСЛОВИЯМИ. Это восьмой механизм образца (Опорный документ Артемия, лист
 * «3. Такты 0-4»): «без ворот предыдущего такта следующий не стартует». Ваныч
 * без ВОР Людмилы — финмодель на воздухе; Людмила без ВОР Денчика — ошибка
 * 30–40 %. Порядок здесь — условие осмысленности, а не оптимизация.
 *
 * ОДИН ТРЕД НА РОЛЬ НА ВЕСЬ ОБЪЕКТ. Людмила видит все сметы объекта из одного
 * разговора — Т9.5 (память в пределах объекта) закрывается конструкцией.
 *
 * ПЕРЕДАЧА — «БЛОК ДЛЯ [ИМЯ]» (Ядро р.2). Роль называет адресата и содержимое;
 * оркестратор складывает блоки в `передачи/для-<Имя>.md` и вставляет их в
 * вводную адресата дословно, в эталонной рамке. Никакой общей истории диалога
 * между ролями нет — как в образце, где каждый агент живёт в отдельном чате.
 *
 * ДИРИЖЁР — ДО ТАКТА 0. Паспорт входа, маршрут, гейт. Гейт здесь ВИДЕН, но не
 * останавливает прогон (решение А4): комплект клиента на показе почти всегда
 * неполон, и остановка оставила бы его без результата. Список дозагрузки уходит
 * всем ролям как обязательство ставить ⚠ и в документ 09 открытыми вопросами.
 *
 * ЗАВИСИМОСТИ ЖДУТСЯ КАК «УЛЕГЛИСЬ», А НЕ «УДАЛИСЬ». Отказ Денчика не должен
 * лишать объект сметного анализа: Людмила стартует, зная, что смежник отказал,
 * и говорит об этом сама. Иначе один сбой треда гасил бы весь пакет.
 */
