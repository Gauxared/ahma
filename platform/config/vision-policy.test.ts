/**
 * Куда можно отправлять листы рабочей документации.
 *
 * ЧТО ЗДЕСЬ ЗАЩИЩАЕТСЯ
 *
 * Одно свойство, и оно про данные заказчика: **изображение не проходит
 * обезличивание.** Промпт проходит анонимизатор и получает расписку; фамилии
 * проектировщиков в штампе чертежа — растр, и заменить их нечем.
 *
 * Значит правило обязано быть fail closed: по умолчанию листы не уходят, и
 * снимается запрет только явным согласием. Проверяется именно это, а не
 * «функция вернула объект»: ошибка здесь означает, что чертежи заказчика
 * уехали на чужую машину, и узнать об этом будет неоткуда.
 */
import { describe, expect, it } from "vitest";

import { declaredContour, LOCAL_MODEL, VISION_EXTERNAL, visionPolicy } from "./vision-policy.js";

describe("куда уходят листы документации", () => {
  it("на модель ВНУТРИ контура — можно, и контур подтверждает владелец", () => {
    // Локального адреса мало: подтверждение того, что за ним модель, а не
    // шлюз, делает человек — код этого не проверит.
    for (const адрес of [
      "http://127.0.0.1:8317/v1",
      "http://localhost:11434/v1",
      "https://127.0.0.1/v1",
      "http://[::1]:8080/v1",
    ]) {
      expect(
        visionPolicy(адрес, { [LOCAL_MODEL]: "да" }).allowed,
        `адрес ${адрес} признан внешним при подтверждённом контуре`,
      ).toBe(true);
    }
  });

  it("ЛОКАЛЬНЫЙ АДРЕС САМ ПО СЕБЕ НЕ РАЗРЕШАЕТ: за ним бывает шлюз", () => {
    /**
     * Обнаружено на собственном контуре: `127.0.0.1:8317` — прокси, за которым
     * тридцать две внешние модели. Листы уходили наружу, а журнал §12.1л
     * записывал «модель локальна: листы не покидают машину».
     *
     * Утверждение о границе данных, сделанное по адресу, границу не проверяет.
     * Это опаснее прямого внешнего адреса: тот выглядит внешним, а этот —
     * безопасным.
     */
    const решение = visionPolicy("http://127.0.0.1:8317/v1", {});

    expect(решение.allowed, "локальный адрес разрешил отправку без подтверждения контура").toBe(false);
    expect(решение.reason).toContain("шлюз");
    expect(решение.reason, "отказ не называет, чем его снять").toContain(LOCAL_MODEL);
    expect(решение.reason).toContain(VISION_EXTERNAL);
  });

  it("согласие на внешнюю отправку работает и через локальный шлюз", () => {
    const решение = visionPolicy("http://127.0.0.1:8317/v1", { [VISION_EXTERNAL]: "да" });

    expect(решение.allowed).toBe(true);
    // И в журнале записано, что листы ушли НЕОБЕЗЛИЧЕННЫМИ, а не «остались».
    expect(решение.reason).toContain("НЕОБЕЗЛИЧЕННЫМИ");
    expect(решение.reason).toContain("шлюз");
  });

  it("на внешнюю — НЕЛЬЗЯ по умолчанию", () => {
    const решение = visionPolicy("https://api.модель.example/v1", {});

    expect(решение.allowed).toBe(false);
    // Причина называет и запрет, и способ его снять: отказ, не говорящий что
    // делать, превращается в «функция не работает».
    expect(решение.reason).toContain("обезличиванию не подлежит");
    expect(решение.reason).toContain(VISION_EXTERNAL);
  });

  it("явное согласие владельца запрет снимает", () => {
    for (const слово of ["да", "ДА", " Да ", "yes"]) {
      expect(visionPolicy("https://api.модель.example/v1", { [VISION_EXTERNAL]: слово }).allowed).toBe(true);
    }
  });

  it("согласие объявляет цену словом «НЕОБЕЗЛИЧЕННЫМИ»", () => {
    // Владелец, снявший запрет, должен видеть в причине, что именно он
    // разрешил, — иначе согласие дано вслепую.
    const решение = visionPolicy("https://api.модель.example/v1", { [VISION_EXTERNAL]: "да" });

    expect(решение.reason).toContain("НЕОБЕЗЛИЧЕННЫМИ");
  });

  it("постороннее значение согласием не считается", () => {
    // «true», «1», «on» — не согласие: список слов задан явно, и расширять его
    // догадками значит расширять разрешение догадками.
    for (const слово of ["true", "1", "on", "возможно", ""]) {
      expect(visionPolicy("https://api.модель.example/v1", { [VISION_EXTERNAL]: слово }).allowed).toBe(false);
    }
  });

  it("без адреса модели — нельзя, и причина об этом", () => {
    expect(visionPolicy(undefined, { [VISION_EXTERNAL]: "да" }).allowed).toBe(false);
    expect(visionPolicy("", {}).reason).toContain("не задан");
  });

  it("похожий на локальный адрес локальным не считается", () => {
    // `127.0.0.1.чужой.example` начинается с локального октета и локальным не
    // является. Проверка по началу строки без границы пропустила бы его.
    for (const адрес of ["https://127.0.0.1.чужой.example/v1", "https://localhost.чужой.example/v1"]) {
      expect(visionPolicy(адрес, {}).allowed, `адрес ${адрес} признан локальным`).toBe(false);
    }
  });
});

/**
 * КОНТУР В ЖУРНАЛЕ §12.1л — ПО ОБЪЯВЛЕНИЮ, А НЕ ПО СОВПАДЕНИЮ АДРЕСА.
 *
 * Маршрут выбирается сопоставлением адреса с назначениями, и `127.0.0.1`
 * попадает во «внутренний» маршрут. Журнал записывал `contour: internal` о
 * вызовах, которые уходили через шлюз к внешним моделям, — а поле `contour` и
 * есть то, ради чего этот журнал существует.
 */
describe("контур в журнале", () => {
  it("внутренний — только при подтверждённом контуре", () => {
    expect(declaredContour("internal", { [LOCAL_MODEL]: "да" })).toBe("internal");
  });

  it("внутренний маршрут БЕЗ подтверждения записывается внешним", () => {
    // Если мы не знаем, лучше записать более сильное утверждение, чем более
    // удобное: §12.1л спрашивает, что вышло за пределы контура.
    expect(declaredContour("internal", {})).toBe("external");
    expect(declaredContour("internal", { [VISION_EXTERNAL]: "да" })).toBe("external");
  });

  it("внешний маршрут остаётся внешним при любом объявлении", () => {
    // Подтверждение замкнутости не превращает внешний адрес во внутренний:
    // иначе метка снималась бы словом, а не свойством.
    expect(declaredContour("external", { [LOCAL_MODEL]: "да" })).toBe("external");
    expect(declaredContour(undefined, { [LOCAL_MODEL]: "да" })).toBe("external");
  });
});
