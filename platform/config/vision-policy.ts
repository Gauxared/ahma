/**
 * ГРАНИЦА ДАННЫХ: куда уходит то, что мы отправляем модели.
 *
 * Модуль отвечает на два вопроса одним признаком — объявлением владельца:
 * можно ли отправлять ЛИСТЫ чертежей (`visionPolicy`) и какой КОНТУР записать
 * в журнал §12.1л (`declaredContour`). Признак один, потому что вопрос один:
 * покидают данные машину или нет.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНОЕ ПРАВИЛО, А НЕ УСЛОВИЕ В КОМПОЗИЦИОННОМ КОРНЕ
 *
 * У изображения есть свойство, которого нет у текста: **оно не проходит
 * обезличивание и пройти не может.** Промпт проходит анонимизатор, и расписка
 * удостоверяет, что в выводе не осталось исходных имён (§8.3, §12.1л). Фамилии
 * проектировщиков в штампе чертежа — растр; заменить их нечем, а «обезличенный
 * запрос с необезличенной картинкой» — это обезличивание наполовину, то есть
 * его отсутствие с видом наличия.
 *
 * Правило, спрятанное условием внутри семисотстрочной сборки, проверяется
 * только через полный запуск. Здесь оно проверяется само.
 *
 * ПРИЗНАК — АДРЕС, А НЕ РЕЖИМ И НЕ ИМЯ ПРОВАЙДЕРА
 *
 * Режим сборки (`development`) ничего не говорит о том, куда уйдёт запрос: на
 * разработке endpoint бывает и внешним. Имя провайдера тем более: его пишет
 * человек в переменной среды. Адрес — единственное, что проверяемо строкой.
 *
 * НО АДРЕС ОТВЕЧАЕТ НЕ НА ТОТ ВОПРОС, НА КОТОРЫЙ ЗДЕСЬ ОТВЕЧАЛИ.
 *
 * Здесь стояло: локальный адрес → «модель локальна: листы не покидают машину».
 * Это неправда, и обнаружилось на собственном контуре: `127.0.0.1:8317` —
 * ПРОКСИ, за которым тридцать две внешние модели. Листы уходили наружу, а
 * журнал §12.1л записывал, что они остались на машине. Утверждение о границе
 * данных, сделанное по адресу, границу не проверяет: локальный адрес говорит
 * только о том, что первый узел — свой.
 *
 * Поэтому локальный адрес больше НЕ РАЗРЕШАЕТ сам по себе. Он снимает
 * требование согласия только там, где владелец объявил контур замкнутым
 * (`STROYINTELLECT_LOCAL_MODEL`), — то есть подтвердил то, чего код знать не
 * может. Во всех остальных случаях решает явное согласие.
 *
 * FAIL CLOSED: по умолчанию листы не уходят. Владелец вправе снять запрет
 * явным согласием — но именно явным, и оно видно в окружении.
 */

/** Локальные адреса, при которых данные не покидают машину. */
const LOCAL = /^https?:\/\/(127\.0\.0\.1|localhost|\[::1\]|0\.0\.0\.0)(:|\/|$)/i;

/** Переменная явного согласия владельца отправлять листы наружу. */
export const VISION_EXTERNAL = "STROYINTELLECT_VISION_EXTERNAL";

/**
 * Владелец объявил, что за локальным адресом стоит МОДЕЛЬ, а не прокси.
 *
 * Код этого не проверит: `127.0.0.1:8317` выглядит одинаково у llama.cpp и у
 * шлюза к Gemini. Утверждение о замкнутости контура делает человек и отвечает
 * за него — здесь оно только записывается, чтобы журнал §12.1л не выдавал
 * догадку за факт.
 */
export const LOCAL_MODEL = "STROYINTELLECT_LOCAL_MODEL";

export interface VisionDecision {
  readonly allowed: boolean;
  /** Почему — словами. Отказ без причины неотличим от неработающей функции. */
  readonly reason: string;
}

export function visionPolicy(
  baseUrl: string | undefined,
  env: Readonly<Record<string, string | undefined>>,
): VisionDecision {
  if (baseUrl === undefined || baseUrl === "") {
    return { allowed: false, reason: "адрес модели не задан: отправлять листы некуда" };
  }

  const местный = LOCAL.test(baseUrl);
  const замкнут = согласие(env[LOCAL_MODEL]);

  // Замкнутый контур: адрес локальный И владелец подтвердил, что за ним модель,
  // а не шлюз. Только тогда можно утверждать, что листы никуда не уходят.
  if (местный && замкнут) {
    return { allowed: true, reason: `модель внутри контура (${LOCAL_MODEL}): листы не покидают машину` };
  }

  if (согласие(env[VISION_EXTERNAL])) {
    return {
      allowed: true,
      reason:
        `владелец дал явное согласие (${VISION_EXTERNAL}): листы уходят на внешнюю модель НЕОБЕЗЛИЧЕННЫМИ` +
        (местный ? ` через локальный шлюз ${baseUrl}` : ""),
    };
  }

  // Локальный адрес без подтверждения — самый опасный случай: он ВЫГЛЯДИТ
  // безопасным. Отказ называет именно это, иначе человек будет искать ошибку
  // в конфигурации, а не читать про прокси.
  if (местный) {
    return {
      allowed: false,
      reason:
        `адрес локальный (${baseUrl}), но за ним может стоять шлюз к внешней модели — ` +
        `проверить это код не может. Изображение обезличиванию не подлежит: фамилии ` +
        `проектировщиков стоят в штампе чертежа растром (§8.3, §12.1л). ` +
        `Подтвердить замкнутый контур: ${LOCAL_MODEL}=да; разрешить отправку наружу: ${VISION_EXTERNAL}=да`,
    };
  }

  return {
    allowed: false,
    reason:
      `модель внешняя (${baseUrl}), а изображение обезличиванию не подлежит: ` +
      `фамилии проектировщиков стоят в штампе чертежа растром (§8.3, §12.1л). ` +
      `Схемы агенту не передаются. Снять запрет: ${VISION_EXTERNAL}=да`,
  };
}

/** «да» либо «yes» — и ничего больше: молчаливое согласие согласием не является. */
function согласие(value: string | undefined): boolean {
  const слово = (value ?? "").trim().toLowerCase();

  return слово === "да" || слово === "yes";
}

/**
 * Контур, который записывается в журнал §12.1л.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ ВЫБОРА МАРШРУТА
 *
 * Маршрут выбирается сопоставлением адреса с объявленными назначениями:
 * `127.0.0.1` попадает в `in-contour-model-route`, и журнал записывал
 * `contour: internal`. На собственном контуре это неправда — за адресом шлюз к
 * внешним моделям, — а поле `contour` и есть то, ради чего журнал существует:
 * §12.1л спрашивает, ЧТО ВЫШЛО за пределы контура.
 *
 * Проверка маршрута при этом остаётся на месте и не ослабляется: она сторожит,
 * чтобы внешний адрес не проехал под меткой «внутренний». Здесь решается
 * другое — что ЗАПИСАТЬ, и решает это объявление владельца, а не догадка по
 * адресу.
 *
 * Правило: «внутренний» — только там, где владелец подтвердил замкнутый контур
 * (`STROYINTELLECT_LOCAL_MODEL`). Во всех остальных случаях — «внешний»: если мы
 * не знаем, лучше записать более сильное утверждение, чем более удобное.
 */
export function declaredContour(
  routeContour: "internal" | "external" | undefined,
  env: Readonly<Record<string, string | undefined>>,
): "internal" | "external" {
  return routeContour === "internal" && согласие(env[LOCAL_MODEL]) ? "internal" : "external";
}
