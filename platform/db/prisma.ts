/**
 * Доступ к данным с обязательным контекстом арендатора (ADR-R-015).
 *
 * RLS в PostgreSQL пропускает строки только при выставленном
 * `stroyintellect.tenant_id`. Настройка живёт в транзакции, поэтому любой доступ
 * к арендуемым данным идёт ЧЕРЕЗ `withTenant`. Запрос без контекста не вернёт
 * ничего — это fail closed, а не удобство.
 *
 * Первый рубеж изоляции — `PolicyDecisionPoint` в приложении; этот второй.
 */
import { PrismaPg } from "@prisma/adapter-pg";

/**
 * Размер пула соединений на клиента.
 *
 * `pg` держит по умолчанию десять. Одиннадцать тестовых файлов, каждый со своим
 * клиентом, дают сто десять — при `max_connections = 100` у PostgreSQL. Отсюда
 * перемежающиеся падения набора: он был не «нестабилен от нехватки процессора»,
 * а на волосок за лимитом соединений, и попадание зависело от планировщика.
 *
 * Признак, по которому это отличается от нехватки процессора: время выполнения
 * тестов вырастало вчетверо (523 с против 124 с) — ожидание соединения, а не
 * счёт.
 */
function poolSize(): number {
  const declared = Number(process.env["DATABASE_POOL_MAX"]);

  return Number.isFinite(declared) && declared > 0 ? declared : 10;
}
import { PrismaClient } from "@prisma/client";

export type Db = PrismaClient;

/**
 * Транзакция в контексте арендатора. Берём тип, который генерирует Prisma:
 * ручное описание формы клиента расходится с генерируемым при первом же
 * изменении схемы и превращает типобезопасность в её видимость.
 */
export type Tx = Parameters<Parameters<PrismaClient["$transaction"]>[0]>[0];

/**
 * Создаёт НОВЫЙ клиент. Нужен там, где соединение не должно быть общим:
 * два тестовых файла с общим синглтоном и своими `disconnect()` рвут
 * соединение друг другу, если попадают в один воркер.
 */
export function createPrismaClient(
  connectionString = process.env.DATABASE_URL,
  options: { readonly poolMax?: number } = {},
): PrismaClient {
  if (connectionString === undefined || connectionString === "") {
    throw new Error("DATABASE_URL не задан: подключение к базе невозможно");
  }

  return new PrismaClient({
    adapter: new PrismaPg({ connectionString, max: options.poolMax ?? poolSize() }),
  });
}

/**
 * Клиент ПОД ПРОДЛЕНИЕ АРЕНДЫ задачи — отдельный от рабочего.
 *
 * НАЙДЕНО В ЖУРНАЛЕ ЖИВЫХ ПРОГОНОВ: «продление аренды не удалось — Unable to
 * start a transaction in the given time» при каждой проверке объекта.
 *
 * КОРЕНЬ УСТАНОВЛЕН ОПЫТОМ, А НЕ ДОГАДКОЙ, и он не в размере пула.
 *
 * Разбор книг и рендер листов — СИНХРОННАЯ работа: она блокирует цикл событий
 * на секунды. Транзакция, успевшая занять соединение до блокировки, не может
 * завершиться, пока цикл занят, — и держит соединение всё это время. Замерено
 * на сервере: при блокировке на 15 с транзакция закрылась через 15 007 мс.
 *
 * Дальше арифметика простая: пока цикл заблокирован, таймеры продления
 * накапливаются и срабатывают залпом, а соединения ещё заняты предыдущими.
 * Пул любого размера можно так осушить; чем он меньше, тем вернее.
 *
 * ПОЭТОМУ ЗДЕСЬ ПЯТЬ, А НЕ ДВА. Сначала было два — по рассуждению «продление
 * идёт по одному за раз». Рассуждение верно для нормального цикла и неверно для
 * заблокированного: тика может ждать сразу несколько. Два соединения делали
 * голодание вероятнее, а не безопаснее.
 *
 * ЧЕГО ЭТО НЕ ЛЕЧИТ — И ЭТО ИЗМЕРЕНО, а не предположено.
 *
 * После подъёма пула до пяти неудача осталась ровно одна за прогон, и
 * самоописывающее сообщение назвало её природу: «после 21 939 мс ожидания» —
 * при бюджете 12 000 мс.
 *
 * Двадцать две секунды на попытку с бюджетом двенадцать возможны только так:
 * таймер сработал, цикл заблокировался разбором, и бюджет ожидания истёк ещё
 * до того, как попытка получила управление. Отсчёт `maxWait` идёт по стенным
 * часам и блокировку не переживает.
 *
 * ЗНАЧИТ НИ ПУЛ, НИ БЮДЖЕТ ЭТОГО НЕ РЕШАЮТ. Пока цикл заблокирован на десяток
 * секунд, один тик продления теряется — и вернуть его можно только тем, чтобы
 * разбор не блокировал поток. Это отдельная работа.
 *
 * Безопасность при этом держится НЕ на пуле и НЕ на бюджете, а на учёте аренды
 * (`LeaseWatch`) и остановке обхода: пропущенный тик при периоде 20 с и сроке
 * 60 с оставляет две попытки в запасе, а настоящая потеря прекращает работу.
 * Замерено на трёх прогонах: потерь ноль, пропуск по одному за прогон.
 */
export function createLeaseClient(connectionString = process.env.DATABASE_URL): PrismaClient {
  return createPrismaClient(connectionString, { poolMax: 5 });
}

let client: PrismaClient | undefined;

export function prisma(connectionString = process.env.DATABASE_URL): PrismaClient {
  if (client === undefined) {
    if (connectionString === undefined || connectionString === "") {
      throw new Error("DATABASE_URL не задан: подключение к базе невозможно");
    }
    client = new PrismaClient({ adapter: new PrismaPg({ connectionString, max: poolSize() }) });
  }

  return client;
}

export async function disconnect(): Promise<void> {
  await client?.$disconnect();
  client = undefined;
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Выполняет работу в транзакции с выставленным контекстом арендатора.
 *
 * `set_config(..., true)` делает настройку локальной для транзакции: она не
 * протекает в соседние запросы пула соединений.
 */
export async function withTenant<T>(
  db: PrismaClient,
  tenantId: string,
  work: (tx: Tx) => Promise<T>,
  options: { readonly maxWaitMs?: number; readonly timeoutMs?: number } = {},
): Promise<T> {
  if (!UUID.test(tenantId)) {
    throw new Error(`Некорректный идентификатор арендатора: ${JSON.stringify(tenantId)}`);
  }

  return db.$transaction(
    async (tx) => {
      await tx.$executeRawUnsafe("SELECT set_config('stroyintellect.tenant_id', $1, true)", tenantId);
      return work(tx);
    },
    {
      ...(options.maxWaitMs === undefined ? {} : { maxWait: options.maxWaitMs }),
      ...(options.timeoutMs === undefined ? {} : { timeout: options.timeoutMs }),
    },
  );
}

/**
 * СКОЛЬКО ПРОДЛЕНИЕ АРЕНДЫ ЖДЁТ НАЧАЛА ТРАНЗАКЦИИ.
 *
 * Умолчание Prisma — две секунды, и оно оказалось слишком тесным. Замерено на
 * сервере: при проверке объекта продление срывалось «Unable to start a
 * transaction in the given time» примерно на сорок пятой секунде прогона —
 * ровно тогда, когда обход разбирает двадцать четыре файла и пишет в ту же
 * базу.
 *
 * ПРОВЕРЕНО, ЧЕГО ПРИЧИНОЙ НЕ БЫЛО. Отдельный пул под аренду её не убрал.
 * Блокировка цикла событий тоже не виновата: опыт на сервере показал, что
 * транзакция открывается даже после шести секунд синхронной блокировки.
 * Соединений при этом занято семь из ста — то есть не исчерпание пула, а
 * задержка самой базы под нагрузкой.
 *
 * Двенадцать секунд — это МЕНЬШЕ периода продления (двадцать секунд), поэтому
 * попытки не наслаиваются, и НАМНОГО меньше срока аренды (шестьдесят): даже
 * ожидание на весь бюджет оставляет две попытки в запасе. Продление, которое
 * подождало и прошло, лучше продления, которое сдалось и напугало журнал.
 */
export const LEASE_TRANSACTION_MAX_WAIT_MS = 12_000;

/**
 * Административный доступ без контекста арендатора — только для миграций,
 * обслуживания и создания самого арендатора. Использовать осознанно.
 */
export async function asPlatform<T>(db: PrismaClient, work: (tx: PrismaClient) => Promise<T>): Promise<T> {
  return work(db);
}
