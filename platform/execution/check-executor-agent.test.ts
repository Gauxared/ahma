/**
 * Обзор сметчика в проверке из веба — ТЗ §5.1, §12.2, ADR-R-026.
 *
 * ЧТО ЭТИ ТЕСТЫ ЗАКРЫВАЮТ
 *
 * Порт обзора жил в `apps/cli`, и обзор умела делать только командная строка.
 * Воркер, выполняющий проверку из веба, до него не дотягивался и молча отдавал
 * результат без обзора: пользователь видел завершённую проверку, в которой не
 * было девяти агентов — то есть того, ради чего система и строится.
 *
 * ПОЧЕМУ ОТСУТСТВИЕ МОДЕЛИ — НЕ ОТКАЗ
 *
 * Детерминированная часть (§12.1а, §12.1б, сверка со сводным расчётом) работает
 * без модели и составляет гейт приёмки. Превратить её отсутствие в отказ значило
 * бы лишить пользователя того, что система умеет считать сама.
 *
 * НО И НЕ УМОЛЧАНИЕ
 *
 * «Проверка завершена» без обзора и «проверка завершена без обзора, потому что
 * модель не настроена» — разные утверждения, и первое из них неправда. Поэтому
 * недостающая способность ОБЪЯВЛЯЕТСЯ деградацией, а полнота артефакта
 * перестаёт быть `full`.
 */
import { describe, expect, it } from "vitest";

import { bootstrap } from "../bootstrap.js";

describe("наличие обзора решается наличием операции", () => {
  it("без настроенной модели операция обзора НЕ зарегистрирована", () => {
    const platform = bootstrap({ env: {} });

    expect(platform.operations.definition("run-estimate-review")).toBeUndefined();
  });

  it("с настроенной моделью операция обзора зарегистрирована", () => {
    // Проверка идёт по РЕЕСТРУ ОПЕРАЦИЙ, а не по переменным среды: исполнитель
    // не должен знать, из чего собрана платформа. Иначе появилось бы второе
    // место, решающее «есть ли модель», и оно разошлось бы с первым.
    const platform = bootstrap({
      env: {
        STROYINTELLECT_MODEL_BASE_URL: "https://api.anthropic.com/v1",
        STROYINTELLECT_MODEL_ID: "м-1",
        STROYINTELLECT_MODEL_API_KEY: "ключ",
      },
    });

    expect(platform.operations.definition("run-estimate-review")).toBeDefined();
  });

  it("сборка с моделью на локальном адресе тоже даёт обзор", () => {
    // Второй этап (ADR-R-020) — модель внутри контура. Обзор обязан работать и
    // там: иначе перевод на локальную модель отнял бы у системы главное.
    const platform = bootstrap({
      env: {
        STROYINTELLECT_MODEL_BASE_URL: "http://127.0.0.1:8317/v1",
        STROYINTELLECT_MODEL_ID: "м-1",
      },
    });

    expect(platform.operations.definition("run-estimate-review")).toBeDefined();
  });
});

describe("накопитель решений шлюза", () => {
  it("забирает записи, а не читает их", () => {
    // Запись, отданная дважды, попадёт в журнал дважды, и по нему нельзя будет
    // посчитать, сколько раз система ходила наружу.
    const platform = bootstrap({ env: {} });

    expect(platform.drainEgressLog()).toEqual([]);
    expect(platform.drainEgressLog()).toEqual([]);
  });
});
