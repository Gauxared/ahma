/**
 * УЧЁТ АРЕНДЫ — против защиты, которая молча перестала работать.
 *
 * НАЙДЕНО В ЖУРНАЛЕ ЖИВЫХ ПРОГОНОВ, а не набором.
 *
 * При каждой проверке объекта на сервере повторялось «продление аренды не
 * удалось — Unable to start a transaction in the given time». Строка писалась и
 * забывалась: воркер продолжал работу, считая аренду своей.
 *
 * Аренда — единственное, что мешает второму воркеру взять ту же проверку.
 * Комментарий в самом воркере помнит, чем это кончалось до её появления: «на
 * настоящем прогоне модель позвали шесть раз вместо одного». Продление и было
 * ответом. Перестав работать, оно не перестало печатать успокоительное.
 *
 * ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ — арифметика границы. Одна неудача не потеря: период
 * равен трети срока именно ради запаса. Потеря — это когда неудачи подряд
 * длятся дольше самого срока: запись в базе к тому моменту истекла, и `claim`
 * соседа забирает задачу условием `leaseExpiresAt <= now`.
 *
 * Ошибиться здесь можно в обе стороны, и обе дорогие: раньше времени — бросить
 * работу из-за сетевой икоты; позже — платить за модель дважды.
 */
import { describe, expect, it } from "vitest";

import { LeaseWatch } from "./lease-watch.js";

/** Те же числа, что у воркера: срок 60 с, продление каждые 20 с. */
function учёт(): LeaseWatch {
  return new LeaseWatch({ leaseSeconds: 60, everySeconds: 20 });
}

describe("учёт аренды задачи", () => {
  it("свежая аренда жива", () => {
    expect(учёт().состояние().kind).toBe("жива");
  });

  it("ОДНА неудача — ещё не потеря: период равен трети срока ради запаса", () => {
    const л = учёт();
    л.неудача("таймаут пула");

    expect(л.состояние().kind, "работу бросили из-за одной сетевой икоты").toBe("под вопросом");
    expect(л.причинаОстановки(), "обход остановлен раньше времени").toBeUndefined();
  });

  it("две неудачи подряд — всё ещё под вопросом, но названо числом", () => {
    const л = учёт();
    л.неудача("таймаут пула");
    л.неудача("таймаут пула");

    const состояние = л.состояние();
    expect(состояние.kind).toBe("под вопросом");
    expect(состояние.kind === "под вопросом" && состояние.reason).toContain("40 с из 60 с");
  });

  it("неудачи ДОЛЬШЕ СРОКА — аренда потеряна: в базе она уже истекла", () => {
    // Три попытки по двадцать секунд — это ровно шестьдесят: запись, которую
    // держал воркер, к этому моменту забирается условием `leaseExpiresAt <= now`.
    const л = учёт();
    л.неудача("таймаут пула");
    л.неудача("таймаут пула");
    л.неудача("таймаут пула");

    expect(л.состояние().kind, "воркер продолжит работу над чужой уже задачей").toBe("потеряна");
    expect(л.причинаОстановки()).toContain("60 с при сроке 60 с");
    expect(л.причинаОстановки()).toContain("3 неудач подряд");
  });

  it("удачное продление СБРАСЫВАЕТ счёт", () => {
    // Иначе редкие одиночные неудачи за час работы накопились бы в ложную
    // потерю, и прогон бросали бы на ровном месте.
    const л = учёт();
    л.неудача("таймаут");
    л.неудача("таймаут");
    л.подтверждена();
    л.неудача("таймаут");

    expect(л.состояние().kind).toBe("под вопросом");
    expect(л.безПодтвержденияСекунд).toBe(20);
  });

  it("«задачу ведёт другой» — потеря СРАЗУ, без счёта попыток", () => {
    /**
     * Это не подозрение, а ответ базы: строка обновилась нулём, потому что
     * `leaseOwner` уже не наш. Ждать после такого нечего — ждать значит
     * работать над задачей, которую в эту секунду делает кто-то ещё.
     */
    const л = учёт();
    л.отобрана();

    expect(л.состояние().kind).toBe("потеряна");
    expect(л.причинаОстановки()).toContain("другой воркер");
  });

  it("отобранную аренду не возвращает удачное продление", () => {
    // Ответ «не твоя» окончателен: если задачу успели переотдать, следующее
    // продление могло бы пройти уже по чужой строке.
    const л = учёт();
    л.отобрана();
    л.подтверждена();

    expect(л.состояние().kind, "потеря отменена успешным продлением").toBe("потеряна");
  });

  it("бессмысленные сроки отвергаются при создании", () => {
    // Период больше срока означает, что первая же неудача — уже потеря, а
    // нулевой срок делает потерянной даже свежую аренду.
    expect(() => new LeaseWatch({ leaseSeconds: 0, everySeconds: 20 })).toThrow(/положительными/u);
    expect(() => new LeaseWatch({ leaseSeconds: 60, everySeconds: 0 })).toThrow(/положительными/u);
  });

  it("длительность попытки попадает в сообщение", () => {
    /**
     * ЗАМЕРЕНО НА СЕРВЕРЕ: с бюджетом ожидания 2 с отказ приходил через 2003 мс,
     * с 12 с — через 12 009 мс. По одному этому числу видно, ждала попытка
     * своего бюджета (занят пул) или упала сразу (причина другая).
     *
     * Без числа два разных дефекта выглядят одной строкой; на их различение
     * ушло два живых прогона.
     */
    const л = учёт();
    л.неудача("Unable to start a transaction", 12009);

    const состояние = л.состояние();
    expect(состояние.kind === "под вопросом" && состояние.reason).toContain("12009 мс");
  });

  it("без длительности сообщение остаётся собой", () => {
    // Не всякая неудача измерима: ответ «не твоя задача» приходит без ожидания.
    const л = учёт();
    л.неудача("сеть недоступна");

    const состояние = л.состояние();
    expect(состояние.kind === "под вопросом" && состояние.reason).toContain("сеть недоступна");
    expect(состояние.kind === "под вопросом" && состояние.reason).not.toContain("мс ожидания");
  });
});
