/**
 * Тесты написаны до реализации. Анонимизация и маскирование — ТЗ §8.3, §11,
 * §12.1л, ADR-R-017.
 *
 * ЧТО ЭТО ЗАКРЫВАЕТ
 *
 * Egress-шлюз (О-67) требует обезличивания перед выходом наружу, но принимает
 * его как УТВЕРЖДЕНИЕ вызывающего: `anonymized: true`. Расписка, а не факт.
 * Здесь она становится фактом: флаг не пишут руками, его выдаёт анонимизатор,
 * и выдаёт только после проверки собственного вывода.
 *
 * ГЛАВНОЕ РЕШЕНИЕ: ЗАМЕНА, А НЕ УДАЛЕНИЕ
 *
 * Модель возвращает замечания, ссылающиеся на участников: «подрядчик завысил
 * объём в позиции 14». Вырезав название, мы получим замечание, которое не к
 * кому отнести. Поэтому имена ЗАМЕЩАЮТСЯ устойчивыми псевдонимами, а карта
 * замен остаётся внутри контура и разворачивается обратно на входе отчёта.
 *
 * ГЛАВНАЯ ОПАСНОСТЬ: СПРЯТАТЬ СЛИШКОМ МНОГО
 *
 * «Устройство подстилающего слоя из щебня» — не сведения о заказчике, а сам
 * предмет проверки. Анонимизатор, замещающий и это, выполнит §11 и уничтожит
 * §5.2: наружу уйдёт текст, по которому нельзя ничего проверить. Отказ был бы
 * честнее такого «успеха», поэтому тексты работ проверяются на неприкосновенность
 * отдельно.
 *
 * ГЛАВНАЯ ЛОВУШКА РУССКОГО ЯЗЫКА: СКЛОНЕНИЕ
 *
 * `text.replaceAll("Оргэнергострой", "Подрядчик-1")` выглядит работающим и
 * пропускает «договор с Оргэнергостроем», «письмо Оргэнергостроя». Пропущенное
 * название и есть утечка, а текст после замены выглядит обезличенным.
 *
 * ПОЧЕМУ АНОНИМИЗАТОР ПРОВЕРЯЕТ СВОЙ СОБСТВЕННЫЙ ВЫВОД
 *
 * Ошибка здесь не видна: пропущенное имя не отличается от текста, где имени и
 * не было. Поэтому после замены вывод перечитывается заново, и остаток
 * останавливает отправку. Это единственный способ отличить «обезличено» от
 * «похоже на обезличенное».
 */
import { describe, expect, it } from "vitest";

import { anonymize, restore } from "./anonymizer.js";

/** Настоящие названия из корпуса заказчика: reference-system/*.xlsx. */
const ИЗВЕСТНЫЕ = ["АО «Оргэнергострой»", "АО «МОДЦ»", "ПАО «АПРИ»"];

function обезличить(text: string, known: readonly string[] = ИЗВЕСТНЫЕ) {
  return anonymize({ text, knownEntities: known, salt: "прогон-1" });
}

describe("замещение известных названий", () => {
  it("замещает название псевдонимом, а не вырезает его", () => {
    const { text } = обезличить("Смету представило АО «Оргэнергострой».");

    expect(text).not.toContain("Оргэнергострой");
    // Замечание модели должно быть к кому отнести — иначе отчёт бесполезен.
    expect(text).toMatch(/Организация-\d/u);
  });

  it("одно и то же название получает ОДИН псевдоним по всему тексту", () => {
    // Иначе модель не сможет рассуждать: «тот же подрядчик в позиции 14 и 22»
    // превратится в двух разных участников.
    const { text } = обезличить(
      "АО «Оргэнергострой» подал смету. Позже АО «Оргэнергострой» её уточнил.",
    );

    const псевдонимы = new Set([...text.matchAll(/Организация-\d+/gu)].map((m) => m[0]));

    expect(псевдонимы.size).toBe(1);
    expect([...text.matchAll(/Организация-\d+/gu)]).toHaveLength(2);
  });

  it("РАЗНЫЕ названия получают разные псевдонимы", () => {
    const { text } = обезличить("АО «Оргэнергострой» и АО «МОДЦ» разошлись в цене.");

    const псевдонимы = new Set([...text.matchAll(/Организация-\d+/gu)].map((m) => m[0]));

    expect(псевдонимы.size).toBe(2);
  });

  it("НАХОДИТ название в косвенном падеже", () => {
    // `replaceAll` пропустил бы это, и текст выглядел бы обезличенным.
    const { text } = обезличить("Договор заключён с Оргэнергостроем в мае.");

    expect(text.toLowerCase()).not.toContain("оргэнергостро");
  });

  it("НАХОДИТ название в родительном падеже", () => {
    const { text } = обезличить("Письмо Оргэнергостроя от 12 мая.");

    expect(text.toLowerCase()).not.toContain("оргэнергостро");
  });

  it("НАХОДИТ название, написанное прописными", () => {
    const { text } = обезличить("ПОДРЯДЧИК: ОРГЭНЕРГОСТРОЙ");

    expect(text.toLowerCase()).not.toContain("оргэнергостро");
  });

  it("НАХОДИТ название без организационной формы и кавычек", () => {
    const { text } = обезличить("Смету проверял Оргэнергострой.");

    expect(text.toLowerCase()).not.toContain("оргэнергостро");
  });
});

describe("сеть для того, что не объявлено", () => {
  it("замещает ИНН", () => {
    // Настоящий из корпуса: reference-system/Опорная_база_Генподряд_РФ_v1.xlsx.
    const { text } = обезличить("ИНН 5024185328", []);

    expect(text).not.toContain("5024185328");
  });

  it("замещает ОГРН, КПП и адрес почты", () => {
    const { text } = обезличить(
      "ОГРН 1027700132195, КПП 502401001, почта smeta@подрядчик.рф",
      [],
    );

    expect(text).not.toContain("1027700132195");
    expect(text).not.toContain("502401001");
    expect(text).not.toContain("smeta@");
  });

  it("замещает организацию в кавычках, даже если она не объявлена", () => {
    // Словарь полон для того, что система знает. Для остального нужна сеть:
    // название подрядчика может впервые встретиться в самом документе.
    const { text } = обезличить("Субподряд отдан ООО «Незнакомец».", []);

    expect(text).not.toContain("Незнакомец");
  });
});

describe("род псевдонима", () => {
  it("объект замещается «Объектом», а не «Организацией»", () => {
    // Первая редакция называла всё «Организация-N», и код стройки «КРГ-1»
    // уходил к модели как компания. Модель рассуждала бы об участнике там, где
    // речь об объекте: псевдоним скрывает имя, но не должен подменять род.
    const { text } = anonymize({
      text: "Смета по объекту КРГ-1 от подрядчика АО «МОДЦ».",
      knownEntities: [{ value: "КРГ-1", kind: "Объект" }, "АО «МОДЦ»"],
      salt: "прогон-1",
    });

    expect(text).toMatch(/Объект-\d+/u);
    expect(text).toMatch(/Организация-\d+/u);
    expect(text).not.toContain("КРГ-1");
  });

  it("разворачивает псевдоним любого рода", () => {
    const исходный = "Объект КРГ-1 проверяет АО «МОДЦ».";
    const { text, map } = anonymize({
      text: исходный,
      knownEntities: [{ value: "КРГ-1", kind: "Объект" }, "АО «МОДЦ»"],
      salt: "прогон-1",
    });

    expect(restore(text, map)).toBe(исходный);
  });
});

describe("что НЕ должно быть тронуто", () => {
  it("сохраняет наименования работ", () => {
    // Это предмет проверки, а не сведения о заказчике. Спрятав его, мы выполним
    // §11 и уничтожим §5.2: проверять станет нечего.
    const исходный = "Устройство подстилающего слоя из щебня фракции 20-40";
    const { text } = обезличить(исходный);

    expect(text).toBe(исходный);
  });

  it("сохраняет числа, единицы и марки бетона", () => {
    const исходный = "Бетон B30 F150 W6 — 1110 м³ на 2 664 000 руб.";
    const { text } = обезличить(исходный);

    expect(text).toBe(исходный);
  });

  it("сохраняет обоснования по нормативным базам", () => {
    // ГЭСН и ФЕР — публичные шифры, а не сведения заказчика.
    const исходный = "ГЭСН 27-04-001-01, ФЕР 08-02-001-03";
    const { text } = обезличить(исходный);

    expect(text).toBe(исходный);
  });
});

describe("проверка собственного вывода", () => {
  it("выдаёт расписку, когда остатка нет", () => {
    const { receipt } = обезличить("АО «Оргэнергострой» подал смету.");

    expect(receipt.clean).toBe(true);
    expect(receipt.replacements).toBeGreaterThan(0);
  });

  it("ОТКАЗЫВАЕТ, если после замены осталось объявленное название", () => {
    // Пропущенное имя ничем не отличается от текста, где имени не было. Это
    // единственный способ отличить «обезличено» от «похоже на обезличенное».
    // Название с иным написанием: словарь его не поймает, сеть — тоже.
    const { receipt } = anonymize({
      text: "Подрядчик Орг-Энерго-Строй завысил объём.",
      knownEntities: ["Орг-Энерго-Строй"],
      salt: "прогон-1",
      // Имитируем пропуск: замена отключена, проверка вывода — нет.
      dryRun: true,
    });

    expect(receipt.clean).toBe(false);
    expect(receipt.leftovers.length).toBeGreaterThan(0);
  });

  it("расписку нельзя написать руками: она несёт отпечаток текста", () => {
    // Расписка относится к КОНКРЕТНОМУ тексту. Иначе её можно приложить
    // к любому — и §12.1л снова станет обещанием.
    const первый = обезличить("АО «МОДЦ» подал смету.");
    const второй = обезличить("АО «Оргэнергострой» подал смету.");

    expect(первый.receipt.outputDigest).not.toBe(второй.receipt.outputDigest);
  });
});

describe("возврат имён", () => {
  it("разворачивает псевдонимы обратно", () => {
    // Отчёт читает человек заказчика: «Организация-1 завысила объём» ему
    // бесполезно.
    const исходный = "АО «Оргэнергострой» и АО «МОДЦ» разошлись в цене.";
    const { text, map } = обезличить(исходный);

    expect(restore(text, map)).toBe(исходный);
  });

  it("разворачивает псевдоним в ответе модели, а не только в исходнике", () => {
    const { text, map } = обезличить("АО «Оргэнергострой» подал смету.");
    const псевдоним = text.match(/Организация-\d+/u)![0];

    const ответ = `${псевдоним} завысил объём в позиции 14 на 12%.`;

    expect(restore(ответ, map)).toBe("АО «Оргэнергострой» завысил объём в позиции 14 на 12%.");
  });

  it("повторное обезличивание не трогает уже поставленные псевдонимы", () => {
    // Иначе «Организация-1» превратится в «Организация-2» на втором проходе,
    // и карта перестанет разворачиваться.
    const первый = обезличить("АО «МОДЦ» подал смету.");
    const второй = anonymize({
      text: первый.text,
      knownEntities: ИЗВЕСТНЫЕ,
      salt: "прогон-1",
    });

    expect(второй.text).toBe(первый.text);
  });
});

describe("устойчивость псевдонимов между прогонами", () => {
  it("один и тот же прогон даёт одинаковые псевдонимы", () => {
    const a = обезличить("АО «МОДЦ» и АО «Оргэнергострой».");
    const b = обезличить("АО «МОДЦ» и АО «Оргэнергострой».");

    expect(a.text).toBe(b.text);
  });

  it("РАЗНЫЕ прогоны дают разные псевдонимы одному названию", () => {
    // Устойчивый между прогонами псевдоним позволил бы внешней стороне
    // сопоставлять обращения: «Организация-1» из марта и из мая — один и тот же
    // подрядчик, и по объёмам его можно узнать.
    const a = anonymize({ text: "АО «МОДЦ».", knownEntities: ИЗВЕСТНЫЕ, salt: "прогон-1" });
    const b = anonymize({ text: "АО «МОДЦ».", knownEntities: ИЗВЕСТНЫЕ, salt: "прогон-2" });

    expect(a.text).not.toBe(b.text);
  });
});
