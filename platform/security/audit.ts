/**
 * Журнал действий — ТЗ §5.5, §11, §12.1л.
 *
 * §5.5: «Журнал — записи о переданных документах и полученных результатах
 * (доступен администратору)». §11: глубина не менее 12 месяцев. §12.1л:
 * обращение к внешним моделям «подтверждается записями журнала».
 *
 * НЕИЗМЕНЯЕМОСТЬ ОБЕСПЕЧЕНА БАЗОЙ, А НЕ ЭТИМ МОДУЛЕМ
 *
 * У роли приложения отозваны UPDATE и DELETE, и сверх того стоят триггеры.
 * Здесь нет и не должно быть функций правки: их отсутствие — не защита, а
 * следствие. Защита в том, что даже написанный по ошибке UPDATE не пройдёт.
 *
 * ЗАПИСЬ НЕ ДОЛЖНА РОНЯТЬ ДЕЙСТВИЕ
 *
 * Спорный выбор, и он сделан осознанно. Если запись в журнал упала, а действие
 * состоялось, есть два плохих исхода: потерять запись либо отменить состоявшееся
 * действие. Для журнала ДЕЙСТВИЙ (а не согласий) второе хуже: пользователь
 * получает отказ на успешную операцию, а причина — в подсистеме, о которой он
 * не знает.
 *
 * Поэтому сбой записи не бросает исключение наружу, но и не проглатывается: он
 * возвращается вызывающему, и тот обязан о нём сообщить. Молчаливое «ок» здесь
 * было бы худшим вариантом из трёх.
 *
 * ЧТО НЕ ПОПАДАЕТ В ЖУРНАЛ
 *
 * Содержимое документов и значения полей. Журнал отвечает на вопрос «что
 * произошло», а не «что было в файле»: копия данных в журнале превращает его в
 * ещё одно хранилище тех же сведений, с теми же требованиями к защите и без
 * возможности их удалить по требованию.
 *
 * Вместо содержимого — хэш: он доказывает, что речь об этом самом документе, и
 * ничего не раскрывает.
 */
import type { Tx } from "@platform/db/prisma.js";

/**
 * Действия, которые журналируются.
 *
 * Перечень закрыт: новое действие добавляется осознанно, а не приходит
 * произвольной строкой из вызывающего кода. Иначе одно и то же событие
 * запишется тремя разными словами, и журнал перестанет искаться.
 */
export type AuditAction =
  | "session.started"
  | "session.ended"
  | "session.denied"
  | "document.received"
  /**
   * Заведение объекта, пользователя и арендатора — ТРИ разных действия.
   *
   * Одним «entity.created» их не покрыть: искать в журнале их будут порознь, и
   * вопросы к ним разные. «Кто завёл этот объект» — вопрос о работе; «кто выдал
   * этому человеку доступ» — вопрос о безопасности, и второй задают тогда,
   * когда уже что-то случилось.
   */
  | "object.created"
  | "user.created"
  | "tenant.created"
  | "check.started"
  | "check.finished"
  // Отмена — отдельное действие, а не «check.finished» с пометкой: завершённая
  // и отменённая Проверка различаются тем, есть ли результат, и в журнале их
  // будут искать порознь.
  | "check.cancelled"
  // Правка извлечённого значения и подпись человека под ним — ДВА действия, а
  // не одно с пометкой. Править и подтверждать могут разные люди, и спор с
  // подрядчиком идёт именно о том, кто что подписал (ADR-R-019).
  | "extraction.revised"
  | "extraction.confirmed"
  | "artifact.exported"
  | "model.called"
  // Недекларированный вызов наружу. Отдельное действие, а не «model.called» с
  // пометкой: заблокированный выход — это не обращение к модели, и искать его
  // в журнале будут отдельно (ТЗ §12.1л).
  | "egress.blocked"
  | "reference-base.loaded";

export interface AuditRecord {
  readonly action: AuditAction;
  readonly resourceKind: string;
  readonly resourceId?: string;
  /** Кто действовал. Отсутствует у событий до входа. */
  readonly actorId?: string;
  /** Почему — для действий, требующих объяснения (отказ, отмена). */
  readonly reason?: string;
  /** Хэш содержимого, но НЕ само содержимое. */
  readonly payloadHash?: string;
  readonly traceId?: string;
}

export type AuditOutcome =
  | { readonly written: true; readonly id: string }
  | { readonly written: false; readonly error: string };

/**
 * Пишет запись журнала.
 *
 * Возвращает исход, а не бросает: см. шапку. Вызывающий обязан сообщить о
 * неудаче — молчаливое «ок» здесь хуже и потери записи, и падения действия.
 */
export async function recordAudit(
  tx: Tx,
  tenantId: string,
  record: AuditRecord,
  at = new Date(),
): Promise<AuditOutcome> {
  try {
    const created = await tx.auditEvent.create({
      data: {
        tenantId,
        action: record.action,
        resourceKind: record.resourceKind,
        at,
        ...(record.resourceId === undefined ? {} : { resourceId: record.resourceId }),
        ...(record.actorId === undefined ? {} : { actorId: record.actorId }),
        ...(record.reason === undefined ? {} : { reason: record.reason }),
        ...(record.payloadHash === undefined ? {} : { payloadHash: record.payloadHash }),
        ...(record.traceId === undefined ? {} : { traceId: record.traceId }),
      },
    });

    return { written: true, id: created.id };
  } catch (cause) {
    return { written: false, error: (cause as Error).message };
  }
}

/**
 * Глубина хранения по §11.
 *
 * Число названо здесь, а не спрятано в задаче обслуживания: срок хранения —
 * требование договора, и оно должно читаться там, где о журнале говорят.
 */
export const RETENTION_MONTHS = 12;
