/**
 * Отбор чертёжных листов.
 *
 * ЧТО ЗДЕСЬ ЗАЩИЩАЕТСЯ
 *
 * Признак «лист графический» выведен ЗАМЕРОМ на курганской подшивке, а не
 * выбран: титульный лист и пояснительная записка дают 16–20 % строк короче
 * двенадцати знаков, структурная схема — 65 %, кабельный журнал — 91 %.
 * Порог 55 % разделяет их с запасом в обе стороны.
 *
 * Проверяется именно РАЗДЕЛЕНИЕ, а не «функция вернула массив»: если признак
 * перестанет различать текст и чертёж, агент получит три титульных листа —
 * то есть картинки без содержания за те же деньги.
 *
 * Рендер здесь не проверяется: он требует настоящего PDF и стоит секунд, а
 * его работоспособность замерена отдельно (1,3 с на лист, PNG около 300 КБ).
 */
import { describe, expect, it } from "vitest";

import { graphicPages } from "./design-sheets.js";

/** Лист-абзац: длинные строки, как в пояснительной записке. */
function текстовый(num: number, строк = 40): { text: string; num: number } {
  return {
    num,
    text: Array.from({ length: строк }, () => "Пояснительная записка описывает принятые решения подробно").join("\n"),
  };
}

/** Лист-чертёж: россыпь коротких подписей. */
function чертёжный(num: number, строк = 200): { text: string; num: number } {
  return { num, text: Array.from({ length: строк }, (_, index) => `ШК ${index % 9}.${index % 5}`).join("\n") };
}

describe("отбор чертёжных листов", () => {
  it("отделяет чертёж от пояснительной записки", () => {
    const выбрано = graphicPages([текстовый(1), чертёжный(2), текстовый(3)]);

    expect(выбрано.map((page) => page.page)).toEqual([2]);
  });

  it("плотные листы идут первыми", () => {
    // При потолке в три листа выбирать надо те, где подписей больше: пустой
    // лист с рамкой формально тоже «графический».
    const выбрано = graphicPages([чертёжный(5, 60), чертёжный(9, 800), чертёжный(7, 200)]);

    expect(выбрано.map((page) => page.page)).toEqual([9, 7, 5]);
  });

  it("почти пустой лист не считается чертежом", () => {
    // Рамка и штамп дают десяток коротких строк на любом листе подшивки.
    // Без порога по числу строк они прошли бы как чертёж.
    expect(graphicPages([чертёжный(4, 8)])).toEqual([]);
  });

  it("лист без текста вовсе не считается чертежом", () => {
    // Ноль строк даёт нулевую долю коротких, а не единицу: делить не на что.
    // Скан без текстового слоя сюда попасть не должен — его отвергает §14.
    expect(graphicPages([{ num: 1, text: "" }])).toEqual([]);
  });

  it("порог держит замеренную границу: 20 % — текст, 65 % — чертёж", () => {
    // Числа из замера курганской подшивки ЭОМ. Если порог поедет, поедет и
    // отбор, а поедет он молча — агент просто получит другие листы.
    const пятая = { num: 1, text: [...Array(20).fill("к"), ...Array(80).fill("длинная строка текста записки")].join("\n") };
    const две_трети = { num: 2, text: [...Array(65).fill("к"), ...Array(35).fill("длинная строка текста записки")].join("\n") };

    expect(graphicPages([пятая, две_трети]).map((page) => page.page)).toEqual([2]);
  });
});
