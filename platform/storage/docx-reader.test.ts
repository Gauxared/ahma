/**
 * Тесты идут по НАСТОЯЩИМ договорам генподряда из папки заказчика.
 *
 * Собранный в тесте docx доказывает, что библиотека вызвана правильно. Он не
 * доказывает главного: что из договора, который система будет читать в работе,
 * достаётся то, ради чего его читают, — существенные условия. А они в договорах
 * живут в ТАБЛИЦАХ: график платежей, размер гарантийного удержания, сроки
 * этапов. Извлечение, роняющее табличный текст, теряет ровно их и выглядит при
 * этом успешным.
 */
import { existsSync, readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

import { russianIncludes } from "@contracts/index.js";

import { DOCX_TEXT_MIN, readDocxText } from "./docx-reader.js";

const ДОГОВОР = "reference-system-new/Выход/АПРИ/Договора ГП/Проет договора генерального подряда 1.docx";

describe.skipIf(!existsSync(ДОГОВОР))("чтение настоящего договора генподряда", () => {
  it("достаёт текст договора", async () => {
    const итог = await readDocxText(readFileSync(ДОГОВОР));

    expect(итог.hasText).toBe(true);
    expect(итог.text.length).toBeGreaterThan(10_000);
  });

  it("достаёт существенные условия, ради которых договор читают", async () => {
    // Виктор ищет в договоре гарантию, пеню и порядок расчётов. Если хотя бы
    // одно из этих слов не доходит до текста, читать нечего.
    //
    // Поиск идёт ЧЕРЕЗ НОРМАЛИЗАЦИЮ: в этом договоре «расчет» встречается
    // 34 раза, а «расчёт» — ни разу, хотя буква ё в документе есть. Прямое
    // сравнение дало бы «условий о расчётах нет» — ответ, выглядящий как
    // результат работы.
    const итог = await readDocxText(readFileSync(ДОГОВОР));

    for (const условие of ["гарантийн", "неустойк", "расчёт", "срок"]) {
      expect(russianIncludes(итог.text, условие)).toBe(true);
    }
  });

  it("НАХОДКА: ответственность названа не тем словом, которое ищут", async () => {
    // Первая версия теста искала «пеня» — и не нашла. В этом договоре:
    //
    //   неустойка — 8 раз, штраф — 25, пени — 9, ПЕНЯ — 0.
    //
    // То есть слово, которым ответственность называют в обиходе и в ТЗ (§6.4
    // говорит «пеня от ключевой ставки»), в самом договоре не встречается ни
    // разу. Агент, ищущий «пеню», ответил бы «условий об ответственности нет» —
    // при девяти упоминаниях пеней и двадцати пяти штрафов.
    //
    // Нормализация написания эту разницу НЕ закрывает: это не ё против е, а
    // разные слова. Нужен словарь синонимов предметной области — работа M5,
    // где строится текстовый путь канонизации.
    //
    // Тест проверяет САМ ФАКТ на настоящем договоре, а не пересказывает его:
    // утверждение о собственных данных теста ничего не доказывало бы.
    const итог = await readDocxText(readFileSync(ДОГОВОР));

    expect(russianIncludes(итог.text, "пеня")).toBe(false);
    expect(russianIncludes(итог.text, "неустойк")).toBe(true);
    expect(russianIncludes(итог.text, "штраф")).toBe(true);
  });

  it("НЕ теряет табличный текст", async () => {
    // Существенные условия в договорах лежат в таблицах. Проверка идёт по
    // числовым значениям с процентами и рублями: вне таблиц они в договоре
    // почти не встречаются.
    const итог = await readDocxText(readFileSync(ДОГОВОР));

    expect(/\d+\s*%/.test(итог.text)).toBe(true);
  });
});

describe("порог пустоты", () => {
  it("не считает прочитанным документ короче порога", async () => {
    // Пустой docx — не ошибка чтения, но и не прочитанный документ. Разница
    // обязана быть видна вызывающему, иначе пустышка пройдёт как разобранная.
    const пустой = await readDocxText(await крошечныйDocx());

    expect(пустой.text.length).toBeLessThan(DOCX_TEXT_MIN);
    expect(пустой.hasText).toBe(false);
  });
});

/** Минимальный валидный docx: один абзац из одного символа. */
async function крошечныйDocx(): Promise<Buffer> {
  const { Document, Packer, Paragraph } = await import("docx");

  return Packer.toBuffer(new Document({ sections: [{ children: [new Paragraph("·")] }] }));
}
