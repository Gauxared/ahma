/**
 * Чтение текста из docx — ТЗ §8.1.
 *
 * Договоры, технические задания и протоколы приходят в Word, и агентам нужен их
 * ТЕКСТ, а не позиции: Виктор ищет в договоре условия по гарантии и пене,
 * Артемий — сроки и этапы. Это принципиально другой выход, чем у сметы, и
 * притворяться, что docx даёт позиции, нельзя.
 *
 * ТАБЛИЦЫ ИЗ ДОГОВОРА НЕ ТЕРЯЮТСЯ
 *
 * Существенные условия в договорах живут в таблицах — график платежей, размеры
 * гарантийного удержания, сроки этапов. Извлечение, роняющее табличный текст,
 * молча теряет ровно то, ради чего договор и читают. `mammoth` разворачивает
 * таблицы в текст, и это проверяется тестом, а не предполагается.
 */
import mammoth from "mammoth";

export interface DocxText {
  readonly text: string;
  /** Предупреждения библиотеки: неподдержанные элементы документа. */
  readonly warnings: readonly string[];
  /**
   * Есть ли содержательный текст. Пустой docx — не ошибка чтения, но и не
   * прочитанный документ: разница обязана быть видна вызывающему.
   */
  readonly hasText: boolean;
}

/** Ниже этого числа знаков документ считается пустым по существу. */
export const DOCX_TEXT_MIN = 20;

/**
 * Разметка → текст с СОХРАНЁННОЙ СТРУКТУРОЙ ТАБЛИЦ.
 *
 * Ячейка отделяется табуляцией, строка таблицы — переводом строки, таблица
 * очерчена рамкой. Всё прочее — абзацами, как и было.
 */
/** Строки таблицы по `<tr>`. */
export function* строкиТаблицы(тело: string): Generator<string> {
  for (const строка of тело.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/gu)) yield строка[1] ?? "";
}

function htmlToText(html: string): string {
  /** Внутренность ячейки: абзацы схлопываются в пробел, иначе строка порвётся. */
  const ячейка = (fragment: string): string =>
    fragment
      .replace(/<[^>]+>/gu, " ")
      .replace(/\s+/gu, " ")
      .trim();

  /**
   * ТАБЛИЦЫ — ОТДЕЛЬНЫМ ПРОХОДОМ, ДО ОБЩЕЙ ЗАМЕНЫ ТЕГОВ.
   *
   * Внутри ячейки лежит `<p>`, и общая замена «абзац → перевод строки» рвала
   * строку таблицы на части раньше, чем расставлялись табуляции. Поэтому
   * сначала каждая таблица целиком превращается в текст, и только потом
   * обрабатывается остальное.
   */
  const сТаблицами = html.replace(/<table[^>]*>([\s\S]*?)<\/table>/gu, (_, тело: string) => {
    const строки = [...строкиТаблицы(тело)].map((строка) =>
      [...строка.matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/gu)].map((cell) => ячейка(cell[1] ?? "")).join("\t"),
    );

    return `\n— таблица —\n${строки.filter((строка) => строка.trim() !== "").join("\n")}\n— конец таблицы —\n`;
  });

  return сТаблицами
    .replace(/<\/?(p|br|li|h[1-6])[^>]*>/gu, "\n")
    .replace(/<[^>]+>/gu, "")
    .replace(/&nbsp;/gu, " ")
    .replace(/&amp;/gu, "&")
    .replace(/&lt;/gu, "<")
    .replace(/&gt;/gu, ">")
    .replace(/&quot;/gu, '"')
    .replace(/[ \t]+\n/gu, "\n")
    .replace(/\n{3,}/gu, "\n\n")
    .trim();
}

/**
 * ТЕКСТ ДОКУМЕНТА WORD — ЧЕРЕЗ РАЗМЕТКУ, А НЕ СЫРЫМ ПОТОКОМ.
 *
 * ЗАМЕРЕНО НА КОМПЛЕКТЕ ЗАКАЗЧИКА 08.09.2026. `extractRawText` отдаёт ячейки
 * таблицы как отдельные абзацы, и строка ведомости объёмов превращается в
 * поток значений:
 *
 *   «Наименование видов работ ⏎ Ед, изм, ⏎ Количество ⏎ Ссылка на чертежи…»
 *
 * Колонка от колонки неотличима, строка от строки — тоже. В «Описании объекта
 * закупки» так лежит ведомость видов работ с графами «№ ЛСР», «Количество» и
 * «Формула расчёта»: количество одной работы читается как относящееся к
 * соседней. Для сметной проверки это худший вид потери — данные на месте, а
 * связь между ними утрачена, и ошибка выглядит как чужое число.
 *
 * Поэтому берём разметку и сами превращаем её в текст: ячейка — табуляция,
 * строка таблицы — перевод строки. Тот же приём, что у книг, где колонки
 * склеиваются табуляцией по той же причине.
 */
export async function readDocxText(bytes: Buffer): Promise<DocxText> {
  const html = await mammoth.convertToHtml({ buffer: bytes });
  let text = htmlToText(html.value);
  let warnings = html.messages.map((message) => message.message);

  // Разметка не вышла — остаётся сырой поток: он беднее, но это лучше пустоты.
  if (text.length < DOCX_TEXT_MIN) {
    const raw = await mammoth.extractRawText({ buffer: bytes });
    if (raw.value.trim().length > text.length) {
      text = raw.value.trim();
      warnings = raw.messages.map((message) => message.message);
    }
  }

  return { text, warnings, hasText: text.length >= DOCX_TEXT_MIN };
}
