/**
 * СМЕТА В ДОКУМЕНТЕ WORD ЧИТАЕТСЯ ЛИСТОМ — И ПОПАДАЕТ В ТОТ ЖЕ РАЗБОР.
 *
 * ЧТО БЫЛО. Реестр читателей листов знал четыре формата: `xlsx`, `xls`, `xlsb`,
 * `csv`. Смета, присланная документом Word, до разбора не доходила ФИЗИЧЕСКИ:
 * превратить её в лист было некому, и она уходила к роли текстом — без позиций,
 * без сходимости, без шифров и без координаты строки.
 *
 * Владелец 09.09.2026 назвал это прямо: «сметы — это не только эксель, но и
 * ворд, и не только те, где написано 421/пр».
 *
 * ПОЧЕМУ ЭТО РЕШАЕТСЯ ЧИТАТЕЛЕМ, А НЕ ВТОРЫМ ПАРСЕРОМ. Разбор сметы написан
 * НАД АБСТРАКЦИЕЙ ЛИСТА (`modules/documents/sheet.ts`), а не над Excel — так и
 * задумано: «одна абстракция — одна логика разбора на оба формата». Значит
 * достаточно построить лист из таблицы Word, и форма 421/пр разбирается тем же
 * кодом, теми же правилами шапки и теми же проверками сходимости.
 *
 * ГРАНИЦА ЧЕСТНОСТИ. Документ Word — это проза И таблицы вперемешку. Листом
 * становится САМАЯ КРУПНАЯ таблица документа: в сметном документе это и есть
 * смета, а проза вокруг неё (титул, подписи, примечания) читается текстом, как
 * и раньше. Если таблиц нет вовсе, читатель отвечает пустым листом — и разбор
 * скажет «формы 421/пр здесь нет», а не притворится, что прочитал.
 */
import { readFile } from "node:fs/promises";

import mammoth from "mammoth";

import type { Sheet } from "@modules/documents/sheet.js";

import { строкиТаблицы } from "./docx-reader.js";

/** Буква колонки по её номеру: 1 → A, 27 → AA. Как в книгах Excel. */
function буква(номер: number): string {
  let результат = "";
  let n = номер;

  while (n > 0) {
    const остаток = (n - 1) % 26;
    результат = String.fromCharCode(65 + остаток) + результат;
    n = Math.floor((n - остаток) / 26);
  }

  return результат;
}

/** Содержимое ячейки: разметка снята, пробелы сжаты. */
function ячейка(fragment: string): string {
  return fragment
    .replace(/<[^>]+>/gu, " ")
    .replace(/&nbsp;/gu, " ")
    .replace(/&amp;/gu, "&")
    .replace(/&lt;/gu, "<")
    .replace(/&gt;/gu, ">")
    .replace(/\s+/gu, " ")
    .trim();
}

/**
 * Таблицы документа — списком строк, каждая строка списком ячеек.
 *
 * Вложенные таблицы Word (ячейка, внутри которой таблица) здесь не
 * разворачиваются: в сметах они не встречаются, а разворот превратил бы одну
 * строку в несколько и сдвинул бы все последующие — то есть изменил бы суммы.
 */
function таблицыДокумента(html: string): readonly (readonly string[])[][] {
  const таблицы: (readonly string[])[][] = [];

  for (const таблица of html.matchAll(/<table[^>]*>([\s\S]*?)<\/table>/gu)) {
    const строки: (readonly string[])[] = [];

    for (const строка of строкиТаблицы(таблица[1] ?? "")) {
      const ячейки = [...строка.matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/gu)].map((cell) => ячейка(cell[1] ?? ""));
      if (ячейки.some((текст) => текст !== "")) строки.push(ячейки);
    }

    if (строки.length > 0) таблицы.push(строки);
  }

  return таблицы;
}

/**
 * Лист из документа Word: самая крупная его таблица.
 *
 * «Крупная» считается по числу ЯЧЕЕК, а не строк: у сметы граф семь и больше, а
 * у титульной таблички подписей — две колонки на десяток строк, и по строкам
 * она обошла бы смету.
 */
export async function readDocxSheet(path: string): Promise<Sheet> {
  const все = await readDocxSheets(path);

  const ячеек = (sheet: Sheet): number =>
    [...sheet.rows.values()].reduce((sum, строка) => sum + строка.size, 0);

  return все.reduce<Sheet>(
    (лучший, sheet) => (ячеек(sheet) > ячеек(лучший) ? sheet : лучший),
    { name: path.split("/").pop() ?? "документ Word", rows: new Map() },
  );
}

/**
 * ВСЕ ТАБЛИЦЫ ДОКУМЕНТА — ОТДЕЛЬНЫМИ ЛИСТАМИ.
 *
 * Крупнейшая таблица годится, когда смета в документе одна. В сметном
 * документе Word их бывает несколько — локальные расчёты по разделам подряд, —
 * и все, кроме самой большой, до разбора не доходили. Здесь они доходят все, а
 * выбирает между ними разбор: он видит, в какой из них есть позиции.
 */
export async function readDocxSheets(path: string): Promise<readonly Sheet[]> {
  const { value } = await mammoth.convertToHtml({ buffer: await readFile(path) });
  const таблицы = таблицыДокумента(value);
  const имя = path.split("/").pop() ?? "документ Word";

  if (таблицы.length === 0) return [{ name: имя, rows: new Map() }];

  return таблицы.map((таблица, номер) => {
    const rows = new Map<number, ReadonlyMap<string, string>>();

    таблица.forEach((строка, индекс) => {
      const ячейки = new Map<string, string>();
      строка.forEach((текст, колонка) => {
        if (текст !== "") ячейки.set(буква(колонка + 1), текст);
      });

      // Номер строки — с единицы, как в книге: по нему человек находит строку.
      if (ячейки.size > 0) rows.set(индекс + 1, ячейки);
    });

    return { name: таблицы.length === 1 ? имя : `${имя} · таблица ${номер + 1}`, rows };
  });
}
