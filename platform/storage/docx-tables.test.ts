/**
 * ТАБЛИЦА В ДОКУМЕНТЕ WORD СОХРАНЯЕТ КОЛОНКИ.
 *
 * ЧТО ТЕРЯЛОСЬ. `extractRawText` отдаёт каждую ячейку отдельным абзацем, и
 * строка ведомости превращается в поток значений: «Наименование ⏎ Ед.изм ⏎
 * Количество ⏎ Ссылка на чертежи». Колонка от колонки неотличима, строка от
 * строки — тоже.
 *
 * ЦЕНА ЭТОЙ ПОТЕРИ ВЫШЕ, ЧЕМ У ПРОПУЩЕННОГО ФАЙЛА. Данные на месте, а связь
 * между ними утрачена: количество одной работы читается как относящееся к
 * соседней, и ошибка выглядит не как пробел, а как ЧУЖОЕ ЧИСЛО. В «Описании
 * объекта закупки» комплекта «Дагестан дороги» так лежит ведомость видов работ
 * с графами «№ ЛСР», «Количество» и «Формула расчёта».
 */
import { describe, expect, it } from "vitest";
import { Document, Packer, Paragraph, Table, TableCell, TableRow, TextRun } from "docx";

import { readDocxText } from "./docx-reader.js";

/** Документ с ведомостью: шапка и строка с количеством. */
async function ведомость(): Promise<Buffer> {
  const строка = (ячейки: readonly string[]): TableRow =>
    new TableRow({
      children: ячейки.map(
        (текст) => new TableCell({ children: [new Paragraph({ children: [new TextRun(текст)] })] }),
      ),
    });

  const документ = new Document({
    sections: [
      {
        children: [
          new Paragraph({ children: [new TextRun("Ведомость объёмов работ по объекту капитального ремонта дороги")] }),
          new Table({
            rows: [
              строка(["№ п/п", "№ ЛСР", "Наименование видов работ", "Ед. изм.", "Количество"]),
              строка(["1", "02-01-01", "Устройство основания из щебня", "м2", "72359.55"]),
              строка(["2", "02-01-02", "Розлив вяжущих материалов", "т", "18.4"]),
            ],
          }),
        ],
      },
    ],
  });

  return Buffer.from(await Packer.toBuffer(документ));
}

describe("ведомость в документе Word", () => {
  it("строка таблицы остаётся строкой, а колонки — колонками", async () => {
    const { text } = await readDocxText(await ведомость());

    // Ключевое: количество стоит В ОДНОЙ СТРОКЕ со своей работой, а не абзацем
    // ниже, где его можно отнести к соседней.
    expect(text).toContain("Устройство основания из щебня\tм2\t72359.55");
    expect(text).toContain("Розлив вяжущих материалов\tт\t18.4");
  }, 60_000);

  it("шапка таблицы читается как шапка", async () => {
    const { text } = await readDocxText(await ведомость());

    expect(text).toContain("№ п/п\t№ ЛСР\tНаименование видов работ\tЕд. изм.\tКоличество");
    // Границы таблицы названы: без них читатель не отличит её от прозы.
    expect(text).toContain("— таблица —");
  }, 60_000);

  it("проза вокруг таблицы не склеивается с ней", async () => {
    const { text } = await readDocxText(await ведомость());

    expect(text).toContain("Ведомость объёмов работ по объекту капитального ремонта дороги");
  }, 60_000);
});
