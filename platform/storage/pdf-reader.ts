/**
 * Чтение текстового слоя PDF — ТЗ §8.1, роадмап M4 («PDF с текстовым слоем»).
 *
 * ТЕКСТОВЫЙ СЛОЙ ЛИБО ЕСТЬ, ЛИБО ФАЙЛ — СКАН
 *
 * §14 исключает распознавание из объёма. Различие проходит ровно здесь: PDF с
 * текстовым слоем читается, PDF без него — скан, и он отклоняется явным
 * статусом. Промежуточного «прочитали немножко» быть не должно: разбор скана
 * даёт ноль позиций, то есть результат, неотличимый от пустой сметы.
 *
 * ПОРОГ ЗАДАН, А НЕ ПОДРАЗУМЕВАЕТСЯ
 *
 * У сканов часто есть КРОХОТНЫЙ текстовый слой: колонтитул, добавленный при
 * печати, или подпись сканера. Проверка «текст непустой» пропустила бы такой
 * файл как читаемый. Поэтому порог назван числом и вынесен в константу —
 * решение видно, а не спрятано в условии.
 */
import { PDFParse } from "pdf-parse";

import { restoreShiftedCyrillic } from "@modules/documents/text-repair.js";

import { pdfLayoutText } from "./pdf-poppler.js";

/**
 * Ниже этого числа знаков на страницу текстовый слой считается служебным.
 *
 * Страница сметы или рабочей документации несёт сотни знаков. Колонтитул,
 * оставленный сканером, — десятки. Порог в 100 знаков на страницу разделяет
 * их с большим запасом в обе стороны: у курганских РД вышло около 3000.
 */
export const TEXT_LAYER_MIN_PER_PAGE = 100;

export interface PdfText {
  readonly text: string;
  readonly pages: number;
  /** Знаков текста на страницу — по этому числу отличают скан. */
  readonly charsPerPage: number;
  /** Есть ли содержательный текстовый слой. `false` — скан по §14. */
  readonly hasTextLayer: boolean;
}

/**
 * ТЕКСТ PDF. Если известен ПУТЬ и в системе есть poppler — читается с
 * СОХРАНЁННОЙ РАСКЛАДКОЙ КОЛОНОК.
 *
 * Замерено 09.09.2026 на локальном сметном расчёте: прежний путь отдавал по
 * одному значению на строку («1», «ГЭСН09-01-015-01», «м3», «0,2» порознь), и
 * понять, какое количество к какой работе, было нельзя. `pdftotext -layout`
 * сохраняет колонки, и строка сметы остаётся строкой.
 *
 * Путь необязателен: адаптер разбора получает байты и пути не знает. Без пути
 * работает прежний способ — он не стал хуже, он просто беднее.
 */
export async function readPdfText(bytes: Buffer, path?: string): Promise<PdfText> {
  const parser = new PDFParse({ data: bytes });

  try {
    const result = await parser.getText();
    const машинный = result.text.trim();
    const раскладкой = path === undefined ? undefined : await pdfLayoutText(path);

    /**
     * РАСКЛАДКА БЕРЁТСЯ, ТОЛЬКО ЕСЛИ ОНА НЕ БЕДНЕЕ ПРЕЖНЕГО.
     *
     * Poppler может отдать меньше на документе с необычной структурой, и
     * менять полный текст на урезанный ради красоты колонок нельзя: сначала
     * полнота, потом форма.
     */
    const выбранный = раскладкой !== undefined && раскладкой.trim().length >= машинный.length * 0.9
      ? раскладкой.trim()
      : машинный;

    /**
     * СБИТАЯ КОДИРОВКА ШРИФТА ЧИНИТСЯ ЗДЕСЬ — до того, как текст уйдёт кому бы
     * то ни было. Иначе роль читает «ɋɈɋɌȺȼ ɉɊɈȿɄɌɇɈɃ ȾɈɄɍɆȿɇɌȺɐɂɂ», а система
     * считает документ прочитанным: знаки пришли, длина большая. См.
     * `text-repair.ts` — там замер и доказательство сдвига.
     */
    const text = restoreShiftedCyrillic(выбранный);
    // Ноль страниц не даёт делить: у испорченного файла показатель на страницу
    // не определён, и приравнивать его нулю значит объявить файл сканом без
    // основания.
    const pages = Math.max(1, result.pages?.length ?? 1);
    const charsPerPage = Math.round(text.length / pages);

    return {
      text,
      pages,
      charsPerPage,
      hasTextLayer: charsPerPage >= TEXT_LAYER_MIN_PER_PAGE,
    };
  } finally {
    await parser.destroy();
  }
}
