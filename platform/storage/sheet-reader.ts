/**
 * Какой книгой читать файл — по СОДЕРЖИМОМУ, а не по расширению (веха Д1б).
 *
 * ЧТО ЭТО ЗАКРЫВАЕТ
 *
 * Единственное место, где обход превращал путь в лист, было записано так:
 * `sheet: await readXlsxSheet(path)`. То есть формат выбирался не по файлу, а
 * по тому, какую функцию однажды вписали в композиционный корень. Смета в
 * старом двоичном формате доходила до этой строки и падала внутри распаковщика
 * ZIP — «Can't find end of central directory», — а на экране становилась
 * документом «не разобран».
 *
 * Теперь читатель выбирается по формату, определённому по первым байтам, и
 * список читателей — ДАННЫЕ. Роадмап M4 требовал именно этого: «реестр с
 * определением типа по содержимому, а не `switch` по расширению».
 *
 * ПОЧЕМУ ЭТОТ РЕЕСТР ОТДЕЛЬНО ОТ `ParserRegistry`
 *
 * Они отвечают на разные вопросы, и сводить их в один значило бы получить
 * реестр, который на половину форматов возвращает не то, что у него просят.
 * Здесь вопрос «какой ЛИСТ у этой книги» — и ответ нужен смете. В
 * `ParserRegistry` вопрос «какой ТЕКСТ у этого документа» — и ответ нужен
 * договору и рабочей документации, вместе с границей §14 по сканам.
 *
 * Перечень «что вообще разбирается» собирается из ОБОИХ (`awaitingParser`), а
 * не пишется третьим литералом: литерал разошёлся бы с реальностью в тот день,
 * когда появится адаптер, и разошёлся бы молча.
 */
import { open as openFile, stat } from "node:fs/promises";

import { detectFormat, type DocumentFormat } from "@modules/documents/format-detector.js";
import type { Sheet } from "@modules/documents/sheet.js";

import { readCsvSheet } from "./csv-reader.js";
import { readDocxSheet, readDocxSheets } from "./docx-sheet-reader.js";
import { readPdfSheets } from "./pdf-sheet-reader.js";
import { readXlsSheet, readXlsSheets } from "./xls-reader.js";
import { readXlsxSheet, readXlsxSheets, type ReadOptions } from "./xlsx-reader.js";

/**
 * Сколько байтов читать для определения формата.
 *
 * То же число, что у обхода папки: подписи контейнеров лежат в начале файла, а
 * читать смету целиком, чтобы узнать, смета ли это, — лишняя работа на каждом
 * файле. Для крупной книги это ещё и вопрос памяти (веха Д5).
 */
const PROBE_BYTES = 8192;

/**
 * Потолок размера книги — веха Д5 плана демо.
 *
 * ЧИСЛО ВЫВЕДЕНО ИЗ ЗАМЕРА, А НЕ НАЗНАЧЕНО. §7 архитектурного документа:
 * книга Excel 39 МБ забирает 4,6 ГБ памяти и 94 секунды. Это ~118-кратное
 * раздувание: разбор держит в памяти и распакованный XML, и объектную модель
 * листа целиком.
 *
 * Воркер идёт с `--max-old-space-size=1024`. Значит книга крупнее восьми
 * мегабайт кладёт его сигналом 137 — то есть прогон исчезает, а причина
 * остаётся в журнале контейнера. Отказ С НАЗВАННОЙ ПРИЧИНОЙ на порядок лучше:
 * человек видит, какой файл и почему не прочитан, и остальные сметы объекта
 * при этом проверены.
 *
 * ПОТОЛОК — НЕ ОТКАЗ ОТ ЗАДАЧИ, А ОБЪЯВЛЕННАЯ ГРАНИЦА. Снимается он не
 * увеличением числа, а потоковым чтением (`exceljs` умеет `WorkbookReader`):
 * тогда память перестаёт зависеть от размера книги. До тех пор потолок честнее
 * молчаливого падения.
 */
export const SHEET_BYTES_LIMIT =
  /**
   * ПОТОЛОК ПОДНЯТ С 8 ДО 64 МБ (08.09.2026).
   *
   * Восемь мегабайт отсекали две книги корпуса заказчика целиком — не часть
   * содержимого, а книгу. Требование владельца: разбирать всё, что загружено.
   * Потолок остаётся сторожем против книги, которая действительно убьёт
   * процесс, но перестаёт быть барьером для обычного крупного файла.
   */
  Number.parseInt(process.env["STROYINTELLECT_SHEET_MAX_MB"] ?? "64", 10) * 1024 * 1024;

/** Форматы, у которых есть читатель книги. Данные, а не ветки кода. */
export const SHEET_READERS: Readonly<
  Partial<Record<DocumentFormat, (path: string, options?: ReadOptions) => Promise<Sheet>>>
> = {
  xlsx: readXlsxSheet,
  xls: readXlsSheet,
  /**
   * `.xlsb` читает тот же SheetJS, что и `.xls`: библиотека определяет формат
   * по содержимому сама. Отдельная строка здесь, а не общий читатель, потому
   * что реестр — это ОБЪЯВЛЕНИЕ поддержанных форматов: то, чего в нём нет,
   * система обязана назвать неразобранным, а не прочитать случайно.
   */
  xlsb: readXlsSheet,
  csv: readCsvSheet,
  /**
   * СМЕТА В ДОКУМЕНТЕ WORD — ТОЖЕ КНИГА.
   *
   * Реестр знал четыре формата, и смета, присланная документом Word, до разбора
   * не доходила ФИЗИЧЕСКИ: превратить её в лист было некому. Она уходила к роли
   * текстом — без позиций, без сходимости, без координаты строки.
   *
   * Разбор написан над абстракцией листа, а не над Excel, поэтому достаточно
   * читателя: форма 421/пр в Word разбирается тем же кодом и теми же правилами.
   * Документ без таблиц даст пустой лист, и разбор честно скажет, что формы
   * здесь нет.
   */
  docx: readDocxSheet,
};

/** Форматы книг, которые система умеет читать. Спрашивается, а не повторяется. */
export function parsableSheetFormats(): readonly DocumentFormat[] {
  return Object.keys(SHEET_READERS) as readonly DocumentFormat[];
}

/** Формат файла по первым байтам. Отдельно, потому что спрашивают дважды. */
export async function detectFileFormat(
  path: string,
  fileName?: string,
): Promise<ReturnType<typeof detectFormat>> {
  const handle = await openFile(path, "r");

  try {
    const buffer = Buffer.alloc(PROBE_BYTES);
    const { bytesRead } = await handle.read(buffer, 0, PROBE_BYTES, 0);

    return detectFormat({
      fileName: fileName ?? (path.split("/").pop() ?? path),
      bytes: buffer.subarray(0, bytesRead),
    });
  } finally {
    await handle.close();
  }
}

/**
 * Читает книгу тем читателем, который подходит её содержимому.
 *
 * Формат без читателя — отказ С НАЗВАННЫМ форматом, а не общая ошибка
 * распаковщика. Разница видна на экране: «выгрузка XML: читателя книги нет» и
 * «Can't find end of central directory» отвечают на разные вопросы, и второй не
 * отвечает ни на один.
 */
export async function readSheetOf(path: string, options: ReadOptions = {}): Promise<Sheet> {
  const { size } = await stat(path);

  // Потолок проверяется ДО открытия книги: смысл потолка в том, чтобы не
  // начинать работу, которая убьёт процесс на середине.
  if (size > SHEET_BYTES_LIMIT) {
    const мегабайты = (bytes: number): string => (bytes / 1024 / 1024).toFixed(1);

    throw new Error(
      `Книга ${path} размером ${мегабайты(size)} МБ превышает потолок разбора ` +
        `${мегабайты(SHEET_BYTES_LIMIT)} МБ: разбор держит в памяти около 118 объёмов файла ` +
        "(замер §7: 39 МБ → 4,6 ГБ), и воркер с потолком кучи 1 ГБ был бы убит на середине. " +
        "Потолок поднимается переменной STROYINTELLECT_SHEET_MAX_MB, но правильное решение — " +
        "потоковое чтение книги.",
    );
  }

  const detection = await detectFileFormat(path);
  const reader = SHEET_READERS[detection.format];

  if (reader === undefined) {
    throw new Error(
      `Файл ${path} не является книгой, которую система умеет читать: ` +
        `формат ${detection.format} (${detection.reason ?? detection.note}). ` +
        `Читаются: ${parsableSheetFormats().join(", ")}`,
    );
  }

  return reader(path, options);
}

/**
 * ВСЕ ЛИСТЫ ФАЙЛА, А НЕ ПЕРВЫЙ.
 *
 * ЧТО ЭТО ЗАКРЫВАЕТ. Разбор сметы получал `readSheetOf(path)` — то есть ЛИСТ
 * НОМЕР ОДИН. Книга, где первым идёт титул, расчёт индексов или пояснительная
 * записка, а смета лежит вторым листом, давала ноль позиций и объявлялась «не
 * сметой» — при живом разборе, который прочёл бы её без единой правки.
 *
 * Читатели множественного числа открывают контейнер ОДИН раз: чтение по листу
 * отдельным вызовом разбирало бы книгу столько раз, сколько в ней листов.
 *
 * Отказ читателя на одном формате не превращается в пустой список: сюда файл
 * доходит уже опознанным, и «читателя нет» обязано остаться ошибкой с
 * названным форматом, как в `readSheetOf`.
 */
export async function readSheetsOf(path: string, options: ReadOptions = {}): Promise<readonly Sheet[]> {
  const detection = await detectFileFormat(path);

  if (detection.format === "xlsx") return readXlsxSheets(path);
  if (detection.format === "xls" || detection.format === "xlsb") return readXlsSheets(path);
  if (detection.format === "docx") return readDocxSheets(path);

  /**
   * PDF ЧИТАЕТСЯ ЛИСТОМ, НО КНИГОЙ НЕ ЯВЛЯЕТСЯ. Его нет и не должно быть в
   * `SHEET_READERS`: тот список идёт в классификацию, и чертёж стал бы сметой.
   * Здесь спрашивают уже про КОНКРЕТНЫЙ файл — «есть ли в нём таблица», — и
   * ответ даёт содержимое (`pdf-sheet-reader.ts`), а не список форматов.
   */
  if (detection.format === "pdf") return readPdfSheets(path);

  return [await readSheetOf(path, options)];
}
