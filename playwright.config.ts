import { defineConfig, devices } from "@playwright/test";

/**
 * Сквозные наборы.
 *
 * РАБОТНИК ОДИН, И ЭТО ПРО ПАМЯТЬ, А НЕ ПРО СКОРОСТЬ
 *
 * Playwright по умолчанию берёт половину ядер. Сначала их урезали до двух:
 * узким местом был ОДИН сервер разработки на все браузеры, и при четырёх
 * работниках он не успевал отдавать страницы — наборы падали по таймауту клика,
 * то есть жаловались на интерфейс, а виновата была очередь к серверу.
 *
 * Теперь работник ОДИН, и повод серьёзнее. Замерено на машине владельца:
 * при двух работниках на два устройства одновременно живут четыре браузера,
 * сервер разработки к тому времени занимает несколько гигабайт, и суммарно
 * занятая память доходила до 24 из 31 ГБ. Дальше срабатывал убийца процессов —
 * контейнер базы был убит сигналом 137, — а несколько раз падала вся машина.
 *
 * НАБОР ИДЁТ ПРОТИВ СОБРАННОГО ПРИЛОЖЕНИЯ, А НЕ ПРОТИВ `next dev`
 *
 * Это главная правка ускорения, и она не про скорость, а про достоверность.
 * Сервер разработки собирает маршрут при ПЕРВОМ обращении — замерено до
 * тридцати секунд, ровно столько же, сколько таймаут теста. Отсюда весь класс
 * ложных красных: набор жаловался на интерфейс, а машина компилировала.
 * Он же пересобирается от любой правки файла на ходу, из-за чего действовало
 * правило «во время прогона E2E ничего не править», и он же однажды упал
 * посреди набора — восемь проверок получили `ERR_CONNECTION_REFUSED`.
 *
 * Сборка стоит 45 секунд один раз и снимает всё перечисленное. Она делается
 * ПЕРЕД запуском, а не отдельным шагом: собранное приложение, отставшее от
 * кода, — это молчаливое расхождение, а набор существует, чтобы таких не было.
 */
export default defineConfig({
  testDir: "./tests/e2e",
  workers: 1,
  use: {
    baseURL: "http://127.0.0.1:3000",
    trace: "retain-on-failure"
  },
  webServer: {
    command: "pnpm build:web && pnpm start:web",
    url: "http://127.0.0.1:3000",
    // Сборка идёт 45 секунд, и на холодной машине бывает дольше.
    timeout: 240_000,
    // Локально удобно переиспользовать уже поднятый сервер; в сборочном
    // конвейере (`CI`) он всегда поднимается заново, иначе набор проверил бы
    // не тот код.
    reuseExistingServer: process.env["CI"] === undefined
  },
  projects: [
    /**
     * Вход по одному разу на роль. Он же — гейт самой формы входа: не пройдёт
     * он, и остальные проекты не стартуют вовсе.
     */
    { name: "вход", testMatch: /auth\.setup\.ts/ },
    {
      name: "desktop-chromium",
      use: { ...devices["Desktop Chrome"] },
      dependencies: ["вход"]
    },
    {
      /**
       * МОБИЛЬНОЕ УСТРОЙСТВО — ТОЛЬКО ТАМ, ГДЕ ОНО ПРО РАСКЛАДКУ.
       *
       * Гоняли всё: 47 экранных проверок дублировались на Pixel 7 и удваивали
       * прогон. Но большинство из них про СОДЕРЖАНИЕ — что отказ назвал право,
       * что замечание несёт основание, что пакет отдаёт книгу, — и ширина
       * экрана к этому отношения не имеет: те же серверные компоненты, тот же
       * ответ.
       *
       * Мобильное остаётся там, где ширина решает: доступность (рельс на узком
       * экране — закрытая шторка), приёмы компоновки, адреса рельса и масштаб
       * 200 %. Ровно эти проверки на телефоне и ловили дефекты.
       */
      name: "mobile-chromium",
      use: { ...devices["Pixel 7"] },
      dependencies: ["вход"],
      grep: /доступность|приёмы компоновки|адреса рельса|масштаб 200/
    }
  ]
});
