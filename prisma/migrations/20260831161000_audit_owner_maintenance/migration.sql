-- Уточнение неизменяемости журнала: ПРИЛОЖЕНИЕ не может никогда, ВЛАДЕЛЕЦ
-- схемы может при обслуживании.
--
-- ЧТО ПОКАЗАЛ ТЕСТ
--
-- Первая версия триггера запрещала удаление всем и всегда — включая каскад при
-- удалении арендатора. То есть отключить клиента стало невозможно вовсе, а
-- чистка старше 12 месяцев (§11), про которую в той же миграции написано
-- «делает владелец схемы отдельной операцией», оказалась запрещена и владельцу.
--
-- Запрет, который нельзя снять законным способом, рано или поздно снимают
-- незаконным: отключают триггер руками и забывают вернуть. Лучше провести
-- границу сразу и назвать её.
--
-- ГРАНИЦА ПО РОЛИ, А НЕ ПО НАМЕРЕНИЮ
--
-- Роль приложения — та, под которой работает система и чьи действия журнал
-- фиксирует. Она не может изменить или удалить ни одной записи ни при каких
-- условиях. Владелец схемы — отдельный доступ; его операции обслуживания видны
-- в журнале самой базы.

CREATE OR REPLACE FUNCTION audit_event_immutable() RETURNS trigger AS $$
BEGIN
  IF current_user <> 'stroyintellect_app' THEN
    RETURN COALESCE(NEW, OLD);
  END IF;

  RAISE EXCEPTION
    'Журнал неизменяем: запись % нельзя ни изменить, ни удалить из приложения (ТЗ §5.5, §12.1л)',
    OLD.id;
END;
$$ LANGUAGE plpgsql;
