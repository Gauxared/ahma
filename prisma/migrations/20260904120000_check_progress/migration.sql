-- Ход прогона — веха Д2 плана демо: «показывать по мере готовности».
--
-- ЧТО БЫЛО. Прогон по семи файлам занимает 36 минут, и всё это время база не
-- знала о нём ничего: `checkObject` шёл в памяти воркера, а запись случалась
-- один раз в конце — один артефакт и статус `completed`. Статус самой Проверки
-- при этом оставался `queued` от постановки до конца: экран честно показывал
-- «в очереди» получаса работы, а упавший прогон оставался «в очереди» навсегда.
--
-- ЧТО ДОБАВЛЯЕТСЯ. Два разных вида записи, и смешивать их нельзя:
--
--  · `check.phase` + счётчики документов — СОСТОЯНИЕ: чем прогон занят сейчас.
--    Одна строка, перезаписывается, истории не ведёт;
--  · колонки `agent_run` — ФАКТ: агент высказался тогда-то и сказал вот это.
--    Строка на пару «агент + предмет», и она уже есть в схеме с самого начала,
--    только не заполнялась ни разу.
--
-- Замечания положены в `agent_run`, а НЕ частичными артефактами: артефакт —
-- канонический результат, и четыре экрана берут «свежий» (`take: 1`).
-- Промежуточные артефакты сделали бы свежим неполный.
--
-- Миграция ТОЛЬКО ДОБАВЛЯЕТ: существующие данные не трогаются. Политики RLS и
-- права на обе таблицы выданы ранее (`20260824180000_tenant_rls`) и на новые
-- колонки распространяются сами — новых таблиц здесь нет, а значит нет и той
-- дыры, которую даёт таблица, забытая политикой.

