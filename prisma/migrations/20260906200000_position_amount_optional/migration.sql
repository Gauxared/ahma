-- Сумма позиции может ОТСУТСТВОВАТЬ.
--
-- НАЙДЕНО НА ПАКЕТЕ ЗАКАЗЧИКА, а не выведено из модели.
--
-- Пакет «Устройство фундаментов линии 720» (Нижний Тагил): все десять ЛСР без
-- стоимостной части — шифры ГЭСН/ФСБЦ, наименования, единицы и объёмы есть,
-- денежные колонки пусты. Двести тридцать одна позиция, и ни одной суммы.
--
-- Пока колонка была NOT NULL, у разбора оставалось два выхода: подставить ноль
-- или выбросить позицию. Выбрасывалась позиция — объект показывался пустым,
-- «нечего проверять, смет 0». Ноль был бы хуже: он сложился бы в сходимости и
-- дал бы «расхождение 0 ₽» на смете, о стоимости которой не известно ничего.
--
-- NULL здесь означает «неизвестно» и НЕ означает «ноль» — инвариант ТЗ §9.
-- Существующие строки не трогаются: у них сумма есть, и она остаётся.
ALTER TABLE "position" ALTER COLUMN "amount" DROP NOT NULL;
