--
-- `knowledge_record.contentHash` уникален: это отпечаток самой записи
-- (ADR-R-027). Отпечаток КНИГИ, из которой загружены тысячи строк, туда не
-- помещается — вторая строка той же книги нарушила бы ограничение.
--
-- Без версии у источника приёмка Т12 «в находке видно, из какого источника и
-- какой версии взято» непроверяема: имя файла версией не является, книгу
-- перезаливают под тем же именем.
ALTER TABLE knowledge_source ADD COLUMN "contentHash" CHAR(64);
