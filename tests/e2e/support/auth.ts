/**
 * Вход в систему для сквозных наборов — ОДИН РАЗ НА РОЛЬ, а не на тест.
 *
 * ЧТО ЭТО ЗАКРЫВАЕТ
 *
 * Замер: в наборах 72 тела тестов и 72 вызова входа. На двух устройствах это
 * около ста сорока входов через форму за прогон — по пять секунд каждый, то
 * есть примерно двенадцать минут из тридцати восьми уходило на повторный ввод
 * одного и того же пароля.
 *
 * Теперь вход делается один раз на роль в проекте `вход`, состояние сессии
 * сохраняется файлом, а тесты подставляют его куки. Экономия — не единственная
 * польза: сто сорок последовательных входов создавали сто сорок сессий в базе и
 * держали сервер занятым тем, что к предмету проверки отношения не имеет.
 *
 * ЧТО ПРИ ЭТОМ НЕ ПОТЕРЯНО
 *
 * Сама форма входа остаётся проверенной: её проходит проект `вход` на каждом
 * прогоне (без него состояний не будет и весь набор не стартует), и отдельно —
 * наборы про отказ доступа, которые входят намеренно неверно.
 */
import { existsSync, readFileSync } from "node:fs";

import type { Page } from "@playwright/test";

export const TENANT = "apri";
export const USER = "user@apri.ru";
export const ADMIN = "admin@apri.ru";
export const PASSWORD = "демо-2026";

/** Куда проект `вход` кладёт состояние сессии каждой роли. */
export function stateFile(email: string): string {
  return `tests/e2e/.auth/${email.replace(/[^a-z]/gi, "-")}.json`;
}

/**
 * Настоящий вход через форму. Используется проектом `вход` и теми наборами,
 * которым важен сам вход, а не то, что за ним.
 */
export async function signInThroughForm(page: Page, email: string): Promise<void> {
  await page.goto("/login");
  await page.getByLabel("Организация").fill(TENANT);
  await page.getByLabel("Адрес").fill(email);
  await page.getByLabel("Пароль").fill(PASSWORD);
  await page.getByRole("button", { name: "Войти" }).click();
  // Вход ведёт на Пульт, а не в реестр: вошедший спрашивает «что требует
  // внимания», а не «какие у меня объекты».
  await page.waitForURL((url) => url.pathname === "/");
}

/**
 * Подставляет сохранённую сессию роли.
 *
 * Если состояния нет — вход делается формой. Это не молчаливый запасной путь:
 * набор, запущенный поштучно (`-g`), проекта `вход` не выполняет, и без этой
 * ветки он падал бы на пустом файле вместо того, чтобы проверить свой предмет.
 */
export async function signIn(page: Page, email: string): Promise<void> {
  const file = stateFile(email);

  if (!existsSync(file)) {
    await signInThroughForm(page, email);
    return;
  }

  // Тип берётся у самого Playwright: куки состояния — это то же, что принимает
  // `addCookies`, и объявлять их форму второй раз значило бы завести описание,
  // способное разойтись с библиотекой.
  type Cookies = Parameters<ReturnType<Page["context"]>["addCookies"]>[0];
  const state = JSON.parse(readFileSync(file, "utf8")) as { readonly cookies: Cookies };

  await page.context().addCookies(state.cookies);

  /**
   * Переход на Пульт обязателен, и это не формальность.
   *
   * Вход через форму заканчивался на Пульте, и наборы на это опирались:
   * половина из них сразу обращается к рельсу и шапке, не делая своего
   * перехода. Подстановка кук без перехода оставляет страницу пустой — и
   * четырнадцать проверок падали за сто пятьдесят миллисекунд, жалуясь на
   * отсутствующий рельс.
   *
   * То есть `signIn` был не только входом, но и началом пути. Замена входа
   * обязана сохранить оба свойства.
   */
  await page.goto("/");
}
