/**
 * Кто входит в демо-контур — ОТДЕЛЬНЫМ модулем, а не константой в скрипте.
 *
 * ПОЧЕМУ ОТДЕЛЬНО
 *
 * `demo-up.ts` выполняет наполнение при импорте (`void (async () => …)()`), и
 * тест, который захотел бы прочитать оттуда список арендаторов, ЗАПУСТИЛ БЫ
 * наполнение базы. Список нужен проверяемым без побочных действий, поэтому он
 * живёт здесь, а скрипт его читает.
 *
 * ДВА АРЕНДАТОРА, И РАЗНИЦА СУЩЕСТВЕННА
 *
 * `apri` — контур конкретного клиента, на нём держатся сквозные наборы
 * (`tests/e2e` входит как `apri`). Трогать его нельзя.
 *
 * `demo` — универсальный: организация называется просто «СтройИнтеллект», без
 * имени клиента, и один вход с полным набором прав. Он для показа: имя чужого
 * клиента на экране во время демонстрации отвечает не на тот вопрос, который
 * задают.
 *
 * ПОЧЕМУ У ДЕМО-ВХОДА ДВЕ РОЛИ, А НЕ ОДНА «СУПЕРАДМИН»
 *
 * Роли `user` и `admin` в `config/roles/apri.json` НЕ ПЕРЕСЕКАЮТСЯ: у админа нет
 * даже `check:read`, у пользователя нет `audit:read`. Их сумма — все права,
 * объявленные системой. Заводить третью роль «суперадмин» значило бы держать
 * список прав в двух местах: он разошёлся бы с первым при добавлении
 * одиннадцатого права.
 *
 * Что «сумма двух ролей» действительно равна всем правам, проверяет
 * `demo-tenants.test.ts` — иначе новое право молча понизило бы демо-вход.
 *
 * ОГОВОРКА: определения ролей грузятся из ОДНОГО файла (`loadRoles()` игнорирует
 * арендатора), то есть демо-арендатор пользуется набором ролей, названным по
 * клиенту. Это работает и не мешает, но по-хорошему набор ролей должен быть
 * общим, а не клиентским.
 */
export interface TenantSeed {
  readonly id: string;
  readonly slug: string;
  /** Как организация называется для человека. Показывается в шапке каркаса. */
  readonly displayName: string;
  readonly users: readonly {
    readonly email: string;
    readonly name: string;
    readonly password: string;
    readonly roles: readonly string[];
  }[];
}

