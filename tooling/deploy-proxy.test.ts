/**
 * ВЫХОД НАРУЖУ ЧЕРЕЗ ТУННЕЛЬ — против двух разных способов соврать о маршруте.
 *
 * НАЙДЕНО НА СЕРВЕРЕ, а не набором.
 *
 * openrouter.ai отвечает с адреса app.strintel.ru `403 Access denied by
 * security policy` при том же ключе, который с машины владельца даёт 200.
 * Блокирован адрес. На сервере стоит sing-box, и через его локальный вход
 * запрос проходит — значит выход к модели идёт ЧЕРЕЗ ТУННЕЛЬ.
 *
 * ЗДЕСЬ ПРОВЕРЯЮТСЯ ДВЕ ВЕЩИ, И ОБЕ ОБНАРУЖИВАЮТСЯ ПОЗЖЕ ВСЕГО.
 *
 * ПЕРВАЯ. `HTTPS_PROXY` сам по себе не действует: встроенный `fetch` (undici)
 * переменные среды не читает, пока не задан `NODE_USE_ENV_PROXY`. Настройка
 * выглядит применённой и не меняет ничего — ровно тот же род дефекта, что уже
 * стоил нам каталога документов (apps/web/lib/upload-root.test.ts). Отличие в
 * цене: там документы легли не туда, здесь КАЖДЫЙ вызов модели вернул бы 403,
 * а причина читалась бы как «провайдер недоступен».
 *
 * ВТОРАЯ, ХУЖЕ. Прокси в переменных среды — глобальный: он забирает ВЕСЬ
 * исходящий трафик процесса. Внутренний маршрут из model-routes.json объявлен
 * с назначениями в петле и частной сети, и весь его смысл в том, что данные НЕ
 * покидают контур. Уйдя в туннель, они покинули бы его через чужой хост —
 * контур перестал бы быть внутренним, ОСТАВАЯСЬ ТАК ОБЪЯВЛЕННЫМ. Это не сбой,
 * который увидишь: запросы продолжают работать, врёт только объявление.
 *
 * Поэтому список исключений сверяется не с самим собой, а С ОБЪЯВЛЕНИЕМ
 * МАРШРУТА: назначение, добавленное во внутренний контур и забытое в NO_PROXY,
 * останавливает сборку.
 */
import { readdirSync, readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

const ПОСТАВКА = new URL("../", import.meta.url);

function файл(путь: string): string {
  return readFileSync(new URL(путь, ПОСТАВКА), "utf8");
}

/** Значение переменной из файла окружения или из строки `Environment=` юнита. */
function значение(текст: string, имя: string): string | undefined {
  const строка = текст
    .split("\n")
    .map((s) => s.trim())
    // `Environment=` — форма systemd; без префикса — форма файла окружения.
    .map((s) => (s.startsWith("Environment=") ? s.slice("Environment=".length) : s))
    .filter((s) => !s.startsWith("#"))
    .find((s) => s.startsWith(`${имя}=`));

  return строка?.slice(имя.length + 1).trim();
}

/**
 * Юниты берутся ЧТЕНИЕМ КАТАЛОГА, а не перечислением. Список, набранный
 * руками, отстаёт от переименования: 10.09.2026 воркеры стали шаблонами
 * systemd (`…-worker@.service`), и этот набор упал на отсутствующем файле.
 * Упал — это лучший исход из двух; при `it.each` по пустому списку он бы
 * молча перестал проверять что-либо.
 *
 * Проверяются ВСЕ юниты поставки, включая стенд: воркер стенда ходит к модели
 * тем же кодом, и без переменной прокси там так же не действует.
 */
const ЮНИТЫ = readdirSync(new URL("deploy/", ПОСТАВКА))
  .filter((имя) => имя.endsWith(".service"))
  .map((имя) => `deploy/${имя}`)
  .sort();
const ОКРУЖЕНИЕ = ".env.deploy.example";

/** Назначения, объявленные для ВНУТРЕННЕГО контура. */
function назначенияВнутреннегоКонтура(): readonly string[] {
  const маршруты = JSON.parse(файл("config/extensions/model-routes.json")) as {
    extensions: readonly { contour: string; egress?: { destinations?: readonly string[] } }[];
  };

  return маршруты.extensions
    .filter((e) => e.contour === "internal")
    .flatMap((e) => e.egress?.destinations ?? []);
}

describe("выход к модели через туннель", () => {
  it.each(ЮНИТЫ)("%s включает чтение прокси из окружения", (юнит) => {
    // Иначе HTTPS_PROXY — объявление без действия: `fetch` уйдёт напрямую и
    // упрётся в тот самый 403, ради обхода которого туннель и заводили.
    expect(
      значение(файл(юнит), "NODE_USE_ENV_PROXY"),
      `${юнит}: без NODE_USE_ENV_PROXY встроенный fetch игнорирует HTTPS_PROXY`,
    ).toBe("1");
  });

  it("поставка ПРЕДЛАГАЕТ прокси — значит ворота выше не про запас", () => {
    // Если переменных в примере нет, требование к юнитам беспредметно. Тест
    // существует, пока туннель является частью поставки.
    const пример = файл(ОКРУЖЕНИЕ);
    expect(значение(пример, "HTTPS_PROXY"), "HTTPS_PROXY не объявлен в примере окружения").toBeDefined();
    expect(значение(пример, "NO_PROXY"), "NO_PROXY не объявлен в примере окружения").toBeDefined();
  });

  it("КАЖДОЕ назначение внутреннего контура исключено из туннеля", () => {
    /**
     * Главное правило файла. Внутренний маршрут не требует расписки об
     * обезличивании именно потому, что данные не покидают контур. Пустить его
     * через чужой хост значило бы отдать наружу необезличенное — и шлюз этого
     * не заметит: он проверяет объявленное назначение, а не то, каким путём
     * туда идут.
     */
    const исключения = (значение(файл(ОКРУЖЕНИЕ), "NO_PROXY") ?? "")
      .split(",")
      .map((s) => s.trim())
      .filter(Boolean);

    const назначения = назначенияВнутреннегоКонтура();
    expect(назначения.length, "внутренний маршрут не найден — проверять нечего").toBeGreaterThan(0);

    for (const назначение of назначения) {
      expect(
        исключения,
        `«${назначение}» объявлено внутренним контуром, но уйдёт в туннель через чужой хост`,
      ).toContain(назначение);
    }
  });

  it("адрес провайдера в туннель НЕ исключён", () => {
    // Обратная ошибка: вписать в NO_PROXY всё подряд «на всякий случай» и
    // оставить внешний вызов идти напрямую — туннель тогда стоит и не работает.
    const исключения = значение(файл(ОКРУЖЕНИЕ), "NO_PROXY") ?? "";
    for (const внешний of ["openrouter.ai", "api.openai.com", "api.anthropic.com"]) {
      expect(исключения, `${внешний} исключён из туннеля — выход наружу пойдёт напрямую`).not.toContain(внешний);
    }
  });
});
