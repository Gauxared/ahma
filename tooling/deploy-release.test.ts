/**
 * ВЫПУСК СО СБОРКОЙ РЯДОМ — против двух минут недоступности при каждом обновлении.
 *
 * НАЙДЕНО НА СЕРВЕРЕ, а не набором.
 *
 * `next build` переписывает `.next` на месте, а работающий процесс читает
 * оттуда же. Замерено 06.09.2026 на app.strintel.ru: каждое обновление роняло
 * живой сайт примерно на две минуты — «Invariant: The client reference
 * manifest for route "/objects/[code]" does not exist».
 *
 * Лечится тем, что выпуск собирается в СВОЁМ каталоге, а ссылка `current`
 * переводится на него только после успешной сборки.
 *
 * ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ — не «скрипт существует», а три вещи, любая из которых
 * молча возвращает прежнюю беду:
 *
 *  1. службы работают из ССЫЛКИ, а не из каталога выпуска. Юнит, указывающий
 *     на конкретный выпуск, переключения не заметит: сборка рядом будет идти,
 *     а отдавать сервер продолжит старое — и различить это по экрану нельзя;
 *  2. окружение живёт ВНЕ выпусков. `.env` внутри выпуска исчезает при каждом
 *     переключении, и его начинают копировать руками — повод однажды забыть
 *     права 600 на файл с ключом модели;
 *  3. сборка идёт ДО переключения. Собрать после — значит вернуть ровно тот
 *     дефект, ради которого всё затевалось, только под другим именем.
 */
import { readdirSync, readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

const ПОСТАВКА = new URL("../", import.meta.url);

function файл(путь: string): string {
  return readFileSync(new URL(путь, ПОСТАВКА), "utf8");
}

/**
 * Юниты берутся ЧТЕНИЕМ КАТАЛОГА, а не перечислением: перечисление отстаёт от
 * переименования. Воркеры стали шаблонами systemd (`…-worker@.service`), и
 * список, набранный руками, продолжал бы проверять файлы, которых нет, —
 * `it.each` по пустому месту молча ничего не проверяет.
 *
 * Стенд держится теми же правилами, что и прод: иначе он проверяет не прод.
 */
const ЮНИТЫ = readdirSync(new URL("deploy/", ПОСТАВКА))
  .filter((имя) => имя.endsWith(".service"))
  .map((имя) => `deploy/${имя}`)
  .sort();

/** Юниты воркеров — они же шаблоны с экземплярами. */
const ВОРКЕРЫ = ЮНИТЫ.filter((путь) => путь.includes("worker"));

const СКРИПТ = "deploy/release.sh";

/** Скрипты развёртывания: все, а не только выпуск. */
const СКРИПТЫ = readdirSync(new URL("deploy/", ПОСТАВКА))
  .filter((имя) => имя.endsWith(".sh"))
  .map((имя) => `deploy/${имя}`)
  .sort();

/** Значение директивы юнита (`WorkingDirectory=…`). */
function директива(текст: string, имя: string): string | undefined {
  const строка = текст
    .split("\n")
    .map((s) => s.trim())
    .filter((s) => !s.startsWith("#"))
    .find((s) => s.startsWith(`${имя}=`));

  return строка?.slice(имя.length + 1).trim();
}

describe("выпуск со сборкой рядом", () => {
  it.each(ЮНИТЫ)("%s работает из ССЫЛКИ current, а не из каталога выпуска", (юнит) => {
    const каталог = директива(файл(юнит), "WorkingDirectory");

    expect(каталог, `${юнит}: не задан рабочий каталог`).toBeDefined();
    expect(
      каталог,
      `${юнит}: рабочий каталог «${каталог}» не ссылка current — переключение выпуска пройдёт мимо службы`,
    ).toMatch(/\/current$/u);
  });

  it.each(ЮНИТЫ)("%s читает окружение ВНЕ выпусков", (юнит) => {
    // `.env` внутри выпуска исчезает при переключении. Ключ модели и пароли
    // базы начинают жить копированием руками, и права 600 держатся на памяти.
    const окружение = директива(файл(юнит), "EnvironmentFile");

    expect(окружение, `${юнит}: не задан файл окружения`).toBeDefined();
    expect(
      окружение,
      `${юнит}: окружение «${окружение}» лежит внутри выпуска и потеряется при переключении`,
    ).not.toMatch(/\/(releases|current)\//u);
  });

  it("сборка идёт ДО переключения ссылки", () => {
    /**
     * Порядок здесь и есть весь смысл. Собрать после переключения — значит
     * переписывать каталог, из которого уже читает служба: тот же дефект под
     * другим именем.
     */
    const скрипт = файл(СКРИПТ);

    const сборка = скрипт.indexOf("next build");
    const переключение = скрипт.indexOf("ln -sfnT");

    expect(сборка, "в скрипте нет сборки").toBeGreaterThan(-1);
    expect(переключение, "в скрипте нет переключения ссылки").toBeGreaterThan(-1);
    expect(
      сборка,
      "сборка стоит ПОСЛЕ переключения — служба снова читает переписываемый каталог",
    ).toBeLessThan(переключение);
  });

  it("выпуск проверяется ответом, а не фактом запуска службы", () => {
    // `systemctl restart` возвращает успех и на процессе, который через
    // секунду упадёт. Выпуск, который не отвечает, надо увидеть у себя.
    const скрипт = файл(СКРИПТ);

    expect(скрипт, "нет проверки ответа после переключения").toMatch(/http_code/u);
    expect(скрипт, "нечего сказать про откат").toMatch(/[Оо]ткат/u);
  });

  it("прежние выпуски НЕ удаляются сразу: откат — это переключение ссылки", () => {
    const скрипт = файл(СКРИПТ);

    expect(скрипт, "не задано, сколько выпусков хранить").toMatch(/KEEP/u);
    // Хранить один — значит не иметь куда откатываться.
    const умолчание = /KEEP:-(\d+)/u.exec(скрипт)?.[1];
    expect(Number(умолчание ?? 0), "хранится меньше двух выпусков — откатываться некуда").toBeGreaterThanOrEqual(2);
  });

  it.each(СКРИПТЫ)("в %s НЕТ имён переменных кириллицей", (скрипт_пути) => {
    /**
     * НАЙДЕНО НА СЕБЕ, дважды за один час.
     *
     * Код этого репозитория написан по-русски: `безСуммы`, `перечислить`,
     * `причинойОтказа` — норма. Рядом с ним кириллическое имя в шелле выглядит
     * естественно, и рука пишет его сама.
     *
     * В bash так нельзя. `КОРЕНЬ=/opt/…` не является присваиванием: строка
     * разбирается как попытка ЗАПУСТИТЬ команду с таким именем и падает с «No
     * such file or directory» — сообщением, которое указывает куда угодно,
     * только не на настоящую причину. Скрипт выпуска был написан именно так и
     * упал бы на сервере целиком.
     *
     * Кириллица в СТРОКАХ, путях и выводе допустима: там она работает, и
     * русские сообщения об ошибках здесь ценнее английских.
     */
    const строки = файл(скрипт_пути).split("\n");
    const плохие: string[] = [];

    for (const [index, строка] of строки.entries()) {
      const без_комментария = строка.replace(/#.*$/u, "");

      // Присваивание: имя в начале выражения. Ищем кириллицу до знака равенства.
      if (/(?:^|[;&|(]\s*|\s)[А-Яа-яЁё_][А-Яа-яЁё0-9_]*=/u.test(без_комментария)) {
        плохие.push(`${index + 1}: ${строка.trim().slice(0, 70)}`);
        continue;
      }

      // Обращение: $ИМЯ, ${ИМЯ}, либо имя внутри арифметики $(( … )).
      if (/\$\{?[А-Яа-яЁё_]/u.test(без_комментария)) {
        плохие.push(`${index + 1}: ${строка.trim().slice(0, 70)}`);
        continue;
      }

      const арифметика = /\$\(\(([^)]*)\)\)/u.exec(без_комментария);
      if (арифметика !== null && /[А-Яа-яЁё]/u.test(арифметика[1] ?? "")) {
        плохие.push(`${index + 1}: ${строка.trim().slice(0, 70)}`);
      }
    }

    expect(плохие, `имена переменных кириллицей — bash их не примет:\n${плохие.join("\n")}`).toEqual([]);
  });
});

/**
 * ДВА КОНТУРА НА ОДНОЙ МАШИНЕ — И НИ ОДНОГО ОБЩЕГО ЗНАЧЕНИЯ.
 *
 * ЗАЧЕМ ЭТО ПРОВЕРЯТЬ. Стенд появился затем, чтобы правки неделю жили не на
 * боевом контуре. Ценность держится ровно до первого совпавшего значения:
 * общий порт — и стенд не поднимется рядом с продом; общее имя службы — и
 * выпуск стенда перезапустит боевые процессы; ОБЩАЯ БАЗА — и «проверка на
 * стенде» пишет в данные настоящих пользователей.
 *
 * Последнее — не догадка о возможном. Роль `stroyintellect_app`, под которой
 * работает приложение, в PostgreSQL принадлежит КЛАСТЕРУ: один кластер на два
 * контура означает один пароль, которым открываются обе базы.
 *
 * Поэтому здесь сверяется каждое различающее значение по отдельности. Забыть
 * одно из восьми — обычное дело; молча остаться при этом с одной базой — нет.
 */
describe("контуры прода и стенда", () => {
  const РАЗЛИЧАЮЩИЕ = [
    "ROOT",
    "BRANCH",
    "PORT",
    "SERVICE_WEB",
    "SERVICE_WORKER",
    "PGPORT",
    "PGDATABASE",
    "OBJECTS",
  ];

  /** Значения контура из `deploy/contours.sh`. */
  function контур(имя: string): Record<string, string> {
    const текст = файл("deploy/contours.sh");
    const блок = new RegExp(`^\\s*${имя}\\)\\r?\\n([\\s\\S]*?)^\\s*;;`, "mu").exec(текст)?.[1];

    expect(блок, `в contours.sh нет контура ${имя}`).toBeDefined();

    const значения: Record<string, string> = {};
    for (const строка of (блок ?? "").split("\n")) {
      const пара = /^\s*([A-Z_]+)=(.*)$/u.exec(строка.replace(/#.*$/u, "").trimEnd());
      if (пара !== null) {
        значения[пара[1] as string] = (пара[2] as string).trim().replace(/^['"]|['"]$/gu, "");
      }
    }

    return значения;
  }

  const ПРОД = контур("prod");
  const СТЕНД = контур("stage");

  it.each(РАЗЛИЧАЮЩИЕ)("%s у стенда и прода РАЗНЫЕ", (ключ) => {
    expect(ПРОД[ключ], `contours.sh: у прода не задан ${ключ}`).toBeDefined();
    expect(СТЕНД[ключ], `contours.sh: у стенда не задан ${ключ}`).toBeDefined();
    expect(
      СТЕНД[ключ],
      `${ключ} совпадает у двух контуров («${СТЕНД[ключ]}») — контуры перестали быть отдельными`,
    ).not.toBe(ПРОД[ключ]);
  });

  it("имя контура обязательно: без него выпуск не идёт", () => {
    // `${1:-prod}` означало бы, что команда, набранная для стенда без имени,
    // выполнилась на боевом контуре. Такую ошибку исправляют задним числом.
    const скрипт = файл(СКРИПТ);

    expect(скрипт, "в выпуске нет загрузки контура").toMatch(/contour_load "\$\{1:-\}"/u);
    expect(скрипт, "у имени контура есть умолчание — команда без имени пойдёт на прод").not.toMatch(
      /contour_load "?\$\{1:-\w/u,
    );
  });

  it("выпуск перезапускает службы СВОЕГО контура, а не названные в тексте", () => {
    const скрипт = файл(СКРИПТ);

    expect(скрипт, "нет перезапуска веба").toMatch(/systemctl restart "\$SERVICE_WEB"/u);
    // Литерал имени боевой службы в скрипте, который зовут и для стенда, —
    // это перезапуск прода при выпуске стенда.
    const литералы = скрипт
      .split("\n")
      .filter((строка) => !строка.trim().startsWith("#"))
      .filter((строка) => /systemctl\s+\w+\s+stroyintellekt-/u.test(строка));

    expect(литералы, `имена служб вписаны в команды:\n${литералы.join("\n")}`).toEqual([]);
  });

  it("контур базы проверяется МЕТКОЙ ИЗ БАЗЫ и до первой записи", () => {
    /**
     * Строка подключения говорит, куда СОБИРАЛИСЬ подключиться. Куда
     * подключились — говорит только сама база. Метка ставится при заведении
     * контура (`alter database … set stroyintellect.contour`), и выпуск обязан
     * прочитать её ДО миграций: миграция, применённая к чужой базе, обратной
     * команды не имеет.
     */
    const скрипт = файл(СКРИПТ);

    const метка = скрипт.indexOf("stroyintellect.contour");
    const миграции = скрипт.indexOf("prisma migrate deploy");

    expect(метка, "выпуск не сверяет метку контура в базе").toBeGreaterThan(-1);
    expect(миграции, "в выпуске нет миграций").toBeGreaterThan(-1);
    expect(метка, "метка контура читается ПОСЛЕ миграций — проверять уже нечего").toBeLessThan(миграции);
  });

  it.each([
    ["deploy/stroyintellekt-stage-web.service", СТЕНД],
    ["deploy/stroyintellekt-stage-worker@.service", СТЕНД],
    ["deploy/stroyintellekt-web.service", ПРОД],
    ["deploy/stroyintellekt-worker@.service", ПРОД],
  ] as const)("%s живёт в каталогах своего контура", (юнит, значения) => {
    const текст = файл(юнит);
    const корень = значения["ROOT"] as string;

    expect(директива(текст, "WorkingDirectory"), `${юнит}: чужой корень`).toBe(`${корень}/current`);
    expect(директива(текст, "EnvironmentFile"), `${юнит}: чужое окружение`).toBe(`${корень}/.env`);
  });

  it("веб каждого контура слушает СВОЙ порт", () => {
    for (const [юнит, значения] of [
      ["deploy/stroyintellekt-web.service", ПРОД],
      ["deploy/stroyintellekt-stage-web.service", СТЕНД],
    ] as const) {
      const запуск = директива(файл(юнит), "ExecStart") ?? "";
      expect(запуск, `${юнит}: порт в запуске не от этого контура`).toMatch(
        new RegExp(`-p ${значения["PORT"] as string}\\b`, "u"),
      );
    }
  });

  it("службы стенда имеют предел памяти, а прод — приоритет процессора", () => {
    /**
     * 4 ядра, 11 ГБ, подкачки нет. Без предела утечка на стенде уводит в OOM
     * весь сервер, и ядро выбирает жертву само — с равной вероятностью боевой
     * воркер. Предел превращает «сервер лёг» в «стенд перезапустился».
     */
    for (const юнит of [
      "deploy/stroyintellekt-stage-web.service",
      "deploy/stroyintellekt-stage-worker@.service",
    ]) {
      const текст = файл(юнит);
      expect(директива(текст, "MemoryMax"), `${юнит}: нет предела памяти`).toBeDefined();

      const вес = Number(директива(текст, "CPUWeight") ?? 100);
      expect(вес, `${юнит}: стенд не уступает проду процессор (CPUWeight=${вес})`).toBeLessThan(100);
    }
  });

  it("nginx каждого домена ходит на порт СВОЕГО контура", () => {
    for (const [конфиг, значения] of [
      ["deploy/app.strintel.ru.conf", ПРОД],
      ["deploy/stage.strintel.ru.conf", СТЕНД],
    ] as const) {
      const текст = файл(конфиг);
      const порты = [...текст.matchAll(/proxy_pass\s+http:\/\/127\.0\.0\.1:(\d+)/gu)].map((m) => m[1]);

      expect(порты.length, `${конфиг}: нет proxy_pass`).toBeGreaterThan(0);
      expect(new Set(порты), `${конфиг}: проксирует на чужой контур`).toEqual(
        new Set([значения["PORT"] as string]),
      );
    }
  });

  it("копия данных идёт ТОЛЬКО с прода на стенд", () => {
    /**
     * Обратного направления быть не должно даже в виде удобной опции: копия
     * стенда в прод затирает работу настоящих пользователей, и «удобная
     * опция» однажды окажется набранной.
     */
    const скрипт = файл("deploy/sync-stage-from-prod.sh");

    const источник = скрипт.indexOf("contour_load prod");
    const цель = скрипт.indexOf("contour_load stage");

    expect(источник, "не назван источник").toBeGreaterThan(-1);
    expect(цель, "не названа цель").toBeGreaterThan(-1);
    expect(источник, "порядок обратный: прод оказался целью").toBeLessThan(цель);

    // Очистка таблиц — самая опасная строка скрипта. Она обязана идти после
    // чтения метки цели и обращаться к порту цели, а не к набранному числу.
    const метка = скрипт.indexOf("TARGET_MARK=");
    const очистка = скрипт.indexOf("truncate table");

    expect(метка, "метка цели не читается").toBeGreaterThan(-1);
    expect(очистка, "нет очистки цели").toBeGreaterThan(-1);
    expect(метка, "цель очищается ДО проверки метки").toBeLessThan(очистка);
    expect(скрипт, "в очистке набран порт вместо порта контура").not.toMatch(/truncate[\s\S]{0,200}5432/u);
  });
});

/**
 * ДВА ПОТОКА ВОРКЕРА НА ПРОДЕ — И НИ ОДНОГО МОЛЧАЛИВОГО СПОСОБА ОСТАТЬСЯ С ОДНИМ.
 *
 * ЗАЧЕМ ПОТОКИ. Проверку ставят до пяти человек, а прогон экипажа идёт до часа.
 * С одним воркером второй человек ждёт не свою работу и не понимает, почему.
 *
 * ЧЕМ ЭТО ДЕРЖИТСЯ, А НЕ ТОЛЬКО ОБЪЯВЛЕНО. Воркер держит замок с номером
 * процесса в дереве проекта — против случайного дубля (5 сентября 2026 их
 * набралось восемь, и systemd-oomd убил рабочий стол владельца). Замок
 * пер-экземплярный, номер приходит из `STROYINTELLECT_WORKER_ID`.
 *
 * Отсюда главная опасность этой схемы: забыть `%i` в шаблоне. Тогда оба
 * экземпляра берут ОДНО имя замка, второй отказывается стартовать — и прод
 * тихо возвращается к одному потоку. `systemctl status` при этом зелёный у
 * первого, а очередь по-прежнему одна.
 */
describe("потоки воркера", () => {
  function контурные(имя: string): Record<string, string> {
    const текст = файл("deploy/contours.sh");
    const блок = new RegExp(`^\\s*${имя}\\)\\r?\\n([\\s\\S]*?)^\\s*;;`, "mu").exec(текст)?.[1];
    const значения: Record<string, string> = {};

    for (const строка of (блок ?? "").split("\n")) {
      const пара = /^\s*([A-Z_]+)=(.*)$/u.exec(строка.replace(/#.*$/u, "").trimEnd());
      if (пара !== null) значения[пара[1] as string] = (пара[2] as string).trim().replace(/^['"]|['"]$/gu, "");
    }

    return значения;
  }

  it.each(ВОРКЕРЫ)("%s — ШАБЛОН systemd, а не одиночный юнит", (юнит) => {
    expect(
      юнит,
      `${юнит}: имя без «@» — экземпляров у такого юнита не бывает, второй поток запускать нечем`,
    ).toMatch(/worker@\.service$/u);
  });

  it.each(ВОРКЕРЫ)("%s передаёт номер потока в замок воркера", (юнит) => {
    /**
     * Без этой строки оба экземпляра берут одно имя замка (`var/worker.lock`),
     * и второй выходит с кодом 1, сообщая про дубль. Прод остаётся с одним
     * потоком, а сообщение об этом лежит в journalctl экземпляра, куда никто
     * не смотрит, пока не начнут ждать очередь.
     */
    const текст = файл(юнит);
    const строки = текст
      .split("\n")
      .map((s) => s.trim())
      .filter((s) => !s.startsWith("#"));

    expect(
      строки,
      `${юнит}: нет Environment=STROYINTELLECT_WORKER_ID=%i — экземпляры поделят один замок`,
    ).toContain("Environment=STROYINTELLECT_WORKER_ID=%i");
  });

  it.each(ВОРКЕРЫ)("%s имеет предел памяти: утечка стоит потока, а не сервера", (юнит) => {
    // 11,7 ГБ на машине и НЕТ подкачки: перебор — это убийство процесса ядром,
    // и жертву ядро выбирает само, с равной вероятностью не виновника.
    const предел = директива(файл(юнит), "MemoryMax");

    expect(предел, `${юнит}: нет MemoryMax`).toBeDefined();
    // Предел ниже потолка кучи (2 ГБ) означал бы смерть на первом большом
    // документе заказчика — то есть лечение хуже болезни.
    const гигабайты = Number(/^(\d+)G$/u.exec(предел ?? "")?.[1] ?? 0);
    expect(гигабайты, `${юнит}: предел «${предел}» не выше потолка кучи 2 ГБ`).toBeGreaterThan(2);
  });

  it("на проде потоков БОЛЬШЕ ОДНОГО, на стенде — хотя бы один", () => {
    const прод = Number(контурные("prod")["WORKERS"] ?? 0);
    const стенд = Number(контурные("stage")["WORKERS"] ?? 0);

    expect(прод, "на проде один поток — второй человек снова ждёт чужую работу").toBeGreaterThanOrEqual(2);
    expect(стенд, "на стенде нет ни одного воркера — прогоны там не пойдут").toBeGreaterThanOrEqual(1);
  });

  it("выпуск перезапускает ВСЕ экземпляры, а не один юнит", () => {
    /**
     * Список экземпляров складывается в contours.sh из числа потоков. Скрипт,
     * считающий их сам, однажды разойдётся с этим числом — и оставит второй
     * поток на прежнем выпуске. Внешне это неотличимо от исправной работы:
     * старый код продолжает брать задачи.
     */
    const контуры = файл("deploy/contours.sh");
    const скрипт = файл(СКРИПТ);

    expect(контуры, "экземпляры не складываются из числа потоков").toMatch(/WORKER_UNITS\+=\("\$\{SERVICE_WORKER\}@\$\{INSTANCE\}"\)/u);
    expect(скрипт, "выпуск не проходит по всем экземплярам").toMatch(/for UNIT in "\$\{WORKER_UNITS\[@\]\}"/u);
    expect(скрипт, "перезапуск идёт мимо списка экземпляров").toMatch(/systemctl restart "\$UNIT"/u);
  });

  it("занятый поток отличается от свободного ПО ВЛАДЕЛЬЦУ АРЕНДЫ", () => {
    /**
     * С одним воркером хватало вопроса «есть ли работающие задачи». С двумя
     * этого мало: один поток может вести часовой прогон, а второй стоять
     * пустым — и новый код обязан попасть в пустой сразу.
     *
     * Различить их можно только по владельцу аренды, поэтому номер потока
     * входит в него в самом воркере.
     */
    const воркер = файл("apps/worker/src/main.ts");
    const скрипт = файл(СКРИПТ);

    expect(воркер, "номер потока не входит в владельца аренды").toMatch(/НОМЕР_ЭКЗЕМПЛЯРА[\s\S]{0,200}hostname\(\)/u);
    expect(скрипт, "выпуск не смотрит на владельца аренды").toMatch(/leaseOwner/u);
    expect(скрипт, "выпуск не отличает занятый поток по номеру").toMatch(/\/\$\{INSTANCE\}#/u);
  });

  it("замок воркера складывается ИЗ НОМЕРА ЭКЗЕМПЛЯРА и номер проверяется", () => {
    const воркер = файл("apps/worker/src/main.ts");

    expect(воркер, "имя замка не зависит от экземпляра — второй поток не стартует").toMatch(
      /worker-\$\{НОМЕР_ЭКЗЕМПЛЯРА\}\.lock/u,
    );
    // Номер попадает в путь файла: без проверки «../../» в переменной уводит
    // замок за пределы дерева, а пустое значение сводит два потока в один замок.
    expect(воркер, "номер экземпляра не проверяется перед подстановкой в путь").toMatch(
      /A-Za-z0-9_-\]\{1,16\}\$\/u\.test\(НОМЕР_ЭКЗЕМПЛЯРА\)/u,
    );
  });
});
