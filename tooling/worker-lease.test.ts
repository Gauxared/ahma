/**
 * ПРОДЛЕНИЕ АРЕНДЫ НЕ КОНКУРИРУЕТ С РАБОТОЙ ЗА СОЕДИНЕНИЯ.
 *
 * НАЙДЕНО В ЖУРНАЛЕ ЖИВЫХ ПРОГОНОВ: при каждой проверке объекта повторялось
 * «продление аренды не удалось — Unable to start a transaction in the given
 * time». Обход держит десятки транзакций (запись хода, журнал §12.1л, разбор),
 * пул один на всех, и продлению — одному короткому UPDATE — не доставалось
 * соединения за отведённые ему секунды.
 *
 * Проигрывало самое важное: аренда — единственное, что мешает второму воркеру
 * взять ту же проверку. Комментарий самого воркера помнит, чем это кончалось:
 * «модель позвали шесть раз вместо одного».
 *
 * ПОЧЕМУ ЭТОТ НАБОР ЧИТАЕТ ИСХОДНИК, А НЕ ЗАПУСКАЕТ ВОРКЕР.
 *
 * Проверяемое утверждение — «продление ходит НЕ ЧЕРЕЗ ТОТ ЖЕ клиент, что
 * работа». Наблюдать его в поведении можно только под нагрузкой, забившей пул:
 * такой набор был бы медленным, шатким и всё равно доказывал бы совпадение, а
 * не причину. Проводка же видна в исходнике однозначно, и сломать её можно
 * ровно одним способом — передать в продление общий клиент.
 *
 * Файл воркера при этом не запускается ни здесь, ни в любом наборе: на импорте
 * он вызывает `main()` и уходит в бесконечный цикл.
 */
import { readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

import { LEASE_TRANSACTION_MAX_WAIT_MS } from "@platform/db/prisma.js";

const ВОРКЕР = new URL("../apps/worker/src/main.ts", import.meta.url);
const исходник = readFileSync(ВОРКЕР, "utf8");

describe("аренда задачи в воркере", () => {
  it("клиент для продления создаётся ОТДЕЛЬНО от рабочего", () => {
    expect(исходник, "нет отдельного клиента под аренду").toMatch(/createLeaseClient\(/u);
    expect(исходник, "клиент аренды не назван").toMatch(/const leaseDb = createLeaseClient\(/u);
  });

  it("продление идёт через клиент аренды, а не через рабочий", () => {
    /**
     * Единственный способ вернуть прежнюю беду — передать сюда `db`. Тогда
     * продление снова встанет в очередь за соединением позади обхода, и
     * защита от двойного исполнения снова исчезнет молча.
     */
    const вызов = /withHeartbeat\(\s*([A-Za-z]+)\s*,/u.exec(исходник);

    expect(вызов, "withHeartbeat не вызывается").not.toBeNull();
    expect(вызов?.[1], "продление ходит через рабочий клиент — пул снова общий").toBe("leaseDb");
  });

  it("клиент аренды закрывается при остановке воркера", () => {
    // Незакрытый клиент держит соединения после `SIGTERM`, и перезапуск службы
    // упирается в `max_connections` — на сервере это два соединения на каждый
    // перезапуск, накапливающиеся до отказа базы.
    expect(исходник, "клиент аренды не отключается").toMatch(/leaseDb\.\$disconnect\(\)/u);
  });

  it("потеря аренды ОСТАНАВЛИВАЕТ обход, а не только пишется в журнал", () => {
    /**
     * Раньше здесь стоял `console.error` и работа шла дальше — с оговоркой
     * «результат всё равно не запишется, `complete` проверяет владельца».
     * Оговорка верна наполовину: строку задачи чужой воркер защищает, но деньги
     * на модель к тому моменту потрачены, а ход прогона писался поверх чужого.
     */
    expect(исходник, "порт остановки не передан обходу").toMatch(/stopRequested:\s*\(\)\s*=>/u);
    expect(исходник, "причина остановки берётся не у учёта аренды").toMatch(
      /причинаОстановки\(\)/u,
    );
  });

  it("остановка НЕ помечает задачу неудачной", () => {
    /**
     * Записать остановку как отказ значило бы увеличить счётчик попыток чужой
     * задачи, вернуть её в очередь с отсрочкой и объявить Проверку упавшей —
     * притом что в эту минуту её доводит до конца другой воркер.
     */
    expect(исходник, "остановка не отличается от отказа").toMatch(/instanceof CheckStopped/u);

    /**
     * Сравнивать надо ВНУТРИ обработчика, а не по всему файлу: `queue.fail`
     * законно встречается и раньше — в ветке неизвестного типа задачи, где
     * никакой остановки быть не может.
     */
    const обработчик = исходник.slice(исходник.indexOf("} catch (cause) {"));
    const остановка = обработчик.indexOf("instanceof CheckStopped");
    const отказ = обработчик.indexOf("queue.fail(");

    expect(остановка, "в обработчике нет проверки остановки").toBeGreaterThan(-1);
    expect(отказ, "в обработчике нет пометки неудачи").toBeGreaterThan(-1);
    expect(
      остановка,
      "остановка разбирается ПОСЛЕ пометки неудачи — задачу успеют объявить упавшей",
    ).toBeLessThan(отказ);
  });

  it("продлению задан ЯВНЫЙ бюджет ожидания, а не умолчание", () => {
    /**
     * ЗАМЕРЕНО НА СЕРВЕРЕ ПОСЛЕ ПЕРВОЙ ПРАВКИ, и это её честный итог.
     *
     * Отдельный пул под аренду единственную неудачу за прогон НЕ убрал: она
     * повторилась на сорок пятой секунде — когда обход разбирает двадцать
     * четыре файла и пишет в ту же базу.
     *
     * Проверено, чего причиной НЕ было: блокировки цикла событий (опыт на
     * сервере — транзакция открывается даже после шести секунд синхронной
     * блокировки) и исчерпания соединений (семь занятых из ста). Осталась
     * задержка самой базы под нагрузкой — против неё помогает не пул, а
     * бюджет ожидания, и умолчание Prisma в две секунды для этого тесно.
     */
    expect(исходник, "бюджет ожидания не задан — вернётся умолчание в 2 с").toMatch(
      /maxWaitMs:\s*LEASE_TRANSACTION_MAX_WAIT_MS/u,
    );
  });

  it("бюджет ожидания МЕНЬШЕ периода продления и намного меньше срока аренды", () => {
    /**
     * Арифметика, в которой легко ошибиться молча.
     *
     * Бюджет больше периода — попытки наслаиваются: вторая начинается, пока
     * первая ещё ждёт, и продления идут не по одному. Бюджет близкий к сроку
     * аренды — одна долгая попытка съедает весь запас, и после неё аренда уже
     * истекла.
     */
    const периодСекунд = 60 / 3;
    const срокСекунд = 60;

    expect(
      LEASE_TRANSACTION_MAX_WAIT_MS / 1000,
      "бюджет больше периода — попытки продления наложатся друг на друга",
    ).toBeLessThan(периодСекунд);

    expect(
      LEASE_TRANSACTION_MAX_WAIT_MS / 1000,
      "бюджет съедает запас аренды: после одной долгой попытки она уже истекла",
    ).toBeLessThan(срокСекунд / 3);

    // И он должен быть БОЛЬШЕ умолчания: иначе правка ничего не изменила.
    expect(LEASE_TRANSACTION_MAX_WAIT_MS, "бюджет не больше умолчания Prisma").toBeGreaterThan(2000);
  });
});
