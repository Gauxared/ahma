/**
 * Алиасы повторяют `paths` из tsconfig.base.json. Импорты пишутся с расширением
 * `.js` (корректно для настоящего ESM), поэтому алиас сопоставляется регулярным
 * выражением и подставляет исходный `.ts`.
 */
/**
 * Расширение `.js` НЕОБЯЗАТЕЛЬНО.
 *
 * Основной код репозитория пишет импорты с `.js` по правилам ESM. Файлы веба
 * пишут без него: сборщик Next не переписывает расширение через псевдонимы, а
 * `moduleResolution: "Bundler"` его и не требует. Обе формы указывают на один
 * и тот же файл, и псевдоним обязан понимать обе — иначе тесты веба не найдут
 * платформу, хотя сборка её находит.
 */
function alias(prefix: string, directory: string) {
  return {
    find: new RegExp(`^${prefix}/(.*?)(?:\\.js)?$`),
    replacement: fileURLToPath(new URL(`./${directory}/$1.ts`, import.meta.url)),
  };
}

